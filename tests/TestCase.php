     * পাওয়ার আগে**। ⓘ নিচের পরীক্ষাটা ঠিক সেই দৃশ্যটাই মেপেছে, আর
     * সেখানে দ্বিতীয়জন থেমেছে — কিন্তু দাবিটা "অসম্ভব" নয়, "প্রায়
     * সবসময়"। এটা দুর্ঘটনার পাহারা, শত্রুর নয়।
     */
    private function refuseToShareTheRunItself(string $database): void
    {
        /*
         * ⛔ রায়টা মনে রাখা হয়, আর **না** হলে প্রতিবার ছোঁড়া হয়।
         *
         * ── ⚠️ প্রথম চেষ্টাটা এখানেই ভুল ছিল, আর মেপে ধরা পড়েছে ──────
         * প্রথমে লেখা ছিল "একবার দেখেছি, আর দেখব না"। ⓘ দুইটা রান
         * একসাথে চালিয়ে দেখা গেল ফলটা: `4 tests, 3 passed, 1 error`।
         *
         * ⛔ অর্থাৎ রানটা **থামেনি** — প্রথম পরীক্ষাটা থেমেছে, আর বাকি
         * তিনটা তালার প্রশ্নই করেনি, তাই সবুজ দেখিয়েছে। ⚠️ আর "তিনটা
         * পাশ, একটা ত্রুটি" পড়ে মানুষ ভাবেন একটা ছোট গণ্ডগোল, অথচ
         * সত্যিটা হলো গোটা রানটাই অচল।
         *
         * ⭐ তাই ব্যর্থতাটা মনে রাখা হয় আর প্রতিবার ছোঁড়া হয়: সব
         * পরীক্ষা লাল, রিপোর্টে কোনো দ্ব্যর্থতা নেই।
         */
        static $refusal = null;
        static $checked = false;

        if ($checked) {
            if ($refusal !== null) {
                throw new RuntimeException($refusal);
            }

            return;
        }

        $checked = true;

        try {
            if (DB::connection()->getDriverName() !== 'mysql') {
                return;
            }

            /*
             * ⛔ তালাটা **নিজের আলাদা সংযোগে**, Laravel-এর সংযোগে নয়।
             *
             * ── ⚠️ প্রথমে Laravel-এর সংযোগেই নেওয়া হয়েছিল, আর মেপে ধরা পড়ল ──
             * দুইটা রান একসাথে চালিয়ে দেখা গেল **দুইটাই মরেছে** সংঘর্ষের
             * ক্ষতি নিয়ে: `Table 'abos_test_d1.migrations' doesn't exist`।
             * অথচ তালাটা তো নেওয়া হয়েছিল।
             *
             * ⓘ কারণ: `RefreshDatabase` তার `migrate:fresh` চালাতে গিয়ে
             * সংযোগটা নতুন করে ধরে, আর `GET_LOCK` **সংযোগ-ভিত্তিক** — পুরনো
             * সংযোগ গেলে তালাও যায়। ⛔ ফল: তালাটা কেবল রানের প্রথম
             * সেকেন্ডগুলোতে ধরা থাকত, তারপর নীরবে খুলে যেত।
             *
             * ⚠️ এটাই ছিল সবচেয়ে বিপজ্জনক রূপ — পাহারাটা **কাজ করছে বলে
             * মনে হত** (প্রথম সংঘর্ষটা ধরেছিল), অথচ আসল সুরক্ষাটা দিত না।
             *
             * ⭐ তাই এখানে একটা নিজস্ব PDO খোলা হয় আর static-এ ধরে রাখা
             * হয়, যাতে সে গোটা প্রসেসের আয়ু বাঁচে। Laravel তাকে চেনে না,
             * তাই purge করতেও পারে না।
             *
             * ⓘ নামটা মাপা (`select database()`), কনফিগ থেকে নেওয়া নয় —
             * উপরের টীকার কারণেই। হোস্ট আর পরিচয়টুকুই কনফিগের।
             */
            $on = config('database.connections.'.config('database.default'));

            $holder = new \PDO(
                'mysql:host='.($on['host'] ?? '127.0.0.1').';port='.($on['port'] ?? '3306'),
                $on['username'] ?? 'root',
                $on['password'] ?? '',
            );

            $got = $holder->query("select get_lock('".$database."', 0)")->fetchColumn();

            // ⚠️ ধরে না রাখলে PHP সংযোগটা বন্ধ করে দিত, আর তালাও ছেড়ে যেত
            self::$lockHolder = $holder;
        } catch (\Throwable) {
            /*
             * ⚠️ তালাটা নেওয়া গেল না — তখন থামানোর কিছু নেই।
             *
             * ⓘ এখানে ব্যতিক্রম ছুঁড়লে পাহারাটা নিজেই রান আটকানোর
             * কারণ হয়ে দাঁড়াত, অথচ সে কোনো সংঘর্ষ দেখেনি।
             */
            return;
        }

        if ((string) $got === '1') {
            return;
        }

        throw new RuntimeException($refusal =
            "⛔ পরীক্ষা থামানো হলো — '{$database}'-এ এই মুহূর্তে আরেকটা রান চলছে।\n\n"
            .'দুইটা রান একই ডাটাবেজে চললে দুইজনের `migrate:fresh` একে অন্যের টেবিল '
            ."ড্রপ করে, আর ফল হয় এরকম বার্তা:\n\n"
            ."    Deadlock found when trying to get lock\n"
            ."    Table '{$database}.companies' doesn't exist\n\n"
            .'⚠️ দুইটাই পড়তে **হুবহু নিজের কোডের রিগ্রেশনের মতো**, তাই সময়টা নষ্ট '
            ."হয় নিজের সারাই সন্দেহ করতে।\n\n"
            ."ⓘ এটা নামের ভুল নয় — নামটা ঠিকই আছে, কেবল আরেকজন আগে বসে আছে।\n\n"
            ."আগের রানটা শেষ হতে দিন, নাহলে সেটা খুঁজে বন্ধ করুন:\n\n"
            ."    Get-CimInstance Win32_Process | Where-Object CommandLine -match 'artisan test|phpunit'\n\n"
            .$this->wayOutOfAStuckLock($database)
        );
    }

    /**
     * তালাটা আটকে গেলে বেরোনোর পথ — কে ধরে আছে, আর কীভাবে ছাড়ানো যায়।
     *
     * ── ⚠️ abos-8b-র সতর্কতা, ২২ সেপ্টেম্বর ২০২৬ ────────────────────
     * *"সমাধানটাই যেন নতুন একটা আটকে যাওয়া দরজা না হয়।"* ⓘ প্রসেস
     * জোর করে মারা হলে (Ctrl+C, বা ব্যাকগ্রাউন্ড টাস্কের টাইমআউট)
     * MySQL তালাটা ছাড়ে কেবল **সংযোগটা সত্যিই বন্ধ হলে**। ⛔ বিরল
     * ক্ষেত্রে সেটা `wait_timeout` পর্যন্ত ঝুলে থাকতে পারে, আর তখন
     * পরের **বৈধ** রানটাও থামবে — কারণ না জেনে।
     *
     * ⭐ তাই বার্তাটা কেবল "থামলাম" বলে না, বলে **কে ধরে আছে** আর
     * **কীভাবে ছাড়াতে হয়**। ⓘ একটা পাহারা যতটা ভালো, তার বেরোনোর
     * পথটাও ততটাই — নাহলে মানুষ পরের বার পাহারাটাই তুলে দেয়।
     */
    private function wayOutOfAStuckLock(string $database): string
    {
        try {
            $holder = DB::connection()->getPdo()
                ->query("select is_used_lock('".$database."')")->fetchColumn();
        } catch (\Throwable) {
            $holder = null;
        }

        if ($holder === null || $holder === false || (string) $holder === '') {
            /*
             * ⓘ এখন আর কেউ ধরে নেই — অর্থাৎ আগেরজন এই কয়েক মিলিসেকেন্ডে
             * শেষ করেছে। ⚠️ তবু থামাই, কারণ যে মুহূর্তে তালা চাওয়া
             * হয়েছিল তখন সংঘর্ষটা সত্যি ছিল।
             */
            return '⚠️ তালাটা এর মধ্যেই ছেড়ে গেছে — আবার চালিয়ে দেখুন।';
        }

        return "ⓘ তালাটা ধরে আছে MySQL সংযোগ **{$holder}**।\n\n"
            ."ঐ প্রসেসটা সত্যিই মরে গিয়ে থাকলে (মেরে ফেলা রান) সংযোগটা ছাড়িয়ে নিন:\n\n"
            ."    mysql -u root -e \"kill {$holder};\"\n\n"
            .'⚠️ কিন্তু আগে নিশ্চিত হোন কোনো রান সত্যিই চলছে না — বেঁচে থাকা রানের '
            .'সংযোগ মেরে দিলে সেটা মাঝপথে ভাঙবে, আর ডাটাবেজটা আধা-মাইগ্রেট অবস্থায় থাকবে।';
    }

    private function refuseToTouchRealData(): void
    {
        /*
         * কনফিগ নয়, সংযোগ।
         *
         * `config('database.connections.….database')` পড়লে এই পাহারাটা
         * ঠিক সেই জিনিসটাই বিশ্বাস করত যেটা সেদিন মিথ্যা বলেছিল। PDO-কে
         * জিজ্ঞেস করলে উত্তরটা আসে **যেখানে কোয়েরি সত্যিই যাবে** সেখান
         * থেকে, আর তার মাঝে কোনো ক্যাশ নেই।
         */
        try {
            $database = (string) DB::connection()->getPdo()
                ->query('select database()')->fetchColumn();
        } catch (\Throwable) {
            /*
             * ডাটাবেজ নাগালে নেই — তখন থামানোর কিছু নেই, আর এখানে
             * ব্যতিক্রম ছুঁড়লে আসল ত্রুটিটা (সংযোগ ব্যর্থ) ঢাকা পড়ত।
             */
            return;
        }

        if ($database === '') {
            return;
        }

        $this->refuseToShareTheRunItself($database);

        if (self::sharedByEverySession($database)) {
            throw new RuntimeException(
                "⛔ পরীক্ষা থামানো হলো — সংযোগটা সবার ভাগের 'abos_test'-এ গেছে।\n\n"
                .'এই নামটা `phpunit.xml`-এ হার্ডকোড করা, তাই যে-ই `DB_DATABASE=` '
                ."বসাতে ভুলবে সে এখানেই এসে পড়ে — অর্থাৎ ডিফল্টটাই ফাঁদ।\n\n"
                .'দুইটা সেশন একসাথে এখানে চললে দুইজনের `migrate:fresh` একে অন্যের '
                ."টেবিল ড্রপ করে, আর ফল হয় এরকম বার্তা:\n\n"
                ."    Deadlock found when trying to get lock\n"
                ."    Table 'abos_test.companies' doesn't exist\n\n"
                .'⚠️ দুইটাই পড়তে **হুবহু নিজের কোডের রিগ্রেশনের মতো**, তাই সময়টা '
                ."নষ্ট হয় নিজের সারাই সন্দেহ করতে।\n\n"
                ."নিজের নামে একটা নিন (`d1`-এর জায়গায় আপনার সেশনের নাম):\n\n"
                .'    mysql -u root -e "create database if not exists abos_test_d1'
                ." character set utf8mb4 collate utf8mb4_unicode_ci;\"\n"
                ."    DB_DATABASE=abos_test_d1 php artisan test …\n\n"
                .'ⓘ CI-তে এই পাহারাটা চুপ থাকে — সেখানে `abos_test` নিজের '
                .'কন্টেইনারে একা থাকে, ভাগাভাগির প্রশ্নই নেই।'
            );
        }

        if (str_starts_with($database, 'abos_test')) {
            return;
        }

        throw new RuntimeException(
            "⛔ পরীক্ষা থামানো হলো — সংযোগটা '{$database}' ডাটাবেজে গেছে, "
            ."কোনো 'abos_test…' ডাটাবেজে নয়।\n\n"
            .'RefreshDatabase-এর প্রথম কাজ migrate:fresh, অর্থাৎ ওই ডাটাবেজের '
            .'প্রতিটা টেবিল ড্রপ। ১২ সেপ্টেম্বর ২০২৬-এ ঠিক সেটাই ঘটেছিল, আর '
            ."রানটা ১৯/১৯ পাস দিয়েছিল — সবুজ ফলটাই ছিল ক্ষতির চিহ্ন।\n\n"
            .'কারণ প্রায় নিশ্চিতভাবেই একটা কনফিগ ক্যাশ পড়ে আছে, যেটা '
            ."phpunit.xml আর DB_DATABASE= দুইটাকেই অকার্যকর করে দেয়:\n\n"
            ."    php artisan config:clear\n\n"
            .'⚠️ ফাইলটা মুছলে চালু প্রসেস থামে না — ওই রানটা বন্ধ করে আবার শুরু করুন।'
        );
    }

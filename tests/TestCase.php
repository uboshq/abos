<?php

namespace Tests;

use Illuminate\Foundation\Testing\TestCase as BaseTestCase;
use Illuminate\Support\Facades\DB;
use RuntimeException;

abstract class TestCase extends BaseTestCase
{
    /**
     * ⛔ কোনো পরীক্ষা কোনোদিন কাজের ডাটাবেজ ছুঁতে পারবে না।
     *
     * ── ⚠️ কী ঘটেছিল, ১২ সেপ্টেম্বর ২০২৬, রাত ২০:৩৩ ─────────────────────
     * `abos:optimise` কমান্ডটা যাচাই করার সময় `config:cache` চালানো হলো,
     * আর সে `bootstrap/cache/config.php` লিখে রাখল — ভেতরে **বাঁধা
     * অবস্থায়** `'database' => 'abos'`, অর্থাৎ ডেভেলপারের কাজের ডাটাবেজ।
     *
     * ⛔ config ক্যাশ থাকলে Laravel আর `env()` পড়ে না, ক্যাশ করা অ্যারে
     * পড়ে। ফলে **দুইটা আলাদা সুরক্ষা একসাথে অকার্যকর হলো**:
     *
     *   · `phpunit.xml`-এর `<env name="DB_DATABASE" value="abos_test"/>`
     *   · কমান্ড-প্রতি `DB_DATABASE=abos_test_xx php artisan test …`
     *
     * তারপর একটা সাধারণ `--filter` রান বুট করল, ক্যাশ করা নামটা পেল, আর
     * `RefreshDatabase` তার প্রথম কাজটাই করল — `migrate:fresh`, অর্থাৎ
     * **`abos`-এর ১৫৯টা টেবিল ড্রপ**। ৯৪ সেকেন্ডে স্কিমা আবার বসল, ডেটা
     * ছাড়া। কোম্পানি, ব্যবহারকারী, শাখা, বিল — সব শূন্য।
     *
     * ── ⭐ আর এটাই ছিল সবচেয়ে খারাপ দিক ───────────────────────────────
     * ঐ রানটা **১৯/১৯ পাস দিয়েছে**। কোনো ত্রুটি নয়, কোনো সতর্কতা নয় —
     * `RefreshDatabase` কাজের ডাটাবেজটা নতুন করে বানিয়ে তার উপরেই
     * পরীক্ষা চালিয়ে সবুজ ফিরিয়েছে। **সবুজ ফলটাই ছিল ক্ষতির চিহ্ন**,
     * আর সবুজ দেখে কেউ কিছু সন্দেহ করেনি।
     *
     * ⓘ ফাইল মুছে দেওয়াও যথেষ্ট ছিল না: `config:clear` চলেছে ২০:৩৩-এ,
     * আর মোছার কাজটা শুরু হয়েছে তার **৪৮ সেকেন্ড পরে** — কারণ চালু
     * প্রসেস কনফিগটা আগেই মেমরিতে তুলে নিয়েছিল। অর্থাৎ ক্যাশ সরানো
     * ভবিষ্যতের রানকে বাঁচায়, চলতি রানকে নয়।
     *
     * ── কেন পাহারাটা এখানে, আর মানুষের মনে রাখার উপর নয় ────────────────
     * সুরক্ষা দুইটাই ছিল (phpunit.xml, আর প্রিফিক্স), দুইটাই **কনফিগের
     * উপর দাঁড়ানো**, আর একটা ক্যাশ ফাইল দুইটাকে একসাথে গিলে ফেলেছে।
     * তিন নম্বর সুরক্ষাটা তাই অন্য জিনিস দেখে: সে কনফিগ কী বলল তা
     * জিজ্ঞেস করে না, সে **সংযোগটা সত্যিই কোথায় গেছে** তা জিজ্ঞেস করে।
     *
     * ⓘ আর ব্যাকআপ এর উত্তর নয়। ঐ দিন সবচেয়ে নতুন ব্যাকআপ ছিল পাঁচ
     * দিনের পুরনো, আর `backups/` ফোল্ডারে `abos-BEFORE-WIPE-…` নামের
     * একটা ফাইল আগে থেকেই পড়ে ছিল — অর্থাৎ এটা প্রথমবার নয়।
     *
     * ── এটা কী করে ───────────────────────────────────────────────────
     * প্রতিটা পরীক্ষার আগে আসল সংযোগটাকে জিজ্ঞেস করে সে কোন ডাটাবেজে
     * বসে আছে। নামটা `abos_test` দিয়ে শুরু না হলে **সাথে সাথে থামে**,
     * আর বার্তায় সারানোর কমান্ডটা লিখে দেয়।
     *
     * ── ⚠️ কোথায় বসাতে হবে, আর প্রথম চেষ্টাটা কেন ব্যর্থ হয়েছিল ────────
     * প্রথমে এটা `setUp()`-এ বসানো হয়েছিল, `parent::setUp()`-এর **আগে** —
     * যুক্তিটা সোজা মনে হয়েছিল: `RefreshDatabase` ওখানেই `migrate:fresh`
     * ডাকে, তাই তার আগে থামাতে হবে।
     *
     * ⛔ কিন্তু `parent::setUp()`-এর আগে **অ্যাপ্লিকেশনটাই তৈরি হয়নি**।
     * তাই `DB` facade-এর কোনো কন্টেইনার নেই, সে ব্যতিক্রম ছোঁড়ে, আর
     * নিচের `catch (Throwable)` সেটা গিলে নিয়ে চুপচাপ `return` করে।
     * ফল: **পাহারাটা প্রতিবার নিজের অন্ধত্বেই পাশ করত** — ঠিক সেই
     * আকারের ভুল যেটা এই একই দিনে চারবার ধরা পড়েছে (livewire-এর ছাড়,
     * ৪% অনুবাদ-দৃষ্টি, স্কোপযুক্ত গণনা, খালি `$planned` তালিকা)।
     *
     * ⓘ ধরা পড়েছে মেপে: ক্যাশ বসিয়ে একটা RefreshDatabase-হীন পরীক্ষা
     * চালিয়ে দেখা গেল `PDO=['abos'] CONFIG=['abos'] ENV=['abos_test']`,
     * অথচ পরীক্ষাটা **পাশ**। সংযোগ সত্যিই কাজের ডাটাবেজে, আর পাহারা নীরব।
     *
     * ⭐ তাই জায়গাটা `setUpTraits()` — Laravel-এর ক্রমে এটা চলে
     * `refreshApplication()`-এর **পরে** (অর্থাৎ `DB` কাজ করে) কিন্তু
     * ট্রেইটগুলোর নিজের setup-এর **আগে**, আর `RefreshDatabase` ঠিক
     * ওখানেই `migrate:fresh` ডাকে। দুইটা শর্তই একসাথে মেলে কেবল এখানে।
     */
    /*
     * ⛔ একসাথে একাধিক সেশন চললে প্রত্যেকের নিজের ডাটাবেজ লাগে।
     *
     * ── কী ঘটেছিল, ১৫ সেপ্টেম্বর ২০২৬ ────────────────────────────────
     * দুইটা সেশন একই `abos_test`-এ একসাথে পরীক্ষা চালিয়েছে, আর দুইজনের
     * `migrate:fresh` মাঝপথে একে অন্যের টেবিল ড্রপ করেছে। ⓘ ফল ছিল
     * বিভ্রান্তিকর ব্যর্থতা যার সাথে কোডের কোনো সম্পর্ক নেই:
     *
     *     Table 'abos_test.migrations' doesn't exist
     *     Table 'password_reset_tokens' already exists
     *
     * ⚠️ আর সময় নষ্ট হয়েছে ঐ বার্তাগুলোর কারণ খুঁজতে গিয়ে — কারণ
     * ওগুলো পড়ে মনে হয় মাইগ্রেশনে কিছু ভেঙেছে।
     *
     * ── ⭐ নিয়ম ────────────────────────────────────────────────────
     * প্রতিটা সেশন নিজের নামে একটা ডাটাবেজ নেবে:
     *
     *     mysql -u root -e "create database if not exists abos_test_1e
     *         character set utf8mb4 collate utf8mb4_unicode_ci;"
     *     DB_DATABASE=abos_test_1e php artisan test …
     *
     * ⓘ নিচের পাহারাটা `abos_test` **দিয়ে শুরু** হলেই ছাড়ে, তাই
     * `abos_test_1e`, `abos_test_4f` — সবই বৈধ।
     *
     * ── ⚠️ আর এই টীকাটা কেন এখানে ───────────────────────────────────
     * `abos_test_1d`, `abos_test_5b`, `abos_test_76` — এই ডাটাবেজগুলো
     * **আগে থেকেই ছিল**। অর্থাৎ নিয়মটা কেউ একজন জানত, কেবল কোথাও লেখা
     * ছিল না। ⛔ তাই পরের সেশন এসে আবার একই ফাঁদে পড়েছে।
     *
     * ⓘ একটা অলিখিত নিয়ম আর কোনো নিয়ম না থাকা — কার্যত এক জিনিস।
     */
    protected function setUpTraits(): array
    {
        $this->refuseToTouchRealData();

        return parent::setUpTraits();
    }

    /**
     * এই নামটা কি সবার ভাগের, নাকি এই সেশনের নিজের?
     *
     * ── ⛔ কেন নিয়মটা মন্তব্যে রেখে দেওয়া যথেষ্ট ছিল না ──────────────
     * উপরের টীকায় নিয়মটা **পরিষ্কার লেখা ছিল** — প্রত্যেকে নিজের নামে
     * ডাটাবেজ নেবে। ⓘ ২২ সেপ্টেম্বর ২০২৬-এ দুইটা সেশন একই রাতে
     * দুইজনেই ভুলেছে, আর **দুইজনেরই নিজের নোটে কথাটা লেখা ছিল**।
     *
     * ⚠️ অর্থাৎ দোষটা মনে রাখার নয়, যন্ত্রটার: ডিফল্টটা যদি ব্যক্তিগত
     * হত, ভোলার সুযোগই থাকত না। ⭐ আর একটা অলিখিত নিয়ম আর কোনো নিয়ম না
     * থাকা যেমন কার্যত এক, তেমনি **মন্তব্যে লেখা নিয়ম আর বলবৎ না করা
     * নিয়মও কার্যত এক**।
     *
     * ── ⓘ CI কেন ছাড় পায় ───────────────────────────────────────────
     * সেখানে `abos_test` একটা ক্ষণস্থায়ী কন্টেইনারে একা বসে
     * (`.github/workflows/ci.yml`), কেউ তার সাথে ভাগ করে না। ⚠️ ছাড়টা
     * না দিলে এই পাহারাটা প্রতিটা বিল্ড লাল করে দিত — অর্থাৎ পাহারা
     * হয়ে দাঁড়াত নিজেই একটা ভাঙা জিনিস।
     */
    private static function sharedByEverySession(string $database): bool
    {
        if ($database !== 'abos_test') {
            return false;
        }

        // ⓘ GitHub Actions দুইটাই বসায়; যেকোনো একটাই যথেষ্ট
        return (getenv('CI') ?: '') === '' && (getenv('GITHUB_ACTIONS') ?: '') === '';
    }

    private function refuseToTouchRealData(): void
    {
        /*
         * কনফিগ নয়, সংযোগ।
         *
         * `config('database.connections.….database')` পড়লে এই পাহারাটা
         * ঠিক সেই জিনিসটাই বিশ্বাস করত যেটা সেদিন মিথ্যা বলেছিল। PDO-কে
         * জিজ্ঞেস করলে উত্তরটা আসে **যেখানে কোয়েরি সত্যিই যাবে** সেখান
         * থেকে, আর তার মাঝে কোনো ক্যাশ নেই।
         */
        try {
            $database = (string) DB::connection()->getPdo()
                ->query('select database()')->fetchColumn();
        } catch (\Throwable) {
            /*
             * ডাটাবেজ নাগালে নেই — তখন থামানোর কিছু নেই, আর এখানে
             * ব্যতিক্রম ছুঁড়লে আসল ত্রুটিটা (সংযোগ ব্যর্থ) ঢাকা পড়ত।
             */
            return;
        }

        if ($database === '') {
            return;
        }

        if (self::sharedByEverySession($database)) {
            throw new RuntimeException(
                "⛔ পরীক্ষা থামানো হলো — সংযোগটা সবার ভাগের 'abos_test'-এ গেছে।\n\n"
                .'এই নামটা `phpunit.xml`-এ হার্ডকোড করা, তাই যে-ই `DB_DATABASE=` '
                ."বসাতে ভুলবে সে এখানেই এসে পড়ে — অর্থাৎ ডিফল্টটাই ফাঁদ।\n\n"
                .'দুইটা সেশন একসাথে এখানে চললে দুইজনের `migrate:fresh` একে অন্যের '
                ."টেবিল ড্রপ করে, আর ফল হয় এরকম বার্তা:\n\n"
                ."    Deadlock found when trying to get lock\n"
                ."    Table 'abos_test.companies' doesn't exist\n\n"
                .'⚠️ দুইটাই পড়তে **হুবহু নিজের কোডের রিগ্রেশনের মতো**, তাই সময়টা '
                ."নষ্ট হয় নিজের সারাই সন্দেহ করতে।\n\n"
                ."নিজের নামে একটা নিন (`d1`-এর জায়গায় আপনার সেশনের নাম):\n\n"
                .'    mysql -u root -e "create database if not exists abos_test_d1'
                ." character set utf8mb4 collate utf8mb4_unicode_ci;\"\n"
                ."    DB_DATABASE=abos_test_d1 php artisan test …\n\n"
                .'ⓘ CI-তে এই পাহারাটা চুপ থাকে — সেখানে `abos_test` নিজের '
                .'কন্টেইনারে একা থাকে, ভাগাভাগির প্রশ্নই নেই।'
            );
        }

        if (str_starts_with($database, 'abos_test')) {
            return;
        }

        throw new RuntimeException(
            "⛔ পরীক্ষা থামানো হলো — সংযোগটা '{$database}' ডাটাবেজে গেছে, "
            ."কোনো 'abos_test…' ডাটাবেজে নয়।\n\n"
            .'RefreshDatabase-এর প্রথম কাজ migrate:fresh, অর্থাৎ ওই ডাটাবেজের '
            .'প্রতিটা টেবিল ড্রপ। ১২ সেপ্টেম্বর ২০২৬-এ ঠিক সেটাই ঘটেছিল, আর '
            ."রানটা ১৯/১৯ পাস দিয়েছিল — সবুজ ফলটাই ছিল ক্ষতির চিহ্ন।\n\n"
            .'কারণ প্রায় নিশ্চিতভাবেই একটা কনফিগ ক্যাশ পড়ে আছে, যেটা '
            ."phpunit.xml আর DB_DATABASE= দুইটাকেই অকার্যকর করে দেয়:\n\n"
            ."    php artisan config:clear\n\n"
            .'⚠️ ফাইলটা মুছলে চালু প্রসেস থামে না — ওই রানটা বন্ধ করে আবার শুরু করুন।'
        );
    }
}

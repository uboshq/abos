<?php

declare(strict_types=1);

namespace Tests\Feature\Design;

use App\Core\Support\Ui;
use App\Models\User;
use Illuminate\Support\Facades\Blade;
use Tests\TestCase;

/**
 * ন'টা রূপ **যা আঁকে** সেটাও বদলায়নি — কেবল টোকেন নয়।
 *
 * ── কেন দ্বিতীয় একটা পাহারা লাগল ─────────────────────────────────────
 * [[\Tests\Feature\Architecture\TheOtherNineLooksWereNotTouchedTest]]
 * `Ui::all()`-এর ঘরগুলো হুবহু মেলায়। সেটা রঙের ভুল ধরে, আর সেটাই তার
 * কাজ।
 *
 * ⛔ **কিন্তু সে যা ধরতে পারে না:** ৪ সেপ্টেম্বর ২০২৬ থেকে ABOS-এর
 * নিজের রূপে (`navy`) নতুন গড়ন যোগ হচ্ছে — চিপ, ট্যাব, স্থির ফুটার,
 * কীবোর্ড। এগুলো টোকেনে হয় না, **শেয়ার্ড কম্পোনেন্টে** হয়:
 *
 *     x-ui.table     ১০২টা পর্দায়
 *     x-ui.toolbar    ৩৫টা পর্দায়
 *
 * ⚠️ ওই দুইটার ভিতরে একটা শর্ত ভুল লিখলে **ন'টা রূপের প্রতিটা তালিকা
 * বদলে যেত**, অথচ `Ui::all()` অক্ষত থাকত — অর্থাৎ পুরনো পাহারাটা সবুজ,
 * আর ক্ষতিটা নীরব।
 *
 * ── তাই এটা টোকেন দেখে না, **আউটপুট** দেখে ────────────────────────────
 * একই ডাক, দুইটা রূপে। ⓘ নমুনাটা NX5-এর: *"tiles + দৃশ্য আছে → ০
 * অক্ষর"* — রেন্ডার করে দেখানো, ঘোষণা পড়ে নয়।
 *
 * ── ⛔ কেন প্রতিটা চিহ্নের আগে "navy আঁকে কি" দেখা হয় ─────────────────
 * "ন'টায় নেই" একা মাপলে সেটা **শূন্যের সাথে শূন্য মিলিয়ে সবুজ** হত:
 * গড়নটা যদি কোথাওই না আঁকা হয় — কেউ গোটা কম্পোনেন্টটা ভেঙে ফেললেও —
 * পাহারাটা তবু পাস করত।
 *
 * ⭐ তাই প্রতিটা চিহ্নের জন্য আগে দেখা হয় **navy সত্যিই আঁকে কি না**
 * (অর্থাৎ দাবিটা পরীক্ষার যোগ্য অবস্থায় আছে), আর তবেই দাবি করা হয়
 * বাকি ন'টা আঁকে না। ⓘ ঠিক এই ফাঁদেই আজ আরেকটা গার্ড পড়েছিল — চারটা
 * `null`-এর সাথে চারটা `null` মিলিয়ে সবুজ।
 *
 * ── কেন হুবহু স্ট্রিং নয় ──────────────────────────────────────────────
 * ⚠️ আউটপুট হুবহু ধরে রাখলে পাহারাটা প্রতিদিন লাল হত: একটা ক্লাসের নাম,
 * একটা ফাঁক, একটা অনুবাদ বদলালেই। তখন মানুষ ওটাকে মুছে ফেলে — আর সেটাই
 * সবচেয়ে খারাপ ফল। তাই মাপা হয় নতুন গড়নগুলোর **চিহ্ন**, চেহারা নয়।
 */
final class TheOtherNineLooksStillDrawTheSameTest extends TestCase
{
    /**
     * নতুন গড়নগুলোর চিহ্ন।
     *
     * ⓘ চিহ্নগুলো **ক্লাসের নাম নয়, ঘোষণার চাবি** — ক্লাস বদলায়, চাবি
     * বদলায় না। যে কম্পোনেন্ট গড়নটা আঁকে সে-ই চিহ্নটা বসাবে, আর
     * `Ui::` কে জিজ্ঞেস করেই বসাবে।
     */
    private const MARKS = [
        'data-look-chip' => 'filters=chips',
        'data-look-tabs' => 'tabs=strip',
        'data-look-listfoot' => 'listfoot=totals',
        'data-look-hints' => 'hints=keys',
    ];

    /**
     * যে গড়নটা ABOS-এ জেগেছে, সেটা বাকি ন'টায় ঢোকেনি।
     *
     * ── ⛔ কেন চিহ্ন ধরে ধরে, "সব একসাথে" নয় ─────────────────────────
     * প্রথমে লেখা ছিল: চারটা চিহ্নই navy-তে আঁকা হতে হবে, নাহলে লাল।
     * ⚠️ কিন্তু কাজটা **ইচ্ছাকৃতভাবে ধাপে ধাপে**, আর প্রতিটা ধাপ আলাদা
     * সেশনের হাতে — চিপ একজনের, ট্যাব আরেকজনের, ফুটার ও কীবোর্ড
     * তৃতীয়জনের। ⛔ "সব বা কিছুই না" ধরলে পাহারাটা **অগ্রগতিকেই ভাঙন
     * বলত**, আর তিনজনের কাজ আটকে থাকত চতুর্থজনের জন্য।
     *
     * ⭐ আসল ঝুঁকিটা "তিনজনের একজন বাকি" নয় — আসল ঝুঁকি **"navy-তে
     * বসেছে, অথচ ন'টাতেও ঢুকে গেছে"**। সেটা চিহ্ন ধরে ধরেও ঠিক
     * ততটাই ধরা পড়ে, আর সাথে সাথে ধরা পড়ে: চিপ বসার দিনেই চিপের
     * পাহারা চালু।
     *
     * ── ⚠️ আর ঘুমন্ত চিহ্ন চুপচাপ সবুজ হয় না ─────────────────────────
     * যেটা এখনো কেউ আঁকে না, তার জন্য দাবি করার কিছু নেই — শূন্যের
     * সাথে শূন্য মিলিয়ে পাস করাটা মিথ্যা সবুজ। ⓘ তাই ওগুলো **নাম ধরে**
     * বলা হয়, আর একটাও জেগে না থাকলে গোটা পাহারা স্কিপ করে।
     */
    public function test_a_shape_that_woke_up_did_not_leak_to_the_other_nine(): void
    {
        $mine = $this->listAs(Ui::DEFAULT);

        $asleep = [];
        $awake = 0;

        foreach (self::MARKS as $mark => $why) {
            /*
             * ⓘ navy-তে নেই মানে গড়নটা এখনো বসানো হয়নি — ঘোষণা আছে
             * (`Ui::` জানে), আঁকা নেই। ওই চিহ্নের জন্য এখানে দাবি
             * করার মতো কিছু নেই।
             */
            if (! str_contains($mine, $mark)) {
                $asleep[] = $mark.' ('.$why.')';

                continue;
            }

            $awake++;

            foreach (Ui::keys() as $look) {
                if ($look === Ui::DEFAULT) {
                    continue;
                }

                $this->assertStringNotContainsString(
                    $mark,
                    $this->listAs($look),
                    "রূপ `{$look}`-এ `{$mark}` আঁকা হয়েছে ({$why})। "
                    .'মালিকের নির্দেশ: শুধু ABOS-এর রূপটাই বদলাবে, বাকি ন\'টা '
                    .'অপরিবর্তিত। গড়নটা সত্যিই ওই রূপেও চাইলে Ui::all()-এ তার '
                    .'ঘরটা বসাতে হবে — কম্পোনেন্টে শর্ত আলগা করে নয়।',
                );
            }
        }

        if ($awake === 0) {
            $this->markTestSkipped(
                'ABOS-এর নতুন গড়নগুলোর একটাও এখনো আঁকা হয় না, তাই মাপার মতো '
                .'কিছু নেই: '.implode(' · ', $asleep).'। '
                .'প্রথম চিহ্নটা বসলেই এই পাহারা নিজে থেকে জেগে উঠবে।',
            );
        }
    }

    /**
     * এই রূপে বসা একজনের চোখে একটা তালিকা।
     *
     * ⚠️ রূপটা ব্যবহারকারীর ঘরে বসে (`users.ui`), আর কম্পোনেন্টগুলো
     * `auth()->user()` ধরেই জিজ্ঞেস করে — ছদ্মবেশ ছাড়া রেন্ডার করলে
     * সবসময় ডিফল্ট রূপটাই আঁকা হত, আর পাহারাটা কিছুই মাপত না।
     *
     * ⓘ ঘরটা হাতে বসানো হয়, `new User([...])` দিয়ে নয়: `User`-এ
     * `$fillable` নেই, আর পরীক্ষায় নীরবে-ফেলে-দেওয়া বন্ধ
     * ([[AppServiceProvider]]) — তাই গণ-বরাদ্দ ব্যতিক্রম ছুড়ত।
     */
    private function listAs(string $look): string
    {
        $user = new User;
        $user->ui = $look;

        $this->actingAs($user);

        /*
         * ⚠️ টুলবারে **ছাঁকনির স্লট** দিতেই হবে।
         *
         * ⛔ প্রথমে স্লট ছাড়া ডাকা হয়েছিল, আর তখন `$hasFilters` মিথ্যা
         * হত (`toolbar.blade.php:102`) — গোটা ছাঁকনির অংশটাই আঁকা হত
         * না। ফলে চিপের চিহ্নটা **navy-তেও** আসত না, আর পাহারাটা
         * চিরকাল "ঘুমন্ত" বলে স্কিপ করত: সবুজ, জীবিত, অন্ধ।
         *
         * ⓘ ধরা পড়েছে ইচ্ছে করে ফাঁস তৈরি করে — শর্তটা তুলে দিয়েও
         * পাহারা লাল হয়নি, আর সেটাই বলে দিয়েছে হারনেসটাই ভুল।
         */
        return Blade::render(
            '<x-ui.toolbar :columns="$columns">'
            .'<label><input type="checkbox" name="due"> Due</label>'
            .'</x-ui.toolbar>'
            .'<x-ui.table :rows="$rows" :columns="$columns" />',
            [
                'rows' => [(object) ['name' => 'SENTINEL']],
                'columns' => [['key' => 'name', 'label' => 'Name']],
            ],
        );
    }
}

<?php

declare(strict_types=1);

namespace Tests\Feature\Design;

use Illuminate\Support\Facades\File;
use Tests\TestCase;

/**
 * অর্ধেক মনিটর ফাঁকা পড়ে থাকত।
 *
 * ── ⭐ মালিকের নির্দেশ, ২৩ সেপ্টেম্বর ২০২৬ ────────────────────────────
 * *"সব কটি পর্দা স্ক্রল করে দেখতে হয়, but এগুলো পাশাপাশি রাখার পর্যাপ্ত
 * জায়গা আছে, তাই সুন্দর করে গুছিয়ে enterprise grade এর মতো করে রাখো"*,
 * আর তারপর: *"এখন তো FHD-র নিচে মনিটর খুব বেশি used হয় না"*।
 *
 * ⓘ অর্থাৎ ১৯২০ পিক্সেল **ভিত্তি**, ব্যতিক্রম নয়। ⚠️ সাইডবার ও প্যাডিং
 * বাদ দিলে কাজের জায়গা প্রায় ১৬০০ — আর `max-w-3xl` মানে ৭৬৮, ঠিক
 * অর্ধেকেরও কম।
 *
 * ── ⛔ এই পাহারাটা কী মাপে, আর কী মাপে না ────────────────────────────
 * ⓘ সব সরু বাঁধন খারাপ নয়। একটা লেখার অনুচ্ছেদে লাইন লম্বা হলে চোখ
 * পরের লাইনের শুরু খুঁজে পায় না — সেজন্যই `--spacing-prose-max` আছে,
 * আর সেটা এই পাহারা ছোঁয় না।
 *
 * ⚠️ যেটা মাপা হয়, সেটা হলো **পুরো পাতাটা** একটা সরু বাক্সে বাঁধা কি
 * না — অর্থাৎ ফর্ম বা পাতার মোড়কে বসানো `max-w-3xl` জাতীয় ক্লাস।
 * ⛔ ঐ একটা ক্লাস গোটা পর্দার ডান অর্ধেক কেড়ে নেয়, আর ভিতরের কোনো
 * গ্রিড তখন আর ছড়াতে পারে না — দুই কলাম চাইলেও দুইটাই সরু হয়।
 *
 * ── ⓘ ছাড় দেওয়া আছে, আর প্রতিটার কারণ লেখা ──────────────────────────
 * নিচের তালিকাটা ছোট রাখাই উদ্দেশ্য। ⚠️ নতুন নাম যোগ করার আগে ভাবুন:
 * পাতাটা কি সত্যিই সরু হওয়ার কথা, নাকি কেবল এখনো গোছানো হয়নি?
 */
final class HalfTheMonitorWentUnusedTest extends TestCase
{
    /**
     * পাতাটাকে সরু করে বাঁধে এমন ক্লাসগুলো।
     *
     * ⓘ `max-w-2xl` আর তার নিচেরগুলো বাদ — ওগুলো সাধারণত একটা ছোট
     * বাক্স বা বার্তার, গোটা পাতার নয়।
     */
    private const NARROW = ['max-w-3xl', 'max-w-4xl', 'max-w-5xl'];

    /**
     * যে পাতাগুলো সরুই থাকবে, কারণসহ।
     *
     * @var array<string, string>
     */
    private const ALLOWED = [
        /*
         * গ্রাহকের নিজের পোর্টাল — বাইরের মানুষ, আর প্রায় সবসময় ফোনে।
         *
         * ⓘ এখানে চওড়া করার কিছু নেই: পাতাটায় একটা বিল আর কয়েকটা সারি,
         * আর পাঠক আমাদের কর্মী নন। ⚠️ ডেস্কটপে ছড়িয়ে দিলে ওটা ERP-র
         * মতো দেখাত, অথচ এটা গ্রাহকের কাছে যাওয়া পাতা।
         */
        'Sales/Resources/views/components/portal/layout.blade.php' => 'গ্রাহকের পোর্টাল, ফোনই প্রধান',
    ];

    /*
     * ⛔ প্রথম খসড়ায় সেটআপ উইজার্ডও এই তালিকায় ছিল — **অনুমানে**।
     *
     * ⚠️ নিচের দ্বিতীয় দাবিটা সেটাই ধরেছে: ঐ পাতা `max-w-2xl` ব্যবহার
     * করে, যা এই পাহারার তালিকাতেই নেই। ⓘ অর্থাৎ ছাড়টা এমন কিছুকে
     * ছাড় দিচ্ছিল যা কখনো ধরাই পড়ত না — একটা মৃত সারি, যা পড়ে পরের
     * জন ভাবতেন ঐ পাতাটা ইচ্ছা করে সরু।
     */

    /**
     * ⛔ কোনো পাতা অর্ধেক মনিটরে বাঁধা থাকতে পারে না।
     */
    public function test_no_screen_is_capped_to_half_the_monitor(): void
    {
        $capped = [];

        foreach (File::allFiles(base_path('app/Modules')) as $file) {
            if (! str_ends_with($file->getFilename(), '.blade.php')) {
                continue;
            }

            $relative = str_replace('\\', '/', substr($file->getPathname(), strlen(base_path('app/Modules')) + 1));

            if (isset(self::ALLOWED[$relative])) {
                continue;
            }

            $body = File::get($file->getPathname());

            foreach (self::NARROW as $class) {
                /*
                 * ⚠️ মন্তব্যের ভিতরের উল্লেখ গোনা হয় না।
                 *
                 * ⓘ এই প্রকল্পের ব্লেডে কারণ লেখা থাকে, আর সেখানে প্রায়ই
                 * *"আগে এখানে `max-w-3xl` ছিল"* জাতীয় বাক্য থাকে। ⛔ ওটা
                 * গুনলে সারানো ফাইলগুলোই চিরকাল লাল থাকত, আর পাহারাটা
                 * ঠিক উল্টো জিনিস শেখাত: কারণ **মুছে ফেলো**।
                 */
                if (preg_match('/class="[^"]*\b'.preg_quote($class, '/').'\b/', $body) === 1) {
                    $capped[] = $relative.' — '.$class;

                    break;
                }
            }
        }

        sort($capped);

        $this->assertSame([], $capped, implode("\n", array_merge(
            ['⛔ এই পর্দাগুলো অর্ধেক মনিটরে বাঁধা:', ''],
            $capped,
            [
                '',
                '⚠️ FHD-তে সাইডবার ও প্যাডিং বাদে প্রায় ১৬০০ পিক্সেল থাকে,',
                'আর `max-w-3xl` মানে ৭৬৮ — ডান পাশ সারাক্ষণ ফাঁকা।',
                '',
                'ⓘ বাঁধনটা তুলে দিন, আর ঘরগুলো পাশাপাশি বসান (`lg:grid-cols-2`)।',
                '⭐ স্ক্রল তাতেই কমে — ঘর লম্বা করে নয়, পাশাপাশি বসিয়ে।',
                '',
                '⚠️ সত্যিই সরু থাকার কথা হলে ALLOWED-এ কারণসহ লিখুন।',
            ],
        )));
    }

    /**
     * পাহারাটা সত্যিই তাকায়।
     *
     * ── ⚠️ কেন এই দাবিটা ছাড়া উপরেরটা কিছুই প্রমাণ করে না ────────────
     * ⓘ regex-টা যদি কোনো কারণে কিছুর সাথেই না মিলত — একটা ভুল ফোল্ডার,
     * একটা ভুল উদ্ধৃতি-চিহ্ন — তবে তালিকাটা **সবসময় খালি** থাকত, আর
     * উপরের দাবিটা চিরকাল সবুজ। ⛔ আর ঐ সবুজটা দেখতে হুবহু সারানো
     * পর্দার মতোই।
     *
     * ⭐ তাই ছাড় দেওয়া পাতাটার দিকে সরাসরি তাকানো: ওখানে ক্লাসটা
     * **আছে**, আর regex সেটা খুঁজে পায়।
     */
    public function test_the_guard_can_actually_find_one(): void
    {
        $exempt = base_path('app/Modules/'.array_key_first(self::ALLOWED));

        $this->assertFileExists($exempt, 'ⓘ ছাড়ের তালিকার পাতাটাই নেই — তালিকাটা বাসি।');

        $found = false;

        foreach (self::NARROW as $class) {
            if (preg_match('/class="[^"]*\b'.preg_quote($class, '/').'\b/', File::get($exempt)) === 1) {
                $found = true;

                break;
            }
        }

        $this->assertTrue($found, implode("\n", [
            '⛔ ছাড় দেওয়া পাতাতেও regex কিছু পেল না।',
            '',
            '⚠️ অর্থাৎ পাহারাটা কিছুই মাপছে না, আর উপরের দাবিটা',
            'খালি জালে সবুজ হয়ে আছে।',
        ]));
    }
}

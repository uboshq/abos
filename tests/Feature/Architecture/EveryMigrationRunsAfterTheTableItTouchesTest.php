<?php

declare(strict_types=1);

namespace Tests\Feature\Architecture;

use Tests\TestCase;

/**
 * যে টেবিল ছোঁয়া হচ্ছে, সে আগে তৈরি হয়েছে তো?
 *
 * ── ⛔ কেন এই পাহারাটা লাগল, ১৩ সেপ্টেম্বর ২০২৬ ───────────────────────
 * `Person` তালিকার কাজে একটা মাইগ্রেশন লেখা হলো, তারিখ দেওয়া হলো **আজকের
 * দিন** — `2026_09_13`। যুক্তিসঙ্গত, আর সম্পূর্ণ ভুল।
 *
 * এই রিপোর মাইগ্রেশনের তারিখ বাস্তব দিনের চেয়ে **অনেক এগিয়ে**: আজ ১৩
 * সেপ্টেম্বর, অথচ শেষ মাইগ্রেশনের নাম `2026_11_07`। তাই আজকের তারিখ দেওয়া
 * ফাইলটা চলে **রিপোর অর্ধেক টেবিল জন্মানোর আগে**।
 *
 * ⚠️ আর সে চুপচাপ কিছুই করে না। ফাইলটায় `Schema::hasTable()` পাহারা ছিল,
 * তাই প্রতিটা সারি `continue` করে বেরিয়ে গেল — `migrate` সবুজ, আউটপুটে
 * "DONE", `migrations` টেবিলে সারি বসা, **আর একটাও কলাম যোগ হয়নি**।
 * দ্বিতীয়বার চালালেও কিছু হত না, কারণ Laravel ওটা "চলে গেছে" ধরে নেয়।
 *
 * ⓘ ধরা পড়েছে কেবল `information_schema`-এ গিয়ে কলাম গুনে দেখায় —
 * "চলেছে" আর "কাজ করেছে" এক প্রশ্ন নয়।
 *
 * ── কেন মন্তব্য যথেষ্ট নয় ────────────────────────────────────────────
 * ওই ফাইলের মন্তব্যে ঘটনাটা লেখা আছে। কিন্তু ফাঁদটা **ওই ফাইলের নয়** —
 * যে কেউ কাল একটা নতুন মাইগ্রেশন লিখে আজকের তারিখ দিলে একই জিনিস ঘটবে,
 * আর সে ওই মন্তব্যটা কোনোদিন পড়বে না। একটা পাহারা পড়ার উপর ভরসা করে না।
 *
 * ── মাইগ্রেশনের আসল ক্রম — মেপে দেখা ─────────────────────────────────
 * ⭐ পথগুলো আলাদা নয়, **নাম ধরে মিশে চলে**। প্রমাণ: একই রানে
 * `2026_09_09_110000` (মডিউলের ফাইল) চলেছে `2026_09_10_100000`
 * (`database/migrations`-এর ফাইল) এর ঠিক আগে। তাই তুলনাটা পথ নির্বিশেষে
 * ফাইলের নামের ক্রমেই হয়।
 */
class EveryMigrationRunsAfterTheTableItTouchesTest extends TestCase
{
    /**
     * প্রতিটা `Schema::table()`-এর টেবিল আগে (বা একই ফাইলে) তৈরি হয়েছে।
     */
    public function test_no_migration_touches_a_table_that_does_not_exist_yet(): void
    {
        $files = $this->migrationsInRunOrder();

        $created = [];
        $tooEarly = [];
        $touches = 0;

        foreach ($files as $name => $path) {
            $code = $this->codeOf($path);

            /*
             * একই ফাইলে তৈরি হওয়া টেবিলগুলো **আগে** জমা করা।
             *
             * একটা মাইগ্রেশন প্রায়ই একটা টেবিল বানিয়ে তারপরই সেটাকে
             * ছোঁয় (সূচক, বিদেশি চাবি)। ক্রমটা উল্টো ধরলে প্রতিটা এমন
             * ফাইল মিথ্যা অভিযোগে ধরা পড়ত।
             */
            foreach ($this->tablesIn($code, 'create') as $table) {
                $created[$table] = $name;
            }

            /*
             * ── কনফিগ থেকে নাম নেওয়া টেবিলগুলো ───────────────────────
             *
             * Spatie-র অনুমতির মাইগ্রেশন টেবিলের নাম **কনফিগ থেকে** নেয়
             * (`Schema::create($tableNames['roles'])`), তাই উপরের regex
             * ওগুলো দেখতে পায় না — আর তখন পরে `roles` ছোঁয়া প্রতিটা
             * মাইগ্রেশন মিথ্যা অভিযোগে ধরা পড়ত।
             *
             * ⭐ নামগুলো হাতে লেখা হয়নি, **একই কনফিগ থেকেই পড়া হয়** —
             * অর্থাৎ কেউ `permission.php`-তে নাম বদলালে এই পাহারাও সাথে
             * বদলায়। হাতে লিখলে ওটা একদিন বেমিল হত, আর তখন পাহারাটা
             * ভুল টেবিলের নামে নীরবে অন্ধ থাকত।
             *
             * ⓘ ক্রমটা অটুট: নামগুলো `$created`-এ বসে ঠিক **এই ফাইলটার
             * পালা এলে**, আগে নয়। তাই এর আগের কোনো মাইগ্রেশন `roles`
             * ছুঁলে সেটা তখনো ধরা পড়বে।
             */
            if (str_contains($code, "config('permission.table_names')")) {
                foreach ((array) config('permission.table_names') as $table) {
                    if (is_string($table) && $table !== '') {
                        $created[$table] = $name;
                    }
                }
            }

            foreach ($this->tablesIn($code, 'table') as $table) {
                $touches++;

                if (! array_key_exists($table, $created)) {
                    $tooEarly[] = "{$name}\n        → `{$table}` তখনো তৈরি হয়নি";
                }
            }
        }

        sort($tooEarly);

        $this->assertSame([], $tooEarly, implode("\n", [
            'এই মাইগ্রেশনগুলো এমন টেবিল ছোঁয় যা তখনো তৈরি হয়নি।',
            '',
            '⚠️ এর ফল নীরব: `Schema::hasTable()` পাহারা থাকলে মাইগ্রেশনটা চুপচাপ',
            'কিছুই করে না — "DONE" লেখা ওঠে, `migrations`-এ সারি বসে, আর কলামটা',
            'কোনোদিন যোগ হয় না। পাহারা না থাকলে deploy মাঝপথে ভাঙে।',
            '',
            '⭐ প্রায় সবসময় কারণ একটাই: ফাইলের নামে **আজকের তারিখ** দেওয়া হয়েছে,',
            'অথচ এই রিপোর মাইগ্রেশনের তারিখ বাস্তব দিনের চেয়ে এগিয়ে। নতুন',
            'মাইগ্রেশনের নাম সবার শেষে পড়তে হবে — শেষ ফাইলটা দেখে তার পরের',
            'একটা তারিখ দিন।',
            '',
            ...$tooEarly,
        ]));

        /*
         * ⚠️ আর এখানেই এই ফাইলের নিজের পাহারা — আর এটা না থাকলে উপরের
         * দাবিটা আজকের সেই রোগেই পড়ত।
         *
         * উপরের দাবিটা "খারাপ কিছু পাওয়া গেল না" দেখে পাশ করে। কোনো
         * কারণে ফাইলগুলো খুঁজে না পাওয়া গেলে, বা regex-টা কিছুই না
         * ধরলে, তালিকাটা খালি আসত আর দাবিটা **সবুজ হত — কিছুই না দেখে**।
         *
         * সংখ্যাগুলো আলগা করে ধরা: প্রশ্নটা "কতগুলো আছে" নয়, "আদৌ কিছু
         * দেখা হয়েছে কি না"। শক্ত সংখ্যা ধরলে প্রতিটা নতুন মাইগ্রেশনে
         * এই টেস্ট ভাঙত, আর অগ্রগতিতে ভাঙা পাহারা কেউ রাখে না।
         */
        $this->assertGreaterThan(100, count($files),
            'মাইগ্রেশন ফাইলই খুঁজে পাওয়া যায়নি — উপরের দাবিটা তখন কিছুই দেখছে না।');

        $this->assertGreaterThan(20, $touches,
            'একটাও `Schema::table()` ধরা পড়েনি — regex ভেঙেছে, আর উপরের দাবিটা '
            .'তখন শূন্যের উপর সবুজ।');

        $this->assertGreaterThan(50, count($created),
            'একটাও `Schema::create()` ধরা পড়েনি — তুলনার ভিত্তিটাই নেই।');
    }

    /**
     * সব মাইগ্রেশন, যে ক্রমে Laravel ওদের চালায়।
     *
     * ⭐ পথ নির্বিশেষে **ফাইলের নাম ধরে** — কারণ Laravel প্রতিটা নিবন্ধিত
     * পথের ফাইল একসাথে করে নাম ধরে সাজায়। মডিউলের ফাইল আর
     * `database/migrations`-এর ফাইল তাই মিশে চলে, আর ঠিক সেটাই ফাঁদটার
     * মূল: মডিউলে আজকের তারিখ দেওয়া একটা ফাইল অনায়াসে শেয়ার করা পথের
     * অক্টোবরের ফাইলের **আগে** পড়ে যায়।
     *
     * @return array<string, string> নাম => পুরো পথ
     */
    private function migrationsInRunOrder(): array
    {
        $found = [];

        foreach ($this->paths() as $dir) {
            foreach (glob($dir.'/*.php') ?: [] as $path) {
                $found[basename($path, '.php')] = $path;
            }
        }

        ksort($found);

        return $found;
    }

    /** @return list<string> */
    private function paths(): array
    {
        $paths = [database_path('migrations')];

        foreach (glob(app_path('Modules/*/Database/Migrations')) ?: [] as $dir) {
            $paths[] = $dir;
        }

        return $paths;
    }

    /**
     * ফাইলের কোড, **মন্তব্য ছাড়া**।
     *
     * ⚠️ মন্তব্য না ছাঁটলে এই পাহারাটা নিজেই অন্ধ হত, আর সেটা আজকের
     * সবচেয়ে দামি শিক্ষা: মাইগ্রেশনের মন্তব্যে প্রায়ই উদাহরণ হিসেবে
     * `Schema::table('…')` লেখা থাকে ("আগে এখানে যা ছিল")। ওগুলো ধরলে
     * টেস্টটা এমন সব টেবিলের নালিশ করত যা কোনো কোড কোনোদিন ছোঁয়নি।
     */
    private function codeOf(string $path): string
    {
        $code = (string) file_get_contents($path);

        return (string) preg_replace(['#/\*.*?\*/#s', '#//[^\n]*#'], '', $code);
    }

    /**
     * `Schema::create('x')` বা `Schema::table('x')`-এর টেবিলের নাম।
     *
     * ⓘ কেবল **আক্ষরিক** নাম। চলক দিয়ে বানানো নাম (`Schema::table($name)`)
     * এখানে ধরা পড়ে না, আর সেটা স্বীকার করাই ভালো: একটা স্থির পরীক্ষা
     * গতিশীল নাম জানতে পারে না। ⭐ আর ঠিক সেজন্যই `Person`-এর মাইগ্রেশনে
     * পাঁচটা `Schema::table()` হাতে লেখা, লুপে নয় — নাহলে larastan-ও এই
     * পাহারাও দুইটাই অন্ধ থাকত।
     *
     * @return list<string>
     */
    private function tablesIn(string $code, string $method): array
    {
        preg_match_all(
            '/Schema::'.$method."\(\s*'([^']+)'/",
            $code,
            $found,
        );

        return array_values(array_unique($found[1]));
    }
}

<?php

declare(strict_types=1);

namespace Tests\Feature\Architecture;

use Tests\TestCase;

/**
 * চার্টের লেবেল-সারি সংকুচিত হতে পারত না, আর গোটা পাতা পাশে সরে যেত।
 *
 * ── ⛔ কী ভাঙা ছিল, ২৯ সেপ্টেম্বর ২০২৬ ────────────────────────────────
 * ফোনের মাপে (৩৬০×৭৪০) `/sales/overview` পাতাটা আড়াআড়ি স্ক্রল করত।
 * ⓘ দায় নিশ্চিত হয়েছে অঙ্কে: নথির পাশে-স্ক্রল ছিল ৬৫px, আর দৈনিক
 * চার্টের শেষ পাঁচটা লেবেল ঠিক ৯·২৩·৩৬·৫১·**৬৫**px পর্দার বাইরে।
 *
 * ── ⚠️ কারণটা CSS-এর একটা ডিফল্ট, আর সেটা সহজে চোখে পড়ে না ───────────
 * ⛔ flex আইটেমের `min-width` ডিফল্টে `auto` — অর্থাৎ সে **নিজের লেখার
 * চেয়ে ছোট হতে পারে না**, `flex-1` লেখা থাকলেও। ⓘ ত্রিশটা তারিখের ঘর
 * (~১০px + ৪px ফাঁক) চায় ~৪২০px, আর সারিটার আছে ৩৩৬px।
 *
 * ⭐ ঠিক উপরের বারের সারিটা এই সমস্যায় পড়ে না, আর তুলনাটাই কারণটা
 * দেখিয়ে দেয়: তার ঘরগুলোর ভিতরে একটা `w-full` ডিভ, যার min-content
 * শূন্য — তাই সে যত খুশি সংকুচিত হয়।
 *
 * ── ⓘ দাবিটা এক পাতার নয়, ছাঁচটার ────────────────────────────────────
 * ⚠️ আজ কেবল বিক্রয়ের দৈনিক চার্টে ত্রিশটা লেবেল, তাই কেবল ওখানে উপচে
 * পড়ে। ⓘ বাকি সারিগুলোয় বারোটা করে, তাই আজ ধরে — কিন্তু ডাটা বাড়লে
 * একই বাগ, আর তখন কেউ এটাকে নতুন বাগ ভেবে আবার খুঁজত।
 *
 * ⛔ তাই নিয়মটা: এই ছাঁচের প্রতিটা ঘরকে সংকুচিত হতে দিতে হবে
 * (`min-w-0`), আর উপচে পড়া লেখাটা কাটতে হবে (`truncate`)।
 *
 * ── ⚠️ এই ফাইলটা যা প্রমাণ করে না ────────────────────────────────────
 * PHPUnit কোনো CSS চালায় না, তাই এখান থেকে `scrollWidth` জানা যায় না।
 * ⓘ আসল মাপটা নেওয়া হয় আসল ব্রাউজারে (`E:\ABOS\e2e\abos_walk.py`), যেটা
 * প্রতিটা পাতার নথি-স্ক্রল মাপে। ⭐ এই ফাইলটা পাহারা দেয় **কারণটা**,
 * আর হাঁটার স্ক্রিপ্টটা দেখায় **ফলটা**।
 */
final class AChartLabelRowCouldNotShrinkTest extends TestCase
{
    /**
     * ⓘ যে ছাঁচটা খোঁজা হয়: সমান ভাগে বসা ছোট লেখার ঘর।
     *
     * ⚠️ `flex-1` একা ধরলে রিপোর শত শত নিরীহ জায়গা উঠে আসত আর পাহারাটা
     * চিৎকার করে অকেজো হয়ে যেত। ⓘ তিনটা শ্রেণি একসাথে থাকা মানে প্রায়
     * নিশ্চিতভাবে একটা চার্টের অক্ষ-সারি।
     */
    private const SHAPE = ['flex-1', 'text-center', 'text-2xs'];

    public function test_every_chart_label_cell_is_allowed_to_shrink(): void
    {
        $looked = 0;
        $complaints = [];

        foreach ($this->blades() as $path) {
            foreach (file($path) as $n => $line) {
                foreach (self::SHAPE as $needed) {
                    if (! str_contains($line, $needed)) {
                        continue 2;
                    }
                }

                $looked++;

                $missing = array_values(array_filter(
                    ['min-w-0', 'truncate'],
                    fn (string $c) => ! str_contains($line, $c),
                ));

                if ($missing !== []) {
                    $complaints[] = sprintf('%s:%d — %s নেই',
                        $this->shortly($path), $n + 1, implode(' ও ', $missing));
                }
            }
        }

        /*
         * ⛔ কয়টা সারি সত্যিই দেখা হলো, আগে সেটা প্রমাণ করা হয়। ⚠️ নাহলে
         * শ্রেণির নাম বদলে গেলে পাহারাটা **শূন্য** সারি দেখে সবুজ থাকত —
         * আর এই প্রকল্পে ঠিক ঐ ধরনের "কিছুই না দেখা" পাহারা আগে ধরা
         * পড়েছে।
         */
        $this->assertGreaterThanOrEqual(3, $looked,
            'মাত্র '.$looked.'টা লেবেল-সারি চোখে পড়ল — ছাঁচটার নাম বদলে গেছে কি না দেখুন।');

        $this->assertSame([], $complaints,
            "চার্টের লেবেল-ঘর সংকুচিত হতে পারে না, তাই সারিটা পাতাকে পাশে সরিয়ে দেবে:\n  "
            .implode("\n  ", $complaints));
    }

    /**
     * কমিট করা ব্লেডগুলো — ডিস্কে যা আছে তার সবটা নয়।
     *
     * ⛔ কারণটা রুচির নয়: এই গাছে একসাথে পাঁচ-ছয়টা সেশন কাজ করে, আর
     * কারও অর্ধেক লেখা খসড়া ডিস্কে পড়ে থাকে। ⚠️ ওগুলো বিচার করলে
     * পাহারাটা **অন্যের অসমাপ্ত কাজের** জন্য সবার রান লাল করত, আর
     * লালটা এমন ফাইলে দেখাত যেটা রিপোতে নেই-ই।
     *
     * ⓘ একই নিয়ম এই ডিরেক্টরির অন্য পাহারাগুলোও মানে
     * ([[EveryViewTheCodeIncludesIsActuallyCommittedTest]])। ⭐ ফাইলটা
     * কমিট হলেই সে নিজে থেকে এই পাহারার আওতায় আসে।
     *
     * @return list<string>
     */
    private function blades(): array
    {
        $lines = [];

        exec('git -C '.escapeshellarg(base_path())
            .' ls-tree -r --name-only HEAD app resources 2>&1', $lines, $code);

        if ($code !== 0) {
            /*
             * ⛔ এড়িয়ে যাওয়া নয়, খালি হাতে ফেরা — আর তফাতটা আসল।
             *
             * ⓘ খালি তালিকা ফিরলে নিচের "কয়টা সারি দেখলাম" দাবিটা নিজেই
             * সরব হয়ে লাল হয়। ⚠️ `markTestSkipped` দিলে পাহারাটা চুপচাপ
             * সরে দাঁড়াত, আর গিট ভাঙা থাকলে কেউ কোনোদিন জানত না।
             *
             * ⓘ আর এড়ানো দাবির সংখ্যা এই রিপোতে ছাদ ধরে মাপা হয়
             * ([[TheNumberOfSkippedClaimsOnlyGoesDown]]) — একটা নতুন
             * skip যোগ করা মানে অন্য কারও জায়গা খেয়ে ফেলা।
             */
            return [];
        }

        $out = [];

        foreach ($lines as $line) {
            if (! str_ends_with($line, '.blade.php')) {
                continue;
            }

            $path = base_path($line);

            if (is_file($path)) {
                $out[] = $path;
            }
        }

        return $out;
    }

    private function shortly(string $path): string
    {
        return str_replace(base_path().DIRECTORY_SEPARATOR, '', $path);
    }
}

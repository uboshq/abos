<?php

declare(strict_types=1);

namespace Tests\Feature\Architecture;

use App\Core\Module\ModuleDefinition;
use App\Core\Module\ModuleRegistry;
use Tests\TestCase;

/**
 * মেঝের লোককে কোনোদিন গোটা কোম্পানির টাকার অঙ্ক দেওয়া হয়নি।
 *
 * ── ⓘ কীভাবে প্রশ্নটা উঠল, ২২ সেপ্টেম্বর ২০২৬ ───────────────────────
 * abos-f9 মজুদের মূল্যের হিসাবে কাজ করতে গিয়ে দেখলেন `inv_cost_layers`
 * সারণিতে **গুদামের ঘরই নেই** — কেবল `company_id`। ⓘ তাই ওটা গুদামের
 * দেয়ালের প্রার্থীই নয়, আর সেটা ভুল নয়, নকশা।
 *
 * ── ⚠️ কিন্তু পরিণতিটা ───────────────────────────────────────────────
 * গুদাম-সীমিত একজন মানুষ মূল্যের রিপোর্ট খুললে **গোটা কোম্পানির টাকার
 * অঙ্ক** দেখবেন, নিজের গুদামের নয়। ⛔ অর্থাৎ মালের **পরিমাণ** দেয়ালে
 * আটকায়, মালের **দাম** আটকায় না।
 *
 * ── ⭐ কেন আজ কিছুই ফাঁস হচ্ছে না ───────────────────────────────────
 * ⓘ abos-f9-র মাপা: `inventory.report` গুদামের ভূমিকায় **নেই**। যিনি
 * গুদামে সীমিত তিনি রিপোর্টটা খুলতেই পারেন না, আর যিনি খুলতে পারেন
 * তাঁর গুদাম-সীমা নেই। ⭐ দুইটা শর্ত একসাথে না মিললে ফাঁসটা ঘটে না।
 *
 * ── ⓘ তাই প্রশ্ন নয়, পাহারা ─────────────────────────────────────────
 * মালিকের হাতে এমনিতেই তিনটা সিদ্ধান্ত ঝুলছে, আর এটার কোনো ফল আজ নেই।
 * ⭐ তাই সিদ্ধান্তটা তোলা থাক **ঘটনার মুহূর্তের জন্য**: যেদিন কেউ
 * দুইটা জোড়া লাগাবে, সেদিন এই দাবিটা লাল হবে আর প্রশ্নটা নিজে থেকেই
 * উঠবে — আজ কাল্পনিকভাবে নয়।
 *
 * ── ⛔ এই পাহারাটা কী ধরে **না**, আর সেটা লুকানো হচ্ছে না ────────────
 * ⚠️ `ScopedToUserWarehouse` বসে **ব্যবহারকারীর** উপর, ভূমিকার উপর নয়।
 * তাই কেউ যদি একজন গুদাম-সীমিত মানুষকে হাতে `Manager` ভূমিকাটা দেন,
 * সেদিন থেকে তিনি গোটা কোম্পানির মূল্য দেখবেন — আর **এই দাবিটা তখনো
 * সবুজ থাকবে**, কারণ ভূমিকার ছকে কিছুই বদলায়নি।
 *
 * ⓘ অর্থাৎ এটা ছকের সরে যাওয়া ধরে, মানুষের সিদ্ধান্ত নয়। ⭐ একটা
 * আংশিক পাহারা লিখে সেটাকে পূর্ণ বলে চালিয়ে দেওয়া এখানকার সবচেয়ে
 * বারবার ফেরা ভুল, তাই সীমাটা দাবির গায়েই লেখা রইল।
 */
final class TheFloorWorkerWasNeverGivenTheCompanyWideValueTest extends TestCase
{
    /**
     * যে কাজগুলো বলে "এই মানুষটা একটা নির্দিষ্ট মেঝেতে কাজ করেন"।
     *
     * ⓘ এগুলোই সেই কাজ যার জন্য কাউকে গুদামে সীমিত করা হয় — মাল
     * বুঝে নেওয়া, সরানো, গোনা। ⚠️ `stock.view` ইচ্ছাকৃতভাবে বাইরে:
     * ওটা Manager-ও পান, আর দেখা মানে মেঝেতে থাকা নয়।
     */
    private const FLOOR_WORK = [
        'inventory.stock.adjust',
        'inventory.stock.hold',
        'inventory.stock.place',
        'inventory.stock.opening',
        'inventory.transfer.receive',
    ];

    /**
     * ⭐ কোনো ভূমিকার ছকে মেঝের কাজ আর মূল্যের রিপোর্ট একসাথে নেই।
     */
    public function test_no_role_template_mixes_floor_work_with_company_wide_reports(): void
    {
        $templates = $this->roleTemplates();

        $this->assertNotSame([], $templates, 'ভূমিকার ছকই পাওয়া গেল না — পরীক্ষাটা কিছুই দেখছে না।');

        $mixed = [];

        foreach ($templates as $role => $granted) {
            $floor = array_values(array_intersect($granted, self::FLOOR_WORK));

            if ($floor === [] || ! in_array('inventory.report', $granted, true)) {
                continue;
            }

            $mixed[] = "{$role} — মেঝের কাজ: ".implode(', ', $floor).' + inventory.report';
        }

        $this->assertSame([], $mixed, implode(PHP_EOL, [
            'এই ভূমিকাগুলো মেঝের কাজ আর মূল্যের রিপোর্ট একসাথে দেয়:',
            '',
            implode(PHP_EOL, $mixed),
            '',
            'ⓘ মজুদের মূল্য আসে `inv_cost_layers` থেকে, আর সেখানে গুদামের',
            'ঘর নেই — তাই গুদাম-সীমিত একজন মানুষ ঐ রিপোর্টে **গোটা',
            'কোম্পানির** টাকার অঙ্ক দেখবেন, নিজের গুদামের নয়।',
            '',
            '⚠️ এটা নিজে থেকে ভুল নয় — মূল্যায়ন কোম্পানি-স্তরের জিনিস হতে',
            'পারে। কিন্তু সিদ্ধান্তটা **মালিকের**, আর এই দাবিটা লাল হওয়ার',
            'মানে সেই সিদ্ধান্তের মুহূর্ত এসে গেছে।',
            '',
            'ⓘ মালিকের RLS-এর যুক্তি ছিল: বাকি গুদামের সংখ্যা স্টোরকিপারের',
            'দেখার কথা নয়, কারণ সেগুলো তিনি মেলাতেও পারবেন না। টাকার অঙ্কে',
            'কথাটা আরো জোরালো।',
        ]));
    }

    /**
     * ⛔ আর মেঝের কাজগুলো সত্যিই কোনো ছকে আছে।
     *
     * ── ⚠️ কেন এই দাবিটা আলাদা লাগে ─────────────────────────────────
     * উপরের দাবিটা দুইটা জিনিসের **মিলন** খোঁজে। ⓘ অনুমতির নামগুলো
     * বদলে গেলে (বা টাইপো থাকলে) `array_intersect` চিরকাল খালি ফেরত
     * দিত, আর দাবিটা চিরকাল সবুজ — কিছু না দেখেই।
     *
     * ⭐ এটা ঠিক সেই রোগ যেটা এই ফোল্ডারের পাহারাগুলোতে বারবার ফিরেছে:
     * সবুজ, কারণ প্যাটার্নটা কোনোদিন কিছুর সাথে মেলেনি।
     */
    public function test_the_floor_work_names_are_real(): void
    {
        $granted = array_merge(...array_values($this->roleTemplates()));

        foreach (self::FLOOR_WORK as $permission) {
            $this->assertContains(
                $permission,
                $granted,
                "'{$permission}' কোনো ভূমিকার ছকেই নেই — নামটা বদলে গেছে, "
                .'আর উপরের দাবিটা এখন এই কাজটা আর দেখে না।',
            );
        }

        $this->assertContains(
            'inventory.report',
            $granted,
            "'inventory.report' কোনো ছকে নেই — উপরের দাবিটা কিছুর সাথেই মিলবে না।",
        );
    }

    /**
     * প্রতিটা মডিউলের ভূমিকার ছক, একসাথে।
     *
     * ⓘ ছকটা **লোড করা হয়**, লেখা ঘেঁটে নয় ([[ModuleRegistry]]) —
     * abos-f9-র সূত্র: পাহারা যখন লেখা ঘেঁটে মান খোঁজে, সে প্রায়ই
     * পাশের ঘরটা পড়ে।
     *
     * @return array<string, list<string>>
     */
    private function roleTemplates(): array
    {
        $all = [];

        foreach (app(ModuleRegistry::class)->all() as $module) {
            /** @var ModuleDefinition $module */
            foreach ($module->roleTemplates as $role => $permissions) {
                $all[$role] = array_merge($all[$role] ?? [], array_values($permissions));
            }
        }

        return $all;
    }
}

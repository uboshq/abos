<?php

declare(strict_types=1);

namespace Tests\Feature\Architecture;

use Illuminate\Support\Facades\File;
use Tests\TestCase;

/**
 * ডবল কোটে মোড়া অ্যাট্রিবিউটের ভেতরে আর ডবল কোট নয়।
 *
 * ── কোন ভুল থেকে এই ফাইলটা এসেছে ─────────────────────────────────────
 * ৩ সেপ্টেম্বর ২০২৬-এ KOT পর্দার `x-data` লেখা হয়েছিল এভাবে:
 *
 *     x-data="{
 *         at: '…',
 *         একটা JS মন্তব্য, আর তার ভেতরে বাংলা উদ্ধৃতি ডবল কোটে
 *         …
 *     }"
 *
 * ব্যাখ্যাটা ভালো ছিল, কিন্তু ওর ভেতরের **ডবল কোট দুইটা** অ্যাট্রিবিউটটাই
 * শেষ করে দিয়েছে। ব্রাউজার প্রথম `"`-এ থেমেছে, বাকিটা আবর্জনা হয়েছে, আর
 * Alpine বলেছে *Invalid or unexpected token*।
 *
 * ⚠️ **আর ফলটা ছিল নীরব — সেটাই সবচেয়ে খারাপ দিক।**
 *
 * পাতাটা ২০০ দিয়েছে, দেখতে ঠিকই লেগেছে। কিন্তু `x-init`-এর
 * `setInterval` কোনোদিন বসেনি, সময়ের ঘর ফাঁকা থেকেছে, আর `x-show`-এর
 * "সংযোগ নেই" ব্যাজটাও কখনো আসেনি — অর্থাৎ **যে ব্যবস্থাটা ভাঙা জানানোর
 * কথা, সে নিজেই ভাঙা**।
 *
 * বাবুর্চি পুরনো পর্দার দিকে তাকিয়ে থাকতেন, নতুন অর্ডার আসত না, আর
 * কোনো সতর্কবার্তাও নয় — অথচ KOT পর্দার গোটা কাজই নিজে থেকে হালনাগাদ
 * হওয়া।
 *
 * ── কেন কেউ ধরত না ───────────────────────────────────────────────────
 * HTTP বলে ২০০। Blade কম্পাইল হয়। PHP-র lint খুশি। **ভুলটা ব্রাউজারের
 * ভেতরে, JavaScript চালু হওয়ার মুহূর্তে** — আর সেখানে আমাদের কোনো
 * পরীক্ষা পৌঁছায় না। ধরা পড়েছে HP-র লাইভ যাচাইয়ে, পাতা খুলে ২৫ সেকেন্ড
 * অপেক্ষা করে নেটওয়ার্কে একটাও অনুরোধ না দেখে।
 *
 * ── একই পরিবারের তৃতীয় বাগ, একই রাতে ─────────────────────────────────
 * ভোরে একটা apostrophe PHP স্ট্রিং বন্ধ করে গোটা অ্যাপ নামিয়ে দিয়েছিল
 * (`'The owner's money'`)। **বিরামচিহ্ন কোডের ভেতরে ঢুকে পড়া** — একই
 * ভুল, তিন রকম চেহারা।
 */
class AQuoteInsideAnAttributeEndsItEarlyTest extends TestCase
{
    public function test_no_double_quote_hides_inside_a_double_quoted_attribute(): void
    {
        $broken = [];
        $seen = 0;

        foreach ($this->blades() as $path) {
            $source = File::get($path);

            // Blade-এর নিজের মন্তব্য ব্রাউজারে যায় না — ওখানে যা খুশি
            $source = (string) preg_replace('/\{\{--.*?--\}\}/su', '', $source);

            /*
             * অ্যাট্রিবিউটটা শুরু হয় `x-…="` বা `@click="` বা `:class="`
             * দিয়ে, আর শেষ হয় পরের `"`-এ। ভেতরে **আরও একটা `"` থাকলে
             * সেটা আসলে অ্যাট্রিবিউটের বাইরে** — অর্থাৎ ব্রাউজার
             * অন্যভাবে পড়ছে।
             *
             * ধরার কৌশলটা তাই উল্টো দিক থেকে: অ্যাট্রিবিউট শুরুর পর
             * প্রথম `"` পর্যন্ত নিলে যদি ভেতরে `/*` বা `{` খোলা থেকে
             * যায় অথচ বন্ধ না হয়, তবে কোটটা ভুল জায়গায় থেমেছে।
             */
            preg_match_all(
                '/\b(x-[a-z:.\-]+|@[a-z.]+|:[a-z\-]+)="([^"]*)"/s',
                $source,
                $found,
                PREG_SET_ORDER,
            );

            foreach ($found as $match) {
                $seen++;

                $body = $match[2];

                /*
                 * খোলা `/*` অথচ বন্ধ নেই — মানে বন্ধের চিহ্নটা
                 * অ্যাট্রিবিউটের বাইরে পড়ে গেছে, আর সেটা ঘটে কেবল
                 * মাঝখানে একটা `"` থাকলে।
                 */
                if (str_contains($body, '/*') && ! str_contains($body, '*/')) {
                    $broken[] = basename($path).": {$match[1]} — মন্তব্য বন্ধ হয়নি";

                    continue;
                }

                // একই যুক্তি বন্ধনীর জন্য: খোলা `{` যা কখনো বন্ধ হয় না
                if (substr_count($body, '{') > substr_count($body, '}')) {
                    $broken[] = basename($path).": {$match[1]} — বন্ধনী মেলেনি";
                }
            }
        }

        $this->assertGreaterThan(100, $seen, 'একটাও অ্যাট্রিবিউট পড়া যায়নি — regex বদলে গেছে?');

        $broken = array_values(array_unique($broken));
        sort($broken);

        $this->assertSame([], $broken, implode("\n", array_merge(
            ['এই অ্যাট্রিবিউটগুলো মাঝপথে শেষ হয়ে গেছে — সম্ভবত ভেতরে',
                'একটা ডবল কোট আছে, আর ব্রাউজার ওখানেই থেমে যায়:'],
            $broken,
            ['',
                '⚠️ পাতাটা তবু ২০০ দেবে আর দেখতে ঠিক লাগবে — কেবল',
                'JavaScript-টা নীরবে মরে থাকবে।',
                '',
                'ব্যাখ্যা লিখতে চাইলে `{{--  --}}`-এ লিখুন, অ্যাট্রিবিউটের',
                'বাইরে — সেটা ব্রাউজারে যায় না, তাই সেখানে যা খুশি চলে।'],
        )));
    }

    /** @return list<string> */
    private function blades(): array
    {
        $out = [];

        foreach ([base_path('app'), resource_path('views')] as $root) {
            foreach (File::allFiles($root) as $file) {
                if (str_ends_with($file->getFilename(), '.blade.php')) {
                    $out[] = $file->getPathname();
                }
            }
        }

        return $out;
    }
}

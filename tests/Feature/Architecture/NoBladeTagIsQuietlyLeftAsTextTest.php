<?php

declare(strict_types=1);

namespace Tests\Feature\Architecture;

use Illuminate\Support\Facades\Blade;
use Tests\TestCase;

/**
 * একটা কম্পোনেন্ট-ট্যাগ নীরবে কাঁচা লেখা হয়ে যেতে পারে।
 *
 * ── ⛔ যা ঘটেছিল, ২৪ সেপ্টেম্বর ২০২৬ ─────────────────────────────────
 * ⓘ `<x-ui.table>`-এর `:columns` অ্যাট্রিবিউটের ভিতরে একটা মন্তব্য বসানো
 * হয়েছিল, আর মন্তব্যটায় ছিল `*"ফেরত"*` — দুইটা **ডবল কোট**।
 *
 * ⚠️ অ্যাট্রিবিউটটা নিজেই ডবল কোটে ঘেরা, তাই ব্লেডের ট্যাগ-পার্সারের
 * কাছে প্রথম কোটেই মানটা **শেষ** হয়ে যায়। ⛔ তারপর সে গোটা ট্যাগটা
 * **কম্পাইলই করে না** — `<x-ui.table :columns="[…]" />` হুবহু কাঁচা লেখা
 * হয়ে পাতায় ছাপা হয়।
 *
 * ── ⚠️ কেন এটা সবচেয়ে বিপজ্জনক আকারের ভুল ───────────────────────────
 * ⓘ কোনো ব্যতিক্রম নেই। ⓘ কম্পাইল করা PHP সিনট্যাক্স-সবুজ, কারণ
 * আউটপুটটা কেবল **লেখা**। ⓘ পাতা ২০০ দেয়, শিরোনাম আসে, উপরের
 * *"১ টি সারি"* গণনাও ঠিক থাকে।
 *
 * ⛔ শুধু ছকটা নেই। আর একটা না-থাকা ছক দেখতে ঠিক *"কিছু নেই"*-এর মতো।
 *
 * ⓘ ধরা পড়েছে মেপে, পড়ে নয়: একটা দাবি লাল হলো, তিনবার কোড পড়ে কারণ
 * পাওয়া যায়নি, তারপর পাতাটা ছেপে দেখা গেল `<x-ui.table` লেখাটাই
 * HTML-এ বসে আছে।
 *
 * ── ⭐ পাহারাটা ব্লেডকেই জিজ্ঞেস করে ────────────────────────────────
 * ⚠️ প্রথম চেষ্টায় অ্যাট্রিবিউটগুলো হাতে পার্স করা হয়েছিল, আর সেই
 * পার্সার নিজেই নয়টা ফাইলে ভুল বলেছিল। ⛔ একটা ভুল বলা পাহারা
 * পাহারা না থাকার চেয়ে খারাপ: সে সহকর্মীর সময় খায়, আর একদিন কেউ
 * ওটাকে চুপ করিয়ে দেয়।
 *
 * ⭐ তাই প্রশ্নটা ব্লেডের নিজের কম্পাইলারকে করা হয়: সে ট্যাগটা
 * কম্পাইল করতে পারলে আউটপুটে `<x-` থাকে না। ⓘ থাকলে সে ওটা
 * **লেখা হিসেবে ছেড়ে দিয়েছে** — আর সেটাই ভুলটা।
 */
class NoBladeTagIsQuietlyLeftAsTextTest extends TestCase
{
    /**
     * যে ফাইলগুলো এই পাহারার বাইরে — কারণসহ।
     *
     * ⓘ ঘরটা খালি, আর সেটাই লক্ষ্য। ⚠️ রাখা হলো যাতে পরে কেউ কারণ
     * **লিখে** ছাড় নেয়, চুপচাপ পাহারাটা তুলে না দেয়।
     *
     * @var array<string, string>
     */
    private const ALLOWED = [];

    public function test_blade_compiles_every_component_tag(): void
    {
        $broken = [];

        foreach ($this->bladeFiles() as $path) {
            $relative = str_replace(base_path().DIRECTORY_SEPARATOR, '', $path);

            if (isset(self::ALLOWED[$relative])) {
                continue;
            }

            $compiled = Blade::compileString((string) file_get_contents($path));

            /*
             * ⓘ ব্লেড নিজের মন্তব্য (`{{-- --}}`) ফেলে দেয়, তাই মন্তব্যে
             * লেখা `<x-ui.table>` উদাহরণটা এখানে আসে না — আর সেটাই ঠিক:
             * কাগজে-কলমে লেখা উদাহরণ ভুল নয়।
             */
            if (! preg_match('/<x-[a-zA-Z0-9]/', $compiled, $m, PREG_OFFSET_CAPTURE)) {
                continue;
            }

            /*
             * ⚠️ `substr`, `mb_substr` নয় — `PREG_OFFSET_CAPTURE` **বাইট**
             * গোনে, আর `mb_substr` অক্ষর। ⛔ বাংলা মন্তব্যভরা একটা
             * ফাইলে দুইটা মিশালে বার্তাটা **ভুল জায়গা** দেখাত,
             * আর পড়ে মনে হত পাহারাটা ভুল বলছে।
             */
            $broken[] = $relative.'  ⛔ '.trim(substr($compiled, (int) $m[0][1], 70));
        }

        $this->assertSame([], $broken, implode("\n", [
            'ব্লেড এই ফাইলগুলোর একটা কম্পোনেন্ট-ট্যাগ কম্পাইল করতে পারেনি,',
            'তাই ট্যাগটা কাঁচা লেখা হয়ে পাতায় ছাপা হবে:',
            '',
            '  '.implode("\n  ", $broken),
            '',
            '⛔ ভুলটা নীরব: কোনো ব্যতিক্রম নেই, কম্পাইল সিনট্যাক্স-সবুজ, পাতা',
            '   ২০০ দেয় — শুধু ঐ কম্পোনেন্টটা নেই। আর একটা না-থাকা ছক দেখতে',
            '   ঠিক "কিছু নেই"-এর মতো।',
            '',
            'ⓘ সবচেয়ে সাধারণ কারণ: অ্যাট্রিবিউটের ভিতরে একটা মন্তব্য, আর',
            '   মন্তব্যে একটা ডবল কোট — ঐ কোটেই অ্যাট্রিবিউটটা শেষ হয়ে যায়।',
            '',
            '⭐ সারানোর পথ: মন্তব্যটা ট্যাগের **উপরে** নিন। অ্যাট্রিবিউটে',
            '   কেবল এক লাইনের তির (`fn () =>`), আর যা বড় সেটা আগেই হিসাব করা।',
        ]));
    }

    /** @return list<string> */
    private function bladeFiles(): array
    {
        $out = [];

        foreach ([app_path(), resource_path('views')] as $base) {
            $walk = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($base));

            foreach ($walk as $file) {
                if ($file->isFile() && str_ends_with($file->getFilename(), '.blade.php')) {
                    $out[] = $file->getPathname();
                }
            }
        }

        sort($out);

        return $out;
    }
}

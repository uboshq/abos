<?php

declare(strict_types=1);

namespace Tests\Feature\Architecture;

use FilesystemIterator;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use Tests\TestCase;

/**
 * পোর্টালের কোড আর তাঁদের "ডিলার" ডাকে না।
 *
 * ── মালিকের সিদ্ধান্ত, ৪ সেপ্টেম্বর ২০২৬ ────────────────────────────
 * **"ডিলার পোর্টাল হবে না, এটা কাস্টমার পোর্টাল হবে।"**
 *
 * ডিলার এগারো শিল্পের একটা ধরন মাত্র — ফার্মেসি, ইলেকট্রনিক্স,
 * গার্মেন্ট, পাইকারি। যিনি পোর্টালে ঢোকেন তিনি একজন **গ্রাহক**, আর
 * তিনি ডিলার হতেও পারেন, না-ও হতে পারেন।
 *
 * ── কেন একটা পাহারা লাগল ────────────────────────────────────────────
 * শব্দটা এই রিপোতে ৫৫১ লাইনে ছিল, আর তার বেশিরভাগ মন্তব্যে। একবার
 * সরালেই কাজ শেষ হয় না: **পরের জন যে ফাইলটা নকল করবেন সেটাতেই
 * শব্দটা আবার বসবে**, আর কেউ খেয়াল করবেন না, কারণ কিছুই ভাঙে না।
 *
 * ⓘ এই একই ভুল NEXUS-এ ঘটেছিল — নোটটা পড়া সত্ত্বেও এক বিকেলে
 * চোদ্দবার পুরনো শব্দটা লেখা হয়েছিল। ওখানে সমাধান ছিল একটা পাহারা,
 * আর এখানেও তাই।
 *
 * ── ⭐ নিয়মটা "dealer শব্দ নিষেধ" নয়, আর সেটাই সবচেয়ে জরুরি ─────────
 * এই রিপোতে শব্দটা **দুইটা আলাদা জিনিস** বোঝায়:
 *
 *   পোর্টালে যিনি ঢোকেন          → গ্রাহক, আর এখানেই নামটা বদলেছে
 *   কমিশন পাওয়া ব্যবসায়িক অংশীদার  → ডিলারই, আর ওটা ব্যবসার শব্দ
 *
 * দ্বিতীয়টা বদলালে কোড **মিথ্যা কথা বলত** — প্রত্যেক গ্রাহক কমিশন
 * পান না, প্রত্যেক গ্রাহকের নিজের গুদাম নেই।
 *
 * ⚠️ Inventory-র লেবেল পর্দায় লেখা আছে *"ডিলারের গুদামে দাম
 * গ্রাহকভেদে আলাদা"* — **এক বাক্যেই দুইটা শব্দ, দুই অর্থে**। যান্ত্রিক
 * replace করলে দাঁড়াত *"গ্রাহকের গুদামে দাম গ্রাহকভেদে আলাদা"* —
 * ব্যাকরণে ঠিক, অর্থে অর্থহীন।
 *
 * তাই পাহারাটা গোটা রিপো দেখে না, দেখে **পোর্টালের এলাকা**: যে
 * ফাইলগুলো নিজেরাই পোর্টালের কথা বলে।
 */
class ThePortalDoesNotCallThemDealersAgainTest extends TestCase
{
    /**
     * যে শব্দগুলো পোর্টালের এলাকায় আর থাকার কথা নয়।
     *
     * ⓘ বড়-ছোট হাতের তিন রূপই ধরা হয় (`DEALER_PORTAL` নামের একটা
     * ধ্রুবক এভাবেই বেঁচে গিয়েছিল), আর বাংলাটাও — কারণ এই রিপোর
     * বেশিরভাগ ব্যাখ্যা বাংলায় লেখা।
     */
    private const RETIRED = ['dealer', 'Dealer', 'DEALER', 'ডিলার'];

    /**
     * পোর্টালের এলাকায় যে ক'টা "ডিলার" ইচ্ছাকৃতভাবে টিকে আছে।
     *
     * চাবি: ফাইল, মান: `[কয়টা, কেন]`। **তালিকাটা কেবল কমবে।**
     *
     * ⚠️ সংখ্যাটার একটা সীমা আছে, আর সেটা লিখে রাখা ভালো: একটা
     * বৈধ উল্লেখ সরিয়ে তার জায়গায় একটা ভুল উল্লেখ বসালে গোনা এক
     * থাকে, আর পাহারাটা চুপ থাকে। **সংখ্যা বাড়লে ধরা পড়ে, বদলালে
     * নয়** — তাই পাশের কারণটাই আসল পাহারা, সংখ্যাটা নয়।
     */
    private const ALLOWED = [
        /*
         * গ্রাহকের **ধরন** — খুচরা, পাইকারি, ডিলার।
         *
         * এটা পোর্টালের গ্রাহক নয়, একটা তালিকার সারি। মালিক ধরনটা
         * নিয়ে আলাদা সিদ্ধান্ত নিচ্ছেন, আর সেটা এই কাজের অংশ নয়।
         */
        'app/Modules/Customer/Models/Customer.php' => [1, 'গ্রাহকের ধরনের তালিকা — খুচরা · পাইকারি · ডিলার'],

        /*
         * জাবেদার উদাহরণ আর ক্রেডিট-লিমিটের গল্প।
         *
         * "ডিলার টাকাটা কোম্পানিকে দিয়েছে" — এটা পরিবেশকের ব্যবসার
         * একটা ঘটনা, পোর্টালের কোনো পর্দা নয়। আর "১৪৮ জনের মধ্যে বড়
         * ডিলারও আছেন" মানে গ্রাহকদের **মধ্যে** কেউ কেউ ডিলার।
         */
        'app/Modules/Customer/module.php' => [2, 'পরিবেশকের ব্যবসার উদাহরণ — গ্রাহকদের মধ্যে যাঁরা ডিলার'],

        /*
         * কমিশনের রুটগুলোর মাথায় লেখা মন্তব্য।
         *
         * ফাইলটা পোর্টালের রুটও ধরে, তাই এলাকার ভিতরে পড়ে — কিন্তু
         * এই লাইনটা কমিশনের, আর কমিশন ডিলারই পান।
         */
        'app/Modules/Sales/Routes/web.php' => [1, 'কমিশনের রুটের মন্তব্য — কমিশন ডিলারই পান, প্রত্যেক গ্রাহক নন'],
    ];

    /** বাজেট — মালিকের ratchet নিয়ম: **কেবল কমবে**। */
    private const BUDGET = 3;

    public function test_the_portal_calls_them_customers(): void
    {
        $offenders = [];
        $scanned = 0;

        foreach ($this->portalTerritory() as $path => $source) {
            $scanned++;

            $found = 0;

            foreach (self::RETIRED as $word) {
                $found += substr_count($source, $word);
            }

            if ($found === 0) {
                continue;
            }

            $relative = $this->relative($path);

            $this->assertArrayHasKey($relative, self::ALLOWED,
                "\n\nপোর্টালের এলাকায় পুরনো শব্দটা ফিরে এসেছে:\n\n  {$relative}\n\n"
                ."মালিকের সিদ্ধান্ত (৪ সেপ্টেম্বর ২০২৬): এটা গ্রাহক পোর্টাল, ডিলার পোর্টাল নয়।\n"
                ."যিনি ঢোকেন তিনি একজন গ্রাহক — ডিলার হতেও পারেন, না-ও পারেন।\n\n"
                ."লাইনটা যদি সত্যিই **কমিশন পাওয়া ব্যবসায়িক অংশীদারের** কথা বলে\n"
                .'(কমিশন · স্কিমের স্তর · ধরনের তালিকা), তবে ALLOWED-এ কারণসহ ঘোষণা করুন।');

            [$allowed, $why] = self::ALLOWED[$relative];

            $this->assertLessThanOrEqual($allowed, $found,
                "\n\n{$relative}-এ আগে {$allowed}টা ছিল, এখন {$found}টা।\n\n"
                ."ছাড়টা এই কারণে: {$why}\n"
                .'নতুন উল্লেখটাও কি সেই কারণেই? না হলে "গ্রাহক" লিখুন।');

            $offenders[$relative] = $found;
        }

        /*
         * ⚠️ অন্ধত্বের পাহারা।
         *
         * উপরের লুপটা "খারাপ কিছু পাওয়া গেল না" দেখে পাশ করে। খোঁজার
         * নিয়মটা একদিন ভুল হয়ে গেলে তালিকাটা খালি আসত আর টেস্টটা
         * **কিছু না দেখেই** সবুজ হত।
         */
        $this->assertGreaterThan(10, $scanned,
            'পোর্টালের এলাকায় দশটার কম ফাইল পাওয়া গেল — খোঁজার নিয়মটাই ভেঙেছে, তাই এই পাহারা কিছুই দেখছে না।');

        $this->assertLessThanOrEqual(self::BUDGET, count(self::ALLOWED),
            'ছাড়ের তালিকা কেবল কমে — বাড়াতে হলে বাজেটের লাইনটাও বদলাতে হবে, আর সেটা একটা সিদ্ধান্ত।');
    }

    /**
     * পোর্টালের এলাকা — যে ফাইলগুলো নিজেরাই পোর্টালের কথা বলে।
     *
     * ── কেন পথের তালিকা নয় ──────────────────────────────────────────
     * হাতে লেখা ফোল্ডারের তালিকা দিলে **আগামীকালের নতুন ফাইলটা
     * তালিকার বাইরে** থাকত, আর পাহারাটা ঠিক সেখানেই অকেজো হত যেখানে
     * তাকে দরকার। "পোর্টাল" শব্দটা যে ফাইল নিজে লেখে, সে নিজেই
     * নিজেকে এলাকার ভিতরে এনেছে।
     *
     * ── ⛔ মাইগ্রেশন বাদ, আর সেটা ইচ্ছাকৃত ──────────────────────────
     * চারটা মাইগ্রেশনের **ফাইলের নামে** শব্দটা আছে। Laravel
     * `migrations` টেবিলে ফাইলের নামটাই রাখে, তাই নাম বদলালে সে
     * ওগুলোকে নতুন মাইগ্রেশন ভেবে আবার চালাত — deploy থামত। ওগুলো
     * ইতিহাস, আর ইতিহাস শোধরানো যায় না; শোধরানো যায় পরের
     * মাইগ্রেশনে ([[2026_10_22_100000_the_column_was_named_after_one_kind_of_customer]])।
     *
     * @return iterable<string, string> পথ => উৎস
     */
    private function portalTerritory(): iterable
    {
        foreach ([app_path(), config_path(), base_path('tests')] as $root) {
            $walk = new RecursiveIteratorIterator(
                new RecursiveDirectoryIterator($root, FilesystemIterator::SKIP_DOTS)
            );

            foreach ($walk as $file) {
                $path = str_replace(DIRECTORY_SEPARATOR, '/', $file->getPathname());

                if (! $file->isFile()) {
                    continue;
                }

                if (! str_ends_with($path, '.php')) {
                    continue;
                }

                if (str_contains($path, '/Database/Migrations/')) {
                    continue;
                }

                /*
                 * ⚠️ এই ফাইলটা নিজে বাদ — নাহলে পাহারাটা **নিজেকেই**
                 * ধরত। যে শব্দটা খোঁজা হচ্ছে সেটা তো এখানে লিখতেই
                 * হবে, আর ব্যাখ্যাটাও এখানেই।
                 */
                if ($path === str_replace(DIRECTORY_SEPARATOR, '/', __FILE__)) {
                    continue;
                }

                $source = file_get_contents($path);

                if ($source === false || stripos($source, 'portal') === false) {
                    continue;
                }

                yield $path => $source;
            }
        }
    }

    private function relative(string $path): string
    {
        $base = str_replace(DIRECTORY_SEPARATOR, '/', base_path()).'/';

        return str_starts_with($path, $base) ? substr($path, strlen($base)) : $path;
    }
}

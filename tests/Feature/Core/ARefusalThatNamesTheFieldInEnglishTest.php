<?php

declare(strict_types=1);

namespace Tests\Feature\Core;

use Tests\TestCase;

/**
 * অস্বীকারটা ঘরের নামটা ইংরেজিতে বলে ফেলত।
 *
 * ── ⛔ কী পাওয়া গেছে লাইভে, ৭ সেপ্টেম্বর ২০২৬ ────────────────────────
 * হাতে একটা পুরো ব্যবসার চক্র চালাতে গিয়ে দুইবার এই বাক্যদুটো এসেছে:
 *
 *     ⛔ "lines দিতেই হবে।"
 *     ⛔ "received into account id দিতেই হবে।"
 *
 * ⓘ কারণটা সরল: `:attribute`-এর কোনো বাংলা নাম না পেলে Laravel ঘরের
 * **কাঁচা নামটাই** বসিয়ে দেয়, আর বাক্যটা অর্ধেক ইংরেজি হয়ে যায়।
 *
 * ── ⚠️ কেন এটা "ছোট" ভুল নয় ────────────────────────────────────────
 * CLAUDE.md-তে নিয়মটা নাম ধরে লেখা: *"ব্যাকএন্ডের বাংলা 4xx বার্তা
 * সরাসরি ফোনের পর্দায় দেখা যায় — মোবাইল অ্যাপ ইংরেজি framework-noise
 * গিলে ফেলে আর বাংলা বার্তাগুলো দেখায়। অর্থাৎ ওগুলো লগ নয়, **UI**।"*
 *
 * ⓘ ডিপোর কাউন্টারে দাঁড়ানো মানুষটা `received into account id` পড়ে
 * বুঝতে পারেন না **কোন ঘরটা** তিনি ভুলে গেছেন। ⛔ বার্তাটা তখন সাহায্য
 * করে না, শুধু জানায় যে কিছু একটা ভুল — আর সেটাই সবচেয়ে খারাপ ধরনের
 * ত্রুটিবার্তা।
 *
 * ── ⭐ পাহারাটা কী করে ───────────────────────────────────────────────
 * প্রতিটা ঘরের নাম আগে থেকে অনুমান করা যায় না — নতুন পর্দা রোজ আসে।
 * ⓘ তাই দাবিটা উল্টো দিক থেকে: **তালিকার প্রতিটা নাম সত্যিই বাংলা কি
 * না**, আর তালিকাটা যেন ছোট হয়ে না যায়।
 *
 * ⚠️ এটা নিখুঁত নয় — যে ঘরটা তালিকায় নেই সেটা এখনো ইংরেজিতে বেরোবে।
 * ⭐ কিন্তু এটা সৎ: যা মাপা যায় তা-ই মাপা হচ্ছে, আর সংখ্যাটা কমতে পারে
 * না।
 */
class ARefusalThatNamesTheFieldInEnglishTest extends TestCase
{
    /**
     * ৭ সেপ্টেম্বর ২০২৬-এ গোনা।
     *
     * ⚠️ **কেবল বাড়বে** — একটা নাম মুছে ফেলা মানে কোনো একটা পর্দায়
     * বার্তাটা আবার অর্ধেক ইংরেজি হয়ে যাওয়া, আর সেটা কেউ টের পাবেন না
     * যতক্ষণ না কোনো ক্রেতা ওই ঘরটা ফাঁকা রাখেন।
     */
    private const AT_LEAST = 77;

    public function test_the_list_of_bangla_field_names_only_grows(): void
    {
        $names = (require base_path('lang/bn/validation.php'))['attributes'] ?? [];

        $this->assertGreaterThanOrEqual(
            self::AT_LEAST,
            count($names),
            "বাংলা ঘরের নামের তালিকা ছোট হয়ে গেছে।\n"
            ."যে নামটা নেই, সেই ঘরের বার্তায় কাঁচা ইংরেজি নামটা বসবে —\n"
            .'যেমন "lines দিতেই হবে।" ⓘ তালিকা কেবল বাড়তে পারে।',
        );
    }

    /**
     * ⛔ প্রতিটা নাম সত্যিই বাংলা — ইংরেজি নাম বসিয়ে রাখা চলবে না।
     *
     * ⚠️ এই দাবিটা না থাকলে কেউ `'lines' => 'lines'` লিখে তালিকার সংখ্যা
     * বাড়িয়ে দিতে পারতেন, আর উপরের দাবিটা সবুজ থাকত অথচ ব্যবহারকারী ঠিক
     * আগের বাক্যটাই দেখতেন।
     */
    public function test_every_name_is_actually_in_bangla(): void
    {
        $names = (require base_path('lang/bn/validation.php'))['attributes'] ?? [];

        $notBangla = [];

        foreach ($names as $key => $label) {
            // ⓘ অন্তত একটা বাংলা অক্ষর থাকতেই হবে
            if (! preg_match('/\p{Bengali}/u', (string) $label)) {
                $notBangla[] = $key.' → '.$label;
            }
        }

        $this->assertSame(
            [],
            $notBangla,
            "এই নামগুলোতে একটাও বাংলা অক্ষর নেই — অর্থাৎ বার্তাটা এখনো\n"
            ."অর্ধেক ইংরেজিই থাকবে, শুধু তালিকায় একটা সারি বেড়েছে।\n"
            .'⚠️ সংখ্যা বাড়ানো সহজ; অনুবাদ করা কঠিন — কাঠিন্যটাই এখানে পাহারা।',
        );
    }

    /**
     * ⭐ আর যেগুলো আজ সত্যিই ভেঙেছিল, সেগুলো নাম ধরে।
     *
     * ⓘ সংখ্যা-ভিত্তিক দাবিটা সাধারণ, এটা নির্দিষ্ট: এই তিনটা ঘর লাইভে
     * ব্যবহারকারীকে ইংরেজি দেখিয়েছে, আর তিনটাই ফিরে আসতে পারে যদি কেউ
     * তালিকাটা সাজাতে গিয়ে সরিয়ে ফেলেন।
     */
    public function test_the_three_that_actually_broke_are_named(): void
    {
        $names = (require base_path('lang/bn/validation.php'))['attributes'] ?? [];

        /*
         * ⓘ `person_id` তালিকায় যোগ হয়েছে ১৩ সেপ্টেম্বর ২০২৬-এ, আর সেটা
         * `contributor_name`-এর **উত্তরসূরি**: অর্থের পাঁচটা পর্দায় নামের
         * মুক্ত-লেখা ঘর সরিয়ে ব্যক্তির তালিকা বসানো হয়েছে, তাই ভুলের
         * বার্তা এখন এই ঘরের নামে আসে। নাম না দিলে ব্যবহারকারী "person
         * id" দেখতেন — হুবহু সেই বাগ যেটা এই ফাইলটা ঠেকাতে বসানো।
         */
        foreach (['lines', 'received_into_account_id', 'contributor_name', 'person_id'] as $key) {
            $this->assertArrayHasKey(
                $key,
                $names,
                "`{$key}` ঘরটার বাংলা নাম নেই — লাইভে এটাই ব্যবহারকারীকে\n"
                .'কাঁচা ইংরেজি নাম দেখিয়েছিল, ৭ সেপ্টেম্বর ২০২৬।',
            );
        }
    }
}

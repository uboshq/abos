<?php

declare(strict_types=1);

namespace Tests\Feature\Core;

use Illuminate\Support\Facades\File;
use Tests\TestCase;

/**
 * অস্বীকারটা হলো, আর কেউ দেখল না।
 *
 * ── ⛔ কী ঘটেছিল লাইভে, ৭ সেপ্টেম্বর ২০২৬ ────────────────────────────
 * একটা বিক্রয় ফেরত নিশ্চিত করতে বোতাম চাপা হলো। ⓘ পাতা ফিরে এল, কাগজ
 * **খসড়াই রইল**, আর পর্দা একটা শব্দও বলল না।
 *
 * ⚠️ সার্ভার ঠিকই আটকাচ্ছিল, আর কারণটাও পরিষ্কার বাংলায় লেখা ছিল:
 *
 *     "গুঁড়ো দুধ ১ কেজি যতটা বেরিয়েছিল তার বেশি ফেরত নেওয়া যায় না।"
 *
 * ⛔ কিন্তু ওই `show` পর্দায় `$errors` **দেখানোর কোনো ব্যবস্থাই ছিল না**,
 * তাই বাক্যটা কোথাও ছাপা হয়নি।
 *
 * ── ⚠️ কেন এটা সবচেয়ে খারাপ ধরনের ভাঙা ──────────────────────────────
 * ⓘ ব্যবহারকারী তিনবার বোতাম চাপেন, তারপর ধরে নেন **ব্যবস্থাটা ভাঙা**।
 * ⭐ অথচ ব্যবস্থাটা ঠিক কাজ করছিল — সে একটা সত্যিকারের ভুল আটকাচ্ছিল,
 * শুধু বলতে পারছিল না।
 *
 * ⚠️ আর এর কোনো চিহ্নও থাকে না: `error_events` খালি, লগে কিছু নেই।
 * ValidationException ভুল নয়, ব্যবস্থার স্বাভাবিক উত্তর — তাই সে কোথাও
 * লেখা হয় না। ⛔ ফলে ব্যর্থতাটা **সম্পূর্ণ নীরব**।
 *
 * ── মাপা ─────────────────────────────────────────────────────────────
 * ৩৬টা `show` পর্দার মধ্যে **১৩টা** ত্রুটি দেখাত, **২৩টা** দেখাত না।
 * ⓘ অর্থাৎ নিয়মটা জানা ছিল — কেউ ১৩ জায়গায় হাতে লিখেছিলেন — কেবল
 * বাকিগুলোয় পৌঁছায়নি। ⭐ আজকের চেনা ছাঁচ: **নীতির অভাব নয়, পৌঁছানোর
 * অভাব**।
 *
 * ── ⭐ পাহারাটা কেন ফাইল পড়ে, পর্দা খুলে নয় ─────────────────────────
 * প্রতিটা `show` পর্দায় ত্রুটি আনতে হলে আগে একটা ভুল ঘটাতে হত, আর
 * প্রতিটার ভুল আলাদা। ⓘ ফাইলটা পড়া সৎ ও সম্পূর্ণ: **যে পর্দায় দেখানোর
 * ব্যবস্থাই নেই, সে কোনোদিন দেখাবে না** — সেটা প্রমাণ করতে ভুল ঘটানোর
 * দরকার নেই।
 */
class ARefusalNobodyEverSawTest extends TestCase
{
    /**
     * ⚠️ যেগুলোতে কাজের বোতাম নেই।
     *
     * ⓘ প্রতিবেদনের পর্দা কেবল দেখায় — সেখানে নিশ্চিত/বাতিল/পোস্ট কিছুই
     * নেই, তাই যাচাইয়ের ত্রুটিও আসে না। ⛔ কারণ ছাড়া ছাড় লেখা হয় না।
     *
     * @var array<string, string>
     */
    private const EXEMPT = [
        'app/Modules/Accounts/Resources/views/report/show.blade.php' =>
            'প্রতিবেদন দেখার পর্দা — কোনো কাজের বোতাম নেই, তাই যাচাইয়ের ত্রুটিও নেই',
    ];

    public function test_every_show_screen_can_say_why_it_refused(): void
    {
        $blind = [];

        foreach (File::allFiles(base_path('app/Modules')) as $file) {
            if ($file->getFilename() !== 'show.blade.php') {
                continue;
            }

            $relative = 'app/Modules/'.str_replace('\\', '/', $file->getRelativePathname());

            if (array_key_exists($relative, self::EXEMPT)) {
                continue;
            }

            $code = $file->getContents();

            if (str_contains($code, '<x-ui.errors') || str_contains($code, 'errors->any()')) {
                continue;
            }

            $blind[] = $relative;
        }

        $this->assertSame(
            [],
            $blind,
            "এই পর্দাগুলো কেন কাজটা হলো না তা বলতে পারে না।\n"
            ."বোতাম চাপা যায়, কিছুই ঘটে না, আর কোনো কারণও দেখা যায় না —\n"
            ."ব্যবহারকারী ধরে নেন ব্যবস্থাটা ভাঙা, অথচ সে একটা ভুল আটকাচ্ছে।\n\n"
            ."এক লাইনেই হয়:  <x-ui.errors />\n"
            .'সত্যিই দরকার না থাকলে EXEMPT-এ **কারণসহ** লিখুন।',
        );
    }

    /**
     * ⓘ পাহারাটা শূন্য জায়গা পাহারা দিচ্ছে না।
     *
     * ⚠️ উপরের দাবিটা খালি ফোল্ডারেও সবুজ থাকত। ⛔ `show` পর্দাগুলো
     * সত্যিই আছে কি না, আর সংখ্যাটা হঠাৎ কমে গেল কি না — সেটা এখানে।
     */
    public function test_the_guard_is_actually_watching_the_show_screens(): void
    {
        $count = 0;

        foreach (File::allFiles(base_path('app/Modules')) as $file) {
            if ($file->getFilename() === 'show.blade.php') {
                $count++;
            }
        }

        $this->assertGreaterThanOrEqual(
            30,
            $count,
            "`show` পর্দার সংখ্যা হঠাৎ কমে গেছে — ৭ সেপ্টেম্বর ২০২৬-এ ছিল ৩৬টা।\n"
            .'পাহারাটা তখন প্রায় কিছুই দেখছে না, অথচ সবুজ থাকবে।',
        );
    }
}

#!/usr/bin/env bash
#
# ABOS-কে সার্ভারে তোলার একমাত্র পথ।
#
# ── কেন এই ফাইলটা লাগল ───────────────────────────────────────────────
# ১ সেপ্টেম্বর ২০২৬-এর নিরীক্ষায় ধরা পড়ল রিপোতে একটাও `.sh` নেই, অথচ
# কোড ধরে নিয়েছে আছে — [[PostMissingOpenings]]-এর নিজের ব্যাখ্যায় লেখা
# *"তাই `deploy.sh`-এ মাইগ্রেশনের ঠিক পরেই"*। ডিপ্লয় মানে ছিল হাতে
# `git pull` আর `artisan migrate`, মনে থাকলে।
#
# মনে না থাকার দামটা এই সেশনেই দেখা গেছে: ৩১ আগস্ট একটা ডিপ্লয়ে
# কলারটা গেল কিন্তু ক্লাসটা গেল না, আর **লাইভে বিল কাটা প্রায় দুই ঘণ্টা
# ভাঙা ছিল** — জানা গেছে দৈবক্রমে।
#
# ── স্ক্রিপ্টটা যা নিশ্চিত করে ─────────────────────────────────────────
#   ১. আগে ব্যাকআপ, আর সেটা **খুলে যাচাই করা** (`abos:backup` নিজেই করে)
#   ২. কোন কমিটে ছিলাম তা মনে রাখা
#   ৩. যে মাইগ্রেশন চলেছে অথচ ফাইলটা আর নেই — সেখানেই থামা
#   ৪. মাইগ্রেশনের পরেই খোলা জেরগুলো বসানো, অনুমতি মেলানো
#   ৫. খাতা মেলে কি না দেখা
#   ৬. `/up` না এলে **নিজেই পুরনো কোডে ফেরা**
#
# ব্যবহার:  ssh ubos-office 'cd /Users/mac/abos && ./infra/deploy.sh'

set -euo pipefail

# ── হোমব্রুর পথ ──────────────────────────────────────────────────────
# ssh দিয়ে ঢুকলে লগইন শেল চলে না, তাই /opt/homebrew/bin PATH-এ থাকে না,
# আর `php`/`composer`/`npm` একটাও পাওয়া যায় না। এই লাইনটা না থাকলে
# স্ক্রিপ্টটা প্রথম কমান্ডেই "command not found" বলে থামত।
export PATH=/opt/homebrew/bin:$PATH

cd "$(dirname "$0")/.."
APP_ROOT="$(pwd)"

HEALTH_URL="${ABOS_HEALTH_URL:-https://abos.univer.com.bd/up}"

say()  { printf '\n\033[1m▸ %s\033[0m\n' "$1"; }
fail() { printf '\n\033[31m✗ %s\033[0m\n' "$1" >&2; }

# ── ০ · এখানে ডিপ্লয় করা যায় কি না ──────────────────────────────────
[ -f artisan ] || { fail "artisan নেই — $APP_ROOT ABOS-এর ফোল্ডার নয়।"; exit 1; }
[ -f .env ]    || { fail ".env নেই — এই মেশিনে ABOS বসানো হয়নি।"; exit 1; }

if ! git diff --quiet || ! git diff --cached --quiet; then
    fail "সার্ভারে হাতে করা পরিবর্তন আছে। git status দেখে ঠিক করুন, নাহলে pull সেগুলো মুছে দেবে।"
    exit 1
fi

BEFORE="$(git rev-parse HEAD)"
MIGRATED=0

# ── রোলব্যাক ─────────────────────────────────────────────────────────
#
# ── কেন ডাটাবেজ ফেরানো শর্তসাপেক্ষ ───────────────────────────────────
# মাইগ্রেশন না চললে ডাটাবেজে ডিপ্লয়ের কিছুই ঘটেনি — তখন ডাম্প ফেরালে
# ডিপ্লয়ের সময়টুকুতে কাউন্টারে যে বিলগুলো কাটা হয়েছে সেগুলো **মুছে
# যেত**। অর্থাৎ সারানোর চেষ্টাটাই সবচেয়ে বড় ক্ষতি করত।
#
# মাইগ্রেশন চলে গিয়ে পরে ভাঙলে উল্টোটা: স্কিমা নতুন, কোড পুরনো, আর
# ওই জোড়া কোনোদিন একসাথে চলেনি। তখন ফেরানো ছাড়া উপায় নেই।
rollback() {
    fail "ডিপ্লয় ব্যর্থ — পুরনো অবস্থায় ফেরানো হচ্ছে।"

    git reset --hard "$BEFORE"
    composer install --no-dev --optimize-autoloader --no-interaction || true
    npm ci --silent || true
    npm run build || true

    if [ "$MIGRATED" -eq 1 ]; then
        fail "মাইগ্রেশন চলে গিয়েছিল — ডাটাবেজও ফেরানো হচ্ছে।"

        # `--no-safety` ইচ্ছে করে দেওয়া হয়নি: ফেরানোর আগে ভাঙা
        # অবস্থাটারও একটা ডাম্প থাকে। ওটা না থাকলে "কী ভেঙেছিল" প্রশ্নের
        # উত্তর চিরতরে হারিয়ে যেত — আর ভুল ফাইল থেকে ফেরালে ফেরার পথও।
        php artisan abos:restore --force || fail "ডাটাবেজ ফেরানো যায়নি — হাতে দেখুন।"
    fi

    php artisan abos:optimise || true

    if curl -fsS --max-time 20 "$HEALTH_URL" >/dev/null 2>&1; then
        fail "পুরনো কোডে ফেরা হয়েছে, সাইট চলছে। কমিট: $BEFORE"
    else
        fail "ফেরানোর পরেও /up আসছে না। এখনই হাতে দেখুন। কমিট: $BEFORE"
    fi

    exit 1
}
trap rollback ERR

# ── ১ · ব্যাকআপ, আর সেটা সত্যিই খোলে কি না ──────────────────────────
say "ব্যাকআপ নেওয়া হচ্ছে (নিয়ে, খুলে, যাচাই করে)"
php artisan abos:backup

# ── ২ · নতুন কোড ─────────────────────────────────────────────────────
say "নতুন কোড আনা হচ্ছে"
git pull --ff-only

AFTER="$(git rev-parse HEAD)"
if [ "$BEFORE" = "$AFTER" ]; then
    say "কোডে নতুন কিছু নেই ($BEFORE) — তবু বাকি ধাপগুলো চলবে, কারণ আগের কোনো ডিপ্লয় অসম্পূর্ণ থাকতে পারে।"
fi

# ── ৩ · যে মাইগ্রেশন চলেছে অথচ ফাইলটা আর নেই ────────────────────────
#
# একটা মাইগ্রেশন চলে যাওয়ার পর কেউ ফাইলটা মুছে দিলে বা নাম বদলালে
# Laravel চুপচাপ মেনে নেয় — কিন্তু `migrate:rollback` তখন আর ওই ধাপটা
# ফেরাতে পারে না, অর্থাৎ **ফেরার পথটাই বন্ধ**। ডিপ্লয়ের আগে জানা ভালো।
say "মাইগ্রেশনের ইতিহাস মিলছে কি না"
MISSING="$(php artisan tinker --execute='
    $ran = DB::table("migrations")->pluck("migration");
    $have = collect(glob(base_path("database/migrations/*.php")))
        ->merge(glob(base_path("app/Modules/*/Database/Migrations/*.php")))
        ->map(fn ($p) => basename($p, ".php"));
    echo $ran->diff($have)->implode(PHP_EOL);
' 2>/dev/null || true)"

if [ -n "${MISSING// /}" ]; then
    fail "এই মাইগ্রেশনগুলো ডাটাবেজে চলেছে, কিন্তু ফাইল নেই:"
    printf '%s\n' "$MISSING" >&2
    fail "ফাইলগুলো ফিরিয়ে আনুন, নাহলে rollback-এর পথ বন্ধ। ডিপ্লয় থামানো হলো।"
    trap - ERR
    exit 1
fi

# ── ৪ · নির্ভরতা ও সম্পদ ─────────────────────────────────────────────
say "PHP নির্ভরতা"
composer install --no-dev --optimize-autoloader --no-interaction

say "সামনের দিকের সম্পদ তৈরি"
npm ci --silent
npm run build

# ── ৫ · স্কিমা ───────────────────────────────────────────────────────
say "মাইগ্রেশন"
MIGRATED=1
php artisan migrate --force

# ── ৬ · মাইগ্রেশনের ঠিক পরে — কোড যেগুলো দাবি করে ───────────────────
say "ঘোষিত অথচ খতিয়ানে না বসা জেরগুলো"
php artisan abos:post-missing-openings

say "module.php-র অনুমতিগুলো ডাটাবেজে"
php artisan abos:sync-permissions

#
# ── কেন `--force` ────────────────────────────────────────────────────
# লিংকটা প্রথম ডিপ্লয়ের পর থেকেই থাকে, তাই প্রতিবার Laravel লাল অক্ষরে
# `ERROR The [public/storage] link already exists` ছাপত। `|| true` ছিল
# বলে ডিপ্লয় থামত না — **কিন্তু একটা নিখুঁত ডিপ্লয়ের মাঝখানে লাল লেখা
# থাকাটাই সমস্যা**: যিনি দেখছেন তিনি থেমে যান, আর পরেরবার সত্যিকারের
# ভুলটাও ওই পরিচিত লালের সাথে মিলিয়ে ফেলেন।
#
# `--force` লিংকটা নতুন করে বসায়, তাই বার্তাটাও আসে না। `|| true` তবু
# থাকল: লিংক বসানো না গেলে (অনুমতি, ফাইল-ব্যবস্থা) ডিপ্লয় থামার মতো
# ঘটনা নয় — সংযুক্তি দেখা যাবে না, বাকি সব চলবে।
say "সংযুক্তির লিংক"
php artisan storage:link --force || true

# ── ৭ · ক্যাশ ────────────────────────────────────────────────────────
say "কনফিগ, রুট, ইভেন্ট ও Blade ক্যাশ"
php artisan abos:optimise

# ── ৮ · খাতা মেলে কি না ──────────────────────────────────────────────
say "প্রতিটা কোম্পানির খাতা"
php artisan abos:books-check

# ── ৯ · সাইট সত্যিই উঠেছে কি না ─────────────────────────────────────
#
# তিনবার, মাঝে বিরতি — php-fpm নতুন ক্যাশ নিতে কয়েক সেকেন্ড নেয়, আর
# প্রথম চেষ্টায় থেমে গেলে ভালো ডিপ্লয়ও ব্যর্থ বলে ফিরে যেত।
say "সাইট দেখা হচ্ছে: $HEALTH_URL"
UP=0
for i in 1 2 3; do
    if curl -fsS --max-time 20 "$HEALTH_URL" >/dev/null 2>&1; then UP=1; break; fi
    sleep 5
done

[ "$UP" -eq 1 ] || false   # false ⇒ trap ⇒ rollback

trap - ERR
printf '\n\033[32m✓ ডিপ্লয় সম্পন্ন\033[0m\n'
printf '  আগে ছিল : %s\n' "$BEFORE"
printf '  এখন     : %s\n' "$AFTER"
printf '  সাইট    : %s — উঠেছে\n\n' "$HEALTH_URL"

<?php

use App\Core\Services\FormIsNotSubmittedTwice;
use Illuminate\Support\Facades\Schedule;

/*
 * নির্ধারিত কাজ।
 *
 * সার্ভার অফিসের একটা মেশিন, তাই এখানে যা লেখা আছে তা সত্যিই চলতে হলে
 * উইন্ডোজে একটা Task Scheduler এন্ট্রি লাগে:
 *
 *     php artisan schedule:run   — প্রতি মিনিটে
 *
 * ওই এন্ট্রিটা না থাকলে নিচের কিছুই চলবে না, আর কেউ টের পাবে না —
 * বিশেষ করে ব্যাকআপ, যেটার অনুপস্থিতি জানা যায় ঠিক সেই দিন যেদিন
 * সেটা দরকার পড়ে।
 */

/*
 * রোজ একটা ব্যাকআপ — ঘড়ি ধরে নয়, অবস্থা ধরে।
 *
 * ── আগে যা ছিল, আর কেন ভাঙত ─────────────────────────────────────────
 * লেখা ছিল `->dailyAt('01:30')`। শিডিউলার প্রতি মিনিটে জেগে দেখে "এখন
 * কি ০১:৩০?" — আর কেবল ওই **এক মিনিটেই** হ্যাঁ বলে। মিনিটটা ফসকে গেলে
 * ওই দিন আর কোনো ব্যাকআপ হয় না, আর পরদিন পর্যন্ত কেউ জানেও না।
 *
 * ফসকানোর কারণ সাধারণ: শিডিউলার ঠিক ৬০.০ সেকেন্ড পরে চলে না (ড্রিফট
 * জমে একদিন পুরো মিনিট লাফায়), মেশিন ঘুমিয়ে থাকলে জেগে ওঠার পর সময়
 * পেরিয়ে গেছে, কিংবা ওই মিনিটে রিবুট।
 *
 * Mac mini-তে ধরা পড়েছে: ১৫, ১৭, ১৮, ১৯ আগস্ট চলেছে — ১৬ আর ২০ চলেনি।
 * লগে কোনো ভুল নেই, কারণ ভুল কিছু হয়নি; প্রশ্নটাই করা হয়নি।
 *
 * ── এখন কীভাবে ──────────────────────────────────────────────────────
 * `abos:backup-due` ঘড়ি দেখে না, **ফোল্ডার দেখে**: আজকের তারিখের ডাম্প
 * আছে কি? না থাকলে নেয়। ঘণ্টায় ঘণ্টায় প্রশ্নটা ওঠে, তাই ফসকানো মিনিট,
 * ঘুমন্ত মেশিন বা রিবুট — কোনোটাই আর ব্যাকআপ কাড়তে পারে না।
 *
 * নির্ধারিত সময়টা (`backup.daily_at`) অক্ষত: চেষ্টাটা হয় ওই মিনিটেই,
 * আর ফসকালে পরের ঘণ্টায় একই মিনিটে আবার। `hourly()` লিখলে প্রথম চেষ্টাটা
 * ০২:০০-এ পড়ত — অর্থাৎ রোজ আধা ঘণ্টা দেরিতে, বিনা কারণে।
 *
 * ── একটা সীমা, লিখে রাখা ────────────────────────────────────────────
 * সময়টা যদি রাত ২৩:৩০ হয়, তবে ওই দিনে চেষ্টা একটাই — পরের ঘণ্টায়
 * তারিখ বদলে যায়, আর তখন প্রশ্নটা নতুন দিনের। ডিপোর সময় ০১:৩০, তাই
 * এখানে দিনে বাইশটা সুযোগ থাকে; সমস্যা নেই। খুব দেরির সময় বসালে এই
 * কথাটা মনে রাখতে হবে।
 */
/*
 * খাতা মেলে কি না — রোজ, ব্যাকআপের পরে।
 *
 * ── কেন এটা এখানে বসল, ৩১ আগস্ট ২০২৬ ────────────────────────────────
 * যাচাইগুলো তৈরিই ছিল, কিন্তু পথ ছিল একটাই: কেউ পর্দাটা খুললে। অর্থাৎ
 * "খাতা মিলছে তো?" প্রশ্নটা মানুষের মনে রাখার উপর দাঁড়িয়ে ছিল, আর
 * ব্যাকআপের বেলায় ঠিক এই ভরসাটাই একবার ভেঙেছে (১৬ ও ২০ আগস্ট)।
 *
 * ── কেন ব্যাকআপের পরে ───────────────────────────────────────────────
 * ব্যাকআপ আগে নেওয়া হোক। খাতা ভাঙা থাকলেও ওই দিনের একটা কপি অন্তত
 * থাকবে — আর ভাঙা খাতার ব্যাকআপও ব্যাকআপ, ওটা থেকেই কারণ খোঁজা হয়।
 *
 * সময়টা ব্যাকআপের এক ঘণ্টা পরে, যাতে দুইটা একসাথে ডিস্ক না টানে।
 */
Schedule::command('abos:books-check')
    ->dailyAt(sprintf('%02d:%s',
        ((int) explode(':', (string) config('abos.backup.daily_at'))[0] + 1) % 24,
        explode(':', (string) config('abos.backup.daily_at'))[1],
    ))
    ->withoutOverlapping()
    ->onFailure(function () {
        logger()->critical('বইয়ের যাচাই ভেঙেছে — হাতে দেখতে হবে।');
    });

Schedule::command('abos:backup-due')
    ->hourlyAt((int) explode(':', (string) config('abos.backup.daily_at'))[1])
    ->when(fn () => now()->format('H:i') >= (string) config('abos.backup.daily_at'))
    ->withoutOverlapping()

    /*
     * ⚠️ আউটপুটটা ফাইলে রাখা — ১৫ সেপ্টেম্বর ২০২৬-এ যোগ।
     *
     * ⛔ এটা না থাকায় ছয় দিনের ব্যর্থতার **কারণটা কোথাও লেখা ছিল না**।
     * `proc_open`-এর ভুলটা কমান্ডের আউটপুটে থেকে যেত — যেখানে কেউ
     * তাকায় না, কারণ সেটা কোথাও যেত না।
     *
     * ── ⭐ আমি এখানে একটা ভুল লিখেছিলাম, আর সেটা সংশোধন করছি ─────────
     * আগে এখানে লেখা ছিল "শিডিউলার exit code দেখে ঐ লাইনটা লেখে না"।
     * ⛔ **কথাটা মিথ্যা।** [[ScheduleRunCommand::runEvent()]] শেষ করে
     * `return $event->exitCode == 0;` দিয়ে, আর ঐ উত্তরটাই `DONE` না
     * `FAIL` ঠিক করে। ⓘ অর্থাৎ শিডিউলার সৎ — সে `FAIL`-ই লিখত।
     *
     * ⚠️ তাহলে ছয় দিন কেউ জানল না কেন? কারণ `FAIL` লেখা হচ্ছিল এমন
     * এক ফাইলে **যা কেউ খোলে না**। ⭐ রোগটা শিডিউলারের সততায় ছিল না,
     * ছিল আমাদের তাকানোয় — আর ঠিক সেজন্যই নিচের পাহারাটা লগে ফিসফিস
     * করে না, `logger()->critical()` আর non-zero exit দিয়ে চিৎকার করে।
     *
     * ⓘ দাবিটা এখন মাপা হয়:
     * [[TheBackupSaidDoneForSixDaysTest::test_the_scheduler_is_told_the_truth_about_a_failed_backup]]
     *
     * ⓘ এখন কারণটা `storage/logs/backup.log`-এ, আর সেই ফাইলটাই খোঁজার
     * প্রথম জায়গা।
     */
    ->appendOutputTo(storage_path('logs/backup.log'))

    ->onFailure(function () {
        // ব্যর্থ ব্যাকআপ নীরবে যেতে দেওয়া যায় না — সবাই ভাববে ব্যাকআপ
        // আছে, অথচ নেই
        logger()->critical('রাতের ব্যাকআপ ব্যর্থ হয়েছে — হাতে দেখতে হবে।');
    });

/*
 * ⭐ পাহারা: শেষ সফল ব্যাকআপ কত পুরনো — আর সেটাই আজকের আসল শিক্ষা।
 *
 * ── কেন এটা উপরের `onFailure`-এর পরেও লাগে ──────────────────────────
 * `onFailure` ধরে **যখন কমান্ড চলে আর ব্যর্থ হয়**। ⛔ কিন্তু ছয় দিন ধরে
 * যা ঘটেছে তার কিছুই ওটা ধরত না: কমান্ডটা চলত, ব্যর্থ হত, আর কেউ জানত
 * না — কারণ সতর্কবার্তাটা যেত এমন এক লগে যা কেউ খোলে না।
 *
 * ⚠️ আর যদি cron নিজেই বন্ধ হয়ে যায়, বা `->when()` কোনোদিন সত্যি না হয়,
 * তখন `onFailure` **কোনোদিন ডাকাই হয় না** — নীরবতা তখন সাফল্যের মতোই
 * দেখায়।
 *
 * ⭐ তাই এই পাহারাটা কমান্ডের দাবি দেখে না, **ফাইলটা দেখে**: শেষ কাজের
 * ডাম্প ৪৮ ঘণ্টার বেশি পুরনো হলে চিৎকার করে।
 *
 * ⓘ দিনে দুইবার, কারণ একবার হলে ঐ একটা ডাকই মিস হলে আরেক দিন যেত।
 */
Schedule::command('abos:backup-fresh')
    ->twiceDaily(9, 21)
    ->withoutOverlapping()
    ->appendOutputTo(storage_path('logs/backup.log'));

/*
 * নির্ধারিত রিপোর্ট — প্রতি পনেরো মিনিটে "কার সময় হয়েছে" দেখে।
 *
 * এত ঘন ঘন, কারণ সূচির সময় যেকোনো মিনিট হতে পারে (সকাল ৮:০৭); ঘণ্টায়
 * একবার দেখলে ওই সূচিটা ৫৩ মিনিট দেরিতে চলত। withoutOverlapping — একটা
 * বড় রিপোর্ট চললে পরের রানটা তার ঘাড়ে চড়ে বসে না।
 */
Schedule::command('abos:reports-due')
    ->everyFifteenMinutes()
    ->withoutOverlapping()
    ->onFailure(function () {
        logger()->critical('নির্ধারিত রিপোর্ট চালানো ব্যর্থ হয়েছে — হাতে দেখতে হবে।');
    });

/*
 * ⛔ দ্বৈত-জমার টোকেনগুলো ছাঁটাই — রোজ একবার।
 *
 * ── কেন সারিগুলো জমে ─────────────────────────────────────────────────
 * প্রতিটা জমায় `submitted_forms`-এ একটা সারি বসে (রেন্ডারে নয় — সেটা
 * ইচ্ছাকৃত, নাহলে প্রতিটা পাতা দেখাও একটা সারি লিখত)। ⓘ দিনে কয়েকশো
 * জমা মানে বছরে লাখখানেক সারি — ছোট, কিন্তু অসীম নয় এমন কিছু রাখাই
 * ভালো।
 *
 * ── ⚠️ কেন খুব তাড়াতাড়ি মোছা যায় না ─────────────────────────────────
 * সারিটা কেবল দ্বৈত-জমা ঠেকায় না, **প্রথম জমার ফলটাও ধরে রাখে**
 * (`result_url`)। ⛔ তাড়াতাড়ি মুছলে কেউ পুরনো ট্যাব থেকে জমা দিলে
 * টোকেনটা আর চেনা যেত না, আর **নতুন একটা সারি তৈরি হত** — অর্থাৎ রোগটা
 * ফিরে আসত, শুধু দেরিতে আর আরও দুর্বোধ্যভাবে।
 *
 * ⭐ মেয়াদটা [[FormIsNotSubmittedTwice::KEEP_DAYS]]-এ, হাতে লেখা সংখ্যা
 * নয় — সেবাটাই জানে কতদিন তার নিজের সারি দরকার।
 */
Schedule::call(fn () => app(FormIsNotSubmittedTwice::class)->prune())
    ->dailyAt('02:10')
    ->name('submitted-forms-prune')
    ->withoutOverlapping();

/*
 * ⭐ কিউ সত্যিই চালানো — ১৭ সেপ্টেম্বর ২০২৬, নিরীক্ষার ধাপ ২।
 *
 * ── ⛔ কী ভাঙা ছিল ───────────────────────────────────────────────────
 * `QUEUE_CONNECTION=database`, `jobs` টেবিল আছে, কনফিগ নিখুঁত — আর
 * **কোনো ওয়ার্কার কোনোদিন চলেনি**। ⓘ তাই কেউ কিউ ব্যবহারও করেননি:
 * [[PasswordResetController]]-এ লেখা আছে চিঠিটা কিউতে দেওয়া যেত, কিন্তু
 * দিলে ওটা *"টেবিলে বসে থাকত আর কোনোদিন যেত না"*।
 *
 * ⚠️ এটা আজকের ব্যাকআপের রোগটারই যমজ: **ব্যবস্থাটা আছে বলে মনে হয়,
 * কিন্তু কিছুই করে না।** পরের কেউ `ShouldQueue` বসিয়ে দিলে কাজটা নীরবে
 * হারাত — কোনো ভুলবার্তা ছাড়াই, কারণ কিউতে ঢোকা মানেই সফল বলে ধরা হয়।
 *
 * ── ⓘ কেন `queue:work`, `--daemon` নয় ────────────────────────────────
 * শেয়ার্ড হোস্টিংয়ে (cPanel) কোনো supervisor নেই, আর দীর্ঘ প্রক্রিয়া
 * রাখা যায় না — হোস্ট ওটা মেরে ফেলে। ⭐ তাই প্রতি মিনিটে একবার এসে
 * **যা জমেছে তা শেষ করে চলে যাওয়া**, আর সেটাই cron-এর স্বভাবের সাথে মেলে।
 *
 *   --stop-when-empty   কাজ ফুরালেই বেরিয়ে যায়, বসে থাকে না
 *   --max-time=50       ৫০ সেকেন্ডের বেশি নয়, তাই পরের মিনিটে ঠোকাঠুকি হয় না
 *   --tries=3           সাময়িক ব্যর্থতা (SMTP আটকে যাওয়া) তিনবার চেষ্টা পায়
 *
 * ⓘ কিছু জমা না থাকলে খরচ কার্যত শূন্য — একটা PHP প্রক্রিয়া চালু হয়ে
 * সাথে সাথেই বেরিয়ে যায়।
 */
Schedule::command('queue:work --stop-when-empty --max-time=50 --tries=3')
    ->everyMinute()
    ->withoutOverlapping()
    ->appendOutputTo(storage_path('logs/queue.log'))
    ->onFailure(function () {
        /*
         * ⚠️ ব্যর্থ কাজ নীরবে `failed_jobs`-এ জমতে দেওয়া যায় না।

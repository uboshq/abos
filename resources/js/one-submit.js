/*
 * ⛔ একটা ফর্ম একবারই জমা — প্রথম স্তর, ১৩ সেপ্টেম্বর ২০২৬।
 *
 * ── কী ঘটেছিল ────────────────────────────────────────────────────────
 * মালিক মূলধনের ফর্মে Save-এ **দুইবার ক্লিক করেছেন**, আর `CAP-0001` ও
 * `CAP-0002` — দুইটা সারি বসেছে, ২৫,০০,০০০ টাকা দুইবার।
 *
 * ── ⭐ কেন `document`-এ, বোতামে নয় ───────────────────────────────────
 * প্রথম ছকটা ছিল "submit বোতাম নিষ্ক্রিয় করো", আর সেটা মেপে দেখে বাদ
 * গেছে। ⓘ গোনা হয়েছে:
 *
 *     x-ui.button type="submit"   ১৭৯
 *     <button type="submit">       ৪৯   ← কম্পোনেন্টের বাইরে
 *
 * ⛔ আর সবচেয়ে বড় ফাঁকটা সংখ্যায় নেই: **Enter চাপা**। একটা টেক্সট ঘরে
 * Enter দিলে ফর্ম জমা হয় **কোনো বোতামে ক্লিক না করেই** — বোতামের উপর
 * বসানো কোনো পাহারা সেটা ধরতেই পারে না। ⚠️ মালিক ক্লিক করেছিলেন, কিন্তু
 * পরের জন Enter চাপবেন।
 *
 * ⭐ `submit` ইভেন্টটা তিনটাই ধরে — ক্লিক, Enter, আর `form.submit()` ছাড়া
 * যেকোনো পথ — আর একটাই শ্রোতায়, ১৪৭টা পর্দার একটাও না ছুঁয়ে।
 *
 * ── ⚠️ এটা যথেষ্ট নয়, আর সেটা ইচ্ছাকৃত ──────────────────────────────
 * JavaScript বন্ধ থাকতে পারে, ধীর নেটে মানুষ রিফ্রেশ করে আবার জমা দিতে
 * পারেন, আর API সরাসরি ডাকা যায়। ⓘ তাই আসল পাহারাটা সার্ভারে —
 * [[App\Core\Services\FormIsNotSubmittedTwice]], যেখানে ডাটাবেসের ইউনিক
 * ইনডেক্স বিচার করে। এটা কেবল **প্রথম স্তর**: দ্বিতীয় অনুরোধটা যেন
 * সার্ভার পর্যন্তই না পৌঁছায়।
 */
export function guardOneSubmit (root = document) {
    root.addEventListener('submit', (event) => {
        const form = event.target

        if (!(form instanceof HTMLFormElement)) {
            return
        }

        /*
         * ⛔ অন্য কেউ জমাটা থামিয়েছে — তাহলে এটা জমা নয় (২৭ সেপ্টেম্বর ২০২৬)।
         *
         * ⓘ ফর্মের নিজের শ্রোতা (কারণ-জিজ্ঞাসা, খাতের পাহারা) এই শ্রোতার
         * **আগে** চলে। ⚠️ আগে এখানে সেটা দেখা হত না: কারণ ফাঁকা রেখে
         * "বাতিল" চাপলে ফর্মে "জমা হয়েছে" বসত আর বোতাম বন্ধ হত, আর কারণ
         * লিখে আবার চাপলেও জমা আটকে থাকত, পাতা রিফ্রেশ না করা পর্যন্ত।
         */
        if (event.defaultPrevented) {
            return
        }

        /*
         * ⓘ যে ফর্ম কিছু বদলায় না তার এই পাহারা লাগে না — খোঁজা, ছাঁকনি,
         * পাতা বদল সবই GET। ⚠️ ওদের আটকালে মানুষ দ্বিতীয়বার খুঁজতেই
         * পারতেন না।
         */
        if ((form.method || 'get').toLowerCase() !== 'post') {
            return
        }

        if (form.dataset.submitted === '1') {
            /*
             * ⛔ দ্বিতীয় জমা — এখানেই থামে, সার্ভার পর্যন্ত যায় না।
             */
            event.preventDefault()

            return
        }

        form.dataset.submitted = '1'

        /*
         * ⚠️ বোতামগুলো নিষ্ক্রিয় করা হয় **জমা ঠেকাতে নয়** — ওটা উপরের
         * পতাকাটাই করে — বরং মানুষকে দেখানোর জন্য যে কাজটা চলছে।
         *
         * ⓘ আর নিষ্ক্রিয়তা বসে `setTimeout`-এ, সাথে সাথে নয়: এই ইভেন্টের
         * ভেতরে বোতাম `disabled` করলে ব্রাউজার **ঐ বোতামের মানটা জমার সাথে
         * পাঠায় না**। যেসব ফর্মে একই ঘরে দুইটা বোতাম (`name="action"`
         * ধরনের) থাকে, তাদের কোনটা চাপা হলো সেটাই হারিয়ে যেত — আর সেটা
         * নীরব ভুল হত, কারণ ফর্মটা জমা হত ঠিকই, শুধু ভুল কাজ নিয়ে।
         */
        setTimeout(() => {
            form.querySelectorAll('button[type="submit"], input[type="submit"]')
                .forEach((button) => {
                    button.disabled = true
                    button.setAttribute('aria-busy', 'true')
                })
        }, 0)
    })
}

    ন'টায় নেই। ⚠️ কিন্তু পর্দায় `@if ($look === 'navy')` লেখা যাবে না —
    তাহলে রূপের নামটা ১০২টা পর্দায় ছড়িয়ে পড়ত, আর দশম রূপ যোগ করতে ওই
    একশোটা ফাইল খুলতে হত।


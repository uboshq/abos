<?php

declare(strict_types=1);

namespace App\Modules\Inventory\Services;

use App\Core\Support\CompanyContext;
use App\Modules\Inventory\Models\Batch;
use Illuminate\Support\Facades\DB;

/**
 * একটা লটের সাথে কত ফ্রি এসেছিল — আর তাই কত ফ্রি দেওয়া যায়।
 *
 * ── ⭐ মালিকের নিয়ম, ২২ সেপ্টেম্বর ২০২৬ ─────────────────────────────
 * *"যে স্লট যেভাবে কেনা, সেইভাবে যাবে।"* ⓘ সরবরাহকারী যে অনুপাতে ফ্রি
 * দিয়েছেন, বিক্রিতেও সেই অনুপাত — **আর এক কার্টনও বেশি নয়।**
 *
 * ── ⓘ কেন অনুপাতটা পণ্যের নয়, লটের ─────────────────────────────────
 * একই পণ্য বহুবার কেনা হয়, আর প্রতিবার অনুপাত এক নাও হতে পারে:
 * জানুয়ারিতে ১০-এ ১, মার্চে ১২-এ ১, মে-তে কিছুই না।
 *
 * ⛔ পণ্যের গায়ে একটা সংখ্যা বসালে প্রশ্ন উঠত *"আজ কোনটা?"* — আর যে
 * উত্তরই বাছা হত, সেটা কোনো না কোনো দিন মিথ্যা হত। ⭐ লট ধরে হিসাব
 * করলে প্রশ্নটাই উবে যায়: **প্রতিটা কার্টন নিজের ইতিহাস নিজে বহন করে।**
 *
 * ── ⚠️ কোন ঘর দেখা হয়, আর কেন ─────────────────────────────────────
 * আসার সারিতে টাকার মাল বসে `unplaced_change`-এ আর ফ্রি মাল বসে
 * `unplaced_free_change`-এ — ক্রয়ের **তিনটা পথেই** (বিল · রসিদ ·
 * সরাসরি ক্রয়, শেষেরটা ভিতরে বিলের সেবাই ডাকে)।
 *
 * ⛔ `floor_change` দেখা যেত না: বসানোর সারি `unplaced` থেকে `floor`-এ
 * সরায়, তাই একই মাল **দুইবার** গোনা হত।
 *
 * ⓘ আর কেবল **ধনাত্মক** সারি — ঋণাত্মকগুলো ফেরত বা বাতিল, আর ওরা
 * "কত এসেছিল" প্রশ্নের উত্তর বদলায় না।
 */
final class FreeRatio
{
    /**
     * ⓘ এই উৎসগুলো দিয়েই মাল **ঢোকে**। বিক্রয় বা বদলির সারি এখানে
     * গোনা হয় না — ওরা মাল সরায়, আনে না।
     */
    private const ARRIVES_FROM = ['purchase_bill', 'purchase_receipt'];

    /**
     * এই লটে কত টাকার মাল আর কত ফ্রি এসেছিল।
     *
     * @return array{paid: string, free: string}
     */
    public function arrivedIn(Batch $batch): array
    {
        $row = DB::table('inv_stock_movements')
            ->where('company_id', CompanyContext::id())
            ->where('batch_id', $batch->id)

            /*
             * ⚠️ `:free` লেজটাও ধরতে হয়, তাই হুবহু মিল নয়।
             *
             * ⓘ ফ্রি মাল আসে নিজের উৎস-নামে (`purchase_bill:free`),
             * আর ওটা বাদ পড়লে প্রতিটা লটের ফ্রি শূন্য দেখাত — অর্থাৎ
             * গোটা নিয়মটাই নীরবে অকেজো থাকত।
             */
            ->where(function ($q) {
                foreach (self::ARRIVES_FROM as $source) {
                    $q->orWhere('source_type', $source)
                        ->orWhere('source_type', 'like', $source.':%');
                }
            })
            ->selectRaw('COALESCE(SUM(GREATEST(unplaced_change, 0)), 0) as paid')
            ->selectRaw('COALESCE(SUM(GREATEST(unplaced_free_change, 0)), 0) as free')
            ->first();

        return [
            'paid' => (string) ($row->paid ?? '0'),
            'free' => (string) ($row->free ?? '0'),
        ];
    }

    /**
     * এই লট থেকে এতটা মাল গেলে সর্বোচ্চ কত ফ্রি দেওয়া যায়।
     *
     * ── ⭐ মালিকের তিনটা নিয়ম, তিনটাই এখানে ─────────────────────────
     * ① *"যে পণ্য কখনো ফ্রি আসেনি, তাতে ফ্রি দেওয়া যাবে না"* — লটে ফ্রি
     *   না এলে উত্তর শূন্য।
     * ② *"অনুপাতের বেশি নয়"* — এটাই সিলিং।
     * ③ *"ভাঙাতে ফ্রি না দেওয়াই ভালো"* — নিচের দিকে গোনা।
     *
     * ── ⚠️ কেন নিচের দিকে ──────────────────────────────────────────
     * প্রাপ্য ১.৫ কার্টন মানে দেড় কার্টন, আর **দেড় কার্টন ফ্রি দেওয়ার
     * কোনো বাস্তব রূপ নেই** — একটা কার্টন কেটে অর্ধেক দিলে সেটা আর ফ্রি
     * কার্টন থাকে না, খোলা মাল হয়ে যায়, আর মেয়াদ-ফেরত-গুদাম সব হিসাব
     * ঘেঁটে যায়।
     *
     * ⓘ মালিকের মূল নীতির সাথেও মেলে: *"কোনোভাবেই বেশি নয়।"*
     *
     * ── ⛔ আর এটা যা বলে **না** ────────────────────────────────────
     * ⚠️ এটা বলে *"নিয়মে কত পাওনা"*, *"ভাণ্ডারে আছে কি না"* নয়। ⓘ লটে
     * ফ্রি মাল ফুরিয়ে গেলে এই সংখ্যাটা তবু পাওনা দেখাবে — **দুইটা আলাদা
     * সীমা, আর যেটা ছোট সেটাই আসল।** ভাণ্ডারের দিকটা দেখে
     * [[Batch::freeBalance()]]।
     */
    public function allowedOn(Batch $batch, string $qty): string
    {
        $came = $this->arrivedIn($batch);

        if (bccomp($came['free'], '0', 4) <= 0 || bccomp($came['paid'], '0', 4) <= 0) {
            return '0';
        }

        if (bccomp($qty, '0', 4) <= 0) {
            return '0';
        }

        /*
         * ⓘ গুণ আগে, ভাগ পরে — উল্টো করলে অনুপাতটা আগে ভগ্নাংশ হয়ে
         * যেত আর গোল করতে গিয়ে সংখ্যাটা নড়ত। ⚠️ চার ঘর নিয়ে কাজ,
         * তারপর একবারই নিচের দিকে।
         */
        $earned = bcdiv(bcmul($qty, $came['free'], 8), $came['paid'], 8);

        return $this->downTo($earned);
    }

    /**
     * নিচের দিকে গোনা — bcmath-এ নিজের হাতে, কারণ সে গোল করে না কাটে।
     *
     * ⚠️ `floor()` ব্যবহার করা যেত না: ওটা float, আর টাকার মতো
     * পরিমাণেও float-এর গোলমাল একই — ০.৯৯৯৯৯৯৯ কে ১ ভেবে বসত।
     */
    private function downTo(string $value): string
    {
        $at = strpos($value, '.');

        return $at === false ? $value : substr($value, 0, $at);
    }
}

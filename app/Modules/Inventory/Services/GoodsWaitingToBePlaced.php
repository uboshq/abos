<?php

declare(strict_types=1);

namespace App\Modules\Inventory\Services;

use App\Core\Support\CompanyContext;
use Illuminate\Support\Facades\DB;

/**
 * কয়টা কাগজের মাল এখনো বসানো হয়নি — মেনুর ব্যাজের সংখ্যাটা।
 *
 * ── মালিকের আপত্তি থেকে জন্ম, ৫ সেপ্টেম্বর ২০২৬ ──────────────────────
 * সরাসরি ক্রয়ের পর্দায় একটা **স্থায়ী** নোটিশ বসানো ছিল: *"মাল ঢোকে
 * বসানো হয়নি অবস্থায়। Inventory ▸ স্টক প্লেসমেন্ট-এ গিয়ে বসিয়ে
 * দিন…"*। তিনি ধরলেন — *"এটার জন্য Notice board আছে কেন? All time
 * Notice চলছে কী জন্য?"*
 *
 * ⚠️ যে লেখা রোজ ওঠে তা কেউ পড়ে না, আর তখন একই জায়গার **আসল**
 * সতর্কতাগুলোও পড়া বন্ধ হয়ে যায়। ⓘ জায়গাটাও ভুল ছিল: লেখাটা কেনার
 * **আগে**, অথচ ঘটনাটা ঘটে কেনার **পরে**।
 *
 * ⭐ **সংখ্যা তথ্য, বাক্য উপদেশ।** "৩" দেখলে মানুষ ক্লিক করেন; একটা
 * উপদেশ পড়ে কেউ কিছু করেন না। আর শূন্য হলে ব্যাজই থাকে না — অর্থাৎ
 * যেদিন কিছু পড়ে নেই, সেদিন পর্দায় কোনো শব্দও নেই।
 *
 * ── ⚠️ কেন কাগজ গোনা হয়, পরিমাণ নয় ─────────────────────────────────
 * গুদামের লোকের প্রশ্ন *"আজ কয়টা কাগজ বাকি"*, *"কত কার্টন বাকি"* নয় —
 * তিনি কাগজ ধরে ধরে বুঝে নেন ([[StockPlacementController]] তালিকাটাও
 * কাগজ ধরেই সাজায়)। ⛔ কার্টন গুনলে সংখ্যাটা হাজার ছাড়াত আর ব্যাজে
 * ধরত না, অথচ কাজ হয়তো দুইটা কাগজের।
 */
final class GoodsWaitingToBePlaced
{
    /**
     * ⓘ নামটা `pendingCount()` — [[MenuBuilder::badge()]] এই নামেই ডাকে।
     * অন্য যেকোনো সেবা একই নাম দিলে তার সারিতেও ব্যাজ বসবে, আর কোরে
     * কোনো মডিউলের নাম লিখতে হবে না।
     */
    public function pendingCount(): int
    {
        $companyId = CompanyContext::id();

        if ($companyId === null) {
            return 0;
        }

        /*
         * ⚠️ শর্তটা [[StockPlacementController::waiting()]]-এর হুবহু
         * একই — `SUM(unplaced) > 0 OR SUM(unplaced_free) > 0`, উৎস ধরে
         * দলবদ্ধ।
         *
         * ⛔ দুইটা আলাদা করে লিখলে একদিন ব্যাজ বলত "৩", আর পর্দা খুলে
         * পাওয়া যেত দুইটা — আর তখন কোনটা সত্যি তা বলার উপায় থাকত না।
         * ⓘ ফ্রি মালও গোনা হয়, কারণ ফ্রি কার্টনও বসাতে হয়।
         */
        return DB::table('inv_stock_movements')
            ->where('company_id', $companyId)
            ->groupBy('source_type', 'source_id')
            ->havingRaw('SUM(unplaced_change) > 0 OR SUM(unplaced_free_change) > 0')
            ->select('source_type', 'source_id')
            ->get()
            ->count();
    }
}

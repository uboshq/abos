<?php

declare(strict_types=1);

namespace App\Modules\Inventory\Services;

use App\Modules\Inventory\Models\Batch;
use App\Modules\Inventory\Models\Product;
use App\Modules\Inventory\Models\Warehouse;

/**
 * এই বিক্রিতে সর্বোচ্চ কত ফ্রি দেওয়া যায় — লটগুলো ধরে ধরে।
 *
 * ── ⭐ মালিকের নিয়ম, ২২ সেপ্টেম্বর ২০২৬ ─────────────────────────────
 * *"যে স্লট যেভাবে কেনা, সেইভাবে যাবে… ফ্রি কম দিতে পারবে কিন্তু কোন
 * ভাবেই বেশি দিতে পারবে না।"*
 *
 * ── ⓘ [[FreeRatio]]-র সাথে পার্থক্য ─────────────────────────────────
 * ওটা **একটা লটের** কথা বলে। ⚠️ কিন্তু একটা বিক্রি প্রায়ই **কয়েকটা
 * লট জুড়ে** যায় — পঞ্চাশ কার্টন চাইলে পুরনো লটে তিরিশ, পরেরটায় বিশ।
 *
 * ⭐ আর লট দুইটার অনুপাত আলাদা হতে পারে: প্রথমটা ১০-এ ১, দ্বিতীয়টায়
 * ফ্রি নেই। ⓘ তাই প্রাপ্যটা **যোগফল** — প্রতিটা লট থেকে যতটা মাল
 * যাচ্ছে, ঠিক ততটার প্রাপ্য।
 *
 * ── ⚠️ লটের ক্রম এখানে ঠিক হয় না ───────────────────────────────────
 * [[BatchAllocator]] যে ক্রমে লট বাছে, এটা ঠিক সেই ক্রমেই হাঁটে — আর
 * সেটাই হওয়া উচিত। ⛔ দুই জায়গায় দুই ক্রম থাকলে পর্দা এক সংখ্যা
 * দেখাত আর বিক্রি আরেকটা মাল বের করত, আর কেউ মিলিয়ে দেখত না।
 *
 * ── ⓘ আর এটা ভাণ্ডারের কথা বলে না ──────────────────────────────────
 * ⚠️ উত্তরটা *"নিয়মে কত পাওনা"*, *"ফ্রি ভাণ্ডারে আছে কি না"* নয়।
 * ⓘ দুইটা আলাদা সীমা, আর যেটা ছোট সেটাই আসল — ভাণ্ডারের দিকটা
 * [[BatchAllocator::allocateFree()]] নিজেই আটকায়, মাল না থাকলে।
 */
final class FreeAllowance
{
    public function __construct(
        private readonly BatchAllocator $batches,
        private readonly FreeRatio $ratio,
    ) {}

    /**
     * এতটা মাল বেচলে সর্বোচ্চ কত ফ্রি দেওয়া যায়।
     *
     * ⚠️ লট ধরা না থাকলে উত্তর শূন্য — আর সেটাই মালিকের নিয়ম।
     * ⓘ *"লট ছাড়া মাল ঢুকবেও না, বেরোবেও না"*; লট না থাকলে *"কোন
     * চালানের মাল"* প্রশ্নের উত্তর নেই, তাই অনুপাতেরও উত্তর নেই।
     */
    public function on(Product $product, Warehouse $warehouse, string $qty): string
    {
        if (! $product->track_batch) {
            return '0';
        }

        if (bccomp($qty, '0', 4) <= 0) {
            return '0';
        }

        $total = '0';

        /*
         * ⓘ `allocate()` কেবল পড়ে — সে কোনো সারি লেখে না, কেবল বলে
         * কোন লট থেকে কতটা যেত। ⚠️ তাই বিল সেভ হওয়ার **আগেই** এটা
         * নিরাপদে জিজ্ঞেস করা যায়।
         */
        foreach ($this->batches->allocate($product, $warehouse, $qty) as $slice) {
            $total = bcadd(
                $total,
                $this->ratio->allowedOn($slice['batch'], (string) $slice['qty']),
                4,
            );
        }

        return $total;
    }

    /**
     * ⭐ **বাছা** লটের অনুপাতে কত ফ্রি — ২৫ সেপ্টেম্বর ২০২৬।
     *
     * ── ⛔ কেন [[on()]] দিয়ে চলে না ────────────────────────────────
     * ওটা FEFO ধরে ঠিক করে *কোন* লট থেকে মাল যেত, আর সেই লটগুলোর
     * অনুপাত যোগ করে। ⚠️ কিন্তু মালিকের সিদ্ধান্তে বিক্রেতা এখন লট
     * **নিজে বাছেন**, আর মাল ঐ লট থেকেই বেরোয়।
     *
     * ⛔ ফলে `on()` এমন একটা লটের অনুপাত বলত যা এই বিলে ছোঁয়াই হবে
     * না — আর সংখ্যাটা দেখতে নিখুঁত লাগত। ⓘ দুইটা লটের অনুপাত এক
     * হলে কেউ টের পেত না; আলাদা হলে ফ্রি ভুল বসত, নীরবে।
     *
     * @return array{allowed: string, short: string}
     *         `allowed` — এই পরিমাণে যত ফ্রি পাওনা
     *         `short`   — আর কতটা নিলে পরের ফ্রি
     */
    public function onLot(Batch $batch, string $qty): array
    {
        if (bccomp($qty, '0', 4) <= 0) {
            return ['allowed' => '0', 'short' => '0'];
        }

        return [
            'allowed' => $this->ratio->allowedOn($batch, $qty),
            'short' => $this->ratio->shortOfNextFree($batch, $qty),
        ];
    }
}

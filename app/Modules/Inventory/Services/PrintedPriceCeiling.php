<?php

declare(strict_types=1);

namespace App\Modules\Inventory\Services;

use App\Modules\Inventory\Models\Batch;
use Illuminate\Validation\ValidationException;

/**
 * প্যাকেটে ছাপা দামের উপরে বেচা যায় না।
 *
 * ── কেন এটার কোনো সুইচ নেই ───────────────────────────────────────────
 * ABOS-এর প্রায় প্রতিটা ঐচ্ছিক নিয়মের একটা Control Panel সুইচ আছে
 * (নিয়ম ৭)। এটার নেই, আর থাকবেও না: **কোম্পানি আইন বন্ধ করতে পারে না।**
 * সুইচ থাকলে একদিন কেউ "আজকের জন্য" বন্ধ করত, আর সেই দিনটার বিক্রয়
 * খাতায় বৈধ দেখাত।
 *
 * ── কেন ব্যাচ ধরে, পণ্য ধরে নয় ───────────────────────────────────────
 * প্রস্তুতকারক দুই উৎপাদনের মাঝে দাম বদলে ছাপেন, তাই একই ড্রয়ারে
 * পুরনো পাতায় ৳২০ আর নতুনটায় ৳২২। পণ্য-স্তরের একটা সিলিং হলে দুইটার
 * একটা ভুল হত — আর ভুলটা হত ওই দিকে যেদিকে **পুরনো পাতা নতুন দামে
 * বেচা হয়**, অর্থাৎ বেআইনি বিক্রয়টা পর্দায় সঠিক দেখাত।
 *
 * ── ছাড়ের পরের দাম দেখা হয়, আগেরটা নয় ──────────────────────────────
 * ক্রেতা যা দেন সেটাই দাম। ছাড়ের আগের অঙ্ক দেখলে ৳২৫ দর আর ঋণাত্মক
 * ছাড় বসিয়ে ৳২৫-এ বেচা যেত, আর নিয়মটা কাগজে টিকে থাকত।
 */
class PrintedPriceCeiling
{
    /**
     * এই লটের মাল এই দামে বেচা যাবে কি না।
     *
     * @param  string  $unitPrice  ক্রেতা প্রতি এককে যা দেবেন — ছাড়ের **পরে**
     *
     * @throws ValidationException দাম ছাপা দামের উপরে হলে
     */
    public function assertWithin(Batch $batch, string $unitPrice): void
    {
        $ceiling = $batch->mrp;

        /*
         * ছাপা দাম না থাকলে কোনো সিলিং নেই।
         *
         * বেশিরভাগ ব্যবসা মালের গায়ে দাম ছাপেই না — চাল, সাবান,
         * বিস্কুট। ওখানে দাম বিক্রেতার সিদ্ধান্ত, আর একটা কাল্পনিক
         * সিলিং বসালে সাধারণ ব্যবসাই আটকে যেত।
         */
        if ($ceiling === null) {
            return;
        }

        if (bccomp($unitPrice, (string) $ceiling, 4) <= 0) {
            return;
        }

        throw ValidationException::withMessages([
            'rate' => __('inventory::validation.above_printed_price', [
                'batch' => $batch->batch_no,
                'mrp' => rtrim(rtrim((string) $ceiling, '0'), '.'),
                'asked' => rtrim(rtrim($unitPrice, '0'), '.'),
            ]),
        ]);
    }

    /**
     * ছাড় বাদ দেওয়ার পর প্রতি এককে ক্রেতা কত দিচ্ছেন।
     *
     * ── কেন এটা এখানে, ডাকা কোডে নয় ─────────────────────────────────
     * প্রতিটা ডাকা জায়গা নিজে হিসাব করলে একদিন একটা জায়গা ছাড়টা
     * বাদ দিতে ভুলত, আর ঠিক ওই পথেই সিলিং পেরোনো যেত। এক জায়গায়
     * রাখলে ভুলটা একবারই সম্ভব, আর সেটা এখানে ধরা।
     *
     * পরিমাণ শূন্য হলে `null` — শূন্য দিয়ে ভাগ করা যায় না, আর শূন্য
     * পরিমাণের কোনো দামও নেই। ডাকা কোড তখন সিলিং দেখারই দরকার নেই।
     */
    public function netUnitPrice(string $qty, string $rate, string $discount = '0'): ?string
    {
        if (bccomp($qty, '0', 4) <= 0) {
            return null;
        }

        $gross = bcmul($qty, $rate, 4);
        $net = bcsub($gross, $discount, 4);

        /*
         * ছাড় দামের চেয়ে বেশি হলে নিট ঋণাত্মক — আর ঋণাত্মক দাম
         * সিলিংয়ের নিচে বলে "ঠিক আছে" হয়ে যেত। কিন্তু ওটা আলাদা
         * সমস্যা (কেউ টাকা ফেরত দিয়ে মাল দিচ্ছেন), আর সেটা ধরার
         * জায়গা বিক্রয়ের নিজের যাচাই, এই নিয়ম নয়। এখানে শূন্যে
         * থামানো হয় যাতে ঋণাত্মক অঙ্ক সিলিং পেরোনোর ফাঁক না হয়।
         */
        if (bccomp($net, '0', 4) < 0) {
            $net = '0';
        }

        return bcdiv($net, $qty, 4);
    }

    /**
     * পুরো একটা লাইন — বাছাই করা লট ধরে ধরে।
     *
     * FEFO একটা বিক্রয়কে কয়েকটা লটে ভাগ করে, আর **প্রতিটা লটের নিজের
     * ছাপা দাম আলাদা হতে পারে**। পুরনো লটের সিলিং ৳২০ আর নতুনটার ৳২২
     * হলে, ৳২১ দরে বেচা নতুন লটের জন্য বৈধ আর পুরনোটার জন্য নয় —
     * তাই প্রতিটা ভাগ আলাদা করে দেখা হয়।
     *
     * @param  list<array{batch: Batch, qty: string}>  $allocation
     */
    public function assertAllocationWithin(array $allocation, string $unitPrice): void
    {
        foreach ($allocation as $row) {
            $this->assertWithin($row['batch'], $unitPrice);
        }
    }
}

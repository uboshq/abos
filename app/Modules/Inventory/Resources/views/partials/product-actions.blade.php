{{--
    পণ্যের সারির কাজগুলো — একটা বোতাম, ভেতরে তালিকা।

    মালিকের নির্দেশ (৩ সেপ্টেম্বর ২০২৬): তালিকার ডান কলামে একটা
    "Action" ড্রপডাউন — সম্পাদনা · সক্রিয় · নিষ্ক্রিয় · ইত্যাদি।
    আগে কলামটা ছিলই না, তাই একটা পণ্য সম্পাদনা করতে হলে আগে তার
    পাতায় ঢুকতে হত।

    ── ⚠️ "মুছে ফেলা" এখানে নেই, আর কারণটা লিখে রাখা দরকার ─────────────
    মালিকের তালিকায় "মুছে ফেলা" ছিল। কিন্তু আজকের `destroy()` রুটটা
    **মোছে না** — সে `ProductService::deactivate()` ডাকে, অর্থাৎ পণ্যটা
    নিষ্ক্রিয় হয়, টেবিলে থেকে যায়।

    তাই ওই বোতামটায় "মুছে ফেলা" লিখলে **পর্দাটা মিথ্যা বলত**: কেউ
    ক্লিক করে ভাবতেন পণ্যটা চলে গেছে, অথচ সে তালিকাতেই আছে — শুধু
    "নিষ্ক্রিয় দেখান" টিক দিলে ফিরে আসে। আর যিনি সত্যিই মুছতে
    চেয়েছিলেন, তিনি ভাবতেন কাজ হয়ে গেছে।

    ⓘ পণ্যের ক্ষেত্রে **নিষ্ক্রিয় করাটাই আসলে ঠিক কাজ** (নিয়ম ৫):
    যে পণ্যের নামে একটাও চলাচল বা বিল আছে, তাকে সত্যিই মুছে দিলে
    পুরনো প্রতিটা সারি এমন কিছুর দিকে দেখাত যা আর নেই — আর সেটা ধরা
    পড়ত ছয় মাস পর, কোনো রিপোর্ট খুলতে গিয়ে।

    সত্যিকারের soft delete দরকার হলে সেটা `ProductService`-এ নতুন
    মেথড ও নতুন রুট চায়। **সেটা আমার ফাইল নয়, আর মালিকের সিদ্ধান্তও
    নেওয়া হয়নি** — তাই এখানে যা আছে তা-ই সৎ ভাষায় লেখা।

    ── কেন `:items`, স্লট নয় ───────────────────────────────────────────
    `x-ui.row-actions` কেবল `items` prop আঁকে, `$slot` নয়। স্লট দিয়ে
    ডাকলে বোতামটা **নীরবে অদৃশ্য** থাকে — কোনো ত্রুটি ছাড়াই।

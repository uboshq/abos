<?php

declare(strict_types=1);

namespace App\Modules\Promotion\Support;

/**
 * শর্ত মিললে ক্রেতা কী পান — স্পেকের ৬ নম্বর ধারার চতুর্থ ধাপ।
 *
 * ── ⚠️ কেন এটা [[PromotionType]] থেকে আলাদা ─────────────────────────
 * ⓘ প্রথমে মনে হয় দুইটা এক জিনিস — *"Buy X Get Y"* তো একটা ধরনও বটে,
 * সুবিধাও বটে। ⛔ কিন্তু একটা অফারের **অনেক** সুবিধার সারি থাকতে পারে,
 * অথচ ধরন একটাই।
 *
 * ⭐ স্ল্যাবই সবচেয়ে পরিষ্কার উদাহরণ: ধরন `quantity_slab`, আর সুবিধা
 * তিনটা সারি — ৫০-এ ২%, ১০০-এ ৫%, ২০০-এ ৮%। ⓘ ধরন বলে *"কীভাবে
 * পড়তে হবে"*, সুবিধা বলে *"কত"*।
 */
enum BenefitKind: string
{
    /** §৭-ক — শতকরা ছাড়। */
    case PERCENT = 'percent';

    /** §৭-খ — নির্দিষ্ট টাকার ছাড়। */
    case AMOUNT = 'amount';

    /**
     * §৭-গ/ঝ — মাল, টাকা নয়।
     *
     * ⛔ এখানেই মজুদ নড়ে: উপহারের পণ্য **আসল পণ্য**, আর সে গুদাম থেকে
     * কমে (§৮)। ⚠️ তাই এই সুবিধার সারিতে পণ্য, পরিমাণ আর একক — তিনটাই
     * লাগে, আর তিনটাই `nullable` নয়।
     */
    case GOODS = 'goods';

    /** §৭-ট — পরের কেনাকাটার জন্য জমা। */
    case CREDIT = 'credit';

    /** §৭-ঠ — পয়েন্ট। */
    case POINTS = 'points';

    /**
     * ⭐ এই সুবিধা দিলে মজুদ কমে কি না।
     *
     * ⚠️ প্রশ্নটা ইঞ্জিনের জন্য দামি: ⓘ মাল দিলে গুদাম, লট আর মূল্যায়ন
     * তিনটাই লাগে, আর উপহারটা সংরক্ষণ করতে হয় (§৮)। ⛔ ছাড়ে কেবল টাকা
     * কমে, মজুদ অক্ষত থাকে।
     */
    public function movesStock(): bool
    {
        return $this === self::GOODS;
    }

    /**
     * ⭐ দুইটা সুবিধার মধ্যে কোনটা ক্রেতার জন্য বড়।
     *
     * ── ⚠️ কেন এটা এখানে উত্তর দেওয়া যায় না ────────────────────────
     * ⛔ *"৫% ছাড়"* আর *"১ কার্টন ফ্রি"* — কোনটা বড়? ⓘ উত্তরটা নির্ভর
     * করে বিলের অঙ্ক আর পণ্যের দামের উপর, অর্থাৎ **প্রসঙ্গের** উপর।
     *
     * ⚠️ তাই তুলনাটা এখানে নয়, ইঞ্জিনে — যেখানে দুইটাকেই টাকায় নামিয়ে
     * মেলানো যায়। ⓘ এখানে কেবল বলা থাকল যে তুলনাটা দরকার, নাহলে
     * *"সবচেয়ে ভালোটা"* ([[PromotionCombines::BEST]]) কথাটার কোনো মানে
     * থাকে না।
     */
    public function needsPricingToCompare(): bool
    {
        return $this !== self::AMOUNT;
    }

    public function label(): string
    {
        return __('promotion::benefit.'.$this->value);
    }
}

<?php

declare(strict_types=1);

namespace App\Modules\Promotion\Support;

/**
 * একটা অফার কোন শর্তে খাটে — স্পেকের ৬ নম্বর ধারার তৃতীয় ধাপ।
 *
 * ── ⭐ স্পেকের চারটা দল ──────────────────────────────────────────────
 * পরিমাণ · মূল্য · পণ্য-শ্রেণি · সময়। ⓘ ক্রেতার শর্তটা এখানে নেই, আর
 * সেটা ইচ্ছাকৃত: *"কে পাবেন"* একটা **সুযোগের** প্রশ্ন, শর্তের নয় —
 * তার জায়গা [[ScopeKind]]।
 *
 * ── ⚠️ তফাতটা দামি, আর ওটা না ধরলে ইঞ্জিন ভুল উত্তর দেয় ─────────────
 * ⓘ সুযোগ ঠিক করে অফারটা **এই বিলের জন্য আদৌ কি না** — ভুল ক্রেতা
 * হলে অফারটা তালিকাতেই আসে না। ⛔ শর্ত ঠিক করে **কতটা কিনলে** সুবিধাটা
 * খোলে — আর ওটা না মিললে অফারটা তালিকায় থাকে, কিন্তু *"আর ৮ কার্টন
 * নিলে"* বলে (§১০-এর Almost Eligible)।
 *
 * ⚠️ দুইটাকে এক ধরলে ভুল ক্রেতাকেও *"আর ৮ কার্টন নিন"* বলা হত — অর্থাৎ
 * এমন একটা অফারের দিকে ঠেলা যেটা তিনি কোনোদিনই পেতেন না।
 */
enum ConditionKind: string
{
    /** §৬ — ন্যূনতম/সর্বোচ্চ পরিমাণ। *"১০ কার্টন কিনলে"*। */
    case QUANTITY = 'quantity';

    /** §৬ — বিলের টাকার অঙ্ক। *"৫০,০০০ টাকার উপরে"*। */
    case VALUE = 'value';

    /**
     * §৬ — নির্দিষ্ট পণ্য বা শ্রেণি থেকে কেনা।
     *
     * ⓘ এটা সুযোগের পণ্য-ছাঁকনি থেকে আলাদা: ⚠️ সুযোগ বলে *"এই অফারটা
     * কোন পণ্যে খাটে"*, আর এই শর্ত বলে *"অফারটা খুলতে হলে **এই** পণ্যটা
     * কিনতেই হবে"* — Buy A Get B-তে A।
     */
    case PRODUCT = 'product';

    /**
     * §৬ — সপ্তাহের দিন বা দিনের সময়।
     *
     * ⛔ এটা অফারের **মেয়াদ** নয়। ⓘ মেয়াদ বসে `promotions`-এর
     * `starts_on`/`ends_on`/`starts_at`/`ends_at`-এ — অফার কবে শুরু আর
     * কবে শেষ। ⚠️ এই শর্তটা *"রোজ দুপুর ১২টা–৩টা"* বা *"কেবল শুক্রবার"*,
     * যা মেয়াদের **ভিতরে** বারবার ফিরে আসে।
     */
    case TIME = 'time';

    public function label(): string
    {
        return __('promotion::condition.'.$this->value);
    }
}

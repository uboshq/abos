/**
 * টাকা আর পরিমাণের ঘরের যাচাই — এক জায়গায়।
 *
 * ── ⚠️ কেন কেবল `numeric` যথেষ্ট নয় ─────────────────────────────────
 * ⓘ পর্যালোচনায় ধরা (২৭ সেপ্টেম্বর): `numeric` নিয়ম `1e5` মেনে নেয়।
 * ⛔ কিন্তু bcmath বৈজ্ঞানিক রূপ চেনে না — ছুঁড়ে ফেলে, আর পাতাটা ৫০০
 * দেয়; কাউন্টারের প্রশ্নে JSON ৪২২-এর বদলে HTML ৫০০, যা পর্দা "কোনো
 * অফার নেই" পড়ত।
 *
 * ⭐ তাই প্রতিটা দরজা এই একটা নিয়মই বসায় — আলাদা আলাদা লিখলে একদিন
 * একটায় বদলাত, বাকিগুলোয় নয়।
 */
final class Decimal
{
    /** ⓘ ১৪ অঙ্ক পর্যন্ত, দশমিকের পরে ৪ — টেবিলের `decimal(18,4)`-এর সমান */
    public const RULE = 'regex:/^\d{1,14}(\.\d{1,4})?$/';
}

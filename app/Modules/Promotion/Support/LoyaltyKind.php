<?php

declare(strict_types=1);

namespace App\Modules\Promotion\Support;

/**
 * পয়েন্টের খাতার সারির ধরন — স্পেক §৭-ঠ ও §১৩।
 *
 * ⭐ চারটাই, আর পঞ্চম নেই: ⓘ *"সংশোধন"* নামে কোনো ধরন নেই, কারণ খাতায়
 * সংশোধন মানে একটা উল্টো সারি (`reverse`)। ⛔ হাতে সংখ্যা বসানোর ধরন
 * থাকলে একদিন কেউ ব্যালান্স মেলাতে ওটা দিয়ে পয়েন্ট বানিয়ে দিতেন —
 * কারণ ছাড়া, কাগজ ছাড়া।
 */
enum LoyaltyKind: string
{
    /** ⓘ অফার থেকে পয়েন্ট এল — ধনাত্মক। */
    case EARN = 'earn';

    /** ⓘ ক্রেতা পয়েন্ট খরচ করলেন — ঋণাত্মক। */
    case REDEEM = 'redeem';

    /** ⓘ মেয়াদ ফুরোল — ঋণাত্মক, কোন অর্জনের বিরুদ্ধে তা লেখা থাকে। */
    case EXPIRE = 'expire';

    /**
     * ⓘ বিল বাতিল — আগের সারির উল্টো।
     *
     * ⚠️ অর্জনের ফেরত ঋণাত্মক, খরচের ফেরত ধনাত্মক। ⓘ চিহ্নটা সারিতে
     * থাকে, তাই যোগফল সবসময় ঠিক।
     */
    case REVERSE = 'reverse';

    public function label(): string
    {
        return __('promotion::loyalty.kind.'.$this->value);
    }
}

<?php

declare(strict_types=1);

namespace App\Modules\Promotion\Support;

/**
 * একটা অফার তার জীবনে যে অবস্থাগুলোয় থাকতে পারে।
 *
 * ── ⭐ মালিকের স্পেক, ২৫ সেপ্টেম্বর ২০২৬, ধারা ৫ ও ১৪ ────────────────
 * তালিকার অবস্থা: *Draft · Pending Approval · Approved · Active · Paused
 * · Expired · Cancelled*। আর অনুমোদনের পথ: *খসড়া → জমা → বিক্রয়
 * ব্যবস্থাপক → বিক্রয় প্রধান → অর্থ → অনুমোদিত → সক্রিয়*।
 *
 * ── ⓘ কেন "Pending Approval" এখানে `SUBMITTED` ───────────────────────
 * স্পেকের দুইটা তালিকা একই জিনিসকে দুই নামে ডাকে: তালিকার পর্দায়
 * *"Pending Approval"*, আর কর্মপ্রবাহে *"Submitted"*। ⛔ দুইটা আলাদা
 * অবস্থা বানালে একই অফার কোথাও একটায় আর কোথাও অন্যটায় পড়ত, আর গোনায়
 * দুইবার আসত। ⓘ নামটা পর্দায় অনূদিত হয়; অবস্থা একটাই।
 *
 * ── ⚠️ কেন অবস্থাটা enum-এ, স্ট্রিং কলামে নয় ────────────────────────
 * ⓘ স্ট্রিং হলে `'aproved'` লেখা যেত, আর সারিটা চিরকাল এমন একটা
 * অবস্থায় বসে থাকত যা কোনো কোড চেনে না। ⛔ অফারটা তখন কোনো তালিকাতেই
 * আসত না — খসড়াও নয়, সক্রিয়ও নয় — অথচ [[PromotionEngine]] ওটাকে
 * "সক্রিয় নয়" ধরে চুপ করে থাকত, আর কেউ বলতে পারত না অফারটা কোথায় গেল।
 */
enum PromotionStatus: string
{
    /** লেখা হচ্ছে — কেউ দেখেননি। */
    case DRAFT = 'draft';

    /** অনুমোদনের জন্য পাঠানো — পর্দায় *"Pending Approval"*। */
    case SUBMITTED = 'submitted';

    /** সই হয়ে গেছে, কিন্তু এখনো চালু নয়। */
    case APPROVED = 'approved';

    /** চলছে — বিলে খাটে। */
    case ACTIVE = 'active';

    /** সাময়িক থামানো — পরে আবার চালু হতে পারে। */
    case PAUSED = 'paused';

    /** সময় ফুরিয়েছে। */
    case EXPIRED = 'expired';

    /** থামিয়ে দেওয়া, আর ফেরার পথ নেই। */
    case CANCELLED = 'cancelled';

    /**
     * এখান থেকে কোথায় কোথায় যাওয়া যায়।
     *
     * ── ⚠️ কেন তালিকাটা এক জায়গায়, শর্তে ছড়ানো নয় ───────────────────
     * ⓘ পথগুলো ছড়িয়ে লিখলে একটা নতুন পর্দা লিখতে গিয়ে কেউ নিজের মতো
     * একটা পথ বানাত — যেমন খসড়া থেকে সোজা সক্রিয়। ⛔ তখন অনুমোদনের
     * ধাপটা নীরবে এড়ানো যেত, আর স্পেকের ১৪ নম্বর ধারা কাগজেই থেকে যেত।
     *
     * @return list<self>
     */
    public function nextAllowed(): array
    {
        return match ($this) {
            self::DRAFT => [self::SUBMITTED, self::CANCELLED],
            self::SUBMITTED => [self::APPROVED, self::DRAFT, self::CANCELLED],

            /* ⓘ সই হওয়ার পর চালু করা একটা আলাদা কাজ — তাই আলাদা ধাপ */
            self::APPROVED => [self::ACTIVE, self::CANCELLED],

            self::ACTIVE => [self::PAUSED, self::EXPIRED, self::CANCELLED],
            self::PAUSED => [self::ACTIVE, self::EXPIRED, self::CANCELLED],

            /*
             * ⛔ মেয়াদ শেষ হলে আর ফেরা নেই, আর সেটাই মূল কথা।
             *
             * ⚠️ ফেরা গেলে একটা পুরনো অফার তারিখ বদলে আবার চালু করা যেত,
             * আর যে বিলগুলো ওটার অধীনে কাটা হয়েছিল তারা হঠাৎ অন্য নিয়মের
             * অধীনে পড়ত। ⓘ বাড়ানোর পথ **নতুন অফার**, এই পথ নয় —
             * স্পেকের §৫-এর `Extend` তাই একটা নকল, সম্পাদনা নয়।
             */
            self::EXPIRED, self::CANCELLED => [],
        };
    }

    /** এখান থেকে ওখানে যাওয়া যায় কি না। */
    public function canBecome(self $next): bool
    {
        return in_array($next, $this->nextAllowed(), true);
    }

    /**
     * ⭐ এই অবস্থার অফার বিলে খাটে কি না।
     *
     * ⓘ একটাই জায়গা, কারণ প্রশ্নটা অনেক দিক থেকে আসে: বিক্রয়ের পর্দা,
     * Direct Sales, ফেরত আসার পর নতুন করে হিসাব, আর ড্যাশবোর্ডের গোনা।
     * ⚠️ প্রতিটায় আলাদা লিখলে একদিন একটায় `PAUSED` যোগ হত, অন্যটায় নয়।
     */
    public function isLive(): bool
    {
        return $this === self::ACTIVE;
    }

    /** ⛔ এই অবস্থা থেকে আর কোথাও যাওয়ার নেই। */
    public function isFinal(): bool
    {
        return $this->nextAllowed() === [];
    }

    /**
     * ⛔ এই অফার কোনোদিন কোনো বিলে বসেনি।
     *
     * ── ⚠️ কেন প্রশ্নটা "সক্রিয় কি না" নয় ──────────────────────────
     * ⓘ মোছা যায় কি না তা ঠিক হয় **অতীত** দিয়ে, বর্তমান দিয়ে নয়। ⛔
     * একটা মেয়াদোত্তীর্ণ অফার এখন সক্রিয় নয়, কিন্তু তার অধীনে বিল কাটা
     * হয়েছে, উপহার বেরিয়েছে, মজুদ কমেছে — মুছে দিলে ঐ বিলগুলো এমন একটা
     * অফারের দিকে ইশারা করত যা আর নেই।
     *
     * ⓘ তাই তালিকাটা উল্টো দিক থেকে লেখা: কোন অবস্থাগুলো **নিশ্চিতভাবে**
     * চালু হওয়ার আগের। ⚠️ নতুন কোনো অবস্থা যোগ হলে সে নিজে থেকেই নিরাপদ
     * দিকে পড়বে — অর্থাৎ মোছা যাবে না।
     */
    public function wasNeverApplied(): bool
    {
        return in_array($this, [self::DRAFT, self::SUBMITTED, self::APPROVED], true);
    }

    public function label(): string
    {
        return __('promotion::status.'.$this->value);
    }

    /**
     * ব্যাজের রং — চোখের জন্য, সিদ্ধান্তের জন্য নয়।
     *
     * ⚠️ রঙের নামগুলো টোকেন, হেক্স নয়। ⓘ থিম বদলালে হেক্স মিথ্যা হয়ে
     * যেত, আর বাতিল অফার সবুজ দেখাত।
     */
    public function tone(): string
    {
        /*
         * ⚠️ নামগুলো [[x-ui.badge]]-এর নিজের তালিকা থেকে — ধরে নেওয়া নয়।
         *
         * ⓘ প্রথম খসড়ায় `warning` আর `muted` লেখা ছিল। ⛔ badge ঐ দুইটা
         * চেনে না, আর অচেনা নাম পেলে **চুপচাপ `draft`-এ পড়ে**। ফল:
         * *"অনুমোদনের অপেক্ষায়"* অফার ধূসর দেখাত, হলুদ নয় — কোনো
         * ভুলবার্তা ছাড়াই, আর চোখে পড়ার মতো কিছু ভাঙত না।
         */
        return match ($this) {
            self::ACTIVE => 'success',
            self::SUBMITTED, self::PAUSED => 'pending',
            self::CANCELLED, self::EXPIRED => 'danger',
            self::APPROVED => 'info',
            self::DRAFT => 'draft',
        };
    }
}

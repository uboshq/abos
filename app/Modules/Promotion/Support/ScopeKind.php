<?php

declare(strict_types=1);

namespace App\Modules\Promotion\Support;

/**
 * অফারটা কার জন্য, আর কোন পণ্যে — স্পেকের ৬ নম্বর ধারার দ্বিতীয় ধাপ।
 *
 * ── ⚠️ কেন সব দিক এক টেবিলে, দিক-প্রতি কলাম নয় ──────────────────────
 * ⓘ স্পেকে তিন দল, আর মোট আঠারোটা দিক: কোম্পানি, শাখা, গুদাম, চ্যানেল,
 * ক্রেতা, ক্রেতার দল, ভূখণ্ড, রুট, পরিবেশক, ডিলার, খুচরা, বড় হিসাব,
 * পণ্য, শ্রেণি, ব্র্যান্ড, পণ্যের দল, SKU, ভ্যারিয়েন্ট।
 *
 * ⛔ প্রতিটার জন্য কলাম বানালে `promotions` টেবিলে আঠারোটা `nullable`
 * কলাম বসত, আর ঊনবিংশতম দিকটার দিন টেবিলটা বদলাতে হত — চলতি
 * প্রতিষ্ঠানে, মাইগ্রেশন দিয়ে।
 *
 * ⭐ তাই সারি, কলাম নয়: একটা অফারের **যত খুশি** সুযোগের সারি থাকতে
 * পারে, আর নতুন দিক মানে কেবল এখানে একটা নতুন case।
 *
 * ── ⓘ "সব" বলতে সারিই থাকে না ───────────────────────────────────────
 * ⚠️ *"সব ক্রেতা"* বোঝাতে কোনো `ALL` মান নেই। ⓘ ঐ দিকের কোনো সারি না
 * থাকলেই সেটা *"সব"* — আর ইঞ্জিন তাই পড়ে। ⛔ `ALL` মান রাখলে দুইটা
 * রূপ দাঁড়াত (সারি নেই, আর `ALL` সারি), আর ইঞ্জিনকে দুইটাই বুঝতে হত।
 */
enum ScopeKind: string
{
    // ── প্রতিষ্ঠানের দিক ────────────────────────────────────────────
    case BRANCH = 'branch';
    case WAREHOUSE = 'warehouse';
    case CHANNEL = 'channel';

    // ── ক্রেতার দিক ─────────────────────────────────────────────────
    case CUSTOMER = 'customer';

    /** ⓘ ABOS-এ ডিলার/পরিবেশক/খুচরা — সবই `PartyType`। */
    case PARTY_TYPE = 'party_type';

    /**
     * ⓘ ভূখণ্ড আর রুট দুইটাই `Location`, কেবল মইয়ের ভিন্ন ধাপ।
     *
     * ⚠️ আলাদা case বানানো হয়নি: ⛔ তখন *"রুট-০৫"* আর *"ময়মনসিংহ"*
     * দুইটা আলাদা দিক হত, অথচ ওরা একই গাছের দুইটা ডাল — আর মালিক
     * একদিন ধাপের নাম বদলালে এখানেও বদলাতে হত।
     */
    case LOCATION = 'location';

    // ── পণ্যের দিক ──────────────────────────────────────────────────
    case PRODUCT = 'product';
    case CATEGORY = 'category';
    case BRAND = 'brand';

    /** ⓘ এই দিকটা ক্রেতার দিক কি না — ইঞ্জিন দুই দলকে আলাদাভাবে ছাঁকে। */
    public function isAboutTheBuyer(): bool
    {
        return in_array($this, [self::CUSTOMER, self::PARTY_TYPE, self::LOCATION], true);
    }

    /** ⓘ আর এই দিকটা পণ্যের কি না। */
    public function isAboutTheGoods(): bool
    {
        return in_array($this, [self::PRODUCT, self::CATEGORY, self::BRAND], true);
    }

    public function label(): string
    {
        return __('promotion::scope.'.$this->value);
    }
}

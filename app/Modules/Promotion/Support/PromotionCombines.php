<?php

declare(strict_types=1);

namespace App\Modules\Promotion\Support;

/**
 * এই অফার অন্য অফারের সাথে কীভাবে চলে — আর সেটা **অফারই বলে**।
 *
 * ── ⭐ মালিকের সিদ্ধান্ত, ২৬ সেপ্টেম্বর ২০২৬ ─────────────────────────
 * *"ze kono ekta othoba sobkoti ba eker odhik — offer ghosonar somoyei
 * tik korbe"*। ⓘ সিদ্ধান্তটা কোম্পানির একটা সুইচ নয়, প্রতিটা অফারের
 * নিজের ঘোষণা — বানানোর সময়েই বলা থাকবে।
 *
 * ── ⛔ আগের নকশায় তিনটা হাতল ছিল, আর দুইটা একসাথে মিথ্যা বলতে পারত ──
 * ⓘ `is_exclusive` (একা চলবে) আর `is_stackable` (সবার সাথে চলবে) —
 * দুইটাই `true` বসানো যেত। ⚠️ তখন অফারটা একই সাথে *"একা"* আর *"সবার
 * সাথে"*, আর কোনটা জিতবে তা নির্ভর করত ইঞ্জিন কোন শর্তটা আগে পড়ে তার
 * উপর। ⛔ দুইজন মানুষ দুই রকম উত্তর পেতেন, আর কেউ বলতে পারত না কে ঠিক।
 *
 * ⭐ একটা ঘরে তিনটা মান রাখলে স্ববিরোধী জোড়টা **লেখাই যায় না** — বৈধতা
 * যাচাই দিয়ে আটকাতে হয় না, ব্যাকরণেই অসম্ভব।
 *
 * ── ⚠️ কোম্পানির সুইচটা তবু আছে, কিন্তু সে এখন কেবল শুরুর মান ────────
 * ⓘ `promotion.stacking` নতুন অফারের ঘরটা আগে থেকে ভরে দেয়। ⛔ সে আর
 * সিদ্ধান্ত নেয় না — নাহলে গতকাল বানানো অফারের আচরণ আজ সুইচ বদলালেই
 * বদলে যেত, আর যিনি অফারটা বানিয়েছিলেন তিনি জানতেনও না।
 */
enum PromotionCombines: string
{
    /**
     * ⭐ সবচেয়ে ভালোটা — একটাই।
     *
     * ⓘ একাধিক অফার খাটলে ক্রেতা সবচেয়ে বড় সুবিধাটা পান, কিন্তু একটাই।
     * ⚠️ মালিকের মার্জিন ৩.৮২% — দুইটা ছাড় নীরবে যোগ হলে ঐ সারিতে লাভ
     * বলে কিছু থাকে না।
     */
    case BEST = 'best';

    /** ⓘ যোগ হবে — এই অফার অন্যগুলোর **উপরে** বসে। */
    case ADDS = 'adds';

    /** ⛔ একা চলবে — এটা খাটলে আর কিছু খাটে না। */
    case ALONE = 'alone';

    /**
     * ⭐ এই দুইটা অফার একসাথে খাটতে পারে কি না।
     *
     * ── ⚠️ কেন সিদ্ধান্তটা **দুইজনকেই** জিজ্ঞেস করে ─────────────────
     * ⓘ একজন *"একা চলব"* বললেই যথেষ্ট — অন্যজন যাই বলুক। ⛔ কেবল
     * প্রথমটাকে জিজ্ঞেস করলে ক্রম বদলালে উত্তর বদলাত, আর একই বিল দুইবার
     * কেটে দুই রকম ছাড় পাওয়া যেত।
     *
     * ⓘ আর দুইজনেই `ADDS` না বললে যোগ হয় না: `BEST` মানে *"আমাকে অন্য
     * কারও সাথে যোগ কোরো না"*।
     */
    public function sitsWith(self $other): bool
    {
        if ($this === self::ALONE || $other === self::ALONE) {
            return false;
        }

        return $this === self::ADDS && $other === self::ADDS;
    }

    public function label(): string
    {
        return __('promotion::combines.'.$this->value);
    }
}

{{--
    ঘড়ির অবস্থা — একটা ছোট ব্যাজ, আর ধরে রাখলে শেষ সময়।

    ── ⚠️ কেন অবস্থাটা এখানে হিসাব করা হয় না ───────────────────────────
    ⓘ [[ApprovalSla::stateOf()]] কন্ট্রোলারে একবার চলে, আর ফলটা এখানে
    আসে। ⛔ ব্লেডে `now()` আর `due_at` মিলাতে গেলে তিন জায়গায় তিন রকম
    হিসাব হত — পর্দা বলত *"সময়ের ভিতরে"* আর ঘণ্টার কমান্ড ওটাকে উপরে
    পাঠিয়ে দিত, আর দুইজনের কেউই ভুল বলে ধরা পড়ত না।

    ── ⓘ "ঘড়ি নেই" কিছুই দেখায় না ─────────────────────────────────────
    ⚠️ প্রতিটা সারিতে একটা ধূসর "—" বসালে কলামটা কেবল জায়গা নিত, আর
    সবচেয়ে খারাপ: ঘড়ি বসানো সারিগুলোর লাল ব্যাজ ঐ ভিড়ে হারাত।

    ── ⛔ রং একা কিছু বলে না ────────────────────────────────────────────
    লেখাটাই মূল ("সময় পার"), রংটা শুধু সাহায্য — [[x-ui.badge]]-এর
    একই কারণে: কালার-ব্লাইন্ড পাঠক আর সাদাকালো ছাপা, দুইটাতেই।
--}}
@php
    /*
     * ⓘ "উপরে পাঠানো" আর "সময় পার" — দুইটাই লাল, কিন্তু লেখা আলাদা।
     * ⚠️ প্রথমটায় কিছু একটা ঘটে গেছে, দ্বিতীয়টায় এখনো কিছুই হয়নি —
     * আর ঠিক ওই পার্থক্যটাই জানার দরকার।
     */
    $tone = match ($state) {
        \App\Core\Engines\Approval\ApprovalSla::ESCALATED,
        \App\Core\Engines\Approval\ApprovalSla::LATE => 'danger',
        \App\Core\Engines\Approval\ApprovalSla::NEAR => 'pending',
        default => 'draft',
    };

    /*
     * ⚠️ শর্তটা এখানে, ট্যাগের ভিতরে নয়।
     *
     * ⛔ `‹x-ui.badge @if (…) :title="…" @endif›` লিখলে ব্লেড কম্পোনেন্ট-
     * ট্যাগের অ্যাট্রিবিউট পার্সার `@endif`-টা খুঁজে পায় না, আর পুরো
     * ফাইলটা parse error হয়ে যায়।
     */
    $due = $approval->due_at
        ? __('approval::message.sla_due', ['when' => $approval->due_at->format('d M Y, H:i')])
        : null;
@endphp

@if ($state !== \App\Core\Engines\Approval\ApprovalSla::NONE)
    <x-ui.badge :tone="$tone" :title="$due">
        {{ __('approval::message.sla_'.$state) }}
    </x-ui.badge>
@endif

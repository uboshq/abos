<?php

declare(strict_types=1);

namespace App\Modules\SystemAdmin\Http\Controllers;

use App\Http\Controllers\Controller;
use App\Modules\SystemAdmin\Services\FirstRun;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Auth;
use Illuminate\Validation\Rules\Password;
use Illuminate\View\View;

/**
 * প্রথম দরজা — নতুন ইনস্টলে ঢোকার একমাত্র পথ।
 *
 * ── কেন এটা `auth`-এর বাইরে ─────────────────────────────────────────
 * এটাই তো সেই মুহূর্ত যখন লগইন করার মতো কেউ নেই। `auth`-এর ভিতরে
 * রাখলে পর্দাটা থাকত অথচ কেউ কোনোদিন দেখতে পেত না।
 *
 * ── তাহলে পাহারা কোথায় ──────────────────────────────────────────────
 * `users` টেবিল **খালি থাকা**-টাই পাহারা। একটাও ব্যবহারকারী বসে গেলে
 * দরজাটা চিরতরে ৪০৪ — অর্থাৎ পাহারাটা সময়ের, চাবির নয়।
 *
 * ⚠️ ৪০৪, ৪০৩ নয়। ৪০৩ বলে দিত "এখানে কিছু একটা আছে, তুমি পাচ্ছ না";
 * ৪০৪ বলে "এখানে কিছু নেই"। বসে যাওয়ার পর দ্বিতীয় কথাটাই সত্যি, আর
 * ওটাই কম তথ্য ফাঁস করে।
 *
 * ── কেন এটা `SystemAdmin`-এর ভিতরে, নতুন মডিউল নয় ───────────────────
 * নতুন মডিউল মানে `module.php`, বাধ্যতামূলক `nav`, অনুমতির তালিকা,
 * মেনুর সারি আর একটা সুইচ — একটা এককালীন পর্দার জন্য ওটা অনেক বেশি।
 * আর `module.php` বুটে পড়া হয়, তাই ওখানে ভুল হলে **গোটা অ্যাপ থামে**।
 *
 * কোরের `routes/web.php`-তেও নয়: ওই ফাইলের নিজের মন্তব্যে লেখা আছে
 * মডিউলের রুট ওখানে লিখলে "কোর না ছুঁয়ে নতুন মডিউল" কথাটাই মিথ্যা হয়।
 * `ModuleServiceProvider` মডিউলের রুটে কেবল `web` বসায় — `auth` আসে
 * মডিউলের নিজের রুট ফাইল থেকে। তাই অতিথির দরজা ওখানেই বসানো যায়।
 */
class SetupController extends Controller
{
    public function __construct(private readonly FirstRun $firstRun) {}

    public function show(): View
    {
        abort_unless($this->firstRun->isOpen(), 404);

        return view('system_admin::setup.index');
    }

    public function store(Request $request): RedirectResponse
    {
        abort_unless($this->firstRun->isOpen(), 404);

        $data = $request->validate([
            'name' => ['required', 'string', 'max:160'],
            'email' => ['required', 'email', 'max:191'],

            /*
             * পাসওয়ার্ডের নিয়ম এখানে কড়া, আর সেটা ইচ্ছাকৃত।
             *
             * এই একটা অ্যাকাউন্টের হাতে গোটা প্রতিষ্ঠান — সব কোম্পানি,
             * সব খতিয়ান, সব ব্যবহারকারী। আর এটা এমন সময়ে বসে যখন
             * এখনো কোনো প্রশাসক নেই যিনি পরে দুর্বল পাসওয়ার্ড ধরতে
             * পারতেন।
             */
            'password' => ['required', 'confirmed', Password::min(10)->letters()->numbers()],

            /*
             * ⚠️ অন্তত একটা ইংরেজি অক্ষর — আর এটা খামখেয়ালি নয়।
             *
             * এই দুইটা নাম থেকে কোড বসে (`CodeFromName`), আর সেই কোড
             * বসে **প্রতিটা ডকুমেন্টের নম্বরে, রিপোর্টে, ছাপায় ও
             * রপ্তানির ফাইলে** — সব জায়গায় ইংরেজি অক্ষরে।
             * `CodeFromName::base()` তাই ইংরেজি অক্ষর ছাড়া সব ফেলে দেয়,
             * আর নিজের মন্তব্যেই লেখা: "বাংলা নামে কিছুই টেকে না"।
             *
             * ── এই নিয়মটা না থাকলে কী হত ────────────────────────────
             * পুরো বাংলা নাম দিলে কোড হত **খালি স্ট্রিং**, আর সেটা
             * নীরবে বসে যেত — ব্রাউজারে চালিয়ে ঠিক এটাই ধরা পড়েছে
             * (৩ সেপ্টেম্বর ২০২৬)। কোড পড়ে ধরা পড়ত না, কারণ কোথাও
             * কিছু ভাঙে না; শুধু ছয় মাস পর কেউ দেখতেন প্রতিটা
             * চালানের নম্বর একটা হাইফেন দিয়ে শুরু।
             *
             * ── কেন কোডের ঘর বসিয়ে দেওয়া হলো না ───────────────────
             * মালিকের নিয়ম: **ব্যবহারকারীকে কোড বানাতে দেওয়া হয় না**।
             * তাই এখানে পথটা উল্টো — কোড চাওয়ার বদলে নামটা এমন চাওয়া
             * হয় যা থেকে কোড বসতে পারে, আর **কেন** সেটা পর্দাতেই লেখা।
             * ভুল হলে চুপ করে থাকার চেয়ে কারণসহ থামা ভালো।
             */
            'company_name' => ['required', 'string', 'max:160', 'regex:/[A-Za-z]/'],
            'branch_name' => ['required', 'string', 'max:160', 'regex:/[A-Za-z]/'],

            'locale' => ['nullable', 'in:bn,en'],
        ], [
            'company_name.regex' => __('system_admin::setup.needs_latin'),
            'branch_name.regex' => __('system_admin::setup.needs_latin'),
        ]);

        /*
         * দরজাটা এখানেও একবার দেখা হয় — কিন্তু আসল সিদ্ধান্তটা
         * `FirstRun::open()`-এর ভিতরে, তালার নিচে।
         *
         * উপরের `abort_unless` কেবল **ভদ্রতা**: যিনি পুরনো ট্যাব থেকে
         * ফর্ম জমা দিলেন তিনি একটা ব্যতিক্রমের বদলে ৪০৪ পান। দুইটা
         * অনুরোধ একই মুহূর্তে এলে ওটা কিছুই আটকায় না — সেটা ডাটাবেসের
         * কাজ, আর সেখানেই করা হয়েছে।
         */
        try {
            $user = $this->firstRun->open($data);
        } catch (\RuntimeException) {
            abort(404);
        }

        /*
         * বসিয়ে দিয়ে লগইনের পর্দায় পাঠানো হয় না — সাথে সাথে ঢুকিয়ে
         * দেওয়া হয়।
         *
         * যিনি এইমাত্র পাসওয়ার্ডটা বানালেন তাঁকে ওটা আবার লিখতে বলার
         * কোনো নিরাপত্তা-লাভ নেই, আর প্রথম অভিজ্ঞতাটা একটা অপ্রয়োজনীয়
         * দেয়াল দিয়ে শুরু হত।
         */
        Auth::login($user);
        $request->session()->regenerate();

        return redirect()
            ->route('dashboard')
            ->with('saved', __('system_admin::setup.done'));
    }
}

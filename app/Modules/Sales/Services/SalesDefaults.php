<?php

declare(strict_types=1);

namespace App\Modules\Sales\Services;

use App\Core\Contracts\ProvisionsCompany;
use App\Core\Services\SettingsService;
use App\Modules\Sales\Models\PricingRule;

/**
 * নতুন কোম্পানির বিক্রয়-সুইচগুলো — খোলার দিনেই বসানো।
 *
 * ── ⭐ মালিকের নিয়ম, ২৩ সেপ্টেম্বর ২০২৬ ───────────────────────────────
 * *"nirdarito sales prices er niche entry nibe na"*।
 *
 * ── ⛔ কেন ডিফল্টে নয়, এখানে ─────────────────────────────────────────
 * ⓘ প্রথম চেষ্টায় [[PricingRule::POLICY]]-র **ডিফল্টটাই** `block` করা
 * হয়েছিল। ⚠️ মেপে দেখা গেল বিক্রয়ের সুইটে **২৫টা লাল**, প্রতিটা এক
 * বার্তায়: *"দরটা মান দাম থেকে % এর বেশি সরে গেছে"*।
 *
 * ⓘ অর্থাৎ ডিফল্টের পাশে বহু আগে লেখা কথাটা অনুমান ছিল না, **মাপা সত্য**:
 * *"কড়া ডিফল্ট দিলে আপগ্রেডের দিন সকালে প্রতিটা কাউন্টার থেমে যেত"* —
 * ⛔ কারণ ডিফল্ট **চলতি** ইনস্টলগুলোর উপরেও গিয়ে পড়ে, যারা কোনোদিন
 * কোনো সীমা বসায়নি।
 *
 * ⭐ নতুন কোম্পানির কোনো "গতকাল" নেই। ⓘ তার প্রথম বিক্রয়ের আগেই সুইচটা
 * বসে, তাই কারও চলতি কাজ থামে না — অথচ মালিকের নিয়মটা নতুন কোম্পানিতেও
 * নিজে থেকেই চালু থাকে, হাতে বসাতে হয় না।
 *
 * ── ⚠️ কেন `set()`, আর তাতে কী বদলায় ─────────────────────────────────
 * ⓘ এটা কোম্পানির নিজের সারি লেখে, ডিফল্ট ছোঁয় না। ⛔ ফলে যে ইনস্টল
 * এই কোডটা পায় কিন্তু নতুন কোম্পানি খোলে না, তার কিছুই বদলায় না।
 *
 * ⓘ পরে মত বদলালে পর্দা থেকেই হয় — বিক্রয় → এন্ট্রি → দামের নীতি।
 * ⚠️ এটা "আটকে দেওয়া" নয়, **শুরুর অবস্থান**।
 */
final class SalesDefaults implements ProvisionsCompany
{
    public function __construct(private readonly SettingsService $settings) {}

    /**
     * ⓘ বারবার ডাকা নিরাপদ — চুক্তিটা সেটাই চায়, আর `set()` সারিটা
     * থাকলে বদলে দেয়, দ্বিতীয়বার বসায় না।
     */
    public function provisionCompany(): void
    {
        /*
         * ⓘ নিচে আটকায়, উপরে নয় — মালিক কেবল নিচের কথা বলেছেন, আর
         * ⚠️ দুইটাই আটকালে বেশি দামে বেচাও থেমে যেত। ⓘ কারণটা
         * [[Sales/module]]-এর সুইচের পাশেও লেখা: নিচে বেচলে টাকা যায়,
         * উপরে বেচলে ওটা বিক্রয়কর্মীর কৃতিত্ব।
         */
        $this->settings->set(PricingRule::POLICY, PricingRule::BLOCK);
        $this->settings->set(PricingRule::BELOW, true);
        $this->settings->set(PricingRule::ABOVE, false);
    }
}

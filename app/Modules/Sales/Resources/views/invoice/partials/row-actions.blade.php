@php
    $isDraft = $invoice->status === \App\Core\Support\DocumentStatus::DRAFT;
    $isCancelled = $invoice->status === \App\Core\Support\DocumentStatus::CANCELLED;

    $items = [];

    /* ⓘ বিস্তারিত সবসময় — দেখার অনুমতি না থাকলে সারিটাই আসত না। */
    $items[] = [
        'label' => __('core.action.view'),
        'url' => route('sales.invoice.show', $invoice),
    ];

    if ($isDraft && auth()->user()?->can('sales.invoice.create')) {
        $items[] = [
            'label' => __('core.action.edit'),
            'url' => route('sales.invoice.edit', $invoice),
        ];

        $items[] = [
            'label' => __('sales::action.confirm'),
            'url' => route('sales.invoice.confirm', $invoice),
            'method' => 'post',
            'tone' => 'success',
        ];
    }

    /*
     * ⚠️ বাতিল এখান থেকে **সরাসরি হয় না** — কাগজের পাতায় পাঠানো হয়।
     *
     * ⛔ কারণ বাতিলে একটা লিখিত কারণ বাধ্যতামূলক, আর ড্রপডাউনের ভিতরে
     * একটা POST বোতাম কারণটা নেওয়ার জায়গা দেয় না। ⓘ কারণ ছাড়া পাঠালে
     * সার্ভার যাচাইয়ে আটকাত, আর ব্যবহারকারী একটা লাল বার্তা পেতেন যার
     * মানে বুঝতেন না।
     *
     * ⭐ বিস্তারিত পাতায় [[sales::cancel-form]] আছে — কারণের ঘরসহ।
     */
    if (! $isDraft && ! $isCancelled && auth()->user()?->can('sales.invoice.cancel')) {
        $items[] = [
            'label' => __('sales::action.cancel_invoice'),
            'url' => route('sales.invoice.show', $invoice).'#cancel',
            'tone' => 'danger',
        ];
    }
@endphp

<x-ui.row-actions :items="$items" />

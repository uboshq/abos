<?php

declare(strict_types=1);

namespace App\Modules\Sales\Auth;

use Illuminate\Auth\EloquentUserProvider;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Model;

/**
 * গ্রাহককে সেশন থেকে তুলে আনা — কোম্পানির ছাঁকনি ছাড়া।
 *
 * ── কী ভাঙা ছিল ─────────────────────────────────────────────────────
 * পোর্টালের **প্রতিটা** অনুরোধে ৫০০ আসত।
 *
 * `auth:portal` সেশনে রাখা আইডি দিয়ে গ্রাহককে খুঁজে আনে, আর সাধারণ
 * `EloquentUserProvider` সেটা করে `Customer::query()` দিয়ে — গ্লোবাল
 * স্কোপসহ। কিন্তু ওই মুহূর্তে কোনো কোম্পানি বসানো নেই: প্রসঙ্গ বসে
 * ব্যবহারকারী চেনার **পরে**, আর এখানে ব্যবহারকারীকে চিনতেই কোয়েরিটা
 * লাগছে। `BelongsToCompany` তখন ঠিক কাজটাই করত — ব্যতিক্রম ছুঁড়ত।
 *
 * ডিম আগে না মুরগি আগে, আর দুইটাই সঠিক আচরণ। ভাঙার জায়গাটা তাই
 * ছাঁকনিতে নয়, প্রোভাইডারে: এই একটামাত্র কোয়েরি প্রসঙ্গের আগে চলে,
 * তাই এটাকেই প্রসঙ্গ ছাড়া চলতে দিতে হয়।
 *
 * ── কেন এতে কোনো দেয়াল ভাঙে না ──────────────────────────────────────
 * খোঁজাটা প্রাথমিক কী ধরে (`retrieveById`) বা কোডসহ শর্ত ধরে। ফলটা
 * একটা সারি, আর সেই সারির নিজের `company_id` থেকেই বাকি অনুরোধের
 * প্রসঙ্গ বসে। অর্থাৎ ছাঁকনিটা এখানে কিছু আটকাত না, কেবল প্রশ্নটাই
 * করতে দিত না।
 *
 * গ্রাহক অন্য কোম্পানির কিছু দেখতে পান না — সেটা আটকায়
 * [[CustomerPapers]], যেখানে প্রতিটা কোয়েরি গ্রাহকের নিজের সারি থেকে
 * শুরু হয়, URL থেকে নেওয়া কোনো আইডি থেকে নয়।
 *
 * ── ধরা পড়েছে ব্রাউজারে, টেস্টে নয় ──────────────────────────────────
 * টেস্টের `setUp()`-এ `CompanyContext::set()` ডাকা হয়, আর ওটা
 * স্ট্যাটিক — তাই টেস্টের ভেতরের অনুরোধেও প্রসঙ্গটা বসানোই থেকে যেত।
 * আসল অনুরোধে কখনো থাকে না।
 */
class CustomerProvider extends EloquentUserProvider
{
    /**
     * @return Builder<Model>
     */
    protected function newModelQuery($model = null)
    {
        return parent::newModelQuery($model)->withoutGlobalScopes();
    }
}

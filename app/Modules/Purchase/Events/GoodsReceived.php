<?php

declare(strict_types=1);

namespace App\Modules\Purchase\Events;

use App\Core\Events\DomainEvent;
use App\Modules\Purchase\Models\PurchaseReceipt;

/**
 * গাড়ি থেকে মাল নেমে গেছে।
 *
 * ── ⓘ কী ঘটে গেছে ───────────────────────────────────────────────────
 * চালানটা খসড়া ছিল, এখন নিশ্চিত। মাল গুদামে উঠেছে (`unplaced`), দাম
 * স্তরে বসেছে, খতিয়ানে অপেক্ষমাণ দায় উঠেছে। ⚠️ **এই সবগুলো ইতিমধ্যেই
 * হয়ে গেছে** — ঘটনাটা ছোড়ার সময় লেনদেনটা শেষ।
 *
 * ── ⛔ শ্রোতা কী করতে পারে না ────────────────────────────────────────
 * হিসাবের দাখিলা, স্টক চলাচল, নম্বর ইস্যু — তিনটাই `confirm()`-এর
 * ভিতরে, একই লেনদেনে হয়ে গেছে, আর সেখানেই থাকবে। ⓘ ইভেন্ট একদিন
 * হারায়; খাতা হারানো যায় না।
 *
 * ── ⭐ পেলোডে চলাচলের **চাবিটা** আছে, সারিগুলো নয় ────────────────────
 * ⓘ পেলোড কেবল scalar নিতে পারে ([[DomainEvent]]), আর সেটাই ঠিক:
 * সারিগুলো পাঠালে শ্রোতা ক্রয়ের ঘরের নামের উপর নির্ভর করত, অথচ সেটাই
 * এড়ানোর জন্য ইভেন্ট।
 *
 * ⭐ তাই যায় `source_type` আর `source_id` — অর্থাৎ **মজুদের নিজের
 * টেবিলে** চলাচলের সারিগুলো খুঁজে নেওয়ার চাবি। ⓘ শ্রোতা তখন নিজের
 * মডিউলের কোড দিয়েই জেনে নেয় কী কত এল, কোন লটে, কোন গুদামে — ক্রয়ের
 * একটাও কলামের নাম না জেনে।
 *
 * ⚠️ `source_id` ভেতরের ক্রমিক আইডি, আর সেটা এখানে ইচ্ছাকৃত: ওটা
 * রেকর্ডের পরিচয় নয়, `inv_stock_movements`-এর জোড়ার চাবি — আর ঐ
 * কলামটা মজুদেরই।
 */
final class GoodsReceived extends DomainEvent
{
    public static function from(PurchaseReceipt $receipt): self
    {
        return new self(
            publicId: (string) $receipt->public_id,
            payload: [
                'document_no' => (string) $receipt->document_no,
                'received_on' => (string) $receipt->trx_date?->toDateString(),

                /*
                 * চলাচলের সারিগুলোর জোড়ার চাবি — উপরের ব্যাখ্যা।
                 *
                 * ⚠️ ফ্রি মালের সারিগুলো আলাদা উৎসে বসে
                 * (`…:free`), আর সেটা এখানে **পাঠানো হয় না**: ⓘ যে
                 * শ্রোতার ওটা লাগবে সে জানে নিয়মটা কী, আর দুইটা চাবি
                 * পাঠালে প্রথমজন ভুলটা করত — দুইবার গোনা।
                 */
                'source_type' => PurchaseReceipt::STOCK_SOURCE,
                'source_id' => $receipt->id,
            ],
        );
    }
}

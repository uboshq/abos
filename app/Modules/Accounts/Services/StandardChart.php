    /**
     * ছকটা বসানো। আগে বসানো থাকলে কিছুই হয় না।
     *
     * @return int কতগুলো খাত তৈরি হল
     */
    public function install(): int
    {
        $this->accounts->assertCompanyContext();

        return DB::transaction(function () {
            $created = 0;

            /*
             * যা আছে তা আগে জেনে নেওয়া, তারপর কেবল অনুপস্থিতগুলো বসানো।
             *
             * ── আগে এখানে কী ছিল, আর কেন সেটা ভুল ───────────────────
             * "একটাও খাত থাকলে কিছুই করব না" — এই নিয়মে ছকটা ছিল সব-বা-
             * কিছুই-না। ফলে ব্যবস্থায় নতুন কোনো খাত যোগ হলে (HR-এর
             * ভবিষ্যৎ তহবিল ২১৩১, কর্মীর অগ্রিম ১১৩১, বিক্রয় ফেরত ৪১১০)
             * পুরনো কোম্পানিগুলো সেটা কোনোদিন পেত না। প্রথম ব্যবহারে
             * তারা পেত "হিসাবের ছকে ৪১১০ খাতটা নেই" — অথচ ছক বসানোর
             * বোতামটা চেপেও কিছু হত না, কারণ ওটা দেখত খাত তো আছেই।
             *
             * এখন বোতামটা যা বলে তা-ই করে: যা নেই তা বসায়, যা আছে তা
             * ছোঁয় না (নাম বা প্রকৃতি বদলালে সেটা কোম্পানির নিজের
             * সিদ্ধান্ত, আর সেটা মুছে দেওয়া হয় না)।
             */
            $byCode = Account::query()->get()->keyBy('code')->all();

            foreach ($this->definition() as $row) {
                [$code, $en, $bn, $type, $parentCode, $isGroup, $flags] = $row;

                if (isset($byCode[$code])) {
                    continue;
                }

                $account = $this->accounts->create([
                    'code' => $code,
                    'name_en' => $en,
                    'name_bn' => $bn,
                    'type' => $type,
                    /*
                     * বাবার খাত না পেলে গোড়ায় বসে।
                     *
                     * তালিকায় বাবা সবসময় সন্তানের আগে, তাই এখানে না
                     * পাওয়ার একটাই মানে: কোম্পানি ওই গ্রুপটা নিজে মুছে
                     * দিয়েছে। তখন সন্তানকে না বসিয়ে ছেড়ে দিলে খাতটা
                     * কোনোদিন তৈরি হত না, আর যে সেবা ওটা খোঁজে সেটা
                     * চিরকাল "খাত নেই" বলত।
                     */
                    'parent_id' => $parentCode === null ? null : ($byCode[$parentCode]->id ?? null),
                    'is_group' => $isGroup,
                    'is_cash' => (bool) ($flags['cash'] ?? false),
                    'is_bank' => (bool) ($flags['bank'] ?? false),
                    'nature' => $flags['nature'] ?? Account::defaultNatureFor($type),

                    /*
                     * অবসরে পাঠানো খাত — ছকে থাকে, নতুন এন্ট্রি নেয় না।
                     *
                     * ⚠️ এই লাইনটা না থাকলে ছকের `is_active` পতাকাটা
                     * **নীরবে উপেক্ষিত** হত: সারিতে লেখা থাকত "নিষ্ক্রিয়",
                     * অথচ নতুন কোম্পানিতে খাতটা সচলই বসত। আর সেটা ধরা
                     * পড়ত অনেক পরে — কারণ পুরনো কোম্পানিতে মাইগ্রেশন
                     * কাজটা করে দিত, তাই এই মেশিনে সব ঠিক দেখাত।
                     *
                     * ⓘ ভাউচারের খাত-তালিকা `->active()` ছাঁকে
                     * ([[VoucherController:349]]), তাই নিষ্ক্রিয় খাত
                     * সত্যিই আর বাছা যায় না — কিন্তু পুরনো দাখিলা ও
                     * রিপোর্ট আগের মতোই থাকে।
                     */
                    'is_active' => (bool) ($flags['is_active'] ?? true),
                ]);

                if (in_array($code, self::SYSTEM_CODES, true)) {
                    $this->accounts->markAsSystem($account);
                }

                $byCode[$code] = $account;
                $created++;
            }

            return $created;
        });
    }


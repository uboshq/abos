<?php

declare(strict_types=1);

namespace App\Modules\Finance\Support;

use Illuminate\Database\Eloquent\Model;

/**
 * ⛔ ঠিকানায় আইডি বসিয়ে অন্য শাখার কাগজ খোলা যায় না — পুরো-ERP পুনঃঅডিট, ৯ অক্টোবর ২০২৬।
 *
 * ── ⛔ কী ছিল ─────────────────────────────────────────────────────────
 * অর্থের মডেলগুলোয় শাখার দেয়াল কেবল তালিকায় ([[ListedInViewedBranch]]) — গ্লোবাল স্কোপ ইচ্ছে করেই নেই, কারণ মূলধন,
 * উত্তোলন, ভাড়ার সারি হিসাবেও পড়া হয় (ঐ ট্রেইটের টীকা)। ফল: ঠিকানার আইডি ধরে কাগজ খোলায় কোনো দেয়াল ছিল না —
 * এক শাখায় আটকানো কর্মী সংখ্যা বদলে অন্য শাখার ভাড়া, হাতধার, বীমা খুলতেন, আর পাতার বোতামে টাকাও নাড়াতেন।
 *
 * ── ⭐ এখন ───────────────────────────────────────────────────────────
 * ঠিকানা থেকে মডেল বাঁধার সময়ই ([[Model::resolveRouteBinding()]]) কাগজের শাখা মানুষটার নাগালে কি না দেখা — না হলে
 * ৪০৪, অন্য মডিউলের দেয়ালের মতোই ("আছে কি নেই" সেটাও বলা হয় না)। ⓘ নাগাল, হেডারে বাছা শাখা নয় ([[ActingBranches]]):
 * মালিক হেডারে এক শাখা রেখে খতিয়ানের লিংক ধরে আরেক শাখার কাগজে গেলে আগের মতোই খোলে। হিসাবের পথ ছোঁয়া হয় না।
 */
trait OpensOnlyInReach
{
    public function resolveRouteBinding($value, $field = null): ?Model
    {
        $row = parent::resolveRouteBinding($value, $field);

        return $row !== null && ActingBranches::allows($row->getAttribute('branch_id')) ? $row : null;
    }
}

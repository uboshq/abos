<?php

declare(strict_types=1);

namespace App\Http\Middleware;

use App\Core\Support\Csp;
use Closure;
use Illuminate\Http\Request;
use Symfony\Component\HttpFoundation\Response;

/**
 * পাতা কোথা থেকে জিনিস আনতে পারবে — ব্রাউজারকে বলে দেওয়া।
 *
 * ── কী ছিল না, ৩১ আগস্ট ২০২৬ ─────────────────────────────────────────
 * লাইভ সার্ভারে HSTS, X-Frame-Options, X-Content-Type-Options আর
 * Referrer-Policy চারটাই বসানো ছিল — **কেবল CSP ছিল না**। ওটাই একমাত্র
 * হেডার যেটা বলে "এই পাতা বাইরের কোনো সার্ভার থেকে স্ক্রিপ্ট আনবে না,
 * আর কোনো তথ্য বাইরে পাঠাবে না"।
 *
 * ক্রেতার IT বিভাগ নিরাপত্তার তালিকা মেলাতে গিয়ে প্রথমেই এটা খোঁজে।
 *
 * ── ⭐ `unsafe-inline` চলে গেছে — ১৪ সেপ্টেম্বর ২০২৬ ──────────────────
 * আগে এখানে লেখা ছিল *"ওগুলো সরানো একটা সত্যিকারের কাজ"*, আর সেটা
 * সত্যি ছিল — কিন্তু **কাজটা কত বড় তা কেউ মেপে দেখেনি**। মেপে পাওয়া গেল:
 *
 *     সত্যিকারের ইনলাইন `<script>`  ৯টা ফাইলে
 *     সত্যিকারের ইনলাইন `<style>`   ৩টা ফাইলে
 *     তৃতীয় পক্ষের JS লাইব্রেরি      ০ (কেবল Alpine)
 *
 * বারোটা জায়গায় `@nonce` বসানোই যথেষ্ট ছিল। ⓘ অর্থাৎ এক বছর ধরে
 * সুরক্ষাটা বন্ধ ছিল একটা **অনুমানের** কারণে, বাধার কারণে নয়।
 *
 * ⭐ এখন কেউ একটা ঘরে `<script>` লিখে জমা দিলে, আর সেটা কোথাও এস্কেপ
 * না হয়ে ছাপা হলে, ব্রাউজার সেটা **চালাবে না** — চিহ্নটা নেই।
 * চিহ্ন কীভাবে তৈরি ও ঘোরে: [[App\Core\Support\Csp]].
 *
 * ── ⭐ `unsafe-eval`-ও চলে গেছে — ১৯ সেপ্টেম্বর ২০২৬ ────────────────────
 * নিরীক্ষার ধাপ ৩.১। Alpine-এর সাধারণ সংস্করণ অ্যাট্রিবিউটের লেখাটা
 * `new Function()` দিয়ে চালাত, তাই `eval` ছাড়া চলত না। ⓘ এখন অ্যাপ চলে
 * `@alpinejs/csp`-এ, যার নিজের পার্সার আছে — কোনো কোড তৈরি করে চালায় না।
 *
 * ⛔ ঋণটা একবার ভুল মাপা হয়েছিল (১,৯০২ — "CSP সংস্করণ কেবল নাম বোঝে"
 * ধরে নিয়ে)। আসল পার্সার দিয়ে মাপলে ২২৩টা, আর সেগুলো শোধ হয়েছে: বড়
 * যুক্তিগুলো `resources/js/components/`-এ নামওয়ালা কম্পোনেন্ট, ছোটগুলো
 * সরল এক্সপ্রেশন। ⚠️ পাঁচটা ইনলাইন `<script>` বৈশ্বিক ফাংশন লিখত আর
 * পর্দা সেগুলো ডাকত — CSP-Alpine বৈশ্বিক নাম দেখে না, তাই ওগুলোও মডিউলে।
 *
 * ⭐ দুইটা পাহারা:
 *   · `resources/js/csp-expressions.test.js` — প্রতিটা ব্লেডের প্রতিটা
 *     এক্সপ্রেশন CSP-Alpine-এর **নিজের** পার্সার দিয়ে পড়ে (`npm test`)
 *   · [[TheBrowserNeverEvaluatesOurCodeTest]] — নীতিতে `unsafe-eval` নেই,
 *     আর পাঠানো বান্ডলে `Function(` নেই
 *
 * ⓘ বাইরে থেকে ঢোকানো `<script>` আগেই আটকাত (nonce); এখন পাতায় থাকা
 * কোডও কোনো লেখাকে কোড বানিয়ে চালাতে পারে না।
 *
 * ── তবু এটা ফাঁকা নয় ─────────────────────────────────────────────────
 * যা আজই আটকায়:
 *   · বাইরের কোনো ডোমেইন থেকে স্ক্রিপ্ট বা স্টাইল আনা;
 *   · `connect-src 'self'` — চুরি করা তথ্য অন্য সার্ভারে পাঠানো;
 *   · `form-action 'self'` — ফর্মকে বাইরের ঠিকানায় submit করানো;
 *   · `base-uri 'self'` — `<base>` বসিয়ে সব লিংক ঘুরিয়ে দেওয়া;
 *   · `frame-ancestors 'self'` — অন্য সাইটে iframe-এ বসিয়ে ক্লিক চুরি।
 *
 * অ্যাপের প্রতিটা অ্যাসেট নিজের ডোমেইনেই আছে (যাচাই করা: ব্লেডে বাইরের
 * ঠিকানা মাত্র একটা, আর সেটা একটা WhatsApp **লিংক**, কোনো ফাইল নয়),
 * তাই এতে কিছু ভাঙার কথা নয়।
 *
 * ── বন্ধ করার সুইচ ───────────────────────────────────────────────────
 * `ABOS_CSP=off` দিলে হেডারটা বসে না। কোনো পর্দা ভাঙলে ডিপ্লয় ফিরিয়ে
 * আনার আগে একটা লাইনেই থামানো যায় — নিরাপত্তার হেডারের জন্য কাউন্টার
 * বন্ধ থাকা সবচেয়ে খারাপ ফল।
 */
class ContentSecurityPolicy
{
    /**
     * @return list<string>
     */
    private function policy(string $nonce): array
    {
        return [
            "default-src 'self'",

            /*
             * ⚠️ nonce থাকলে ব্রাউজার `'unsafe-inline'` **উপেক্ষা করে** —
             * CSP2 থেকে এটাই নিয়ম। তাই "পুরনো ব্রাউজারের জন্য রেখে দিই"
             * বলে ওটা রাখা অর্থহীন হত: যে ব্রাউজার nonce বোঝে সে ওটা
             * মানে না, আর যে বোঝে না তার কাছে গোটা হেডারটাই নতুন।
             *
             * ⓘ `unsafe-eval` নেই — কেন আর কবে থেকে, উপরের মন্তব্যে।
             */
            "script-src 'self' 'nonce-{$nonce}'",

            // Tailwind ফাইল থেকেই আসে; তিনটা ইনলাইন `<style>` চিহ্ন নিয়ে
            "style-src 'self' 'nonce-{$nonce}'",

            /*
             * ⓘ ১২০টা ইনলাইন `style=` অ্যাট্রিবিউট, আর Alpine-এর
             * `x-show` নিজেও `element.style.display` বসায়। আলাদা করে না
             * বললে উপরের `style-src` অ্যাট্রিবিউটেও খাটত, আর প্রতিটা
             * `x-show` নীরবে কাজ করা বন্ধ করত।
             *
             * ⭐ ভাগ করার লাভটা আসল: ইনজেক্ট করা গোটা `<style>` ব্লক
             * এখন আটকায়, অথচ অ্যাট্রিবিউট চলে।
             */
            "style-src-attr 'unsafe-inline'",

            // data: — বারকোড ও কিউআর ছবি ইনলাইন হিসেবে তৈরি হয়
            "img-src 'self' data:",
            "font-src 'self' data:",

            "connect-src 'self'",
            "form-action 'self'",
            "base-uri 'self'",
            "frame-ancestors 'self'",
            "object-src 'none'",
        ];
    }

    public function handle(Request $request, Closure $next): Response
    {
        /*
         * ⛔ `$next()`-এর **আগে**, কারণ ভিউ রেন্ডার হওয়ার সময় ব্লেডগুলো
         * `@nonce` ডাকবে — তখন চিহ্নটা তৈরি হয়ে থাকতে হবে।
         *
         * ⚠️ আর `rotate()`, `nonce()` নয়: Octane বা কিউ-কর্মীতে
         * প্রক্রিয়াটা বেঁচে থাকে, আর তখন একই চিহ্ন সব অনুরোধে যেত।
         * ⓘ সেটা কিছুই ভাঙত না — কেবল সুরক্ষাটা নীরবে শূন্য হত।
         */
        $nonce = Csp::rotate();

        $response = $next($request);

        if (strtolower((string) env('ABOS_CSP', 'on')) === 'off') {
            return $response;
        }

        /*
         * আগে থেকে বসানো থাকলে ছোঁয়া হয় না।
         *
         * সামনের প্রক্সি (nginx বা Caddy) একদিন নিজে একটা CSP বসালে
         * দুইটা হেডার একসাথে যেত, আর ব্রাউজার তখন **দুইটার মধ্যে
         * কড়াটা** মানে — ফল হত অপ্রত্যাশিতভাবে ভাঙা পর্দা।
         */
        if (! $response->headers->has('Content-Security-Policy')) {
            $response->headers->set('Content-Security-Policy', implode('; ', $this->policy($nonce)));
        }

        return $response;
    }
}

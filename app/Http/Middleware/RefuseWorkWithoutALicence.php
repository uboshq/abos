<?php

declare(strict_types=1);

namespace App\Http\Middleware;

use App\Core\Licence\LicenceReader;
use Closure;
use Illuminate\Http\Request;
use Symfony\Component\HttpFoundation\Response;

/**
 * কাগজ না থাকলে নতুন কাজ হয় না — কিন্তু নিজের খাতা সবসময় খোলা।
 *
 * ── ⭐ মালিকের সিদ্ধান্ত, ২২ সেপ্টেম্বর ২০২৬ ────────────────────────
 * *"মেয়াদ শেষে সব বন্ধ, কেবল লগইন খোলা"*।
 *
 * ── ⚠️ আর একটা জিনিস মালিকের সাথে কথা বলে খোলা রাখা হয়েছে ──────────
 * **ব্যাকআপ ও রপ্তানি।** ⓘ এটা ক্রেতার **নিজের হিসাবের খাতা** — টাকা
 * না দিলে নতুন কাজ বন্ধ হোক, কিন্তু নিজের খাতা বের করে নেওয়ার পথ বন্ধ
 * করলে সেটা আর লাইসেন্সিং থাকে না, জিম্মি করা হয়ে যায়।
 *
 * ⛔ আর বাংলাদেশে হিসাবের খাতা চাইলে দেখাতে বাধ্য — অর্থাৎ ওটা কেবল
 * ভদ্রতা নয়, আইনি ঝুঁকিও।
 *
 * ── ⓘ কেন "কাগজ নেই" মানে **বন্ধ**, খোলা নয় ────────────────────────
 * উল্টোটা করলে তালাটার কোনো মানেই থাকত না: যে কেউ ফাইলটা মুছে দিলেই
 * সব খুলে যেত। ⚠️ তাই মালিকের নিজের ইনস্টলও একটা কাগজ পায় — কেবল
 * সেখানে মেয়াদের ঘর খালি, চিরকালীন।
 *
 * ⭐ কোনো বিশেষ নিয়ম নেই, আর সেটাই মূল কথা: *"আমাদের নিজের সার্ভার
 * হলে ছাড়"* — যেভাবেই সেটা চেনানো হোক (ডোমেইন, `.env`-এর একটা লাইন),
 * **ক্রেতাও ঠিক সেভাবেই নিজেকে চেনাতে পারবেন**।
 *
 * ── ⚠️ ডিফল্টে তালাটা ঘুমিয়ে থাকে ──────────────────────────────────
 * `abos.licence.enforced` ডিফল্ট `false`। ⛔ নাহলে এই কোড নামার
 * মুহূর্তেই প্রতিটা সার্ভার তালাবদ্ধ হত — মালিকেরটাসহ, কারণ কোথাও
 * এখনো কাগজ বসানো নেই।
 */
final class RefuseWorkWithoutALicence
{
    /**
     * ⭐ যে পথগুলো কোনোদিন তালাবদ্ধ হয় না।
     *
     * ⓘ নাম ধরে, ঠিকানা ধরে নয় — ঠিকানা বদলায়, নাম বদলায় না। ⚠️ আর
     * শুরুর অংশ মিলিয়ে দেখা হয় (`backup.`), তাই ব্যাকআপ মডিউলে নতুন
     * একটা পর্দা যোগ হলে সেটা নিজে থেকেই খোলা থাকে — নাহলে একদিন কেউ
     * "ব্যাকআপ নামানো" যোগ করে এখানে বসাতে ভুলতেন, আর ক্রেতা নিজের
     * খাতা নামাতে না পেরে আটকে যেতেন।
     *
     * @var list<string>
     */
    private const ALWAYS_OPEN = [
        /* ঢোকা-বেরোনো — নাহলে কেউ পর্দাটাই দেখতে পেতেন না */
        'login',
        'logout',
        'password.',
        'two_factor.',

        /* ⭐ নিজের খাতা — উপরের টীকা দেখুন */
        'backup.',

        /* কাগজটা বসানোর ও অবস্থা দেখার পর্দা */
        'licence.',

        /* ⓘ স্বাস্থ্য-পরীক্ষা, নাহলে তালাবদ্ধ সার্ভার "মৃত" দেখাত */
        'up',
    ];

    public function __construct(private readonly LicenceReader $licences) {}

    public function handle(Request $request, Closure $next): Response
    {
        if (! config('abos.licence.enforced', false)) {
            return $next($request);
        }

        $name = (string) $request->route()?->getName();

        foreach (self::ALWAYS_OPEN as $open) {
            if ($name === $open || str_starts_with($name, $open)) {
                return $next($request);
            }
        }

        $verdict = $this->licences->read();

        if ($verdict->isValid()) {
            return $next($request);
        }

        /*
         * ⓘ পর্দায় পাঠানো হয়, ৪০৩ নয়।
         *
         * ⚠️ ৪০৩ দিলে মানুষ ভাবতেন তাঁর **অনুমতি** নেই, আর প্রশাসককে
         * খুঁজতেন — অথচ সমস্যাটা অনুমতির নয়, কাগজের। ⛔ একটা ভুল
         * ব্যাখ্যা মানুষকে ভুল জায়গায় ঘণ্টাখানেক ঘোরায়।
         */
        return redirect()->route('licence.show');
    }
}

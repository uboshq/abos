<?php

declare(strict_types=1);

namespace App\Http\Controllers\Auth;

use App\Core\Engines\Audit\AuditEngine;
use App\Http\Controllers\Controller;
use App\Models\User;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\Password as PasswordBroker;
use Illuminate\Support\Str;
use Illuminate\Validation\Rules\Password;
use Illuminate\Validation\ValidationException;
use Illuminate\View\View;

/**
 * ⛔ পাসওয়ার্ড ভুলে গেলে ফেরার পথ — ১৩ সেপ্টেম্বর ২০২৬।
 *
 * ── কী ভাঙা ছিল ──────────────────────────────────────────────────────
 * ⓘ আজ পর্যন্ত পথটা একটাই ছিল: **মালিককে বলা**। তিনি
 * `UserController::update()`-এ গিয়ে হাতে পাসওয়ার্ড বসিয়ে দিতেন
 * (`password_set`)। ⚠️ অর্থাৎ রাত দশটায় ডিপোর একজন কর্মী নিজের
 * পাসওয়ার্ড ভুলে গেলে **পরদিন সকাল পর্যন্ত ব্যবস্থাটার বাইরে**, আর
 * মালিকের ফোনে আরেকটা কল।
 *
 * ── ⭐ চারটা সিদ্ধান্ত, আর প্রতিটাই একটা আক্রমণ ঠেকায় ────────────────
 *
 * **১ · ইমেইল আছে কি নেই — উত্তর একই।** ⛔ Laravel-এর ডিফল্ট আচরণ
 * "We can't find a user with that email address" বলে, অর্থাৎ বাইরের
 * যে কেউ ঠিকানা বসিয়ে বসিয়ে **কর্মীদের তালিকা গুনে নিতে পারতেন**।
 * এখানে দুই ক্ষেত্রেই এক বার্তা — `CredentialCheck`-এ লগইনের বেলায়
 * ঠিক এই একই সিদ্ধান্তটা নেওয়া আছে, আর একই কারণে।
 *
 * **২ · রিসেটের পর ঢোকানো হয় না।** ⛔ Laravel-এর নিজের starter kit
 * রিসেটের পরপরই `Auth::login()` ডাকে। ⚠️ এখানে সেটা করলে **দুই ধাপের
 * লগইনটাই এড়িয়ে যাওয়া যেত**: যার MFA চালু, তার ইমেইল দখল করতে পারলেই
 * ফোনের কোড ছাড়াই ভেতরে। তাই রিসেট কেবল পাসওয়ার্ডটা বদলায়, আর মানুষ
 * স্বাভাবিক দরজা দিয়েই ঢোকেন — যেখানে MFA আগের মতোই চায়।
 *
 * **৩ · `remember_token` নতুন করে বসে।** ⓘ পাসওয়ার্ড ভুলে যাওয়ার
 * সবচেয়ে সাধারণ কারণ যেমন ভুলে যাওয়া, তেমনি একটা সম্ভাবনা **অ্যাকাউন্ট
 * অন্য কারও হাতে যাওয়া**। পুরনো "মনে রাখুন" কুকি বেঁচে থাকলে রিসেটের
 * পরেও সেই ব্রাউজারটা ভেতরে থেকে যেত।
 *
 * **৪ · খাতায় আলাদা নাম।** `password_set` মানে মালিক বসিয়েছেন;
 * `password_reset` মানে মানুষটা নিজে ইমেইল যাচাই করে বদলেছেন। ⚠️ দুইটা
 * এক নামে লিখলে নিরীক্ষায় **"এটা কি অনুমোদিত ছিল"** প্রশ্নের উত্তর
 * হারাত।
 *
 * ── throttle কোথায় ──────────────────────────────────────────────────
 * ⓘ এখানে নয়, রুটে — `routes/auth.php`। `CredentialCheck`-এর মন্তব্যে
 * কারণটা লেখা: একটা সার্ভিস বা কন্ট্রোলার হারের সীমা বহন করতে পারে না।
 */
class PasswordResetController extends Controller
{
    public function __construct(private readonly AuditEngine $audit) {}

    /** ঠিকানা চাওয়ার পর্দা। */
    public function request(): View
    {
        return view('auth.forgot');
    }

    /**
     * লিংক পাঠানো — বা না পাঠানো, কিন্তু বলা একই কথা।
     *
     * ── ⚠️ কেন ফলটা দেখা হয় না ──────────────────────────────────────
     * `sendResetLink()` চারটা আলাদা অবস্থা ফেরত দেয় — পাঠানো হয়েছে,
     * ব্যবহারকারী নেই, সদ্য পাঠানো হয়েছে (ব্রোকারের নিজের ৬০ সেকেন্ডের
     * তালা), পাঠাতে ব্যর্থ। ⛔ চারটার জন্য চার রকম বার্তা দিলে **প্রতিটা
     * বার্তাই একটা তথ্য**: "এই ঠিকানাটা আছে", "এই ঠিকানায় একটু আগে
     * চাওয়া হয়েছিল"।
     *
     * ⓘ তাই ফলটা ইচ্ছাকৃতভাবে ফেলে দেওয়া হয়, আর পর্দা একটাই বাক্য বলে।
     * ⭐ যিনি সত্যিই ভুলে গেছেন তাঁর কিছু হারায় না — তিনি চিঠিটা পান।
     * যিনি তালিকা বানাতে এসেছেন তিনি কিছুই শেখেন না।
     *
     * ⚠️ যা এটা ঢাকে না: **সময়**। ব্যবহারকারী থাকলে একটা চিঠি তৈরি ও
     * পাঠানো হয়, আর সেটা কয়েক মিলিসেকেন্ড বেশি নেয় — অর্থাৎ ঘড়ি ধরে
     * মাপলে তফাতটা এখনো বোঝা যায়।
     *
     * ⓘ সাধারণ সমাধান হলো চিঠিটা কিউতে পাঠানো, আর `QUEUE_CONNECTION`
     * সত্যিই `database`। ⛔ কিন্তু এই রিপোর নিজের খাতায় মেপে লেখা
     * আছে — *"কিউ বসানো আছে, ব্যবহার শূন্য"*, `ShouldQueue` ব্যবহার
     * শূন্য আর কোনো ওয়ার্কার চলে না। ⚠️ তাই আজ কিউতে দিলে চিঠিটা
     * টেবিলে বসে থাকত আর **কোনোদিন যেত না** — একটা মাপা যায় এমন
     * সময়-ফাঁকের বদলে একটা সম্পূর্ণ নীরব ব্যর্থতা।
     *
     * ⭐ ওয়ার্কার চালু হওয়ার দিন এখানে `ShouldQueue` বসানোই সঠিক পদক্ষেপ।
     * কথাটা লেখা রইল যাতে কেউ ভেবে না নেন ফাঁকটা নেই।
     */
    public function email(Request $request): RedirectResponse
    {
        $data = $request->validate([
            'email' => ['required', 'string', 'email', 'max:191'],
        ]);

        PasswordBroker::sendResetLink(['email' => $data['email']]);

        return back()->with('sent', true);
    }

    /**
     * নতুন পাসওয়ার্ড বসানোর পর্দা।
     *
     * ⓘ টোকেনটা এখানে যাচাই করা হয় না, ইচ্ছাকৃতভাবে। যাচাই হয় জমা
     * দেওয়ার সময় (`PasswordBroker::reset()`), কারণ ততক্ষণে মেয়াদ শেষ
     * হয়ে যেতে পারে — আর দুই জায়গায় যাচাই মানে দুই জায়গায় নিয়ম, আর
     * একদিন একটা বদলে অন্যটা থেকে যায়।
     */
    public function reset(Request $request, string $token): View
    {
        return view('auth.reset', [
            'token' => $token,
            'email' => (string) $request->query('email', ''),
        ]);
    }

    /**
     * বদলটা বসানো।
     *
     * ⚠️ পাসওয়ার্ডের নিয়ম **কর্মীর দরজার সমান**, আর সেটা এখানে হাতে
     * মেলানো হয়নি — [[NoDoorIsWeakerThanTheStaffDoorTest]] প্রতিটা
     * পাসওয়ার্ড-নিয়ম খুঁজে বের করে প্রমাণ করে কোনোটাই ঢিলা নয়। ঢিলা
     * লিখলে যন্ত্রই বলে দেবে।
     */
    public function store(Request $request): RedirectResponse
    {
        $data = $request->validate([
            'token' => ['required', 'string'],
            'email' => ['required', 'string', 'email', 'max:191'],
            'password' => ['required', 'confirmed', Password::min(8)->letters()->numbers()],
        ]);

        $status = PasswordBroker::reset($data, function (User $user, string $password): void {
            /*
             * ⓘ `forceFill` — `password` আর `remember_token` কোনোটাই
             * `$fillable`-এ নেই, আর থাকা উচিতও নয়।
             *
             * ⚠️ `password` ঘরে `hashed` cast বসানো, তাই সাদা লেখাটাই
             * দিতে হয়; এখানে নিজে `Hash::make()` করলে **দুইবার হ্যাশ**
             * হত আর কেউ আর কোনোদিন ঢুকতে পারতেন না।
             */
            $user->forceFill([
                'password' => $password,
                'remember_token' => Str::random(60),
            ])->save();

            /*
             * ⭐ খাতায় ঘটনাটা, মানটা নয়।
             *
             * ⓘ `password` আর `remember_token` দুইটাই অডিটের বাদ-তালিকায়
             * ([[User::auditIgnores()]] ও `AuditEngine::NEVER_LOGGED`),
             * তাই উপরের `save()` থেকে কোনো ঘর-ধরে সারি বসে না — আর
             * যেহেতু বদলের তালিকা খালি, "সম্পাদনা" সারিটাও বসে না।
             * ঘটনাটা তাই আলাদা করে লিখতে হয়।
             *
             * ── ⚠️ কর্তার ঘরটা খালি থাকে, আর সেটাই সত্যি ─────────────
             * এই মুহূর্তে কেউ লগইন করা নেই, তাই `audit_trails.user_id`
             * null। ⛔ সেটা তথ্যের অভাব নয়, **তথ্যটাই**: `password_set`
             * সারিতে একজন প্রশাসকের নাম থাকে, আর এখানে থাকে না —
             * অর্থাৎ সারিটা নিজেই বলে দেয় এটা মালিকের বসানো নয়, মানুষটার
             * নিজের রিসেট। ⓘ আর "কে" প্রশ্নের যতটা উত্তর দেওয়া সম্ভব
             * তা সারিতেই আছে: কার অ্যাকাউন্ট, কোন IP, কোন ব্রাউজার।
             */
            $this->audit->recordAction($user, 'password_reset');
        });

        if ($status !== PasswordBroker::PASSWORD_RESET) {
            /*
             * ⛔ দুইটা আলাদা ব্যর্থতা, **একটাই বার্তা** — আর এটা এখানে
             * ঠিক ততটাই জরুরি যতটা প্রথম ধাপে।
             *
             * ── কী ধরা পড়েছিল (১৩ সেপ্টেম্বর ২০২৬, লেখার সময়) ───────
             * প্রথম খসড়ায় এখানে `__($status)` ছিল, অর্থাৎ ব্রোকারের
             * নিজের বার্তা। ⚠️ ব্রোকার দুইটা আলাদা কথা বলে:
             *
             *     passwords.user   "We can't find a user with that email"
             *     passwords.token  "This password reset token is invalid"
             *
             * ⛔ আর এই পদ্ধতিতে পৌঁছাতে **বৈধ টোকেন লাগে না** — যে কেউ
             * সরাসরি `POST /reset-password`-এ যেকোনো আবোল-তাবোল টোকেন
             * আর একটা ঠিকানা পাঠাতে পারেন। ব্যবহারকারী থাকলে উত্তর
             * আসত "টোকেন অচল", না থাকলে "এই ঠিকানায় কেউ নেই।"
             *
             * ⚠️ অর্থাৎ প্রথম ধাপে যে দরজাটা সাবধানে বন্ধ করা হলো,
             * **এই ধাপটা সেটাই খুলে দিত** — একই তালিকা, অন্য পথে।
             *
             * ⓘ এক বার্তা দিলে কিছু হারায় না: যাঁর লিংকটা সত্যিই পুরনো,
             * তাঁর করণীয় দুই ক্ষেত্রেই এক — নতুন একটা লিংক চাওয়া।
             */
            throw ValidationException::withMessages([
                'email' => __('auth.reset_link_dead'),
            ]);
        }

        /*
         * ⛔ `Auth::login()` **নেই**, আর এটাই এই পদ্ধতির সবচেয়ে জরুরি
         * লাইন — যেটা লেখা হয়নি সেটাই।
         *
         * ⚠️ ঢুকিয়ে দিলে যার দুই ধাপের লগইন চালু, তার ইমেইল দখল করেই
         * ফোনের কোড এড়ানো যেত — অর্থাৎ MFA-টা একটা ইমেইল-রিসেটের
         * সমান হয়ে যেত। তিনি স্বাভাবিক দরজা দিয়েই ফিরবেন, আর সেখানে
         * কোডটা আগের মতোই চাওয়া হবে।
         */
        return redirect()->route('login')->with('password_reset', true);
    }
}

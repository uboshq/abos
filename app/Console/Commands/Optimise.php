<?php

declare(strict_types=1);

namespace App\Console\Commands;

use Illuminate\Console\Command;

/**
 * সার্ভারে তোলার পর একবার — কনফিগ, রুট, ইভেন্ট আর Blade আগেভাগে গুছিয়ে রাখা।
 *
 * ── কেন আলাদা কমান্ড, ডেভেও চালু নয় ─────────────────────────────────
 * ক্যাশগুলো ছাড়া প্রতিটা রিকোয়েস্টে ফ্রেমওয়ার্ক ৩০-এর বেশি কনফিগ ফাইল
 * পড়ে, সব মডিউলের রুট নতুন করে সাজায়, আর প্রতিটা Blade ফাইলের তারিখ
 * মিলিয়ে দেখে বদলেছে কি না। মাপা লাভ পাতাপ্রতি প্রায় ১০ মিলিসেকেন্ড —
 * বড় নয়, কিন্তু দিনে কয়েকশো পাতায় সেটা জমে।
 *
 * তবু ডেভেলপমেন্টে এটা চালানো হয় না, আর কারণটা তেতো অভিজ্ঞতা:
 *
 *   • config ক্যাশ থাকলে .env বদলে আর কিছুই হয় না — মানুষ ভাবে কোড
 *     ভেঙেছে, আসলে ক্যাশ পুরনো
 *   • config ক্যাশ থাকলে টেস্টও ওই ক্যাশ পড়ে, অর্থাৎ ডেভ ডাটাবেজে
 *     — টেস্ট স্যুট আসল তথ্য মুছে দিতে পারত
 *   • route ক্যাশ থাকলে নতুন রুট ৪০৪ দেয়, নীরবে
 *
 * তাই নিয়মটা সহজ: ডেভে ক্যাশ নেই, সার্ভারে আছে। এই কমান্ডটাই সেই
 * সীমারেখা — আর নিচের সতর্কবার্তাটা যাতে ভুল জায়গায় কেউ চালিয়ে না বসে।
 */
class Optimise extends Command
{
    protected $signature = 'abos:optimise
        {--clear : উল্টোটা করো — সব ক্যাশ মুছে দাও (কোড বদলানোর আগে)}
        {--force : local পরিবেশেও চালাও (মেপে দেখার জন্য)}';

    protected $description = 'সার্ভারের জন্য কনফিগ, রুট, ইভেন্ট ও Blade ক্যাশ তৈরি করে';

    public function handle(): int
    {
        if ($this->option('clear')) {
            foreach (['config:clear', 'route:clear', 'event:clear', 'view:clear'] as $command) {
                $this->call($command);
            }

            $this->info('সব ক্যাশ মোছা হয়েছে। এখন কোড বদলালে সাথে সাথেই কাজ করবে।');

            return self::SUCCESS;
        }

        /*
         * local-এ থামা, কিন্তু দেয়াল নয়।
         *
         * কেউ ইচ্ছে করে ডেভে মেপে দেখতে চাইলে --force দিয়ে পারবেন;
         * ভুল করে চালিয়ে ফেলা আর জেনেশুনে চালানো এক জিনিস নয়।
         */
        if (app()->environment('local') && ! $this->option('force')) {
            $this->warn('এটা local পরিবেশ। ক্যাশ বানালে .env ও নতুন রুট আর কাজ করবে না,');
            $this->warn('আর টেস্ট ভুল ডাটাবেজে চলতে পারে। সত্যিই দরকার হলে --force দিন।');

            return self::FAILURE;
        }

        /*
         * অনুমতিগুলো আগে, ক্যাশ পরে।
         *
         * ── কেন এটা এখানে বসল ───────────────────────────────────────
         * এটা ক্যাশের কাজ নয়, কিন্তু এই কমান্ডটাই ডিপ্লয়ের শেষ ধাপ,
         * আর অনুমতি বসানো ভুলে যাওয়ার খেসারত নীরব: নতুন পর্দা সবার
         * জন্য "Forbidden" দেখায় আর কোথাও কোনো ভুলের চিহ্ন থাকে না।
         *
         * একবার সত্যিই ঘটেছে — `sales.cost.view` ও
         * `sales.reprint.override` কয়েক দিন ধরে চালু সাইটে ছিল অথচ
         * কাজ করেনি, কারণ ডিপ্লয়ের পর কমান্ডটা চালানো হয়নি।
         *
         * আলাদা কমান্ডটা রয়ে গেছে (`abos:sync-permissions`), কারণ
         * ক্যাশ না বানিয়েও কখনো কখনো কেবল অনুমতি বসাতে হয়।
         */
        $this->call('abos:sync-permissions');

        /*
         * একই কারণে ছকও — আর একই ভুল দ্বিতীয়বার ধরা পড়ার পর।
         *
         * চেকের খাতা বানিয়ে ব্রাউজারে চালাতে গিয়ে দেখা গেল চলমান
         * কোম্পানিতে "হিসাবের ছকটা এখনো বসানো হয়নি" — কারণ নতুন খাত
         * দুইটা (হাতে চেক ১১০৪, দেওয়া চেক ২১১৫) কেবল **নতুন** কোম্পানি
         * তৈরির সময় বসত। `install()` আগে থেকেই কেবল অনুপস্থিতগুলো
         * বসায়; কেউ ওটা ডাকত না, এই যা।
         *
         * এখন ডিপ্লয় নিজেই নিজেকে সারায়, ঠিক অনুমতির মতো।
         */
        $this->call('abos:sync-chart');

        foreach (['config:cache', 'event:cache', 'route:cache', 'view:cache'] as $command) {
            $this->call($command);
        }

        $this->newLine();
        $this->info('হয়ে গেছে। কোড বা .env বদলালে আবার এই কমান্ডটা চালাতে হবে —');
        $this->info('নইলে পুরনো ক্যাশই চলতে থাকবে।');

        return self::SUCCESS;
    }
}

<?php

declare(strict_types=1);

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Symfony\Component\Process\Process;

/**
 * সুইট চালানোর তালা — একই টেস্ট-ডাটাবেসে দুইজন যেন একসাথে না ঢোকে।
 *
 * ── কেন এটা লেখা হলো, ২ সেপ্টেম্বর ২০২৬ ─────────────────────────────
 * এই রিপোতে একই ওয়ার্কিং ট্রি ও একই `abos_test` ভাগ করে একাধিক সেশন
 * কাজ করে। এক বিকেলে **তিনবার** দুইটা রান পরস্পরকে কেটে দিয়েছে, আর
 * প্রতিবারই দুই পক্ষ শিষ্টাচার মানছিল: "নিচ্ছি" বলে নেওয়া, শেষ হলে
 * "ছাড়লাম" বলা।
 *
 * শিষ্টাচারটা কাজ করেনি, আর কারণটা সরল — **বার্তা পৌঁছাতে সময় লাগে,
 * রান শুরু হতে লাগে না**। আর মাপাও কাজ করেনি: `information_schema`-তে
 * টেবিলের সংখ্যা স্থির দেখে "শেষ" ধরে নেওয়া হয়েছিল, অথচ ওই নিঃশব্দ
 * মুহূর্তটা ছিল **দুইটা রানের মাঝখান** — সিডিং আর assert-এর ফাঁক।
 *
 * > বাইরে থেকে "শেষ হয়ে গেছে" আর "মাঝখানে আছে" **দেখতে হুবহু এক**।
 * > কোনো পরিমাপ এই দুইটাকে আলাদা করতে পারে না — কেবল ধরে রাখা পারে।
 *
 * তাই নিয়মটা আর মনে রাখার উপর নয়, যন্ত্রে।
 *
 * ── কেন MySQL-এর নিজের তালা, ফাইল নয় ────────────────────────────────
 * একটা lock-ফাইলের সবচেয়ে বড় সমস্যা **বাসি তালা**: প্রক্রিয়াটা ক্র্যাশ
 * করলে, কেউ Ctrl-C চাপলে, বা মেশিন রিবুট হলে ফাইলটা থেকে যায় আর
 * পরের জন চিরকাল আটকে থাকেন।
 *
 * `GET_LOCK` **সংযোগের সাথে বাঁধা** — সংযোগ মরলেই তালা খুলে যায়, তা
 * সে যেভাবেই মরুক। বাসি তালা বলে কিছু থাকে না, আর কোনো নতুন নির্ভরতাও
 * লাগে না; mysqld তো চলছেই।
 *
 * ── ⚠️ পুরো রানটা ধরে রাখা হয়, শুধু শুরুটা নয় ───────────────────────
 * এটাই আসল কথা। কেবল শুরুতে তালা নিয়ে ছেড়ে দিলে ঠিক সেই ফাঁদটাই ফিরে
 * আসত: সিডিং আর assert-এর মাঝের নিঃশব্দ মুহূর্তটা আবার "শেষ"-এর মতো
 * দেখাত। তাই তালাটা নেওয়া হয় `migrate:fresh`-এর আগে আর ছাড়া হয়
 * **শেষ assert-এর পরে** — গোটা নিঃশব্দতাটা তালার ভেতরে থাকে।
 *
 * ── ব্যবহার ─────────────────────────────────────────────────────────
 *     php artisan abos:test-lock                      পুরো সুইট
 *     php artisan abos:test-lock --filter=SyncEngine  অংশ
 *     php artisan abos:test-lock --wait=900           খালি হওয়া পর্যন্ত অপেক্ষা
 */
class TestLock extends Command
{
    protected $signature = 'abos:test-lock
        {--filter= : phpunit-এর --filter, হুবহু পাস হয়}
        {--wait=0 : তালার জন্য কত সেকেন্ড অপেক্ষা; ০ মানে অপেক্ষা নয়}';

    protected $description = 'তালা ধরে টেস্ট চালায় — একই abos_test-এ দুইজন একসাথে ঢোকে না';

    /**
     * তালার নাম। MySQL-এর তালা **সার্ভার-ব্যাপী**, ডাটাবেস-ভিত্তিক নয়,
     * তাই নামটাই একমাত্র সীমানা — আর সে কারণেই নামে ডাটাবেসটা আছে।
     */
    private const LOCK = 'abos_test_owner';

    public function handle(): int
    {
        $wait = max(0, (int) $this->option('wait'));

        /*
         * ⚠️ তালাটা এই সংযোগের, তাই এই সংযোগটাই পুরো রান জুড়ে খোলা
         * থাকতে হবে।
         *
         * Laravel-এর ডিফল্ট সংযোগটাই ব্যবহার করা হয় আর কমান্ডটা শেষ
         * না হওয়া পর্যন্ত সেটা বাঁচে। টেস্টগুলো চলে **আলাদা প্রক্রিয়ায়**
         * (নিচের Process), তাদের নিজের সংযোগে — তাই তারা এই তালার
         * খবরই রাখে না, আর রাখারও দরকার নেই।
         */
        $got = (int) DB::selectOne('SELECT GET_LOCK(?, ?) AS ok', [self::LOCK, $wait])->ok;

        if ($got !== 1) {
            $holder = DB::selectOne('SELECT IS_USED_LOCK(?) AS who', [self::LOCK])->who;

            /*
             * "অন্য কেউ চালাচ্ছে" বললে মানুষটা খুঁজতে বেরোন। সংযোগের
             * নম্বরটা বললে প্রশ্নটা শেষ হয়ে যায় — `SHOW PROCESSLIST`-এ
             * ওই আইডি দেখলেই বোঝা যায় কে, কতক্ষণ ধরে, কী চালাচ্ছে।
             */
            $this->error('abos_test এখন অন্য কারো দখলে — সংযোগ #'.($holder ?? 'অজানা'));
            $this->line('  কে ধরে আছে দেখতে:  SHOW PROCESSLIST;');
            $this->line('  খালি হওয়া পর্যন্ত অপেক্ষা করতে:  --wait=900');

            return self::FAILURE;
        }

        $this->info('তালা পাওয়া গেল।');

        try {
            $command = [PHP_BINARY, 'artisan', 'test'];

            if (($filter = $this->option('filter')) !== null && $filter !== '') {
                $command[] = '--filter='.$filter;
            }

            /*
             * ⚠️⚠️ `DB_*` চলকগুলো সন্তানের পরিবেশ থেকে **মুছে দেওয়া হয়**।
             *
             * ── এটা না থাকায় এই কমান্ডটা dev ডাটাবেস মুছে ফেলেছিল ──────
             * ২ সেপ্টেম্বর ২০২৬, প্রথম রানেই। ঘটনাটা হুবহু এই:
             *
             * সাব-প্রসেস বাবার পরিবেশ উত্তরাধিকার পায়। বাবা হলো
             * `php artisan`, যে বুট করার সময় `.env` পড়ে `DB_DATABASE=abos`
             * **পরিবেশে বসিয়ে** দেয়। আর `phpunit.xml`-এর
             * `<env name="DB_DATABASE" value="abos_test"/>` **ইতিমধ্যে থাকা
             * পরিবেশ চলককে ছাপিয়ে যায় না** — PHPUnit ওটাকে ডিফল্ট ধরে,
             * নির্দেশ নয় (`force="true"` ছাড়া)।
             *
             * ফল: পুরো সুইট `abos_test`-এর বদলে **`abos`-এ** চলল, আর
             * `RefreshDatabase` সেখানেই `migrate:fresh` করল। **কোনো
             * ভুলবার্তা নয়** — শুধু dev-এর ডেটা মুছে গেল, আর একই সময়ে
             * পাশের সেশনের `migrate:fresh`-এর সাথে সংঘর্ষ।
             *
             * সবচেয়ে বড় শিক্ষাটা এই কমান্ডের নিজের সম্পর্কে: **দুর্ঘটনা
             * ঠেকাতে লেখা একটা যন্ত্র নতুন একটা দুর্ঘটনা ঘটাল**, আর ঠিক
             * সেই ডাটাবেসেই যেটা ওই দিন আগে দুইবার হারিয়েছিল।
             *
             * `false` মানে Symfony চলকটা সন্তানের পরিবেশ থেকে **সরিয়ে
             * দেয়** — খালি করে না, সরায়। তখন `phpunit.xml`-এর ঘোষণাটাই
             * একমাত্র উৎস, যা শুরু থেকেই উদ্দেশ্য ছিল।
             */
            $target = $this->testDatabaseName();

            if ($target === null) {
                $this->error('phpunit.xml-এ DB_DATABASE ঘোষণা নেই — কোন ডাটাবেসে টেস্ট চলবে বলা যাচ্ছে না।');

                return self::FAILURE;
            }

            /*
             * ⚠️ শেষ পাহারা: টেস্টের ডাটাবেস আর চলতি ডাটাবেস এক হলে থামো।
             *
             * উপরের env-পরিষ্কার করাটা সমস্যাটা সারায়; এই লাইনটা সারানোর
             * **প্রমাণ** চায়। কেউ যদি একদিন `.env`-এ `DB_DATABASE=abos_test`
             * বসিয়ে দেন, বা `phpunit.xml` বদলে যায়, তখন এই কমান্ড dev
             * ডাটাবেসেই `migrate:fresh` করত — নীরবে, আজকের মতোই।
             *
             * সন্দেহ হলে চালানোর চেয়ে থেমে যাওয়া ভালো: থামলে কেউ বিরক্ত
             * হন, চললে কারো একদিনের কাজ চলে যায়।
             */
            if ($target === DB::connection()->getDatabaseName()) {
                $this->error("টেস্টের ডাটাবেস আর চলতি ডাটাবেস একই — '{$target}'.");
                $this->line('  এভাবে চালালে migrate:fresh উন্নয়নের ডেটা মুছে ফেলত।');
                $this->line('  phpunit.xml আর .env মিলিয়ে দেখুন — দুইটা আলাদা হতেই হবে।');

                return self::FAILURE;
            }

            /*
             * ⚠️ নামটা চোখের সামনে ছাপা হয়, কেবল যাচাই করা হয় না।
             *
             * আজ দুইজন মানুষ **দুইটা আলাদা উপায়ে** একই ভুল করেছি: একটা
             * কনফিগ ফাইল পড়েছি যেটা প্রশ্নের উত্তর দিচ্ছে বলে মনে হয়েছিল,
             * আর চলন্ত প্রক্রিয়াটা আসলে কোথায় যুক্ত হয়েছে তা কখনো
             * যাচাই করিনি। কেউ অসাবধান ছিলাম না — তথ্যটাই পর্দায় ছিল না।
             *
             * উপরের `if`-টা ভুল হলে থামায়; এই লাইনটা **ঠিক থাকলেও দেখায়**,
             * তাই মানুষ প্রতিবার নিজের চোখে মিলিয়ে নিতে পারেন।
             */
            $this->line('  চলতি ডাটাবেস : '.DB::connection()->getDatabaseName());
            $this->line('  টেস্ট চলবে   : '.$target);

            $process = new Process($command, base_path(), [
                /*
                 * নামটা **স্পষ্ট করে** পাঠানো হয়, উত্তরাধিকারের উপর ছেড়ে
                 * নয়। বাকি `DB_*` চলকগুলো `false` দিয়ে সরিয়ে দেওয়া হয়,
                 * যাতে `.env`-এর কোনো অংশ চুপিসারে ভেতরে না ঢোকে।
                 */
                'DB_DATABASE' => $target,
                'DB_CONNECTION' => false,
                'DB_HOST' => false,
                'DB_PORT' => false,
                'DB_USERNAME' => false,
                'DB_PASSWORD' => false,
                'DB_URL' => false,
            ]);

            /*
             * সময়সীমা নেই। পুরো সুইট প্রায় তিন ঘণ্টার, আর Symfony-র
             * ডিফল্ট ৬০ সেকেন্ড — সেটা রেখে দিলে কমান্ডটা প্রতিবার
             * রানের মাঝখানে টেস্ট প্রক্রিয়াটা মেরে ফেলত, আর **তালাটা
             * ছেড়ে দিত ঠিক তখনই যখন ডাটাবেস অর্ধেক-মাইগ্রেটেড** — অর্থাৎ
             * ঠিক যে দুর্ঘটনাটা এই কমান্ড ঠেকানোর জন্য লেখা।
             */
            $process->setTimeout(null);

            $process->run(function (string $type, string $buffer): void {
                $this->output->write($buffer);
            });

            return $process->getExitCode() ?? self::FAILURE;
        } finally {
            /*
             * `finally` — কারণ টেস্ট লাল হলেও, ব্যতিক্রম উঠলেও তালাটা
             * ছাড়তেই হবে। না ছাড়লেও সংযোগ বন্ধ হলে MySQL নিজেই ছেড়ে
             * দিত, কিন্তু সেটা ভাগ্যের উপর ছেড়ে দেওয়া — আর পরের জন
             * ততক্ষণ অপেক্ষা করতেন।
             */
            DB::selectOne('SELECT RELEASE_LOCK(?) AS ok', [self::LOCK]);
            $this->line('তালা ছাড়া হলো।');
        }
    }

    /**
     * টেস্ট কোন ডাটাবেসে চলার কথা — `phpunit.xml` থেকে, অনুমান থেকে নয়।
     *
     * ── কেন ফাইলটা নিজে পড়া হয় ──────────────────────────────────────
     * `config('database...')` এখানে **চলতি** প্রক্রিয়ার উত্তর দেয়, আর
     * সেটা `.env` থেকে আসা dev ডাটাবেস — অর্থাৎ ঠিক ভুল উত্তরটা। আর
     * নামটা কোডে হাতে লিখলে `phpunit.xml` বদলানোর দিন দুইটা আলাদা সত্য
     * হত, যার একটা নীরবে পুরনো।
     *
     * তাই যে ফাইলটা আসলে ঠিক করে, সেটাই জিজ্ঞেস করা হয়।
     */
    private function testDatabaseName(): ?string
    {
        $path = base_path('phpunit.xml');

        if (! is_file($path)) {
            return null;
        }

        $xml = @simplexml_load_file($path);

        if ($xml === false) {
            return null;
        }

        foreach ($xml->xpath('//php/env') ?: [] as $env) {
            if ((string) $env['name'] === 'DB_DATABASE') {
                $value = trim((string) $env['value']);

                return $value === '' ? null : $value;
            }
        }

        return null;
    }
}

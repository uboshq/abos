<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Core\Services\BackupService;
use Illuminate\Console\Command;
use Illuminate\Support\Carbon;

/**
 * আজকের ব্যাকআপটা কি হয়েছে? না হলে এখনই নাও।
 *
 * ── কী ভাঙা ছিল ─────────────────────────────────────────────────────
 * ব্যাকআপ বাঁধা ছিল একটা **ঘড়ির কাঁটায়**: `dailyAt('01:30')`। Laravel-এর
 * শিডিউলার প্রতি মিনিটে জেগে দেখে "এখন কি ০১:৩০?" — আর কেবল ওই এক
 * মিনিটেই হ্যাঁ বলে।
 *
 * ফলে ওই এক মিনিটটা ফসকে গেলে **ওই দিন আর কোনো ব্যাকআপ হয় না**, আর
 * পরদিন পর্যন্ত কেউ জানেও না। ফসকানোর কারণ অনেক, আর সবগুলোই সাধারণ:
 *
 *   · শিডিউলার প্রতি মিনিটে ঠিক ৬০.০ সেকেন্ড পরে চলে না — সামান্য
 *     ড্রিফট জমে একদিন পুরো একটা মিনিট লাফিয়ে যায়;
 *   · মেশিন ঘুমিয়ে থাকলে জেগে ওঠার পর ওই মিনিটটা পেরিয়ে গেছে;
 *   · রিবুট, আপডেট, বা এক মিনিটের নেটওয়ার্ক আটকে যাওয়া।
 *
 * Mac mini-তে ধরা পড়েছে: ১৫, ১৭, ১৮, ১৯ আগস্ট চলেছে — **১৬ আর ২০ চলেনি**।
 * লগে কোনো ভুল নেই, কারণ ভুল কিছু হয়নি; প্রশ্নটাই কেবল করা হয়নি।
 *
 * ── কেন এই কমান্ডটা আলাদা ───────────────────────────────────────────
 * এটা ঘড়ি দেখে না, **ফোল্ডার দেখে**: আজকের তারিখের কোনো ডাম্প আছে কি?
 * না থাকলে নেয়। ঘণ্টায় ঘণ্টায় চললে ফসকানো মিনিট, ঘুমন্ত মেশিন বা
 * রিবুট — তিনটার কোনোটাই আর ব্যাকআপ কাড়তে পারে না, কারণ পরের ঘণ্টাতেই
 * প্রশ্নটা আবার ওঠে।
 *
 * এটাকে বলে self-healing: ব্যর্থতা মনে রাখতে হয় না, অবস্থাটাই উত্তর।
 *
 * ── কেন দিনে একবারই, ঘণ্টায় নয় ──────────────────────────────────────
 * ঘণ্টায় ব্যাকআপ নেওয়া যেত, কিন্তু প্রতিটা ডাম্প যাচাইও করা হয়
 * (ফিরিয়ে এনে টেবিল গোনা) — সেটা ডিস্ক ও সময় দুইটাই খায়। দিনে একটা
 * যাচাই করা ডাম্পই এখানকার নীতি; এই কমান্ড কেবল নিশ্চিত করে যে ওই
 * একটা সত্যিই হয়েছে।
 */
class BackupDue extends Command
{
    protected $signature = 'abos:backup-due
        {--force : আজকের ডাম্প থাকলেও আরেকটা নাও}';

    protected $description = 'আজকের ব্যাকআপ না হয়ে থাকলে এখনই নেয়';

    public function handle(BackupService $backups): int
    {
        $today = Carbon::today();

        if (! $this->option('force') && $this->takenOn($backups, $today)) {
            $this->line('আজকের ব্যাকআপ আগেই নেওয়া হয়েছে — কিছু করার নেই।');

            return self::SUCCESS;
        }

        $this->info('আজকের ব্যাকআপ পাওয়া যায়নি, এখনই নেওয়া হচ্ছে…');

        /*
         * কাজটা `abos:backup`-কেই দেওয়া হয়, এখানে আবার লেখা হয় না।
         *
         * ডাম্প নেওয়া, যাচাই করা, দ্বিতীয় কপি, পুরনো মোছা — সবই ওখানে
         * আছে। দ্বিতীয় একটা কপি লিখলে একদিন দুইটা আলাদা হত, আর তখন
         * কোনটা সত্যি তা বলা যেত না।
         */
        return $this->call('abos:backup');
    }

    /**
     * ওই দিনের কোনো ডাম্প ফাইলের নামেই আছে কি না।
     *
     * ── কেন ফাইলের নাম, ফাইলের সময় নয় ───────────────────────────────
     * `filemtime()` বদলে যায় — ফাইল কপি করলে, ডিস্ক থেকে ডিস্কে সরালে,
     * বা কিছু ব্যাকআপ-টুল ছুঁয়ে গেলে। নামটা বদলায় না, আর নামেই তারিখ
     * লেখা আছে (`abos-2026-08-20-013041.sql.gz`)।
     *
     * তাই প্রশ্নটা হয় "আজকের নামে কিছু আছে?", "সাম্প্রতিক কিছু আছে?" নয়।
     */
    private function takenOn(BackupService $backups, Carbon $day): bool
    {
        $stamp = $day->format('Y-m-d');

        foreach ($backups->all() as $file) {
            if (str_contains(basename($file), $stamp)) {
                return true;
            }
        }

        return false;
    }
}

<?php

declare(strict_types=1);

namespace App\Models;

use App\Core\Concerns\BelongsToCompany;
use App\Core\Concerns\HasPublicId;
use Illuminate\Database\Eloquent\Model;

/**
 * একটা ডিভাইস একটা মডিউলের কতদূর পর্যন্ত নামিয়েছে — ওয়াটারমার্ক।
 *
 * ── কেন সার্ভার মনে রাখে, ফোন নয় ────────────────────────────────────
 * ফোন `since` পাঠালে দুইটা জিনিস ভাঙত।
 *
 * **এক, ফোনের ঘড়ি।** সেটা ভুল হতে পারে, আর ভুল ঘড়ির `since` মানে হয়
 * একই ডেটা বারবার নামা, নয় **চুপচাপ বাদ পড়ে যাওয়া রেকর্ড** — আর
 * দ্বিতীয়টা নীরব, তাই খারাপ।
 *
 * **দুই, হারানো উত্তর।** ফোন অনুরোধ পাঠাল, সার্ভার উত্তর দিল, উত্তরটা
 * পথে হারাল। ফোন জানে না সে ওটা পেয়েছিল কি না — তাই `since` এগোবে কি
 * না বলতেই পারে না।
 *
 * সার্ভার মনে রাখলে `GET .../pull` **প্যারামিটারহীন** হয়ে যায়, আর
 * সেটাই তাকে নিরাপদে পুনরাবৃত্তিযোগ্য করে: পরপর দুইবার ডাকলে হুবহু একই
 * ব্যাচ ফেরে।
 *
 * ── ⚠️ এগোনোর নিয়মটাই সবচেয়ে সূক্ষ্ম জায়গা ─────────────────────────
 * [[SyncService::recordSuccessfulPull()]] ওয়াটারমার্ককে **"এখন"**-এ
 * নিয়ে যায়, শেষ ব্যাচের নিজের কাটঅফে নয়। তাই ফোনকে ওটা ডাকতে হয়
 * **কেবল তখনই যখন `hasMore` মিথ্যা আর `unreadable` খালি** — নাহলে ওই
 * ব্যাচের কাটঅফ আর "এখন"-এর মাঝের প্রতিটা রেকর্ড **কোনোদিন না পাঠিয়েই**
 * সিঙ্ক-হয়ে-গেছে বলে চিহ্নিত হত, আর আর কখনো আসত না।
 *
 * নিয়মটা দুই পাশেই লেখা — এখানে আর `reference_sync.dart`-এ — ইচ্ছে
 * করে। এক পাশ ভুল করলে অন্য পাশ ধরে ফেলে।
 */
class SyncState extends Model
{
    use BelongsToCompany;
    use HasPublicId;

    protected $table = 'sync_states';

    protected $fillable = [
        'company_id', 'device_id', 'module', 'last_synced_at',
    ];

    protected function casts(): array
    {
        return [
            'last_synced_at' => 'datetime',
        ];
    }
}

<?php

declare(strict_types=1);

namespace App\Core\Security;

use RuntimeException;

/**
 * পাসওয়ার্ড ঠিক, কিন্তু দুই ধাপের কোডটা বাকি — বা ভুল।
 *
 * ── কেন নিজের ব্যতিক্রম, `ValidationException` নয় ───────────────────
 * এটা "ভুল পরিচয়" নয়, **অসম্পূর্ণ পরিচয়** — আর দুইটার উত্তর আলাদা।
 * ওয়েবে কোডের ঘরটা দেখাতে হয়; ফোনে একটা আলাদা সংকেত পাঠাতে হয় যাতে
 * অ্যাপ কোডের পর্দাটা খোলে।
 *
 * `ValidationException` দিয়ে করলে দুই পাশকেই বার্তার লেখা পড়ে সিদ্ধান্ত
 * নিতে হত — আর বার্তা অনুবাদ হয়, তাই একদিন বাংলা লেখা বদলালে ফোনের
 * পর্দাটা নীরবে ভেঙে যেত।
 *
 * ── ⚠️ কোড ভুল হওয়াটা তালা বাড়ায়, কোড না দেওয়া বাড়ায় না ───────────
 * পার্থক্যটা [[LoginLock::locked()]]-এ বসানো: সে `needs_code` গোনে না,
 * `wrong_code` গোনে। কারণ কোড না দেওয়া লগইনের **স্বাভাবিক প্রথম ধাপ**,
 * প্রতিবারই ঘটে — গোনায় ধরলে দুই-ধাপের প্রতিটা মানুষ আট বার ঢোকার পর
 * নিজেই তালাবদ্ধ হতেন। নিরাপত্তার মতো দেখতে, আসলে নিজেদের কর্মীর উপর
 * একটা denial of service।
 *
 * তাই এই ব্যতিক্রমটা দুই ক্ষেত্রেই ছোঁড়া হয়, আর কোনটা তা [[$wasWrong]]
 * বলে — কিন্তু খাতায় দুইটা আলাদা কারণ বসে, আর তালা কেবল দ্বিতীয়টাকে
 * গোনে।
 */
final class MfaCodeRequired extends RuntimeException
{
    public function __construct(
        string $message,
        /** কোডটা দেওয়া হয়েছিল কিন্তু মেলেনি — না দেওয়ার বদলে। */
        public readonly bool $wasWrong = false,
    ) {
        parent::__construct($message);
    }
}

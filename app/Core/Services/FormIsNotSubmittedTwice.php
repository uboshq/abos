<?php

declare(strict_types=1);

namespace App\Core\Services;

use Illuminate\Database\QueryException;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;

/**
 * ⛔ একটা রেন্ডার, একটা সারি — ১৩ সেপ্টেম্বর ২০২৬।
 *
 * ── কী ঘটেছিল ────────────────────────────────────────────────────────
 * মালিক মূলধনের ফর্মে Save-এ দুইবার ক্লিক করেছেন, আর `CAP-0001` ও
 * `CAP-0002` দুইটা সারি বসেছে — ২৫,০০,০০০ টাকা দুইবার।
 *
 * ── ⭐ কেন নিয়মটা অঙ্কের নয়, রেন্ডারের ──────────────────────────────
 * [[SlipIsNotUsedTwice]]-এ মালিকের নিজের কথায় সিদ্ধান্তটা আগেই নেওয়া:
 * *"একই গ্রাহক পরপর দুই সপ্তাহে হুবহু একই মাল নিতে পারেন, হুবহু একই
 * টাকা দিতে পারেন — ওটা নকল নয়, ওটাই ব্যবসা।"* ⛔ পেলোড মিলিয়ে
 * আটকালে সফটওয়্যার সৎ লেনদেনই আটকাত।
 *
 * ⓘ যা কখনো দুইবার হয় না তা হলো **ফর্মের একটা রেন্ডার**। বৈধ
 * পুনরাবৃত্তিতে মানুষ ফর্মটা আবার খোলেন — নতুন রেন্ডার, নতুন টোকেন।
 * দুইবার ক্লিক একটাই রেন্ডার।
 *
 * ── ⚠️ কেন `claim()` INSERT দিয়ে, "আছে কিনা দেখে" নয় ────────────────
 * দুইবার ক্লিকে অনুরোধ দুইটা **কয়েক মিলিসেকেন্ডের ব্যবধানে** আসে।
 * ⛔ দুইটাই আগে পড়লে দুইটাই দেখত "নেই", তারপর দুইটাই লিখত — অর্থাৎ
 * পড়া-তারপর-লেখা ঠিক যে ঘটনাটা ঠেকাতে হবে সেটাই ঠেকায় না।
 *
 * ⭐ তাই বিচারটা ডাটাবেসের: `token` ইউনিক, আর INSERT নিজেই বলে দেয় কে
 * প্রথম। এটা `vouchers_bank_reference_unique`-এর ছাঁচ।
 *
 * ── কী আটকায়, আর কী আটকায় না ───────────────────────────────────────
 * **আটকায়:** একটা ফর্ম একবার এঁকে দুইবার (বা দশবার) জমা দেওয়া — ক্লিক,
 * Enter, রিফ্রেশ করে পুনরায় জমা, বা পুরনো ট্যাব থেকে আবার জমা।
 * **আটকায় না:** ফর্মটা আবার খুলে আবার ভরে জমা দেওয়া — সেটা বৈধ, আর
 * সেটাই বেশিরভাগ সময় ঘটে। ⓘ `_once` ঘরটা নেই এমন অনুরোধও আটকায় না
 * (API, বা কোনো পুরনো পর্দা), কারণ পাহারার অভাবে কাজ থামানো যায় না —
 * ওটা `EveryFormCarriesItsOwnTokenTest` ধরে।
 */
final class FormIsNotSubmittedTwice
{
    /** ফর্মে যে ঘরটা টোকেনটা বয়ে আনে। */
    public const FIELD = '_once';

    /**
     * ⚠️ প্রথম অনুরোধের ফলের জন্য কতক্ষণ অপেক্ষা।
     *
     * ── কেন অপেক্ষা, আর কেন সাথে সাথে `back()` নয় ───────────────────
     * ⛔ সাথে সাথে ফর্মে ফেরত পাঠানো **সবচেয়ে খারাপ ফল**: ব্যবহারকারী
     * ভাবেন কিছু হয়নি, আর **তৃতীয়বার চাপেন** — ঠিক যেটা ঠেকাতে চাইছি।
     *
     * ⓘ আর মালিক আজ যেটা করেছেন সেটা এই অবস্থাটাই ছিল: দুইটা ক্লিক
     * মিলিসেকেন্ডের ব্যবধানে, প্রথমটা তখনো চলছিল। অর্থাৎ এটাই
     * সবচেয়ে সাধারণ কেস, ব্যতিক্রম নয়।
     *
     * ⭐ দুই সেকেন্ড, ২০০ms করে দশবার। প্রথম অনুরোধ সাধারণত এক সেকেন্ডের
     * মধ্যেই শেষ, তাই বাস্তবে অপেক্ষাটা চোখে পড়ে না।
     */
    private const WAIT_TRIES = 10;

    private const WAIT_MS = 200;

    /** পুরনো সারি কতদিন রাখা হয় — `routes/console.php`-এর ছাঁটাই এটাই পড়ে। */
    public const KEEP_DAYS = 7;

    /** একটা নতুন রেন্ডারের টোকেন। */
    public function newToken(): string
    {
        return (string) Str::uuid7();
    }

    /**
     * ফর্মে বসার লুকানো ঘরটা — `@csrf` নির্দেশিকা এটাই ডাকে।
     *
     * ⓘ প্রতিবার ডাকায় **নতুন** টোকেন, আর সেটাই পুরো নকশার ভিত্তি:
     * একটা রেন্ডার = একটা টোকেন = সর্বোচ্চ একটা সারি। ⚠️ ক্যাশ করলে বা
     * সেশনে রাখলে একই পাতার দুইটা ফর্ম একই টোকেন পেত, আর তখন একটা
     * ফর্ম জমা দিলে অন্যটা আটকে যেত।
     *
     * `e()` আচারের জন্য — uuid7-এ এমন কিছু নেই যা escape লাগে, কিন্তু
     * HTML বানানোর জায়গায় ব্যতিক্রম রাখা অভ্যাস খারাপ করে।
     */
    public function field(): string
    {
        return '<input type="hidden" name="'.self::FIELD.'" value="'.e($this->newToken()).'">';
    }

    /**
     * এই টোকেনটা দাবি করা — প্রথম হলে `true`।
     *
     * ⓘ ফেরত `false` মানে কেউ আগেই দাবি করেছে, অর্থাৎ এটা পুনরাবৃত্তি।
     */
    public function claim(string $token, ?int $userId, ?string $route): bool
    {
        try {
            DB::table('submitted_forms')->insert([
                'token' => $token,
                'user_id' => $userId,
                'route' => $route,
                'created_at' => now(),
            ]);

            return true;
        } catch (QueryException $failed) {
            /*
             * ⚠️ ইউনিক-ভঙ্গ = পুনরাবৃত্তি। কেবল এইটাই, যেকোনো ত্রুটি নয়।
             *
             * ⛔ সব `QueryException` "পুনরাবৃত্তি" ধরলে যেকোনো ডাটাবেস
             * সমস্যায় **প্রতিটা জমা নীরবে ফিরে যেত**, আর কেউ কারণ
             * জানত না — পাহারাটাই তখন একটা নীরব ফাঁক।
             *
             * ⓘ SQLSTATE 23000 = integrity constraint violation, আর
             * এই INSERT-এ একটাই constraint: `submitted_forms_token_unique`।
             */
            if ($this->isDuplicate($failed)) {
                return false;
            }

            /*
             * ⛔ টেবিলটাই নেই — তখন পাহারা **নেই**, কিন্তু কাজ চলে।
             *
             * ── কেন, আর কেন এটা "নীরব ফাঁক" নয় ─────────────────────
             * ⚠️ `infra/deploy.sh`-এ `git pull` লাইন ১৪২, আর
             * `php artisan migrate --force` লাইন ১৮২ — অর্থাৎ **নতুন
             * কোড চলতে শুরু করে টেবিল বসার আগে**। ঐ জানালাটায় এখানে
             * ব্যতিক্রম ছুঁড়লে অ্যাপের **প্রতিটা ফর্ম ৫০০ দিত** — একটা
             * নিরাপত্তা-জাল নিজেই মেঝে ভেঙে ফেলত।
             *
             * ⭐ তাই বিনিময়টা সচেতন: দ্বৈত-জমা ঠেকানো একটা **জাল**, আর
             * জাল না থাকলে মানুষ পড়ে যায় না — কেবল অরক্ষিত থাকে। ত্রিশ
             * সেকেন্ড অরক্ষিত থাকা আর ত্রিশ সেকেন্ড সাইট বন্ধ থাকা এক
             * জিনিস নয়।
             *
             * ⓘ আর ফাঁকটা নীরব নয়, কারণ প্রশ্নটা CI-তে করা হয়:
             * [[EveryFormCarriesItsOwnTokenTest]] টেবিলটা আছে কি না
             * **গুনে দেখে**। ভুলে যাওয়া মাইগ্রেশন তাই যন্ত্র ধরে,
             * ব্যবহারকারী নয়।
             */
            if ($this->isMissingTable($failed)) {
                return true;
            }

            throw $failed;
        }
    }

    /** এই ব্যতিক্রমটা কি `token` দুইবার বসানোর চেষ্টা? */
    private function isDuplicate(QueryException $failed): bool
    {
        return ($failed->errorInfo[0] ?? null) === '23000';
    }

    /** টেবিলটাই নেই — মাইগ্রেশন এখনো চলেনি (MySQL: 42S02)। */
    private function isMissingTable(QueryException $failed): bool
    {
        return ($failed->errorInfo[0] ?? null) === '42S02';
    }

    /**
     * প্রথম অনুরোধ শেষ — ফলটা লিখে রাখা, যাতে পুনরাবৃত্তি সেখানেই যেতে পারে।
     */
    public function remember(string $token, string $url): void
    {
        try {
            DB::table('submitted_forms')
                ->where('token', $token)
                ->update(['result_url' => $url, 'completed_at' => now()]);
        } catch (QueryException $failed) {
            // টেবিল নেই — উপরের `claim()`-এর একই কারণে, আর একই বিনিময়ে
            if (! $this->isMissingTable($failed)) {
                throw $failed;
            }
        }
    }

    /**
     * প্রথম জমাটা কোথায় পৌঁছেছিল — জানা না থাকলে `null`।
     *
     * ⚠️ অপেক্ষা করে, কারণ পুনরাবৃত্তিটা প্রায়ই আসে **প্রথম অনুরোধ শেষ
     * হওয়ার আগেই**। ⓘ সাথে সাথে `null` ফেরালে ব্যবহারকারী ফর্মে ফিরে
     * গিয়ে তৃতীয়বার চাপতেন।
     */
    public function resultFor(string $token): ?string
    {
        for ($try = 0; $try < self::WAIT_TRIES; $try++) {
            $url = DB::table('submitted_forms')
                ->where('token', $token)
                ->value('result_url');

            if ($url !== null) {
                return (string) $url;
            }

            usleep(self::WAIT_MS * 1000);
        }

        return null;
    }

    /** পুরনো সারি মুছে ফেলা — রোজকার কাজ। */
    public function prune(): int
    {
        return DB::table('submitted_forms')
            ->where('created_at', '<', now()->subDays(self::KEEP_DAYS))
            ->delete();
    }
}

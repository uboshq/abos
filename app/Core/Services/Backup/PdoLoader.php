<?php

declare(strict_types=1);

namespace App\Core\Services\Backup;

use PDO;
use RuntimeException;

/**
 * [[PdoDumper]]-এর লেখা ডাম্প ফিরিয়ে আনা — বাইরের প্রোগ্রাম ছাড়া।
 *
 * ── ⭐ কেন কোনো SQL পার্সার নেই ──────────────────────────────────────
 * ডাম্পের প্রতিটা লাইন একটা সম্পূর্ণ বিবৃতি ([[PdoDumper]] সেটাই লেখে)।
 * তাই এখানে কাজটা সোজা: লাইন পড়ো, চালাও।
 *
 * ⛔ পার্সার লিখলে ডেটার ভিতরের `;` বা `--` একদিন তাকে বোকা বানাত, আর
 * ভুলটা ধরা পড়ত ঠিক পুনরুদ্ধারের দিনে। ⚠️ তাই দুইটা ক্লাস **জোড়া** —
 * একটার ফরম্যাট বদলালে অন্যটাও বদলাতে হবে।
 *
 * ── ⚠️ mysqldump-এর ফাইল এখানে চলবে না, আর সেটা জেনেই ────────────────
 * mysqldump বহু-লাইনের `INSERT` লেখে। ⓘ এই লোডার তখন অর্ধেক বিবৃতি
 * চালাতে গিয়ে ভাঙত — কিন্তু **নীরবে নয়**, কারণ প্রতিটা ব্যর্থ লাইনে
 * এটা থামে আর লাইন নম্বরসহ বলে।
 */
final class PdoLoader
{
    /**
     * ফাইলটা চালিয়ে দেয়, আর কয়টা বিবৃতি চলল সেটা ফেরত দেয়।
     */
    public function load(PDO $pdo, string $file): int
    {
        $in = @fopen($file, 'rb');

        if ($in === false) {
            throw new RuntimeException("ডাম্প ফাইলটা পড়া গেল না: {$file}");
        }

        $ran = 0;
        $lineNo = 0;

        try {
            while (($line = fgets($in)) !== false) {
                $lineNo++;
                $sql = trim($line);

                // খালি লাইন ও মন্তব্য — কিছু করার নেই
                if ($sql === '' || str_starts_with($sql, '--')) {
                    continue;
                }

                try {
                    $pdo->exec($sql);
                    $ran++;
                } catch (\PDOException $e) {
                    /*
                     * ⛔ এখানে থামা হয়, এড়ানো হয় না।
                     *
                     * ⚠️ একটা ব্যর্থ বিবৃতি এড়িয়ে গেলে পুনরুদ্ধারটা
                     * "সফল" দেখাত অথচ একটা টেবিল বা কিছু সারি নেই — আর
                     * সেটাই আজকের পুরো সমস্যার আকৃতি: নীরবে অসম্পূর্ণ।
                     *
                     * ⓘ লাইন নম্বর ও বিবৃতির শুরুটা বার্তায় থাকে, যাতে
                     * খোঁজা যায়। পুরোটা নয় — একটা INSERT কয়েক হাজার
                     * অক্ষরের হতে পারে।
                     */
                    throw new RuntimeException(sprintf(
                        'ডাম্পের %d নম্বর লাইনে থেমে গেল: %s … (%s)',
                        $lineNo,
                        mb_substr($sql, 0, 120),
                        $e->getMessage(),
                    ), 0, $e);
                }
            }
        } finally {
            fclose($in);
        }

        if ($ran === 0) {
            throw new RuntimeException("ডাম্পে চালানোর মতো কিছুই ছিল না: {$file}");
        }

        return $ran;
    }
}

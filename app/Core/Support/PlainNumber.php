<?php

declare(strict_types=1);

namespace App\Core\Support;

/**
 * মানুষের লেখা সংখ্যা থেকে যন্ত্রের সংখ্যা — "১০,০০০" বা "1,00,000" থেকে "10000"/"100000"।
 *
 * ── ⛔ কেন লাগল, পুনঃনিরীক্ষা ৯ অক্টোবর ২০২৬ ──────────────────────────
 * Control Panel-এর সংখ্যার ঘর যাচাই ছাড়াই বসত। ⚠️ মালিক অনুমোদনের নিজের সীমায়
 * "10,000" লিখলে সেটাই টেক্সট হয়ে জমত, আর [[ApprovalEngine]]-এর `bccomp()`
 * ঐ লেখা পেয়ে ব্যতিক্রম ছুঁড়ত — অর্থাৎ **প্রতিটা অনুমোদন** ভাঙত।
 *
 * ⭐ বাংলা অঙ্ক ইংরেজিতে, অঙ্কের মাঝের কমা (হাজার বা লাখের ছাঁদ) আর ফাঁকা বাদ। তারপর
 * কেবল সাধারণ দশমিক সংখ্যা চলে; ⛔ `1e5`-এর মতো বিজ্ঞানের ছাঁদ নয় — `is_numeric()`
 * ওটা মেনে নেয়, অথচ bcmath নেয় না।
 */
final class PlainNumber
{
    /** সংখ্যা হলে যন্ত্রের লেখা, নইলে null। */
    public static function from(mixed $raw): ?string
    {
        if (! is_scalar($raw)) {
            return null;
        }

        $text = strtr(trim((string) $raw), ['০' => '0', '১' => '1', '২' => '2', '৩' => '3', '৪' => '4',
            '৫' => '5', '৬' => '6', '৭' => '7', '৮' => '8', '৯' => '9']);

        $text = preg_replace('/(?<=\d)[,\s](?=\d)/u', '', $text) ?? $text;

        return preg_match('/^-?\d+(\.\d+)?$/', $text) === 1 ? $text : null;
    }
}

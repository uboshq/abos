<?php

declare(strict_types=1);

namespace App\Core\Support;

/**
 * চিঠি সত্যিই বাইরে যাবে কি না — একটাই প্রশ্ন, একটাই জায়গা।
 *
 * ── ⛔ কেন এই ক্লাসটা লাগল, ১৫ সেপ্টেম্বর ২০২৬ ───────────────────────
 * লাইভে `MAIL_MAILER=log`। ⚠️ ওই অবস্থায় Laravel চিঠিটা **সফলভাবে
 * পাঠায়** — `storage/logs/laravel.log`-এ। কোনো ব্যতিক্রম ওঠে না, কোনো
 * ভুল ফেরে না, তাই কোড নির্দ্বিধায় বলে *"লিংক পাঠানো হয়েছে"*।
 *
 * ⛔ ফল: ব্যবহারকারী ইনবক্স খুলে বসে থাকেন, আর কোনোদিন কিছু আসে না।
 * ⓘ আজকের দিনের সবচেয়ে বেশিবার ফিরে আসা আকৃতিটাই — **সফল দেখানো
 * ব্যর্থতা**, যার লক্ষণ কেবল ব্যবহারকারীর অপেক্ষা।
 *
 * ⭐ তাই প্রশ্নটা পাঠানোর আগে করা হয়: এই মেইলার দিয়ে চিঠি আদৌ কারও
 * কাছে পৌঁছাবে? না পৌঁছালে **কাজটা করাই হয় না**, আর পর্দায় সত্যি কথাটা
 * লেখা হয়।
 *
 * ── ⚠️ এটা SMTP বসানোর বিকল্প নয় ────────────────────────────────────
 * SMTP কে দেবে, কোন ঠিকানা থেকে — সেটা মালিকের সিদ্ধান্ত, কোডের নয়।
 * ⓘ এই ক্লাসটা কেবল **মিথ্যা বলাটা** বন্ধ করে। ঠিকঠাক বসানোর দিন
 * `silent()` নিজে থেকেই `false` হবে, আর কোনো কোড বদলাতে হবে না।
 *
 * ⓘ বসানোর ধাপগুলো লেখা আছে: docs/ইমেইল — SMTP বসানোর নিয়ম.md
 */
final class MailReach
{
    /**
     * ⛔ যে মেইলারগুলো কিছুই পাঠায় না, অথচ সফল বলে।
     *
     * `log`   — ফাইলে লেখে
     * `array` — স্মৃতিতে রাখে (পরীক্ষার জন্য)
     *
     * ⚠️ `smtp`, `ses`, `postmark` ইত্যাদি এই তালিকায় নেই: ওরা ব্যর্থ
     * হলে **চিৎকার করে** ব্যর্থ হয় (সংযোগের ব্যতিক্রম), আর সেটা এই
     * ক্লাসের সমস্যা নয় — নীরবতাই এখানে ধরার জিনিস।
     */
    private const SILENT = ['log', 'array'];

    private function __construct() {}

    /**
     * চিঠি পাঠালে সেটা কি কোথাও হারিয়ে যাবে?
     */
    public static function silent(): bool
    {
        $mailer = config('mail.default');

        /*
         * ⓘ খালি বা অনুপস্থিত মানেও নীরব — ⚠️ `.env`-এ `MAIL_MAILER`
         * মুছে ফেললে Laravel ডিফল্টে `log` ধরে (config/mail.php:17),
         * তাই সেটাও এখানে পড়ে। ⛔ অচেনা কিছু বসানো থাকলে **নীরব ধরা
         * হয় না**: তখন পাঠানোর চেষ্টাটা হোক, আর ব্যর্থ হলে জোরে হোক।
         */
        if (! is_string($mailer) || $mailer === '') {
            return true;
        }

        return in_array($mailer, self::SILENT, true);
    }
}

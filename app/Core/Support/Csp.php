<?php

declare(strict_types=1);

namespace App\Core\Support;

/**
 * এই উত্তরটার নিজস্ব গোপন চিহ্ন — যেটা ছাড়া কোনো স্ক্রিপ্ট চলবে না।
 *
 * ── কেন, ১৪ সেপ্টেম্বর ২০২৬ ──────────────────────────────────────────
 * CSP-তে `'unsafe-inline'` থাকলে হেডারটার সবচেয়ে বড় কাজটাই বাদ যায়:
 * কেউ একটা ঘরে `<script>alert(1)</script>` লিখে জমা দিলে, আর সেটা
 * কোথাও এস্কেপ না হয়ে ছাপা হলে, ব্রাউজার সেটা **চালিয়ে দিত**।
 *
 * ⭐ nonce ঠিক এই জায়গাটা বন্ধ করে। প্রতিটা উত্তরে একটা নতুন এলোমেলো
 * চিহ্ন তৈরি হয়, হেডারে বসে, আর আমাদের নিজের ১২টা ইনলাইন ব্লকে বসে।
 * আক্রমণকারীর লেখা স্ক্রিপ্টে ওটা থাকে না — কারণ সে জানে না — তাই
 * ব্রাউজার তারটা চালায় না, আমাদেরটা চালায়।
 *
 * ── ⚠️ কেন View::share() নয়, একটা static ─────────────────────────────
 * ছাপার ব্লেডগুলো (`print/layout`, `print/labels`) কেবল ব্রাউজারে নয়,
 * PDF বানানোর সময়ও রেন্ডার হয় — কখনো HTTP অনুরোধের বাইরে। শেয়ার করা
 * ভেরিয়েবল তখন **থাকত না**, আর পাতাটা "Undefined variable" দিয়ে ৫০০
 * দিত। ⓘ এখানে চিহ্নটা প্রথম ডাকেই নিজে তৈরি হয়, তাই ওই পথেও চলে।
 *
 * ── ⛔ এক প্রক্রিয়ায় একাধিক অনুরোধ ──────────────────────────────────
 * PHP-FPM-এ প্রতি অনুরোধে নতুন প্রক্রিয়া, তাই static নিজেই পরিষ্কার
 * হয়। কিন্তু Octane বা কিউ-কর্মীতে প্রক্রিয়াটা **বেঁচে থাকে**, আর তখন
 * একই চিহ্ন চিরকাল চলত — অর্থাৎ nonce-টা আর গোপন থাকত না, আর সুরক্ষাটা
 * নীরবে শূন্য হয়ে যেত।
 *
 * ⚠️ সেজন্যই [[ContentSecurityPolicy]] প্রতিটা অনুরোধের **শুরুতে**
 * `rotate()` ডাকে। ওটা বাদ পড়লে কিছুই ভাঙে না — আর সেটাই বিপদ, তাই
 * এখানে লিখে রাখা।
 */
final class Csp
{
    private static ?string $nonce = null;

    /**
     * এই অনুরোধের চিহ্ন — না থাকলে তৈরি করে।
     */
    public static function nonce(): string
    {
        /*
         * ১৬ বাইট = ১২৮ বিট। CSP-র নির্দিষ্টকরণ ন্যূনতম ১২৮ বিট
         * এলোমেলোতা চায়, আর `random_bytes()` ব্যর্থ হলে ছুঁড়ে দেয় —
         * চুপচাপ দুর্বল কিছু ফেরত দেয় না।
         */
        return self::$nonce ??= base64_encode(random_bytes(16));
    }

    /**
     * নতুন অনুরোধ, নতুন চিহ্ন।
     */
    public static function rotate(): string
    {
        self::$nonce = null;

        return self::nonce();
    }
}

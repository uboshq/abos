    /** @return list<string> */
    public static function keys(): array
    {
        return array_keys(self::all());
    }

    public static function exists(string $key): bool
    {
        return isset(self::all()[$key]);
    }

    /** @return array{label: string, swatch: string, scale: array<string, string>} */
    public static function get(string $key): array
    {
        return self::all()[$key] ?? self::all()[self::DEFAULT];
    }

    /**
     * <html> ট্যাগে বসানোর জন্য CSS ভেরিয়েবল।
     *
     * সার্ভারেই তৈরি হয় — JavaScript-এ করলে প্রথম রঙে পাতা এঁকে তারপর
     * বদলাত, আর প্রতিটা পাতা লোডে একবার করে ঝলকানি দেখা যেত।
     */
    public static function styleFor(string $key): string
    {
        $accent = self::get($key);
        $css = '';

        foreach ($accent['scale'] as $step => $rgb) {
            $css .= "--accent-{$step}:{$rgb};";
        }

        /*
         * রঙের উপরে লেখাটা কোন কালিতে — রংটাই বলে।
         *
         * ── কেন এটা বোতামে হার্ডকোড করা যেত না ──────────────────────
         * আগে প্রধান বোতাম `text-(--color-ink-inverse)` ধরত, অর্থাৎ
         * সবসময় সাদা। তাতে তালিকায় কেবল সেইসব রংই রাখা যেত যাদের
         * উপরে সাদা লেখা পড়া যায় — আর অ্যাম্বার (#E08C1A সাদার সাথে
         * ২.৩:১) কোনোদিন ঢুকতেই পারত না।
         *
         * এখন প্রতিটা রং নিজের কালি নিজে ঘোষণা করে, আর বোতাম সেটা
         * পড়ে। পাহারাটাও সেই অনুযায়ী: "সাদা লেখা পড়া যায়" নয়,
         * "**নিজের ঘোষিত** লেখা পড়া যায়"।
         */
        $css .= "--accent-ink:{$accent['ink']};";

        /*
         * গাঢ় জমিনের নিজস্ব ধাপ।
         *
         * ── কী ভাঙা ছিল ─────────────────────────────────────────────
         * `tokens.css`-এর গাঢ় ব্লকে `--color-brand-500: #3b82f6`
         * হার্ডকোড ছিল। ফলে গাঢ় মোডে **পনেরোটা রংই এক নীলে মিশে
         * যেত** — ব্যবহারকারীর বাছাই নীরবে বাতিল, আর প্রতিটা নকলের
         * বোতাম নিজের ব্র্যান্ড হারাত। Odoo রূপে অবার্জিন মাথার পাশে
         * নীল বোতাম বসত।
         *
         * ── কেন হালকা ধাপটা দরকার, আর কেন সবার নয় ───────────────────
         * বোতামের দুইটা আলাদা দাবি: লেখা বনাম বোতাম ≥ ৪.৫:১, আর
         * **বোতাম বনাম পাতা ≥ ৩:১** (WCAG ১.৪.১১ — নাহলে বোতামের
         * কিনারাই গাঢ় জমিনে মিশে যায়)।
         *
         * হিসাব করে দেখা গেছে পনেরোটার মধ্যে **এগারোটা নিজের হেক্স
         * অবিকল রাখতে পারে**; কেবল চারটায় (ইন্ডিগো, ভায়োলেট,
         * অবার্জিন, নেটস্যুট) সামান্য lightness তুলতে হয় — hue ও
         * saturation অক্ষত, তাই রংটা বদলায় না, কেবল একটু উজ্জ্বল হয়।
         */
        $css .= "--accent-dark:{$accent['dark']};";
        $css .= "--accent-dark-600:{$accent['dark_600']};";

        return $css."--accent-dark-ink:{$accent['dark_ink']};";
    }

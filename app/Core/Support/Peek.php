<?php

declare(strict_types=1);

namespace App\Core\Support;

use App\Core\Services\SettingsService;
use Illuminate\Http\Request;

/**
 * ⭐ এই অনুরোধটা কি পিক — অর্থাৎ খোলস ছাড়া কেবল ভিতরটা?
 *
 * ── ⭐ মালিকের নিয়ম, ২৮ সেপ্টেম্বর ২০২৬ ───────────────────────────────
 * *"হাইপার লিংকে চাপলে পপআপ এলেই ভালো, নাহলে মডিউল/মেনু পরিবর্তন হয়ে
 * যায়, সেটা অত্যন্ত বিরক্তিকর।"*
 *
 * ── ⓘ কেন হেডার, কেন `?peek=1` নয় ───────────────────────────────────
 * ⚠️ ঘরের চলতি ছাঁচ কোয়েরি ধরে ([[ExportListing]] + `?export=csv`), আর
 * এটাই এই রিপোর **প্রথম** হেডার-নির্ভর শাখা — তাই কারণটা লেখা থাকা
 * দরকার।
 *
 * ⛔ পিক আর আসল পাতা **একই URL** না হলে তিনটা জিনিস দুইটা আলাদা পাতা
 * দেখতে শুরু করে: ব্রাউজারের ক্যাশ, পিছনে-যাওয়ার বোতাম, আর কোডের
 * `route()` মিলানো। ⓘ হেডারে সেটা হয় না — ঠিকানাটা অপরিবর্তিত থাকে।
 *
 * ⚠️ তার দাম `Vary: X-Peek` ([[PeekVaries]]) — নাহলে প্রক্সি বা ব্রাউজার
 * খোলসহীন টুকরোটাকেই আসল পাতা ধরে পরিবেশন করত, আর মেনুহীন একটা পাতা
 * দেখে মানুষ ভাবতেন সিস্টেম ভেঙে গেছে।
 *
 * ── ⛔ খোলসটা যায়, দরজা যায় না ──────────────────────────────────────
 * ⚠️ এটা কেবল **আঁকার** সিদ্ধান্ত। অনুমতি, কোম্পানির ছাঁকনি, স্কোপ —
 * কিছুই এই হেডার দেখে না, আর কোনোদিন দেখবে না। পিক দিয়ে ৪০৩-এর পাতা
 * খুললে ৪০৩-ই আসে।
 */
final class Peek
{
    public const HEADER = 'X-Peek';

    /**
     * ⭐ টুকরোর গায়ের চিহ্ন — "এটা সত্যিই একটা পিক-টুকরো", ২ অক্টোবর ২০২৬।
     *
     * ── ⛔ কেন লাগল ─────────────────────────────────────────────────
     * জানালাটা আগে যা আসত তা-ই বসাত। ⚠️ কিন্তু একটা ঠিকানা সবসময়
     * [[layouts.app]] দিয়ে আঁকা হয় না: লগইন ফুরিয়ে গেলে লগইনের গোটা
     * পাতা, ফাইলের ঠিকানায় ফাইল, ত্রুটিতে ত্রুটির নিজের `<html>`। ⛔ তখন
     * পপআপের ভিতরে আরেকটা গোটা অ্যাপ বসত — মেনু, টপবার, আরেকটা পিকের
     * জানালা আর তার নিজের ক্লিক-শ্রোতা — আর ৩০২টা পাতার যেকোনোটার
     * গড়ন ভেঙে যেত।
     *
     * ⭐ এখন জানালা কেবল সেই উত্তর বসায় যার একমাত্র মূল উপাদান এই
     * চিহ্ন বহন করে ([[shell.js::peek]])। বাকি সব আগের মতোই পুরো পাতায়
     * খোলে।
     */
    public const FRAGMENT = 'data-peek-fragment';

    /**
     * ⭐ এই কোম্পানিতে পিক চালু কি না — কোম্পানির সুইচ `system.document_peek`।
     *
     * ⛔ পড়তে না পারলে **বন্ধ**: বন্ধ মানে কেবল "আগের মতো পুরো পাতা",
     * আর অজানা অবস্থায় সেটাই নিরাপদ দিক।
     */
    public static function enabled(): bool
    {
        try {
            return (bool) app(SettingsService::class)->get('system.document_peek', true);
        } catch (\Throwable) {
            return false;
        }
    }

    public static function wanted(?Request $request = null): bool
    {
        $request ??= request();

        /*
         * ⛔ কেবল GET। ⚠️ POST-এর উত্তরে খোলস বাদ দিলে সফল সংরক্ষণের পর
         * মানুষ একটা মেনুহীন পাতায় আটকে যেতেন — আর ওটা দেখতে ঠিক
         * ভেঙে-যাওয়া সিস্টেমের মতো।
         */
        if (! $request->isMethod('GET')) {
            return false;
        }

        /*
         * ⛔ যে অনুরোধ JSON চায় সে খোলসও চায় না, টুকরোও চায় না —
         * ওটা আলাদা পথ, আর দুইটা মিশলে fetch একটা HTML টুকরো পেয়ে
         * সেটাকে সফল JSON ধরে নিত।
         */
        if ($request->expectsJson()) {
            return false;
        }

        /*
         * ⛔ সুইচ বন্ধ থাকলে হেডার এলেও গোটা পাতা। ⓘ পুরনো ট্যাবে পুরনো
         * জাভাস্ক্রিপ্ট তখনো হেডার পাঠাতে পারে — উত্তরটা তখন চিহ্নহীন,
         * আর জানালা নিজেই পুরো পাতায় গড়িয়ে পড়ে।
         */
        return $request->hasHeader(self::HEADER) && self::enabled();
    }
}

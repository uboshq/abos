<?php

declare(strict_types=1);

namespace App\Core\Support;

/**
 * রোলের যে নামটা মানুষ পড়েন, আর যে নামটা কোড খোঁজে — দুইটা এক নয়।
 *
 * ── কেন এটা লাগল, ১৩ সেপ্টেম্বর ২০২৬ ─────────────────────────────────
 * রোলের নাম এতদিন পর্দায় কাঁচাই দেখানো হত (`$role->name`), আর সেটা
 * চলে যাচ্ছিল কারণ নামগুলো পড়ার মতোই ছিল — `Field Sales`, `Manager`,
 * `HR`, `Warehouse`।
 *
 * ⛔ `owner` → `super_admin` হওয়ার পর ওটা আর চলে না: পর্দায় বসত
 * **"super_admin"**, আন্ডারস্কোরসহ। ⓘ মালিক নামটা বদলাতে বলেছেন
 * পড়ার জন্যই (ERP-তে সবাই Administrator বলে), তাই আন্ডারস্কোর দেখানো
 * পুরো উদ্দেশ্যটাই হারাত।
 *
 * ── কেন একটা তালিকা, আর কেন fallback কাঁচা নামেই ─────────────────────
 * ⚠️ রোল ব্যবহারকারীরা নিজেরাও বানাতে পারেন (`store_keeper`)। তাদের
 * কোনো অনুবাদ থাকবে না, আর থাকার কথাও নয়। ⛔ অনুবাদ না পেলে `__()`
 * **চাবিটাই ফেরত দেয়** — তখন পর্দায় বসত
 * `system_admin::role_name.store_keeper`, যা আন্ডারস্কোরের চেয়েও খারাপ।
 *
 * ⭐ তাই অনুবাদ থাকলে সেটা, নাহলে নামটা যেমন আছে তেমন। নতুন রোল
 * বানানোর পথে এই ফাইলটা কোনো বাধা নয়।
 */
final class RoleLabel
{
    public static function for(string $name): string
    {
        $key = 'system_admin::role_name.'.$name;
        $label = __($key);

        return is_string($label) && $label !== $key ? $label : $name;
    }
}

     * শেলটাই — সাইডবার উধাও, উপরে বেগুনি বার, লঞ্চার শিট। দুইটাকে
     * একইভাবে দেখানো মানে **বাছাইটাই আন্দাজে করানো**।
     *
     * ── কেন দুইটা শর্ত, একটা নয় ─────────────────────────────────────
     * প্রথম ভাবনা ছিল কেবল ঘোষিত চতুষ্টয় (`nav`·`commands`·`filters`·
     * `views`) ডিফল্টের সাথে মেলানো। তাতে **Redwood ভুল দলে পড়ত**:
     * তার চতুষ্টয় হুবহু Navy-র সমান, অথচ সে একটা ৪px ইটরঙা পটি আর
     * টালির স্প্রিংবোর্ড আঁকে।
     *
     * অর্থাৎ ঘোষণাটাই পুরো গল্প নয় — নিজস্ব markup-ও বিন্যাসের অংশ।
     * ঠিক এই ভুলটাই আজ সারাদিনের বিষয়:
     * [[AClonePromisedAShapeAndDrewAnotherTest]]।
     *
     * ── কেন `view()->exists()`, কোনো তালিকা নয় ───────────────────────
     * `chrome.blade.php` নিজেও ঠিক এই যাচাইটাই করে ঠিক করে কোন ফাইলটা
     * ডাকবে। একই প্রশ্নের দুইটা উত্তর থাকলে একদিন একটা বদলাত আর অন্যটা
     * থেকে যেত — আর তখন পর্দায় লেখা থাকত এক, আঁকা হত আরেক।
     */
    public static function changesArrangement(?string $key): bool
    {
        $look = self::clean($key);

        if (view()->exists('components.shell.chrome.'.$look)) {
            return true;
        }

        $shape = static fn (string $k): array => array_map(
            static fn (string $part): string => self::all()[$k][$part],
            ['nav', 'commands', 'filters', 'views'],
        );

        return $shape($look) !== $shape(self::DEFAULT);
    }


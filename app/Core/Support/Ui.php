     * অদৃশ্য।
     *
     * সাইডবার কোন রূপ চলছে তা জানে না, কেবল প্যানেলটা গাঢ় কি না
     * তা জিজ্ঞেস করে — তাই কাল আরেকটা গাঢ় রূপ এলে সে নিজেই ঠিক
     * ছবিটা পাবে।
     */

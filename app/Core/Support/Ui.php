     * ১০৪টা পর্দা তাদের শিরোনাম ও বোতাম `header` স্লটে পাঠায়, আগেও
     * পাঠাত। কেবল **শেল** ঠিক করে ওই স্লটটা কোথায় আঁকা হবে।
     *
     * এটাই "জায়গাটা শেলের সিদ্ধান্ত, পাতার নয়" — আর প্রমাণটা হল
     * এই বদলে একটাও পর্দার ফাইল ছোঁয়া লাগেনি।

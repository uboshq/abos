     * তাই এই একটাই জিনিস চেহারা থেকে **PHP-তে** আসে, আর শেল সেটা
     * দেখে ঠিক করে কোন partial-টা আঁকবে।
     *
     * ── কারা উপরে রাখে, আর কেন ──────────────────────────────────────
     * পাঁচটা নকলের চারটাই: Odoo (অ্যাপ-মেনু), Fiori (শেল বার),

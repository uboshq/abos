<?php

declare(strict_types=1);

namespace App\Core\Support;

use Illuminate\Database\Eloquent\Builder;

/**
 * নাম থেকে কোড — একক, কর, কারণ কোড আর হিসাবের ছকের জন্য।
 *
 * ── কেন সিরিয়াল নম্বর নয় ──────────────────────────────────────────
 * বাকি মাস্টারে কোড আসে নম্বর সিরিজ থেকে (CUS-0001)। এই কয়টায় নয়,
 * কারণ এখানে **অক্ষরগুলোই অর্থ বহন করে**: PCS মানে পিস, KG মানে
 * কিলোগ্রাম, VAT15 মানে পনেরো শতাংশ। UNT-0007 লেখা থাকলে খাতা পড়ে
 * কেউ বুঝত না কার্টন না কেজি।
 *
 * ── কেন যন্ত্র CTN দিতে পারে না ────────────────────────────────────
 * "Carton" থেকে "CTN" মানুষের সংক্ষেপ, কোনো নিয়মের ফল নয় — "Kilogram"
 * থেকে "KG" তো আরও নয়। তাই এখানে যা হয় তা একটা **প্রস্তাব**: নামের
 * প্রথম অক্ষরগুলো নিয়ে একটা পড়ার মতো কোড, যেটা মুছে নিজের পছন্দেরটা
 * লেখা যায়।
 *
 * মালিকের সিদ্ধান্ত (২০২৬-০৮-০৯): "সব কোড আগে নিজে বসবে, তারপর কারো
 * লাগলে এডিট করে নতুন কোড বসাবে।"
 */
final class CodeFromName
{
    /** কত অক্ষরের কোড — তিনটাই যথেষ্ট, আর তালিকায় সরু কলামে আঁটে। */
    private const LENGTH = 3;

    /**
     * নাম থেকে একটা কোড, আর সেটা যেন আগে কারো না হয়।
     *
     * @param  callable(string): bool  $taken  কোডটা ইতিমধ্যে আছে কি না
     */
    public static function suggest(string $name, callable $taken): string
    {
        $base = self::base($name);

        if ($base === '') {
            return '';
        }

        if (! $taken($base)) {
            return $base;
        }

        /*
         * নেওয়া হয়ে গেলে পেছনে সংখ্যা — CAR, CAR2, CAR3।
         *
         * সীমাটা আছে যাতে কোনোদিন অসীম লুপ না হয়: শতাধিক একই আদ্যক্ষরের
         * নাম থাকলে মানুষকেই নামটা ঠিক করতে হবে, আর তখন খালি কোড ফেরত
         * দিয়ে তাকে লিখতে দেওয়াই সৎ — একটা আজগুবি কোড বসিয়ে দেওয়ার
         * চেয়ে।
         */
        for ($n = 2; $n <= 99; $n++) {
            $candidate = $base.$n;

            if (! $taken($candidate)) {
                return $candidate;
            }
        }

        return '';
    }

    /**
     * একই কাজ, তবে একটা কোয়েরির উপর — সচরাচর যেভাবে ডাকা হয়।
     *
     * কোয়েরিটা ডাকার জায়গা থেকে আসে, কারণ "আগে আছে কি না" প্রশ্নের
     * সীমা প্রতিটা তালিকায় আলাদা: একক দেখে শুধু এককের মধ্যে, হিসাবের
     * খাত দেখে সব খাতের মধ্যে।
     */
    public static function forQuery(string $name, Builder $scope, string $column = 'code'): string
    {
        return self::suggest(
            $name,
            fn (string $code): bool => (clone $scope)->where($column, $code)->exists(),
        );
    }

    /**
     * নামের গোড়া থেকে অক্ষরগুলো।
     *
     * ── কেন প্রথম শব্দ, আদ্যক্ষর নয় ────────────────────────────────
     * "Payment Term" থেকে PT বানানো যেত, কিন্তু এক শব্দের নামেই
     * ("Carton", "Litre") ওই নিয়ম ভেঙে পড়ে, আর তালিকার বেশিরভাগ নামই
     * এক শব্দের। তাই একটাই নিয়ম: গোড়া থেকে তিন অক্ষর, আর কম পড়লে
     * পরের শব্দ থেকে বাকিটা।
     *
     * বাংলা নাম থেকে কোড বানানো হয় না — কোডগুলো ইংরেজি অক্ষরে লেখা
     * হয় সব জায়গায় (রিপোর্ট, ছাপা, রপ্তানি), আর বাংলা অক্ষর ওখানে
     * বসালে ফাইল খুলতে গিয়ে ভাঙত।
     */
    private static function base(string $name): string
    {
        // ইংরেজি অক্ষর ও অঙ্ক ছাড়া সব বাদ; বাংলা নামে কিছুই টেকে না
        $words = preg_split('/[^A-Za-z0-9]+/', $name, -1, PREG_SPLIT_NO_EMPTY) ?: [];

        $code = '';

        foreach ($words as $word) {
            $code .= $word;

            if (strlen($code) >= self::LENGTH) {
                break;
            }
        }

        return strtoupper(substr($code, 0, self::LENGTH));
    }
}

<?php

declare(strict_types=1);

namespace App\Core\Support;

/**
 * টাকার অঙ্ক — গোনা থেকে দেখানো পর্যন্ত, একবারও float ছোঁয়া ছাড়া।
 *
 * ── কেন এটা দরকার হলো ───────────────────────────────────────────────
 * নিয়মটা প্রকল্পে আগে থেকেই লেখা (সেকশন ৮): টাকা DECIMAL, হিসাব bcmath,
 * কখনো float নয়। `RunningBalance` সেটা মানে, খতিয়ানের যোগফল মানে,
 * রিপোর্টের মোট মানে।
 *
 * কিন্তু **দেখানোর শেষ ধাপে** সবাই float-এ ফিরে যাচ্ছিল:
 *
 *     number_format((float) $value, 2)
 *
 * ওই একটা কাস্টে সাবধানে রাখা সবটুকু হারায়। ১২৩৪.৫৬৫ দশমিকে ঠিক
 * মাঝামাঝি, কিন্তু বাইনারিতে সে ১২৩৪.৫৬৪৯৯৯…, তাই `number_format`
 * নিচে নামিয়ে ১২৩৪.৫৬ দেখায় — অথচ bcmath দিয়ে গোনা মোট বলত ১২৩৪.৫৭।
 * এক পয়সা, কিন্তু এক পর্দায় দুইটা আলাদা সংখ্যা, আর তখন কোনটা সত্যি তা
 * বলার উপায় থাকে না।
 *
 * ── কেন গোল করা এখানে, ভিউতে নয় ────────────────────────────────────
 * "কত ঘর পর্যন্ত" সিদ্ধান্তটা একটাই হওয়া দরকার। একই সংখ্যা পর্দায় দুই
 * দশমিকে আর ছাপায় চার দশমিকে দেখালে ব্যবহারকারী ধরে নেন দুইটা আলাদা
 * হিসাব — আর সেটা ধরে নেওয়াই স্বাভাবিক।
 */
final class Money
{
    /** ভেতরের হিসাব চার ঘরে — DECIMAL(18,4)-এর সাথে মিলিয়ে। */
    public const SCALE = 4;

    /**
     * যেকোনো মানকে হিসাবযোগ্য স্ট্রিং বানানো।
     *
     * null আর খালি স্ট্রিং দুইটাই '0' — bcmath খালি স্ট্রিংকে শূন্য ধরে
     * না, ত্রুটি দেয়, আর ফাঁকা ঘর থেকে আসা মান রোজকার ঘটনা।
     *
     * float ঢুকলে সেটা এখানেই স্ট্রিং হয়ে যায়। ঢুকতে দেওয়া হচ্ছে কারণ
     * পুরনো কোড ও ফর্মের মান float হয়ে আসতে পারে — কিন্তু বেরোনোর সময়
     * আর কখনো float নয়।
     *
     * ── কেন এখানে ঘর কাটা হয় না ────────────────────────────────────
     * প্রথম লেখায় এটা চার ঘরে নামিয়ে দিত (DECIMAL(18,4)-এর সাথে মিলিয়ে)।
     * কিন্তু bcmath কাটে, গোল করে না — তাই ১.২৩৪৫৫ এখানেই ১.২৩৪৫ হয়ে
     * যেত, আর তারপর গোল করার মতো কিছু থাকত না। **পয়সাটা নিঃশব্দে হারাত,
     * আর কোনো ভুল দেখাত না।** ঘর ঠিক করা এখন কেবল সেখানেই যেখানে
     * সিদ্ধান্তটা আসলেই নিতে হয়: `round()` ও `sumOf()`।
     */
    public static function of(int|float|string|null $value): string
    {
        if ($value === null || $value === '') {
            return '0';
        }

        return is_float($value) ? sprintf('%.*F', self::SCALE, $value) : (string) $value;
    }

    /**
     * নির্দিষ্ট ঘর পর্যন্ত গোল করা — অর্ধেক হলে উপরে।
     *
     * bcmath নিজে গোল করে না, কেটে দেয়। তাই আধা ঘর যোগ করে তারপর কাটা
     * হয়: ১.২৩৫ + ০.০০৫ = ১.২৪০, কেটে ১.২৪। ঋণাত্মকে বিয়োগ, নাহলে
     * −১.২৩৫ কেটে −১.২৩ হত — শূন্যের দিকে, অথচ বাকি সব হিসাব দূরে সরে।
     *
     * ঋণাত্মক দিকে একটা সুবিধা নিজে থেকেই আসে: −০.০০৪ গোল হয়ে '0.00'
     * হয়, '-0.00' নয়। পর্দায় "−০.০০" দেখলে ব্যবহারকারী ভাবেন কিছু
     * একটা ঘাটতি আছে, অথচ নেই।
     */
    public static function round(int|float|string|null $value, int $decimals = 2): string
    {
        $value = self::of($value);
        $half = '0.'.str_repeat('0', $decimals).'5';

        return bcadd($value, bccomp($value, '0', self::SCALE) < 0 ? '-'.$half : $half, $decimals);
    }

    /**
     * পর্দায় ও কাগজে দেখানোর রূপ — হাজারে কমা, ঠিক দশমিক ঘর।
     *
     * ── কেন নিজের হাতে কমা বসানো ────────────────────────────────────
     * `number_format` কাজটা করত, কিন্তু সে float ছাড়া কিছু নেয় না — আর
     * ওই কাস্টটাই এই ক্লাসের অস্তিত্বের কারণ।
     *
     * অঙ্কগুলো সবসময় ইংরেজি (সেকশন ১৮.৪): টাকার অঙ্ক বাংলা সংখ্যায়
     * লিখলে ব্যাংকের কাগজ ও ক্যালকুলেটরের সাথে মেলাতে হোঁচট লাগে।
     */
    public static function format(int|float|string|null $value, int $decimals = 2): string
    {
        $rounded = self::round($value, $decimals);

        $negative = str_starts_with($rounded, '-');
        $rounded = ltrim($rounded, '-');

        [$whole, $fraction] = array_pad(explode('.', $rounded, 2), 2, '');

        $grouped = strrev(implode(',', str_split(strrev($whole), 3)));

        return ($negative ? '-' : '')
            .$grouped
            .($decimals > 0 ? '.'.str_pad($fraction, $decimals, '0') : '');
    }

    /**
     * যোগফল — সারি ধরে ধরে, bcmath-এ।
     *
     * @param  iterable<mixed>  $rows
     * @param  callable(mixed): (int|float|string|null)  $amount
     */
    public static function sumOf(iterable $rows, callable $amount): string
    {
        $total = '0';

        foreach ($rows as $row) {
            $total = bcadd($total, self::of($amount($row)), self::SCALE);
        }

        return $total;
    }

    /**
     * পরিমাণ দেখানোর রূপ — ভগ্নাংশ থাকলে দেখাও, না থাকলে নয়।
     *
     * "১০.০০০০ পিস" কেউ লেখে না; লেখে "১০ পিস"। কিন্তু "২.৫ কেজি"-র
     * অর্ধেকটা ফেলে দেওয়া যায় না, তাই শূন্যগুলো কাটা হয় শেষ থেকে,
     * নির্দিষ্ট কোনো দশমিক ঘর ধরে নয়।
     *
     * ── কেন এটা এখানে ───────────────────────────────────────────────
     * একই `rtrim(rtrim(…, '0'), '.')` চারটা জায়গায় হাতে লেখা ছিল, আর
     * তার একটায় ভেতরে `(float)` ঢুকে পড়েছিল — লট-ট্রেসের যোগফলে।
     * চারটা কপির একটায় ভুল ঢুকলে বাকি তিনটা দেখে সেটা ধরা যায় না।
     *
     * ── কেন `number_format` নয়, `fmod` নয় ──────────────────────────
     * দুইটাই float নেয়। ভগ্নাংশ আছে কি না সেটাও স্ট্রিং ধরেই দেখা হয়,
     * নাহলে সংখ্যাটা পথেই float হয়ে যেত — আর তখন ০.১ + ০.২ ≠ ০.৩।
     *
     * খালি হলে '0' — সব শূন্য কেটে ফেলার পর কিছুই না থাকা মানে শূন্যই,
     * কিন্তু পর্দায় ফাঁকা ঘর দেখলে মানুষ ভাবে সংখ্যাটা আসেনি।
     */
    /**
     * শূন্য কি না — তুলনাটাও bcmath-এ।
     *
     * ── কেন `(float) $value` নয় ─────────────────────────────────────
     * পর্দায় শূন্য ঘরগুলো ফাঁকা রাখা হয় (খতিয়ানের ডেবিট/ক্রেডিট কলামে
     * দুই দিকেই সংখ্যা থাকলে চোখ কোনটা পড়বে বুঝতে পারে না)। সেটা করতে
     * আটটা জায়গায় লেখা ছিল `(float) $e->debit ? … : ''` — কাজ করত,
     * কিন্তু প্রতিটাই টাকাকে float বানাত।
     *
     * `'0.0000' == 0` PHP-তে সত্যি, কিন্তু `(float)` লিখে ফেলাটা
     * অভ্যাস তৈরি করে, আর পরের বার কেউ ওটার উপর যোগ বসিয়ে দেয় — লট
     * ট্রেসে ঠিক তাই হয়েছিল।
     */
    public static function isZero(mixed $value): bool
    {
        return bccomp(self::of($value), '0', self::SCALE) === 0;
    }

    public static function quantity(mixed $value, int $scale = self::SCALE): string
    {
        $trimmed = rtrim(rtrim(self::format($value, $scale), '0'), '.');

        return $trimmed === '' ? '0' : $trimmed;
    }
}

<?php

declare(strict_types=1);

namespace App\Core\Support;

use InvalidArgumentException;

/**
 * Code 128 — দাগগুলো নিজেরাই আঁকা, কোনো লাইব্রেরি ছাড়াই।
 *
 * ── কেন নিজে লেখা, প্যাকেজ নয় ───────────────────────────────────────
 * বারকোড আঁকার প্যাকেজ অনেক আছে, আর আজই এই রিপোতে দেখা গেল একটা
 * অব্যবহৃত নির্ভরতা (phpspreadsheet) কীভাবে গোটা সার্ভারে
 * `composer install` আটকে দিয়েছিল। Code 128-এর ছকটা একশো সারির একটা
 * টেবিল আর একটা যোগফল — যতটুকু লাগে ততটুকুই এখানে, আর ওটা কোনোদিন
 * PHP সংস্করণের সাথে ঝগড়া করবে না।
 *
 * ── কেন Code 128, EAN-13 নয় ─────────────────────────────────────────
 * EAN-13 খুচরা পণ্যের বিশ্বজোড়া নম্বর — ওটা কেনা হয়, বানানো যায় না।
 * ডিপো নিজের পণ্যের নিজের কোড দেয় (`PRD-0004`), আর তাতে অক্ষর ও
 * ড্যাশ থাকে। Code 128-B ঠিক ওটাই বইতে পারে, আর যেকোনো স্ক্যানার
 * সেটা পড়ে।
 *
 * ── কেন দাগগুলো div, SVG নয় ─────────────────────────────────────────
 * কাগজটা mPDF ছাপে। SVG-র সমর্থন ওখানে আংশিক, আর ভাঙলে লেবেলে
 * নীরবে একটা ফাঁকা ঘর ছাপা হত — যা স্ক্যানারের কাছে "পণ্য নেই"।
 * নিরেট রঙের সরু ঘর প্রতিটা রেন্ডারারেই একইভাবে ছাপে।
 */
final class Barcode
{
    /**
     * Code 128-এর ১০৭টা ছক — প্রতিটা ছয়টা সংখ্যার (দাগ, ফাঁক, দাগ…)।
     *
     * তালিকাটা স্পেকের, আবিষ্কারের নয়। শেষ তিনটা (স্টার্ট A/B/C) আর
     * থামার ছকটা আলাদা করে নিচে ব্যবহার হয়।
     *
     * @var list<string>
     */
    private const PATTERNS = [
        '212222', '222122', '222221', '121223', '121322', '131222', '122213', '122312',
        '132212', '221213', '221312', '231212', '112232', '122132', '122231', '113222',
        '123122', '123221', '223211', '221132', '221231', '213212', '223112', '312131',
        '311222', '321122', '321221', '312212', '322112', '322211', '212123', '212321',
        '232121', '111323', '131123', '131321', '112313', '132113', '132311', '211313',
        '231113', '231311', '112133', '112331', '132131', '113123', '113321', '133121',
        '313121', '211331', '231131', '213113', '213311', '213131', '311123', '311321',
        '331121', '312113', '312311', '332111', '314111', '221411', '431111', '111224',
        '111422', '121124', '121421', '141122', '141221', '112214', '112412', '122114',
        '122411', '142112', '142211', '241211', '221114', '413111', '241112', '134111',
        '111242', '121142', '121241', '114212', '124112', '124211', '411212', '421112',
        '421211', '212141', '214121', '412121', '111143', '111341',
        '131141', '114113', '114311', '411113', '411311', '113141', '114131', '311141',
        '411131', '211412', '211214', '211232', '233111',
    ];

    /** স্টার্ট-B — অক্ষর, সংখ্যা ও চিহ্ন সবই বইতে পারে। */
    private const START_B = 104;

    private const STOP = 106;

    /**
     * একটা লেখা থেকে দাগের চওড়াগুলো।
     *
     * ফেরত আসে ১–৪ একক চওড়ার একটা তালিকা, আর প্রথমটা সবসময় কালো দাগ,
     * তারপর একটা করে বদলে বদলে।
     *
     * @return list<int>
     */
    public static function bars(string $value): array
    {
        $value = trim($value);

        if ($value === '') {
            throw new InvalidArgumentException('A barcode needs something to encode.');
        }

        $codes = [self::START_B];
        $sum = self::START_B;
        $position = 1;

        foreach (str_split($value) as $character) {
            $point = ord($character);

            /*
             * Code 128-B ৩২ থেকে ১২৬ পর্যন্ত ASCII বইতে পারে।
             *
             * এর বাইরের অক্ষর — বাংলা নাম, ট্যাব — নীরবে বাদ দিলে
             * স্ক্যান করে অন্য একটা পণ্য বেরোত। তাই থামানো হয়, আর
             * ডাকা জায়গায় কোডটাই পাঠানো হয়, নাম নয়।
             */
            if ($point < 32 || $point > 126) {
                throw new InvalidArgumentException(
                    "Code 128-B cannot carry the character '{$character}'. Encode the product code, not its name."
                );
            }

            $code = $point - 32;
            $codes[] = $code;
            $sum += $code * $position++;
        }

        // চেক ডিজিট — ১০৩ দিয়ে ভাগশেষ; ছাড়া কোনো স্ক্যানার পড়বে না
        $codes[] = $sum % 103;
        $codes[] = self::STOP;

        $bars = [];

        foreach ($codes as $code) {
            foreach (str_split(self::PATTERNS[$code]) as $width) {
                $bars[] = (int) $width;
            }
        }

        // থামার ছকের শেষে দুই এককের একটা বাড়তি দাগ — স্পেকের অংশ
        $bars[] = 2;

        return $bars;
    }

    /**
     * ছাপার জন্য HTML — নিরেট ঘরের সারি।
     *
     * @param  float  $unit  এক এককের চওড়া, মিলিমিটারে
     * @param  float  $height  দাগের উচ্চতা, মিলিমিটারে
     */
    public static function html(string $value, float $unit = 0.33, float $height = 12): string
    {
        $html = '';
        $black = true;

        foreach (self::bars($value) as $width) {
            $mm = round($width * $unit, 3);

            $html .= '<span style="display:inline-block;width:'.$mm.'mm;height:'.$height.'mm;'
                .'background:'.($black ? '#000' : '#fff').';vertical-align:top;"></span>';

            $black = ! $black;
        }

        return $html;
    }
}

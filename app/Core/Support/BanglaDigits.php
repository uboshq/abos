<?php

declare(strict_types=1);

namespace App\Core\Support;

/**
 * বাংলা নকশার কাগজে বাংলা অঙ্ক — মালিক, ১০ অক্টোবর ২০২৬: *"বাংলা নকশার বিলে বাংলা সংখ্যা, ইংরেজি নকশার বিলে ইংরেজি সংখ্যা"*।
 *
 * ⓘ টাকা, তারিখ, নম্বর সব জায়গায় ইংরেজি অঙ্কে সাজানো হয় ([[Money]], [[DateFormat]]); বাংলা নকশা ছাপা শেষে নিজের লেখার
 * অঙ্কগুলো একবারে বদলায় ([[inText()]])। ⓘ ব্যতিক্রম কেবল মানুষ যে নম্বর খুঁজে টাইপ করেন — কাগজের নম্বর, গাড়ি, TrxID, BIN, ফোন,
 * ইমেইল, ওয়েব — সেগুলো ইংরেজি অঙ্কে ([[keepsItsDigits()]], fe-র ডিফল্ট, ১১ অক্টোবর ২০২৬; মালিকের উত্তরের অপেক্ষায়)।
 */
final class BanglaDigits
{
    private const MAP = ['0' => '০', '1' => '১', '2' => '২', '3' => '৩', '4' => '৪', '5' => '৫', '6' => '৬', '7' => '৭', '8' => '৮', '9' => '৯'];

    public static function of(string $text): string
    {
        return strtr($text, self::MAP);
    }

    /**
     * ⚠️ কেবল পড়ার লেখা বদলায়: ট্যাগের ভিতর (CSS-এর মাপ, ছবির ঠিকানা, বারকোডের মান), `<style>`/`<script>` আর
     * `&#2453;`-এর মতো চিহ্ন যেমন আছে তেমন থাকে — নইলে কাগজের নকশা আর বারকোড ভাঙত।
     */
    public static function inText(string $html): string
    {
        /*
         * ⓘ এক একটা "শব্দ" ধরে দেখা (ফাঁকা, ট্যাগ বা চিহ্ন পর্যন্ত), কেবল অঙ্ক নয় — শব্দটা দেখে ঠিক হয় বদলাবে কি না ([[keepsItsDigits()]])।
         * ⛔ ফল `null` হলে (নষ্ট একটা বাইট, বা PCRE-র সীমা) মূল কাগজটাই ফেরে — আগে `(string) null` গোটা বিল/চালান ফাঁকা করে দিত,
         * কোনো ত্রুটি ছাড়া (১১ অক্টোবর ২০২৬, PR #17 রিভিউ ⚠️৯)। ইংরেজি অঙ্কের কাগজ ফাঁকা কাগজের চেয়ে ঢের ভালো।
         */
        $out = preg_replace_callback(
            '/(<style\b.*?<\/style>|<script\b.*?<\/script>|<[^>]*>|&#?[a-zA-Z0-9]+;)|[^\s<>&]*[0-9][^\s<>&]*/su',
            static fn (array $m): string => ($m[1] ?? '') !== '' || self::keepsItsDigits($m[0]) ? $m[0] : self::of($m[0]),
            $html,
        );

        return $out ?? $html;
    }

    /**
     * ⭐ মানুষ যে নম্বর খুঁজে টাইপ করেন, সেটা ইংরেজি অঙ্কেই — fe-র ডিফল্ট, ১১ অক্টোবর ২০২৬ (মালিকের উত্তরের অপেক্ষায়; PR #17 রিভিউ ⚠️৯)।
     *
     * ⓘ বাংলা অঙ্ক কেবল টাকা, পরিমাণ আর তারিখে। কাগজের নম্বর (S-2610-0001), গাড়ির নম্বর, TrxID, BIN, ফোন, ইমেইল আর ওয়েবসাইট
     * ইংরেজিতে — `adi২০২৪@gmail.com` বা `S-২৬১০-০০০১` খোঁজার ঘরে টাইপ করে পাওয়া যায় না।
     * চেনার নিয়ম: শব্দে ইংরেজি অক্ষর বা `@` (নম্বর, গাড়ি, ইমেইল, ওয়েব, TrxID), টানা ৯+ অঙ্ক (BIN, ফোন, সংখ্যার TrxID), বা
     * মোবাইলের ছাঁচ (01711-123456)। টাকা (১,২০০.০০), পরিমাণ আর তারিখ (১১-১০-২০২৬) এর কোনোটায় পড়ে না।
     */
    private static function keepsItsDigits(string $word): bool
    {
        return preg_match('/[A-Za-z@]/', $word) === 1
            || preg_match('/[0-9]{9,}/', $word) === 1
            || preg_match('/(?:\+?88)?01[3-9][0-9]{2}-[0-9]{6}/', $word) === 1;
    }
}

<?php

declare(strict_types=1);

namespace App\Core\Support;

/**
 * ⭐ অবস্থার চিপের রং — এক মানচিত্র, সব পর্দা (পাতা সাজানোর পরিকল্পনা ধাপ ১, ১০ অক্টোবর ২০২৬: *"অবস্থার চিপ: একটাই
 * চিপ, একটাই রঙের মানে — খসড়া ধূসর, নিশ্চিত সবুজ, দেরি/সীমার নিচে লাল-হলুদ"*)।
 *
 * ── কেবল যে শব্দের মানে সব জায়গায় এক ──────────────────────────────────────────
 * "খসড়া", "নিশ্চিত", "বাতিল", "ফেরানো", "মেয়াদ শেষ", "বন্ধ" — কোন কাগজের হোক, মানে একই, তাই রংও একই। ⓘ "অনুমোদিত",
 * "জমা দেওয়া" এখানে নেই, আর সেটা ইচ্ছাকৃত: বিক্রয় আদেশে "অনুমোদিত" মানে এখনও নিশ্চিত হয়নি (নীল, পথে), অনুমোদনের
 * ইনবক্সে মানে কাজ শেষ (সবুজ) — এক রং চাপালে একটা পর্দা মিথ্যা বলত।
 *
 * ⓘ রঙের নাম [[x-ui.badge]]-এর নিজের ছয়টার মধ্যে — অচেনা নাম ব্যাজ চুপচাপ ধূসর করে দেয়।
 * ⓘ পাহারা: [[EveryStatusWearsOneColourTest]] — কোনো পর্দা বা অবস্থা-শ্রেণি এই শব্দগুলোর অন্য রং দিলে লাল।
 */
final class StatusTone
{
    /** @var array<string, string> অবস্থা → ব্যাজের রং */
    public const MAP = [
        DocumentStatus::DRAFT => 'draft',
        DocumentStatus::CONFIRMED => 'success',
        DocumentStatus::CANCELLED => 'danger',
        DocumentStatus::CLOSED => 'info',
        'rejected' => 'danger',
        'expired' => 'danger',
    ];

    /** অবস্থার রং — মানচিত্রে না থাকলে ধূসর (খসড়ার রং), যেমন ব্যাজ নিজে করে */
    public static function of(string $status): string
    {
        return self::MAP[$status] ?? 'draft';
    }
}

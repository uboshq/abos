<?php

declare(strict_types=1);

namespace App\Core\Support;

use App\Models\LookSkin;
use Illuminate\Support\Facades\Session;

/**
 * নিজের রূপ না বদলে একটা রূপ পরে দেখা — থিম ইঞ্জিনের ধাপ ৩ (অংশ ৭)।
 *
 * ── কেন নমুনা পর্দা নয়, আসল ERP ─────────────────────────────────────
 * প্রিভিউ বলতে সাধারণত একটা ছোট নমুনা কার্ড বোঝানো হয় — একটা বোতাম,
 * একটা ছক, দুইটা ব্যাজ। ওটা দিয়ে রঙের ভুল ধরা যায় না, কারণ ভুলগুলো
 * ঠিক ওখানে থাকে না: থাকে ভরা একটা ছকে, ঢাকা টুলবারে, ব্যাজের ভিতরে
 * বসা সংখ্যায়, আর গাঢ় থিমে খোলা একটা ড্রপডাউনে।
 *
 * তাই এখানে প্রিভিউ মানে **গোটা ERP-টাই** ওই রূপে ঘুরে দেখা।
 *
 * ── কেন সেশনে, ব্যবহারকারীর সারিতে নয় ───────────────────────────────
 * সারিতে লিখলে ওটা আর প্রিভিউ থাকত না — ওটাই তাঁর রূপ হয়ে যেত, আর
 * ব্রাউজার বন্ধ করলেও থেকে যেত। সেশনে থাকলে এটা এক বসার জিনিস, আর
 * অন্য কারো পর্দায় কোনোদিন পৌঁছায় না।
 *
 * ── কেন সময়ের সীমা ──────────────────────────────────────────────────
 * মানুষ প্রিভিউ চালু করে অন্য কাজে চলে যান। সীমা না থাকলে তিন দিন পরে
 * তিনি ভাবতেন ERP-র রংটাই বদলে গেছে, আর সেটা নিয়ে অভিযোগ করতেন —
 * অথচ কেবল তাঁরই পর্দা।
 *
 * উপরের ব্যানারটা সবসময় দেখা যায় সেই একই কারণে: প্রিভিউ কখনো নীরব নয়।
 */
final class LookPreview
{
    /**
     * সেশনের চাবি।
     *
     * `public`, কারণ পরীক্ষায় একটা চলমান প্রিভিউ সাজিয়ে দিতে হয়:
     * পরীক্ষায় সেশন-ড্রাইভার `array`, তাই এক অনুরোধে লেখা সেশন পরের
     * অনুরোধে থাকে না। চাবিটা লুকিয়ে রাখলে পরীক্ষাটা হয় হাতে লেখা
     * স্ট্রিং ধরে চলত (নাম বদলালেই নীরবে অচল), নয় প্রিভিউয়ের
     * দ্বিতীয় অর্ধেকটা মাপাই হত না।
     */
    public const KEY = 'look.preview';

    /**
     * কত মিনিট পরে নিজে থেকে থামে।
     *
     * ত্রিশ — একটা রূপ ঘুরে দেখার জন্য যথেষ্ট, আর ভুলে যাওয়ার জন্য
     * যথেষ্ট কম।
     */
    public const MINUTES = 30;

    public static function start(LookSkin $skin): void
    {
        Session::put(self::KEY, [
            'skin' => $skin->public_id,
            'until' => now()->addMinutes(self::MINUTES)->getTimestamp(),
        ]);
    }

    public static function stop(): void
    {
        Session::forget(self::KEY);
    }

    /**
     * চলতি প্রিভিউয়ের রূপ — না থাকলে, মেয়াদ শেষ হলে, বা রূপটা আর
     * না থাকলে নাল।
     *
     * মেয়াদ শেষ হলে সেশন থেকে মুছেও দেওয়া হয়, নাহলে ব্যানারটা
     * প্রতিটা পাতায় একই হিসাব করত।
     */
    public static function skin(): ?LookSkin
    {
        /** @var array{skin: string, until: int}|null $said */
        $said = Session::get(self::KEY);

        if ($said === null) {
            return null;
        }

        if (now()->getTimestamp() > (int) ($said['until'] ?? 0)) {
            self::stop();

            return null;
        }

        $skin = LookSkin::query()->where('public_id', $said['skin'])->first();

        if ($skin === null) {
            self::stop();   // মুছে ফেলা রূপের প্রিভিউ ধরে রাখার মানে নেই

            return null;
        }

        return $skin;
    }

    /**
     * প্রিভিউ চললে প্রিভিউয়ের রূপ, নাহলে ব্যবহারকারীর নিজেরটা।
     *
     * ── কেন খোলসটাও বদলাতে হয় ───────────────────────────────────────
     * রূপ কেবল রং নয় — মেনু বাঁয়ে না উপরে, সেটাও রূপের কথা, আর
     * সেটা markup। প্রিভিউ শুধু রং বদলালে Odoo-র উপর দাঁড়ানো একটা
     * রূপ Odoo-র রং নিয়ে Navy-র খোলসে দেখা যেত, আর মানুষ ভাবতেন
     * রূপটাই ভাঙা — অথচ ভাঙা ছিল প্রিভিউ।
     */
    public static function orChosen(?string $chosen): ?string
    {
        return self::skin()?->public_id ?? $chosen;
    }

    /**
     * প্রিভিউয়ের টোকেনগুলো, `<html style="…">`-এ বসার মতো — নাহলে নাল।
     *
     * ── কেন খসড়াটা, প্রকাশিতটা নয় ───────────────────────────────────
     * প্রিভিউয়ের গোটা কারণটাই হলো **যা এখনো প্রকাশ হয়নি** সেটা দেখা।
     * প্রকাশিতটা দেখাতে হলে প্রিভিউ লাগত না — সেটা তো এমনিতেই পর্দায়।
     */
    public static function style(string $theme = 'light'): ?string
    {
        $skin = self::skin();

        if ($skin === null) {
            return null;
        }

        $css = '';

        foreach ($skin->tokens($theme) as $name => $value) {
            $css .= $name.':'.$value.';';
        }

        return $css;
    }
}

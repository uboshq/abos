<?php

declare(strict_types=1);

namespace App\Core\Concerns;

use App\Core\Services\SettingsService;
use Throwable;

/**
 * একটা দেয়াল যা মালিক চাইলে সরে, আর না চাইলে দাঁড়িয়ে থাকে।
 *
 * ── ⭐ মালিকের নির্দেশ, ২২ সেপ্টেম্বর ২০২৬ ──────────────────────────
 * *"HR প্রতিটা কোম্পানিতে আলাদা বসে — eta chailew keu korte parbe
 * tajonno control panel e bebosta rako"*।
 *
 * ⓘ একই মালিকের তিনটা কোম্পানি, আর কর্মীরা প্রায়ই সবগুলোর জন্যই কাজ
 * করেন। ⚠️ আজ একজন মানুষকে তিনবার বসাতে হয়, আর তিনটা বেতনশিট ও তিনটা
 * ছুটির খাতা তৈরি হয় যেগুলো মেলানো যায় না।
 *
 * ── ⛔ কেন এটা [[BelongsToCompany]]-র পাশে একটা উত্তর, দ্বিতীয় স্কোপ নয় ──
 * প্রথম চালে একটা আলাদা স্কোপ বসিয়ে ভিতরে `withoutGlobalScope('company')`
 * ডাকা হয়েছিল, আর সেটা **কিছুই করেনি**: স্কোপগুলো ক্রমে প্রয়োগ হয়, তাই
 * ঐ ক্লোজার চলার আগেই `where company_id` কোয়েরিতে বসে গেছে।
 *
 * ⓘ তাই এখন একটাই স্কোপ, আর সে নিজেই জিজ্ঞেস করে
 * [[BelongsToCompany::bootBelongsToCompany()]]-এ।
 *
 * ── ⚠️ লেখা চওড়া হয় না, ইচ্ছাকৃতভাবে ──────────────────────────────
 * `company_id` বসেই — TCL-এ বসানো কর্মী TCL-এরই থাকেন। ⛔ লেখাও চওড়া
 * হলে সুইচ বন্ধ করার দিন ঐ সারিগুলোর কোনো ঘর থাকত না, আর তাঁরা নীরবে
 * অদৃশ্য হয়ে যেতেন। ⓘ একটা সুইচ যা ফেরানো যায় না, সেটা সুইচ নয়।
 *
 * ── ⚠️ দুইটা বিপদ, দুইটাই ঠেকানো ──────────────────────────────────
 * ⓵ **অসম দেয়াল।** সেটিংটা `scope => product`, তাই উত্তরটা সবার জন্য
 * এক। ⛔ কোম্পানি ধরে হলে TCL দেখত DEM-কে আর DEM দেখত না TCL-কে,
 * অথচ DEM কখনো রাজি হয়নি।
 *
 * ⓶ **আধখানা ফিচার।** HR-এর নয়টা মডেল কোম্পানি ধরে ছাঁকা। ⛔ কয়েকটায়
 * বসিয়ে বাকিগুলো ভুলে গেলে কর্মীর তালিকা চওড়া হত আর তাঁর বেতনশিট হত
 * না — পর্দায় নাম, কিন্তু খুললে কিছু নেই। ⓘ পাহারা দেয়
 * [[Tests\Feature\Modules\Hr\TheStaffRegisterCanBeOneForTheGroupTest]]।
 */
trait SharedAcrossCompaniesWhenAsked
{
    /**
     * মালিক কি দেয়ালটা খুলে রেখেছেন?
     *
     * ⓘ প্রতিটা কোয়েরিতে ডাকা হয়, আর সেটাই ঠিক: সুইচ বন্ধ করলে
     * **পরের কোয়েরিতেই** দেয়াল ফিরে আসে, কোনো ক্যাশ বা স্মৃতি নেই।
     * ⚠️ [[SettingsService]] নিজেই অনুরোধ-প্রতি ক্যাশ রাখে, তাই খরচটা
     * একবারের পড়া।
     *
     * ⛔ সেটিংটা পড়তে গিয়ে কিছু ভাঙলে উত্তর **বন্ধ**। ⓘ নিরাপদ দিকটা
     * সবসময় দেয়ালের দিকে: একটা ব্যতিক্রমের কারণে টেন্যান্টের দেয়াল
     * খুলে যাওয়ার চেয়ে ফিচারটা কাজ না করা ভালো।
     */
    public static function sharesAcrossCompanies(): bool
    {
        try {
            return app(SettingsService::class)->get('hr.shared_across_companies', false) === true;
        } catch (Throwable) {
            return false;
        }
    }
}

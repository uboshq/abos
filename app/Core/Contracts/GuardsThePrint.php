<?php

declare(strict_types=1);

namespace App\Core\Contracts;

use Illuminate\Http\Request;

/**
 * ⭐ ছাপার রুটের একটা পাহারা — "এই কাগজ এখন ছাপা যাবে না, কারণ …" (পুরো ERP অডিট, ৬ অক্টোবর ২০২৬, ফোন ⚠️৮)।
 *
 * <p>ওয়েবে এমন পাহারা রুটের মিডলওয়্যার হয়ে বসে (যেমন চালানে পরিবহন না বাছলে ছাপা নয়)। ফোনের দলিল-দরজা
 * ([[DocumentApiController]]) ওয়েবের ছাপার রুটের কন্ট্রোলার সরাসরি চালায় — মিডলওয়্যার চলে না, তাই এই নিয়ম এড়িয়ে যেত।
 * ⓘ কোর মডিউলের নাম জানে না; তাই মিডলওয়্যার নিজে এই চুক্তি সই করে, আর দরজা রুটের যেকোনো সই-করা মিডলওয়্যারকে জিজ্ঞেস করে।
 */
interface GuardsThePrint
{
    /** ছাপা আটকালে কারণ (বাংলায়, পর্দার জন্য), নইলে null — অনুরোধের রুট আর তার বাঁধা মডেল ধরে */
    public function whyNotPrint(Request $request): ?string;
}

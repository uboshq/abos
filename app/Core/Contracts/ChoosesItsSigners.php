<?php

declare(strict_types=1);

namespace App\Core\Contracts;

use App\Models\Approval;
use App\Models\User;

/**
 * কাগজ নিজে বলে কে তাতে সই দিতে পারেন — ছকের ধাপের **উপরে** একটা বাড়তি "না" (বাকি নিয়ন্ত্রণ ধাপ ২.৫, ১১ অক্টোবর ২০২৬)।
 *
 * ── ⭐ কেন ─────────────────────────────────────────────────────────────
 * মালিকের উত্তর ৫: সীমা বাড়ানোর অনুরোধ বসে কেবল **মালিকের** সইয়ে, আর যিনি লিখলেন তিনি নিজে সই দিতে পারেন না। ⚠️ ছক
 * কোম্পানির নিজের হাতে বসানো, আর নিজের-সইয়ের সীমা (`approval.self_limit`) ছোট অঙ্কে নিজের অনুরোধে সই দিতে দেয় — দুইটার
 * কোনোটাই এই নিয়ম নিশ্চিত করে না।
 *
 * ⓘ কোর কোনো মডিউল চেনে না (§১৯.৭) — তাই প্রশ্নটা কাগজকে: [[ApprovalEngine::canDecide()]] সইয়ের আগে জিজ্ঞেস করে, আর "না"
 * হলে সই হয় না। ⛔ কেবল সরু করে, কখনো চওড়া নয়: "হ্যাঁ" মানে ছকের বাকি সব নিয়ম তবুও খাটে। যে কাগজ এটা দেয় না, তার কিছুই
 * বদলায় না।
 */
interface ChoosesItsSigners
{
    public function mayBeSignedBy(User $user, Approval $approval): bool;
}

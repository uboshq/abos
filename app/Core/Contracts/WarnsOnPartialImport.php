<?php

declare(strict_types=1);

namespace App\Core\Contracts;

/**
 * ঐচ্ছিক — একটা ইমপোর্টার যখন বলতে চায় "আমার আংশিক ইমপোর্ট নীরব ক্ষতি"।
 *
 * বেশিরভাগ ইমপোর্ট একটা তালিকা: তিনশো গ্রাহকের দুইশো উঠলে বাকিটা পরে
 * তোলা যায়, ক্ষতি নেই। কিন্তু কিছু ইমপোর্ট একটা **দলিল** — খোলার জের
 * অর্ধেক বসলে খতিয়ান মেলে ঠিকই, অথচ স্থিতিপত্র ভুল, আর সেটা কেউ চোখে
 * দেখে না। "৮ সফল, ২ ব্যর্থ" একটা পরিসংখ্যান; ওই ব্যবহারকারীর একটা
 * সতর্কবার্তা দরকার, যাতে তিনি না ভাবেন "পরে ঠিক করে নেব"।
 *
 * এই ইন্টারফেসটা কেবল **যোগ**, `Importer` চুক্তির বদল নয়: যে চারটা
 * ইমপোর্টার আজ আছে তারা এটা ঘোষণা না করলে তাদের কিছুই বদলায় না।
 * `ImportController` কেবল `instanceof` দেখে, আর কিছু সারি ব্যর্থ হলে
 * এই বার্তাটা ফলাফলের পর্দায় তোলে।
 */
interface WarnsOnPartialImport
{
    /**
     * আংশিক ইমপোর্ট হলে যে জোরালো বার্তাটা দেখাতে হবে — অনুবাদের কী নয়,
     * ব্যবহারকারীর ভাষায় তৈরি বাক্য। কিছু বলার না থাকলে null।
     */
    public function partialWarning(): ?string;
}

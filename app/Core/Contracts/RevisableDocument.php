<?php

declare(strict_types=1);

namespace App\Core\Contracts;

use Carbon\CarbonInterface;

/**
 * পোস্ট হয়ে যাওয়া একটা কাগজ যা সংশোধন করা যায় — আর প্রতিটা সংশোধন আগে-পরে দুইটাই রাখে।
 *
 * ── ⭐ মালিকের নিয়ম, ৩ অক্টোবর ২০২৬ ──────────────────────────────────────
 * মাস বন্ধ না হওয়া পর্যন্ত সুপার অ্যাডমিন **যেকোনো** পোস্ট হওয়া কাগজ সম্পাদনা করতে পারেন —
 * ভাউচার, নোট, বিল, চালান, ক্রয়ের কাগজ, মজুদের কাগজ, ১০০%। মাস বন্ধ হলে আর নয়, যতক্ষণ না
 * মাসটা খোলা হয়। প্রতিটা সম্পাদনায় আগের আর পরের রূপ থাকে, যাতে প্রশ্ন উঠলে দেখানো যায়।
 * নম্বর একই থাকে; খাতা উল্টে আবার বসে।
 *
 * ── ⓘ কাজের ভাগ ─────────────────────────────────────────────────────────
 * কোর জানে: কে পারেন ([[App\Core\Services\PostedEdit]]), কোন মাস খোলা, এক লেনদেন আর সারির
 * তালা, খাতা আর মজুদের ছবি, আর সংশোধনের সারি ([[App\Core\Services\RevisionKeeper]])।
 * মডিউল জানে কেবল নিজের অংশ: নিজের ঘর আর সারি, নিজের খাতা আর মজুদ কোন নামে বসে।
 * ⓘ সাধারণ ক্ষেত্রের ("মাথা + সারি + উৎস ধরে খাতা") সব ডিফল্ট [[App\Core\Concerns\KeepsRevisions]]-এ —
 * মডিউলকে লিখতে হয় কেবল [[revisionLedgerSources()]]।
 *
 * ⓘ এই চুক্তি কেবল **ছবি** — [[RevisionKeeper::keep()]]-এর জন্য যথেষ্ট, যেখানে উল্টানো আর আবার বসানো
 * ডাকনেওয়ালা নিজে করে (কাউন্টারের সম্পাদনা)। কোর নিজে উল্টাবে আর বসাবে ([[RevisionKeeper::edit()]]),
 * তাহলে [[RepostsAfterRevision]]-ও লাগে।
 *
 * ⚠️ এই চুক্তির কোনো মেথড নিজে থেকে লেনদেন খোলে না, অনুমতি দেখে না, মাসও দেখে না — সেগুলো
 * সবসময় [[RevisionKeeper]]-এর কাজ, যাতে কোনো মডিউল একটা পাহারা ভুলে যেতে না পারে।
 */
interface RevisableDocument
{
    /**
     * কাগজের নিজের অংশের ছবি — মাথার ঘর আর সারিগুলো, সাধারণ মানে (লেখা, সংখ্যা, null)।
     *
     * ⓘ খাতা আর মজুদ এখানে নয় — সেগুলো কোর নিজে তোলে, [[revisionLedgerSources()]] আর
     * [[revisionStockSources()]] ধরে, যাতে প্রতিটা মডিউলের ছবি একই মাপের হয়।
     *
     * @return array{header: array<string, scalar|null>, lines: list<array<string, scalar|null>>}
     */
    public function revisionSnapshot(): array;

    /**
     * খাতায় এই কাগজ কোন নামে বসে — `[source_type, source_id]` জোড়ার তালিকা।
     *
     * ⓘ সাধারণত একটা জোড়া (ভাউচার: `['journal_voucher', 12]`)। বিক্রির মতো যে কাগজের খাতা
     * দুই নথিতে বসে, সে দুইটাই দেয়। উল্টো সারির নাম (`…:reversal`) কোর নিজেই জানে।
     *
     * @return list<array{0: string, 1: int}>
     */
    public function revisionLedgerSources(): array;

    /**
     * মজুদে এই কাগজের চলাচল কোন কোন নামে — **উল্টো চলাচলের নামসহ**।
     *
     * ⚠️ মজুদের উল্টো সারির নাম মডিউলভেদে আলাদা (`…:cancel`, `…_reversal`), তাই কোর আন্দাজ
     * করে না: এখানে যা দেওয়া হয় তার **নিট** চলাচলই ছবিতে বসে। মজুদ না ছুঁলে খালি তালিকা।
     *
     * @return list<array{0: string, 1: int}>
     */
    public function revisionStockSources(): array;

    /** কাগজের নিজের তারিখ — কোন মাসে পড়ে, আর উল্টো সারি কোন তারিখে বসে। */
    public function revisionDate(): ?CarbonInterface;

    /** কাগজের নম্বর — সংশোধনে কখনো বদলায় না। */
    public function revisionNumber(): string;

    /** পোস্ট হয়েছে কি না — খসড়া সাধারণ সম্পাদনার পথেই বদলায়, এই পথে নয়। */
    public function isPostedForRevision(): bool;

    /**
     * ছাপার খাতায় ([[App\Core\Services\PaperTrail::DOCUMENT_ROUTES]]) এই কাগজের ধরন —
     * কাগজটা আগে বেরিয়েছিল কি না জানতে। ছাপা হয় না এমন কাগজে `null`।
     */
    public function revisionPaperType(): ?string;
}

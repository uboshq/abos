<?php

declare(strict_types=1);

namespace App\Core\Contracts;

/**
 * পুরনো খাতা থেকে সারি নিয়ে আসার চুক্তি।
 *
 * প্রতিটা নতুন গ্রাহক আসে Tally, Excel বা হাতের খাতা নিয়ে। প্রথম দিনেই
 * তার তিনশো গ্রাহক ও দুইশো সরবরাহকারী হাতে তুলতে বললে সে ছয় মাসেও শুরু
 * করতে পারবে না — go-live আটকায় ঠিক এখানেই, ফিচারের অভাবে নয়।
 *
 * নিয়ম দুইটা:
 *
 *   ১. ইমপোর্টার নিজে কিছু সেভ করে না — মডিউলের নিজের Service ডাকে।
 *      নাহলে ইমপোর্টে বাংলা নামের নিয়ম, কোডের অনন্যতা বা খোলা ব্যালেন্সের
 *      দাখিলা — কোনোটাই খাটত না, আর ইমপোর্ট করা ডেটা হাতে বসানো ডেটার
 *      চেয়ে আলাদা নিয়মে চলত।
 *
 *   ২. আগে দেখা, তারপর বসানো। ফাইলের ভুল সারিগুলো আগে দেখিয়ে দিতে হয়,
 *      কারণ তিনশো সারির মধ্যে দুইটা ভুল থাকলে ব্যবহারকারী জানতে চান
 *      কোন দুইটা — "ইমপোর্ট ব্যর্থ" বলে থামলে তিনি ফাইলটা চোখে খুঁজবেন।
 */
interface Importer
{
    /**
     * পর্দায় দেখানোর নাম — অনুবাদের কী।
     */
    public static function label(): string;

    /**
     * CSV-র কলামগুলো।
     *
     * ক্রম গুরুত্বপূর্ণ: নমুনা ফাইলটা এই ক্রমেই তৈরি হয়, আর ব্যবহারকারী
     * ওই ফাইলটাই ভরে ফেরত দেন।
     *
     * @return array<string, array{label: string, required: bool}>
     */
    public static function columns(): array;

    /**
     * একটা সারি যাচাই — কিছু সেভ না করে।
     *
     * @param  array<string, string>  $row
     * @return list<string> ভুলগুলো; খালি মানে সারিটা ঠিক আছে
     */
    public function check(array $row): array;

    /**
     * একটা সারি সত্যিই বসানো।
     *
     * @param  array<string, string>  $row
     */
    public function import(array $row): void;
}

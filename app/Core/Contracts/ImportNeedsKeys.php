namespace App\Core\Contracts;

/**
 * ⛔ একটা ইমপোর্ট কোন চাবিতে চলে — নিজের মডিউলের, পর্দার একই কাজের চাবি (পুরো ERP অডিট, ৬ অক্টোবর ২০২৬, SystemAdmin ⛔৫)।
 *
 * ⓘ আগে ইমপোর্টের দরজায় কেবল `system_admin.import.manage` — "সেটিং রক্ষক"-এর ছকে — আর কোনো ইমপোর্টার নিজের চাবি দেখত
 * না: খোলা জের ইমপোর্ট যেকোনো পোস্টযোগ্য খাতে খাতার খোলা সারি বসাত, হিসাবের খাত, গ্রাহক, সরবরাহকারী, পণ্য — সব চাবি
 * ছাড়া। ⭐ এখন [[ImportRunner::available()]] কেবল সেই ইমপোর্ট দেখায় যার প্রতিটা চাবি মানুষটার আছে আর যার মডিউল চালু।
 * ⚠️ এই চুক্তি না মানা ইমপোর্টার কোনো মানুষের তালিকায় আসেই না — ভুলে বাদ পড়লে বন্ধ, খোলা নয়।
 */
interface ImportNeedsKeys
{
    /**
     * প্রতিটাই লাগে — পর্দায় একই কাজ যে চাবিতে হয়।
     *
     * @return list<string>
     */
    public static function requiredPermissions(): array;
}

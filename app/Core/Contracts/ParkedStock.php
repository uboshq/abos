<?php

declare(strict_types=1);

namespace App\Core\Contracts;

/**
 * কাউন্টারে ধরে রাখা বিলের আটকানো মাল ছেড়ে দেওয়া (পিওএস ধাপ ২, ১১ অক্টোবর ২০২৬)।
 *
 * ── ⚠️ কেন কোরে একটা চুক্তি ──────────────────────────────────────────
 * বিল ধরে রাখলে মাল আটকায় কাউন্টার (পিওএস মডিউল), কিন্তু বিলটা নিশ্চিত বা বাতিল
 * হয় বিক্রয়ের সেবায় — আর তখনই আটকানো মাল ছাড়তে হয়। ⛔ বিক্রয় পিওএসকে চেনে না
 * (নির্ভরতার দিক `pos → sales`), তাই মাঝে এই চুক্তি — [[CreditHolds]]-এর ছাঁচে।
 *
 * ⓘ পিওএস বাস্তবায়ন দেয় (`module.php`-র `bindings`); কেউ না দিলে কোরের
 * [[NoParkedStock]] কিছুই করে না — কাউন্টার না থাকলে ধরে রাখা বিলও নেই।
 */
interface ParkedStock
{
    /**
     * এই বিলের নামে খাতায় যতটা মাল আটকে আছে ততটাই ছাড়ে; কিছু না থাকলে কিছুই নয়।
     *
     * ⓘ বারবার ডাকা নিরাপদ — নিশ্চিত আর বাতিল দুই পথেই ডাকা হয়।
     */
    public function release(int $invoiceId, ?string $documentNo): void;
}

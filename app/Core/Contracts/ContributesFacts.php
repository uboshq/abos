<?php

declare(strict_types=1);

namespace App\Core\Contracts;

use App\Core\Panels\Fact;

/**
 * এক মডিউল অন্য মডিউলের রেকর্ড সম্পর্কে যা জানে, তা দিতে পারে।
 *
 * ── কেন এই চুক্তিটা লাগল ─────────────────────────────────────────────
 * গ্রাহকের পাতায় "শেষ কেনা কবে" দেখানো হত, আর তথ্যটা আসত
 * `Customer::lastPurchaseOn()` থেকে — যে পদ্ধতিটা `SalesInvoice`
 * খুঁজত। অর্থাৎ Customer নির্ভর করত Sales-এর উপর, অথচ Sales আগে থেকেই
 * নির্ভর করত Customer-এর উপর। **একটা চক্র।**
 *
 * চক্রটা কেবল কাগুজে সমস্যা নয়: দুইটার একটাকেও আলাদা করে ইনস্টল করা,
 * বন্ধ করা বা বদলানো যেত না, আর Sales বন্ধ থাকা কোনো প্রতিষ্ঠানে
 * গ্রাহকের পাতাটাই খুলত না। module.php-তে নির্ভরতাটা ঘোষণা করে দিলে
 * চক্রটা "বৈধ" হয়ে যেত, কিন্তু সমস্যাটা থেকেই যেত।
 *
 * ── কোন দিকটা সঠিক ──────────────────────────────────────────────────
 * "শেষ কেনা" কথাটা গ্রাহকের নয়, বিক্রয়ের — গ্রাহক কেবল সেটার বিষয়।
 * তাই তথ্যটা Sales দেয়, আর গ্রাহকের পাতা কেবল জিজ্ঞেস করে "এই
 * রেকর্ডটা সম্পর্কে কারও কিছু বলার আছে?" — কে বলল তা না জেনেই।
 *
 * Sales আগে থেকেই Customer-কে চেনে, তাই নতুন কোনো নির্ভরতা তৈরি হয় না;
 * উল্টো দিকেরটা মুছে যায়।
 */
interface ContributesFacts
{
    /**
     * এই রেকর্ডটা সম্পর্কে এই মডিউলের যা বলার আছে।
     *
     * @param  string  $entity  drill_sources-এ ঘোষিত নাম — 'customer', 'vendor'
     * @param  int  $id  ওই রেকর্ডের চাবি
     * @return list<Fact> চেনা না হলে খালি তালিকা — ব্যতিক্রম নয়, কারণ
     *                    প্রতিটা সরবরাহকারীকে প্রতিটা রেকর্ড চিনতে হবে না
     */
    public static function factsFor(string $entity, int $id): array;
}

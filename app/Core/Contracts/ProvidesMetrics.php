<?php

declare(strict_types=1);

namespace App\Core\Contracts;

use App\Core\Metrics\Metric;

/**
 * যে মডিউল তার নিজের সংখ্যাগুলোর সংজ্ঞা ঘোষণা করে।
 *
 * ── কেন মডিউল বলে, কোর নয় ───────────────────────────────────────────
 * কোর কোনো মডিউলের নাম জানে না (সেকশন ১৯.৭)। "আজকের বিক্রয়" কী দিয়ে
 * তৈরি সেটা কেবল Sales-ই জানে, তাই সংজ্ঞাটাও Sales-এর ঘরেই থাকে —
 * কোর শুধু জিজ্ঞেস করে আর তালিকা রাখে।
 *
 * ── কেন সংজ্ঞা এক জায়গায় ────────────────────────────────────────────
 * "আজকের বিক্রয়" এই রিপোতেই চার জায়গায় হিসাব হত, আর একবার তারা
 * দুইটা আলাদা উত্তর দিয়েছিল। প্রশ্ন এক, উত্তর দুই — মিটিংয়ে যেটা ধরা
 * পড়ে না, ধরা পড়ে ছয় মাস পরে, সিদ্ধান্তটা নেওয়া হয়ে যাওয়ার পর।
 */
interface ProvidesMetrics
{
    /**
     * এই মডিউলের সংখ্যাগুলো — চাবি ধরে।
     *
     * @return array<string, Metric>
     */
    public static function metrics(): array;
}

<?php

declare(strict_types=1);

namespace App\Core\Contracts;

/**
 * রেসিপির বই — "এই খাবারটা বানাতে কী কী লাগে", কে জানে সেটা না জেনেই।
 *
 * ── ⭐ মালিকের সিদ্ধান্ত, ১৫ সেপ্টেম্বর ২০২৬ ─────────────────────────
 * *"রেসিপি রান্নাঘরে যাবে।"* রান্না ও খাদ্য-খরচ ঐদিনই মজুদ থেকে
 * রেস্তোরাঁয় গেছে; রেসিপিও তাদের সাথেই যাওয়ার কথা।
 *
 * ── ⛔ কিন্তু একটা দেয়াল ছিল, আর সেটা আসল ───────────────────────────
 * [[App\Modules\Sales\Services\SalesInvoiceService]] রেসিপি **পড়ে** —
 * এক প্লেট বিরিয়ানি বিক্রি হলে চাল-মাংস গুদাম থেকে কাটতে হয়। সে আজ
 * সরাসরি `Inventory\Services\RecipeService` ইনজেক্ট করে।
 *
 * ⚠️ রেসিপি রেস্তোরাঁয় সরালে **বিক্রয়কে রেস্তোরাঁ চিনতে হত**, আর সেটা
 * উল্টো দিক: বিক্রয় রেস্তোরাঁ ছাড়াও চলে, উল্টোটা নয়। [[BoundariesTest]]
 * ঠিকই লাল হত।
 *
 * ── সমাধান: যে ছাঁচে [[SettledByAVoucher]] বসেছে, সেটাই ───────────────
 * বিক্রয় কেবল **এই চুক্তিটা** চেনে। রেস্তোরাঁ বাস্তবায়নটা দেয় আর
 * নিজের `module.php`-এ বেঁধে দেয়। ⭐ তাই তীরটা থাকে এক দিকেই:
 * রেস্তোরাঁ → কোর ← বিক্রয়।
 *
 * ── ⚠️ কেন সব ঘরে কেবল সংখ্যা ও লেখা, কোনো মডেল নয় ─────────────────
 * ⛔ এই ফাইলটা `app/Core`-এ, আর সেখানে কোনো মডিউলের নাম লেখা যায় না —
 * পাহারাটা [[BoundariesTest::test_the_core_names_no_module]]।
 *
 * ⓘ তাই `Recipe` তো দূরের কথা, `Product` বা `Warehouse`-ও এখানে টাইপ
 * হিসেবে বসতে পারে না। প্রতিটা ঘর তাই `int` আইডি আর দশমিক-নিরাপদ
 * `string` অঙ্ক। ডকব্লকে মডিউলের নাম লেখা চলে (পাহারাটা মন্তব্য বাদ
 * দিয়ে পড়ে), কিন্তু কোডে নয়।
 */
interface RecipeBook
{
    /**
     * এই পণ্য বিক্রি হলে উপকরণ কাটতে হবে কি না।
     *
     * ⭐ বিক্রয়ের পুরো রেসিপি-পথটা এই একটা প্রশ্নের পিছনে দাঁড়িয়ে —
     * `false` ফিরলে বাকি কিছুই ডাকা হয় না। ⓘ যে ডিপোতে রান্নাঘর নেই
     * সেখানে এটা সবসময় `false`, আর বিক্রয় আগের মতোই চলে।
     */
    public function consumesOnSale(int $productId): bool;

    /**
     * এত সার্ভিং বানাতে কোন উপকরণ কতটা লাগবে।
     *
     * ⚠️ খালি অ্যারে মানে দুইটা আলাদা জিনিস হতে পারে — রেসিপি নেই, বা
     * রেসিপিটা অসম্পূর্ণ (কোনো লাইন নেই)। ⓘ ডাকার জায়গায় পার্থক্যটা
     * দরকার হলে আগে [[consumesOnSale()]] জিজ্ঞেস করতে হবে: সেটা `true`
     * অথচ এটা খালি মানে **রেসিপিটা অসম্পূর্ণ**, আর তখন থামা উচিত।
     *
     * @return list<array{product_id: int, qty: string}>
     */
    public function needsFor(int $dishId, string $servings): array;

    /**
     * উপকরণগুলো গুদাম থেকে সত্যিই কেটে নেওয়া।
     *
     * ⚠️ এটা **লিখে ফেলে** — [[needsFor()]] কেবল হিসাব করে। দুইটা আলাদা
     * রাখা হয়েছে কারণ বিক্রয় আগে দেখে নেয় যথেষ্ট মাল আছে কি না, আর
     * না থাকলে কিছুই কাটে না।
     *
     * @return list<array{product_id: int, qty: string}> যা সত্যিই কাটা হলো
     */
    public function consume(
        int $dishId,
        string $servings,
        int $warehouseId,
        string $sourceType,
        int $sourceId,
        ?string $date = null,
        ?string $documentNo = null,
    ): array;

    /**
     * আর কত বেচা যাবে — নিজের স্টক, নাকি উপকরণে যতটা কুলায়।
     *
     * ── ⭐ কেন প্রশ্নটা আলাদা ────────────────────────────────────────
     * হাঁড়ির খাবার গুদামে বসে থাকে, তাই তার উত্তর নিজের স্টক। কিন্তু
     * মেড-টু-অর্ডার খাবার কোথাও বসে নেই — এক প্লেট বিরিয়ানি "আছে" কি
     * না সেটা নির্ভর করে চাল-মাংস আছে কি না তার উপর।
     *
     * ⚠️ `$ownStock` ভেতরে পাঠানো হয় কারণ চুক্তিটা গুদামের হিসাব জানে
     * না, আর জানারও কথা নয়। রেসিপি না থাকলে সে ঐ সংখ্যাটাই ফেরত দেয় —
     * অর্থাৎ "আমি কিছু বদলাইনি"।
     */
    public function sellableQty(int $productId, string $ownStock, ?int $warehouseId = null): string;
}

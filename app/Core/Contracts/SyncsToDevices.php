<?php

declare(strict_types=1);

namespace App\Core\Contracts;

use App\Core\Engines\Sync\PushedChange;
use App\Core\Engines\Sync\SyncRecord;
use App\Models\User;
use Illuminate\Support\Carbon;

/**
 * একটা মডিউল বলে দেয় তার কোন রেকর্ড ফোনে যেতে পারে, আর ফোন থেকে কী আসতে
 * পারে।
 *
 * ── কেন মডিউল বলে, কোর নয় ──────────────────────────────────────────
 * কোর জানে না একটা গ্রাহকের কোন ঘরগুলো সেলসম্যানের কাজে লাগে, বা একটা
 * অর্ডার বসানোর নিয়ম কী। যে মডিউল নিয়মটা লিখেছে সে-ই কেবল বলতে পারে
 * (সেকশন ১৯.৭)। কোরে একটা তালিকা রাখলে নতুন মডিউল যোগ করতে কোরের ফাইল
 * খুলতে হত।
 *
 * ── ⚠️ `$user` প্রতিটা পদ্ধতিতে কেন ────────────────────────────────
 * **এক অ্যাপ, সবার জন্য** — মালিক, কর্মী, ডিলার, সরবরাহকারী; যে যার
 * রোল অনুযায়ী (মালিকের সিদ্ধান্ত, ২ সেপ্টেম্বর ২০২৬)।
 *
 * তাই সিঙ্ক **কোম্পানি ধরে ছাঁকলেই যথেষ্ট নয়**। একজন ডিলার সিঙ্ক করলে
 * তাঁর ফোনে পুরো গ্রাহক-তালিকা নেমে যাওয়া মানে **প্রতিযোগীর তালিকা
 * প্রতিযোগীর হাতে** — আর সেটা একবার নেমে গেলে ফেরত আনার উপায় নেই।
 *
 * `$user` না দিলে হ্যান্ডলার ছাঁকতেই পারত না, আর `Auth::user()` ভেতর
 * থেকে ডাকলে হ্যান্ডলারটা পরীক্ষা করা যেত না। তাই এটা প্যারামিটার,
 * সুবিধা নয়।
 *
 * ── কেন `pull` আর `apply` একই শ্রেণিতে ─────────────────────────────
 * দুইটাই একই রেকর্ড-ধরনের কথা বলে, আর দুইটাকে আলাদা শ্রেণিতে রাখলে
 * একটা বদলালে অন্যটা পিছিয়ে থাকত — যেমন `pull` একটা ঘর পাঠানো বন্ধ
 * করল অথচ `apply` সেটা এখনো আশা করে।
 */
interface SyncsToDevices
{
    /**
     * কোন মডিউলের — `sales`, `inventory`, `customer`…
     *
     * ফোন মডিউল ধরে কিউ করে আর মডিউল ধরে টানে, তাই এটাই ভাগ করার একক।
     */
    public static function module(): string;

    /**
     * রেকর্ডের ধরন — `Customer`, `Product`, `SalesOrder`…
     *
     * পুরো ব্যবস্থায় unique হতে হবে; [[SyncRegistry]] বুট-টাইমেই দুইটা
     * এক নাম ধরে ফেলে।
     */
    public static function entityType(): string;

    /**
     * এই রেকর্ডগুলো পেতে যে চাবি লাগে — বা `null`, যদি সত্যিই না লাগে।
     *
     * ── ⚠️ কেন এটা চুক্তির অংশ, হ্যান্ডলারের ভেতরের একটা লাইন নয় ────
     * সিঙ্কের দরজাগুলোয় রুট-স্তরে `can:` নেই, আর সেটা ইচ্ছাকৃত (এক
     * অ্যাপ, সব রোল — [[EveryRouteIsGuardedTest::TOKEN_SYNC]] দেখুন)।
     * তার মানে **ছাঁকনির পুরো ভারটা এখানে**।
     *
     * প্রথমে এটা প্রতিটা `pull()`-এর ভেতরে একটা `$user->can(...)` লাইন
     * ছিল, আর ডক-কমেন্টে "ভুলবেন না" লেখা ছিল। সেটা যথেষ্ট নয়: তিন
     * সপ্তাহ পর দশম হ্যান্ডলারটা লিখবেন এমন কেউ যিনি আগেরগুলো দেখে
     * নকল করছেন — আর তিনি লাইনটা বাদ দিলে **কিছুই লাল হত না**। রুটের
     * পাহারা দেখত না (আমরাই তাকে ছাড় দিয়েছি), আর ডক-কমেন্ট বিল্ড
     * ভাঙে না।
     *
     * ইন্টারফেসের পদ্ধতি হওয়ায় **ভোলা অসম্ভব** — না লিখলে ক্লাসটা
     * তৈরিই হয় না। আর প্রয়োগটা এক জায়গায়, [[SyncService::pull()]]-এ,
     * তাই হ্যান্ডলারের ভেতরে আর ওটা লিখতে হয় না।
     *
     * `null` ফেরত দেওয়া যায়, কিন্তু সেটা তখন একটা **লিখিত সিদ্ধান্ত** —
     * অনুপস্থিতি নয়। কারণটা ওই পদ্ধতির ডক-কমেন্টে লিখুন।
     *
     * ── এটা কেবল মোটা দাগের গেট ────────────────────────────────────
     * "এই ব্যবহারকারী এই ধরনের রেকর্ড আদৌ পাবেন কি না"। **কোন সারিগুলো**
     * পাবেন সেটা এখনো `pull()`-এর কাজ — একজন ডিলার `customer.view`
     * পেলেও তাঁর কেবল নিজের সারিটাই পাওয়ার কথা।
     */
    public static function requiredPermission(): ?string;

    /**
     * `$since`-এর পর যা বদলেছে, **এই ব্যবহারকারীর জন্য**।
     *
     * `$since` null মানে এই ডিভাইস কখনো কিছু পায়নি — পুরোটা যাবে।
     *
     * ⚠️ **`$limit` মানার দায়িত্ব হ্যান্ডলারের**, আর ফেরত তালিকাটা
     * `updatedAt` ধরে সাজানো থাকতে হবে। না সাজালে পাতা-ভাগ অর্থহীন:
     * পরের ডাকে একই রেকর্ড আবার আসত আর অন্যগুলো কোনোদিন আসত না।
     *
     * @return list<SyncRecord>
     */
    public function pull(User $user, ?Carbon $since, int $limit): array;

    /**
     * এই ধরনটা ফোন থেকে আসতে পারে কি না।
     *
     * ── কেন প্রায় সবগুলোয় `false` ───────────────────────────────────
     * মালিকের সিদ্ধান্ত (২ সেপ্টেম্বর ২০২৬): **নেট না থাকলে শুধু
     * অর্ডার।** চালান, বিল, আদায়, POS — কোনোটাই নয়।
     *
     * কারণ চারটা, আর প্রতিটাই অফলাইনে অন্ধ: নম্বরের সিরিজ · তাকের
     * মজুদ · গ্রাহকের ক্রেডিট সীমা · চলতি দাম। অর্ডার এই চারটার
     * একটাতেও হাত দেয় না — ওটা প্রতিশ্রুতি, দাখিলা নয়।
     */
    public function acceptsPush(): bool;

    /**
     * একটা বদল বসানো। ফেরত দেয় বসানো সারির আইডি।
     *
     * ── কীভাবে "না" বলতে হয় ────────────────────────────────────────
     * [[SyncRejection]] ছুঁড়ুন, **বাংলা বার্তা সহ**। ওই বার্তাটা সরাসরি
     * সেলসম্যানের ফোনের পর্দায় যায় — ওটা লগ নয়, UI।
     *
     * `ValidationException`-ও ধরা হয় আর একইভাবে দেখানো হয়, তাই মডিউলের
     * নিজের নিয়মগুলো নতুন করে লিখতে হয় না।
     *
     * ── ⚠️ যা এখানে করবেন না ───────────────────────────────────────
     * নিজের লেনদেন খুলবেন না। [[SyncService]] প্রতিটা বদলকে নিজের
     * লেনদেনে মুড়ে দেয়, যাতে একটা বদল ব্যর্থ হলে **কেবল সেটাই** ফিরে
     * যায় — ব্যাচের বাকিগুলো নয়।
     */
    public function apply(User $user, PushedChange $change): string;
}

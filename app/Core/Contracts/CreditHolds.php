namespace App\Core\Contracts;

/**
 * একজন গ্রাহকের কতটা বাকির সীমা খাতার **বাইরে** আটকে আছে।
 *
 * ── ⭐ মালিকের নিয়ম, ২৬ সেপ্টেম্বর ২০২৬ ─────────────────────────────
 * *"bill khosora hole product zemon atkay temon customer er balanceo
 * atkabe"* — বিল না হওয়া ডিও আর খসড়া বিলও সীমা আটকায়।
 *
 * ── ⚠️ কেন কোরে একটা চুক্তি ──────────────────────────────────────────
 * গ্রাহকের পাতা "অবশিষ্ট সীমা" দেখায়, আর সেটা কাউন্টারের সংখ্যার সাথে
 * **হুবহু** মিলতে হবে — নইলে একই গ্রাহকের দুই পর্দায় দুই সংখ্যা। ⛔ কিন্তু
 * ডিও আর বিল বিক্রয়ের জিনিস, আর গ্রাহক মডিউল বিক্রয়কে চেনে না (নির্ভরতার
 * দিক `sales → customer`)।
 *
 * ⓘ তাই মাঝে এই চুক্তি — [[RecipeBook]]-এর ছাঁচে। বিক্রয় মডিউল বাস্তবায়ন
 * দেয় (`module.php`-র `bindings`), আর বিক্রয় বন্ধ থাকলে কোরের
 * [[NoCreditHolds]] শূন্য বলে — তখন আটকানোর মতো কিছু আসলেই নেই।
 */
interface CreditHolds
{
    /** খাতার বাইরে আটকে থাকা টাকা — না থাকলে `'0'`। */
    public function heldFor(int $customerId): string;
}

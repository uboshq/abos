<?php

declare(strict_types=1);

namespace App\Core\Contracts;

/**
 * একজন ব্যক্তির টাকা কোন খাতে বসার কথা — যে মডিউল জানে, সে বলে।
 *
 * ── ⚠️ কেন এই চুক্তিটা দরকার হলো ────────────────────────────────────
 * ভাউচারের পর্দা জানতে চায়: *"এই লোকটার আদায় কোন খাতে যাবে?"* ⓘ সাধারণ
 * উত্তর প্রাপ্য (১১১০)। ⛔ কিন্তু যিনি আগে মূলধন দিয়েছেন, তাঁর টাকা
 * যাওয়ার কথা মূলধনে (৩১০০) — আর **সেটা Accounts জানে না, Finance জানে**।
 *
 * ── কী ভাঙা ছিল ─────────────────────────────────────────────────────
 * Accounts সরাসরি `Finance\Models\CapitalEntry` ডাকত। ⚠️ তীরটা উল্টো:
 * Finance নিজের `module.php`-তে লিখে রেখেছে সে accounts চেনে, উল্টোটা
 * নয়। ⛔ Accounts সবার নিচের স্তরের কাছাকাছি — সে Finance ছাড়া চলবে না
 * এমন হলে Finance বন্ধ করে দিলে ভাউচারের পর্দাই ভাঙত।
 *
 * ── ⭐ এখন কে কাকে বলে ───────────────────────────────────────────────
 * Finance নিজে এই চুক্তিটা পূরণ করে আর `module.php`-র `bindings`-এ
 * ঘোষণা করে। ⓘ Accounts কেবল চুক্তিটা চায়; কে দিচ্ছে, দিচ্ছে কি না —
 * কিছুই জানে না। ⚠️ Finance বন্ধ থাকলে কেউ বাঁধেনি, আর তখন ডিফল্ট
 * উত্তরটাই চলে ([[NobodyKnowsWhereTheMoneyBelongs]])।
 */
interface KnowsWhereAPersonsMoneyBelongs
{
    /**
     * এই ব্যক্তির আদায় কোন খাতের কোডে বসবে — না জানলে `null`।
     *
     * ⓘ `null` মানে "আমার কিছু বলার নেই", "ভুল" নয় — ডাকনেওয়ালা তখন
     * নিজের সাধারণ নিয়মেই চলে।
     */
    public function accountCodeFor(int $personId): ?string;

    /**
     * যাঁদের সম্পর্কে এই মডিউলের কিছু বলার আছে।
     *
     * ⚠️ পর্দার জন্য আলাদা করে লাগে, আর সারি-প্রতি প্রশ্ন নয়: ফর্মটা
     * একবারে গোটা তালিকাটা নিয়ে যায়, নাহলে দুইশো মানুষের পিকারে
     * দুইশোটা প্রশ্ন হত।
     *
     * @return list<string> ব্যক্তির আইডি, লেখা হিসেবে
     */
    public function peopleItKnowsAbout(): array;
}

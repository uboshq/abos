<?php

declare(strict_types=1);

namespace App\Core\Contracts;

/**
 * অন্য মডিউলের ফর্মে এই মডিউল যে তালিকাগুলো দেয়।
 *
 * ── ⚠️ কেন এই চুক্তিটা দরকার হলো ────────────────────────────────────
 * ভাউচারের ফর্মে চারটা ঘর অন্য মডিউলের তথ্য চায় — কোন মাধ্যমে টাকা গেল
 * (MasterData), কাকে দেওয়া হচ্ছে (Supplier), কোন ক্রয় বিলের ভাড়া
 * (Purchase)। ⛔ কন্ট্রোলার ঐ মডেলগুলো সরাসরি ডাকত, অথচ **তিনটাই
 * accounts-এর উপর দাঁড়িয়ে** — নির্ভরতাটা ঘোষণা করলে চক্র হত আর
 * রেজিস্ট্রি বুট-টাইমেই থামাত।
 *
 * ── ⭐ ছাঁচটা [[ContributesFacts]]-এর হুবহু ─────────────────────────
 * ওখানে লেখা আছে: *"শেষ কেনা কবে" গ্রাহকের পাতায় বসে, কিন্তু কথাটা
 * বিক্রয়ের।* ⓘ এখানেও তাই — ঘরটা ভাউচারের পর্দায় বসে, কিন্তু তালিকাটা
 * যার, সে-ই দেয়।
 *
 * ⚠️ ফর্মের চাবিটা (`accounts.voucher`) ঐ পর্দার নাম, আর সেটা দিয়েই
 * ছাঁকা হয় — নাহলে প্রতিটা মডিউল প্রতিটা ফর্মে নিজের সব তালিকা ঢেলে
 * দিত, আর পর্দাগুলো ভারী হয়ে যেত কোনো কারণ ছাড়াই।
 *
 * ⛔ মডিউল বন্ধ থাকলে তার তালিকাগুলো আসে না, আর ঘরটা ফাঁকা দেখায় —
 * পর্দা ভাঙে না। ⓘ তাই ব্যবহারকারীকে `?? []` ধরে নিতে হয়, আর সেটাই ঠিক:
 * "মডিউলটা নেই" একটা বৈধ অবস্থা।
 */
interface OffersChoicesOnAForm
{
    /**
     * ঐ ফর্মের জন্য এই মডিউলের তালিকাগুলো — নাম => তালিকা।
     *
     * ⓘ যে ফর্মে কিছু দেওয়ার নেই, সেখানে খালি অ্যারে। ⚠️ শর্তটা এখানেই
     * মাপা হয়, ডাকনেওয়ালার দিকে নয় — নাহলে প্রতিটা তালিকা সবসময়
     * তৈরি হত, এমনকি যে পর্দায় সেটা লাগে না সেখানেও।
     *
     * @return array<string, mixed>
     */
    public function choicesFor(string $form): array;
}

namespace App\Core\Contracts;

/**
 * ঐচ্ছিক — একটা ইমপোর্টার যখন বলে "আমার আংশিক ইমপোর্ট চলবেই না"।
 *
 * ── [[WarnsOnPartialImport]]-এর সাথে পার্থক্য ─────────────────────────
 * ওটা **বলে**, এটা **থামায়**। ওটা এসেছিল একই সমস্যা থেকে আর ফলটাও ঠিক
 * ধরেছিল — *"খতিয়ান মেলে ঠিকই, অথচ স্থিতিপত্র ভুল"* — কিন্তু উত্তরটা
 * ছিল পর্দায় একটা জোরালো বার্তা।
 *
 * ⚠️ বার্তাটা ঠিক সেই মুহূর্তে দুর্বল যখন সবচেয়ে বেশি দরকার: নতুন
 * ক্রেতা **প্রথম দিনে** একের পর এক ফাইল তুলছেন, পর্দায় বার্তার ভিড়,
 * আর তখনই মানুষ সবচেয়ে কম পড়েন। আর "পরে ঠিক করে নেব" ভেবে রেখে দিলে
 * ফেরার পথও সরু: আবার চালালে ডুপ্লিকেটের ভয়, না চালালে বই অসম্পূর্ণ,
 * আর **কোন সারিগুলো ঢুকেছিল সেটা বের করাই আসল কষ্ট**।
 *
 * ── কারা এটা ঘোষণা করবে, আর কারা নয় ──────────────────────────────────
 * তালিকা নয়, **দলিল** — এই পার্থক্যটাই নিয়ম। তিনশো গ্রাহকের দুইশো
 * উঠলে বাকিটা পরে তোলা যায়, ক্ষতি নেই; কেউ ভুল সংখ্যা দেখেন না।
 * কিন্তু খোলার জেরের উপর **বাকি সবকিছু দাঁড়ায়**, আর ওটা একবারই বসে —
 * অর্ধেক বসলে প্রথম দিন থেকে প্রতিটা রিপোর্ট ভুল, নীরবে, আর ধরা পড়ে
 * ছয় মাস পরে যখন কেউ স্থিতিপত্র মেলাতে বসেন।
 *
 * ⛔ তাই এটা **সবার জন্য নয়**। গ্রাহক · সরবরাহকারী · পণ্য আগের মতোই
 * চলে: ভুল সারি বাদ, বাকিটা বসে।
 *
 * ── কেন এটা নিষ্ঠুর নয় ───────────────────────────────────────────────
 * কারণ শুকনো দৌড় আগে থেকেই আছে ([[ImportRunner::check()]]) আর সে
 * **প্রতিটা** খারাপ সারি একসাথে দেখায়, একটা করে নয়। ব্যবহারকারী পুরো
 * তালিকাটা দেখে ফাইল শুধরে তারপর আসল দৌড় দেন। ওটা না থাকলে সব-বা-
 * কিছুই-না মানে হত পাঁচ হাজার সারির ফাইল ৪,৯৯৯ নম্বরে থেমে যাওয়া।
 */
interface RefusesAPartialImport
{
    /**
     * পুরো ফাইল ফিরিয়ে দেওয়ার পর যে বাক্যটা দেখাতে হবে — কেন একটাও
     * সারি বসেনি, ব্যবহারকারীর ভাষায়। অনুবাদের কী নয়, তৈরি বাক্য।
     */
    public function refusalNotice(): string;
}

<?php

declare(strict_types=1);

namespace App\Core\Contracts;

use App\Models\Approval;

/**
 * ⭐ ইনবক্সের সারিতে একটা অনুরোধ নিজে কী বলে — কাগজ নয়, অনুরোধ (a6, ২১ অক্টোবর ২০২৬; §৮ ⚠️৫, fe-র উত্তর ৪)।
 *
 * ⓘ [[ShowsItselfForSigning]] কাগজের নিজের পাতা দেয়; কিন্তু কিছু কাজের প্রস্তাব কাগজে নেই, অনুরোধে জমা থাকে (বেতনের কাঠামো বদল:
 * কর্মী কাগজ, বদলটা অনুরোধে)। ⭐ তাই মডিউল `approval_rules`-এ কাজ ধরে একটা ক্লাস ঘোষণা করে, আর ইনবক্স — একসাথে সইয়ের তালিকাও —
 * সেই লেখাটা সারিতে দেখায় ([[ApprovalFacts::of()]])। অনুমোদন কোরের, মডিউলের ভিতরে তাকায় না (§১৯.৭)।
 *
 * ⛔ লেখাটা চলতি দর্শকের জন্য — গোপন অঙ্ক তাঁর চাবি না থাকলে ঢাকা ([[FieldSecurity]]), কারণ ইনবক্স নিরীক্ষকও খোলেন।
 */
interface SummarisesAnApproval
{
    /** ⓘ `null` = বলার কিছু নেই — সারি আগের মতোই কাগজের তথ্য দেখায়। */
    public function summary(Approval $approval): ?string;
}

<?php

declare(strict_types=1);

namespace App\Core\Contracts;

use App\Core\Panels\TradeGlance;

/**
 * একজন গ্রাহকের কেনাবেচার এক নজরের ছবি — বিল, বকেয়া বিল, শেষ কেনা, শেষ জমা।
 *
 * ── ⭐ মালিকের নির্দেশ, ২৭ সেপ্টেম্বর ২০২৬ ─────────────────────────────
 * গ্রাহক তালিকার 👁 চাপলে বিস্তারিত খাতা নয়, **এক নজরের সারাংশ**:
 * এই মাসের ও সারা জীবনের বিল, বকেয়া, বকেয়া বিল কয়টা ও তাতে কয়টা পণ্য,
 * শেষ কেনা, শেষ জমা, আর অবশিষ্ট সীমা। খাতা কেবল বকেয়ার লিংকে।
 *
 * ── ⚠️ কেন কোরে একটা চুক্তি ──────────────────────────────────────────
 * বিল আর আদায় বিক্রয়ের জিনিস, অথচ পাতাটা গ্রাহকের। ⛔ গ্রাহক মডিউল
 * বিক্রয়কে চেনে না (নির্ভরতার দিক `sales → customer`) — [[CreditHolds]]-এর
 * একই ছাঁচ। বিক্রয় বাস্তবায়ন দেয় (`module.php`-র `bindings`), আর বিক্রয়
 * বন্ধ থাকলে কোরের [[NoCustomerTrade]] `null` বলে — তখন পাতাটা কেবল খাতা
 * আর সীমার অংশ দেখায়, মিথ্যা শূন্য নয়।
 */
interface CustomerTrade
{
    /**
     * @param  string  $monthStart  চলতি মাসের প্রথম দিন (Y-m-d)
     * @param  string  $today  আজ (Y-m-d) — এই মাসের শেষ সীমা
     */
    public function glanceFor(int $customerId, string $monthStart, string $today): ?TradeGlance;
}

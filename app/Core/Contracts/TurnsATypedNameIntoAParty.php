<?php

declare(strict_types=1);

namespace App\Core\Contracts;

/**
 * কেউ হাতে একটা নাম লিখলেন — সেটাকে একটা সারিতে পরিণত করা।
 *
 * ── ⚠️ কেন এই চুক্তিটা দরকার হলো ────────────────────────────────────
 * কাউন্টারে অচেনা একজন টাকা দিয়ে গেলে রসিদ কাটতেই হয়, আর তখন নামটা
 * হাতে লেখা হয়। ⓘ নামটা কোথায় বসবে, আগে বসানো আছে কি না, মোবাইল নম্বর
 * ধরে মেলে কি না — সেটা **MasterData জানে, Accounts নয়**।
 *
 * ── কী ভাঙা ছিল ─────────────────────────────────────────────────────
 * ভাউচারের যাচাই সরাসরি `MasterData\Services\PersonResolver` ডাকত।
 * ⛔ কিন্তু MasterData নিজেই accounts-এর উপর দাঁড়িয়ে আছে, তাই
 * নির্ভরতাটা ঘোষণা করলে **চক্র** হত আর রেজিস্ট্রি বুট-টাইমেই থামাত
 * ([[App\Core\Module\ModuleRegistry]])।
 *
 * ── ⭐ এখন কে কাকে বলে ───────────────────────────────────────────────
 * MasterData নিজে চুক্তিটা পূরণ করে আর `module.php`-র `bindings`-এ
 * ঘোষণা করে। ⓘ Accounts কেবল চুক্তিটা চায়; কে দিচ্ছে, দিচ্ছে কি না —
 * কিছুই জানে না। ⚠️ কেউ না বাঁধলে কোরের "পারি না" বাঁধনটা চলে, আর
 * উত্তর `null` — তখন হাতে লেখা নামটা সারি হয় না, কিন্তু পর্দা ভাঙে না
 * ([[App\Core\Services\NobodyCanMakeAParty]])।
 */
interface TurnsATypedNameIntoAParty
{
    /**
     * হাতে লেখা নামটা থেকে একটা পক্ষের আইডি — না পারলে `null`।
     *
     * ⓘ মোবাইল নম্বরটা ঐচ্ছিক, কিন্তু থাকলে সেটাই একই মানুষকে দুইবার
     * বসা থেকে বাঁচায় — নামের বানান বদলায়, নম্বর বদলায় না।
     *
     * ⚠️ `null` মানে "পারলাম না", "ভুল" নয় — ডাকনেওয়ালা তখন নিজের
     * স্বাভাবিক নিয়মেই চলে।
     */
    public function fromTypedName(string $name, ?string $mobile = null): ?int;

    /**
     * ঐ আইডিটা কোন ধরনের পক্ষ — খতিয়ানের সারিতে যে লেখাটা বসে।
     *
     * ⓘ আলাদা করে জিজ্ঞেস করা হয়, কারণ কোর ধরনের নামগুলো নিজে জানে না;
     * ওগুলো মডিউলের ঘোষণা থেকে আসে ([[PartyRegistry]])।
     */
    public function partyType(): string;
}

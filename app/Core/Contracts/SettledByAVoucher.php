<?php

declare(strict_types=1);

namespace App\Core\Contracts;

/**
 * একটা নথি যা রসিদ বা পরিশোধ ভাউচার পোস্ট হলে নিষ্পন্ন হয়।
 *
 * ── ⭐ মালিকের স্থাপত্যগত সিদ্ধান্ত, ১৪ সেপ্টেম্বর ২০২৬ ────────────────
 * তিনি প্রশ্ন করেছিলেন: *"অর্থে মূলধন লিখে হিসাবে রিসিভ করলেই তো সমাধান
 * — এক জায়গায় হয়, এত কী করো?"*
 *
 * তাই কাজটা ভাগ হলো: **অর্থ কেবল লেখে "কে কত দেবেন", টাকা গ্রহণ করে
 * একাই রসিদের পর্দা।** কিন্তু ভাগটা তখনই কাজ করে যখন রসিদ পোস্ট হলে
 * অর্থের সারিটাও নিষ্পন্ন হয়।
 *
 * ⛔ ঘরটা না থাকলে সারিটা **চিরকাল খসড়া থেকে যেত** — অর্থের পর্দা বলত
 * "এখনো আসেনি", হিসাবের খাতা বলত টাকাটা এসে গেছে। এক সত্যের দুইটা উৎস,
 * আর এই রিপোর দেখা সবচেয়ে দামি রোগ।
 *
 * ── ⚠️ কেন একটা চুক্তি, কেন সরাসরি ডাক নয় ────────────────────────────
 * [[App\Modules\Accounts\Services\VoucherService]] **কখনোই** জানতে পারবে
 * না `capital_entry` মানে কোন ক্লাস — Accounts-এর `depends_on` ফাঁকা,
 * বাকি সবাই তার উপর দাঁড়ায়। Finance-এর নাম ঐ ফাইলে লিখলে চক্রাকার
 * নির্ভরতা, আর [[Tests\Feature\Architecture\BoundariesTest]] ঠিকই ধরত।
 *
 * ⭐ তাই একই ছাঁচ যেটা [[Drillable]] ও [[ProvisionsCompany]] ব্যবহার করে:
 * ধরনের নামটা module.php-র `drill_sources`-এ ক্লাসের সাথে বাঁধা থাকে,
 * [[App\Core\Engines\Drill\DrillResolver]] সেটা খুলে দেয়, আর Accounts
 * কেবল **Core-এর চুক্তিটা** চেনে।
 *
 * ── ⛔ যে মডিউল এটা প্রয়োগ করবে, তার জন্য দুইটা শর্ত ──────────────────
 * ১. ধরনের নামটা তার নিজের module.php-র `drill_sources`-এ থাকতে **হবে**।
 *    না থাকলে ধরনটা কোনোদিন সমাধান হবে না আর হুকটা **নীরবে কিছুই করবে
 *    না** — যা এই কাজের সবচেয়ে খারাপ ফল, কারণ পর্দা সবুজ দেখাবে।
 *
 * ২. ⚠️ দুইটা মেথডই **idempotent** হতে হবে। একই রসিদ দুইবার পোস্ট হতে
 *    পারে (বাতিল করে আবার), আর তখন সারিটা দুইবার বদলালে ইতিহাসটাই
 *    মিথ্যা হয়ে যেত।
 */
interface SettledByAVoucher
{
    /**
     * ভাউচারটা পোস্ট হয়েছে — নথিটা এখন নিষ্পন্ন।
     *
     * ⓘ ডাকা হয় **পোস্টিংয়ের একই লেনদেনের ভেতরে**, তাই এখানে ছুঁড়লে
     * ভাউচারটাও খাতায় বসে না। অর্ধেক নিষ্পন্ন সারি কখনো থাকে না।
     */
    public function settleWith(int $voucherId): void;

    /**
     * ভাউচারটা বাতিল হয়েছে — নথিটা আবার খসড়া।
     *
     * ⚠️ এটা না থাকলে ভুল করে কাটা একটা রসিদ বাতিল করার পরেও অর্থের
     * সারিটা "পাওয়া গেছে" বলে বসে থাকত, আর টাকাটা দ্বিতীয়বার চাওয়া
     * হত না।
     */
    public function unsettle(int $voucherId): void;
}

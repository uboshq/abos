<?php

declare(strict_types=1);

namespace App\Core\Contracts;

/**
 * ⭐ সিঙ্কের উত্তরে বাড়তি তথ্য — যে জিনিস ফোনকে বসার সাথে সাথেই কিছু বলতে চায় (টাকা নেওয়ার নকশা ১০০, a4-এর চুক্তি, ২১ অক্টোবর ২০২৬)।
 *
 * ⓘ আদায় বসলে ফোনের রসিদ সঙ্গে সঙ্গে নম্বর, অবস্থা, টাকা কথায়, রসিদের PDF, কোন বিলে কত বসল আর কত অপ্রয়োগকৃত চায় —
 * পরের টানার অপেক্ষা না করে। [[SyncService]] বসার উত্তরে (আর একই বদল দ্বিতীয়বার এলেও) এগুলো যোগ করে।
 * ⓘ ঐচ্ছিক: যে জিনিস এটা মানে না, তার উত্তর আগের মতোই। ⛔ উত্তর বানাতে ভাঙলেও বসাটা টেকে — বাড়তি তথ্য বাদ পড়ে, বদল নয়।
 */
interface AnswersAfterSync
{
    /**
     * @return array<string, mixed> উত্তরের বাড়তি ঘর — `changeId`, `status`, `entityId`, `message` নাম বাদে
     */
    public function answerFor(string $entityId): array;
}

<?php

declare(strict_types=1);

namespace App\Core\Contracts;

/**
 * ⭐ প্রাপকের ব্যাংক — দেখানোর জন্য, ঢাকা নম্বরে (রসিদ-পরিশোধ মিল-তালিকা #৬৬ আর #৮০, ২৫ অক্টোবর ২০২৬; নকশা পাতা ৪:
 * "সোনালী ব্যাংক · হিসাব ••••4521 · ✓ দুজনের সইয়ে যাচাই-করা")।
 *
 * ── কেন কোরে একটা চুক্তি ([[PayeeBankGuard]]-এর জোড়া) ─────────────────
 * [[PayeeBankGuard]] টাকা যাওয়ার মুহূর্তে থামায়; এটা তার আগেই পর্দায় বলে কোন অবস্থায় আছে, যাতে লেখক পোস্টে গিয়ে প্রথম
 * জানতে না পারেন। ব্যাংক তথ্য সরবরাহকারী মডিউলের, তাই বাস্তবায়নও সেখানে (`module.php`-র `bindings`); মডিউল বন্ধ থাকলে
 * কোরের [[NoPayeeBankView]] `null` বলে।
 *
 * ⓘ উত্তরের আকার ফোনের অ্যাপেরও (a4) — তাই এখানে স্থির: `state` আর `line`, আর কিছু নয়।
 * ⛔ পুরো হিসাব নম্বর কখনো নয় — কেবল শেষ চার অঙ্ক।
 */
interface PayeeBankView
{
    /**
     * `state`: `signed` (দুই হাতে সই-পাওয়া তথ্য আছে — টাকা সেখানেই যাবে), `pending` (কেবল সইয়ের অপেক্ষার বদল আছে), `none`;
     * `line`: "ব্যাংক ••••7890" — যে তথ্যের কথা `state` বলছে তার, `none`-এ `null`।
     *
     * `null`: পক্ষটা এই চুক্তির ধরনের নয়, বা অচেনা বা অন্য কোম্পানির।
     *
     * @return array{state: 'signed'|'pending'|'none', line: ?string}|null
     */
    public function bankOf(string $partyType, int $partyId): ?array;
}

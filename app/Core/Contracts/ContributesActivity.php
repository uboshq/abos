/**
 * যে মডিউল বলতে পারে তার ঘরে সদ্য কী হয়েছে।
 *
 * ── কেন মডিউল বলে, কোর নয় ───────────────────────────────────────────
 * "সদ্য কী হয়েছে" প্রশ্নটার উত্তর মডিউলভেদে সম্পূর্ণ আলাদা: বিক্রয়ে
 * একটা বিল, হিসাবে একটা নগদ গণনা, ক্রয়ে মাল আসা। কোর যদি নিজে

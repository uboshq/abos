 */
interface ContributesActivity
{
    /**
     * সদ্য যা হয়েছে — সাম্প্রতিকতমটা আগে।
     *
     * @param  int  $limit  এর বেশি সারি ফেরত দেওয়ার দরকার নেই — কোর
     *                      সবগুলো মিলিয়ে আবার ছাঁটবে
     * @return list<Happening>
     */
    public static function activity(int $limit): array;
}

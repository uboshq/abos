<?php

declare(strict_types=1);

namespace App\Core\Contracts;

/**
 * নতুন কোম্পানি তৈরি হলে যে সার্ভিসটাকে একবার ডাকতে হয়।
 *
 * ── কেন এই চুক্তিটা লাগল ─────────────────────────────────────────────
 * CompanyProvisioner আগে সরাসরি দুইটা সার্ভিস ডাকত: হিসাবের প্রমিত ছক
 * বসানো, আর মাস্টার তালিকার ডিফল্ট সারিগুলো। অর্থাৎ **কোর জানত
 * "accounts" আর "master_data" নামে দুইটা মডিউল আছে** — আর সবাই যার উপর
 * দাঁড়ায় সে দুইজনের উপর দাঁড়িয়ে ছিল (§১৯.৭)।
 *
 * বাস্তবে এর দাম হলো: HR-এর প্রমিত বেতন-খাতগুলোও নতুন কোম্পানিতে বসার
 * কথা, কিন্তু বসত না — কারণ কোরে আরেকটা লাইন যোগ করতে হত, আর সেটা
 * কেউ করেনি। মডিউল নিজে ঘোষণা করলে ওই ভুলটা আর সম্ভব নয়।
 *
 * ── ক্রম ─────────────────────────────────────────────────────────────
 * ModuleRegistry নির্ভরতার ক্রমে ফেরত দেয়, তাই ছক (accounts) সবসময়
 * মাস্টার তালিকার (master_data, যে accounts-এর উপর নির্ভর করে) আগে
 * চলে। ক্রমটা কোথাও হাতে লেখা নেই — নির্ভরতাই সেটা ঠিক করে দেয়।
 */
interface ProvisionsCompany
{
    /**
     * এই মডিউলের যা যা নতুন কোম্পানিতে থাকা দরকার, বসিয়ে দাও।
     *
     * কোম্পানির প্রেক্ষাপট (CompanyContext) ইতিমধ্যেই বসানো, আর পুরোটা
     * একটা ট্রানজেকশনের ভেতরে — অর্ধেক বসানো কোম্পানি বলে কিছু থাকবে না।
     *
     * বারবার ডাকা নিরাপদ হতে হবে: যা আছে তা আবার বসানো যাবে না।
     */
    public function provisionCompany(): void;
}

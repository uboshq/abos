<?php

declare(strict_types=1);

namespace App\Core\Contracts;

/**
 * রিপোর্টের একটা সাধারণ ছাঁকনির বাছাই-তালিকা — রিপোর্ট সেন্টার ধাপ ১ (মালিক, ১ অক্টোবর ২০২৬)।
 *
 * ⓘ যে মডিউলের জিনিস, সে-ই ঘোষণা করে (module.php `report_filters`) — কোর কোনো মডিউল চেনে না।
 * ⛔ তালিকা দেয়াল মানে: কোম্পানি, হেডারে বাছা শাখা, আর ব্যবহারকারীর ডেটার পরিধি।
 */
interface ReportFilterSource
{
    /** ঘরের নাম — অনুবাদ-কী */
    public function label(): string;

    /**
     * এই ব্যবহারকারী যা দেখতে পারেন: নম্বর → "কোড · নাম"। ⓘ কোডসহ, যাতে একই নামের দুইটা দোকান গুলিয়ে না যায়।
     *
     * @return array<int, string>
     */
    public function options(): array;

    /**
     * ঠিকানার মান থেকে নম্বর — নম্বর হোক বা বাছাই-ঘরের "কোড · নাম"।
     *
     * ⛔ কেবল যা [[options()]]-এ আছে: অন্যের নম্বর হাতে বসালে `null`, আর ইঞ্জিন তখন রিপোর্টটাই ফেরায় — ছাঁকনি
     * ফেলে দিয়ে গোটা তালিকা দেখায় না।
     */
    public function resolve(string $raw): ?int;
}

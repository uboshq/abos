<?php

declare(strict_types=1);

namespace App\Core\Contracts;

/**
 * ⭐ একজন পক্ষের বাকির সীমা — সীমা, ব্যবহৃত আর অবশিষ্ট (রসিদ-পরিশোধ মিল-তালিকা #১৯, ২৫ অক্টোবর ২০২৬: পিকারের নিচে
 * "বাকির সীমা ৳1,00,000")।
 *
 * ── কেন কোরে একটা চুক্তি ([[PayeeBankGuard]], [[CreditHolds]]-এর ছাঁচ) ─────
 * সীমা গ্রাহক মডিউলের ঘর, আর রসিদ হিসাবের পর্দা — হিসাব গ্রাহককে চেনে না (নির্ভরতার দিক `customer → accounts`,
 * BoundariesTest)। ⓘ তাই গ্রাহক মডিউল বাস্তবায়ন দেয় (`module.php`-র `bindings`), আর গ্রাহক মডিউল বন্ধ থাকলে কোরের
 * [[NoPartyCreditLimit]] `null` বলে — তখন সীমার কথাই নেই।
 *
 * ⛔ সংখ্যাগুলো গ্রাহকের পাতা আর কাউন্টারের দেয়ালের হুবহু — বাস্তবায়ন নিজে কিছু গোনে না, গ্রাহকের নিজের হিসাব ডাকে।
 * ⓘ সব অঙ্ক bcmath লেখা, দুই দশমিকে; কখনো float নয়।
 */
interface PartyCreditLimit
{
    /**
     * এই পক্ষের সীমা — `limit` (চলতি সীমা, অস্থায়ীসহ), `used` (বকেয়া + আটকে থাকা + ক্লিয়ার না হওয়া চেক) আর `available`
     * (সীমা − ব্যবহৃত, শূন্যের নিচে নয়)।
     *
     * `null`: পক্ষটা এই চুক্তির ধরনের নয়, এই কোম্পানির নয় বা পাওয়া যায় না, অথবা কোম্পানিতে সীমার সুইচই বন্ধ।
     *
     * @return array{limit: string, used: string, available: string}|null
     */
    public function creditOf(string $partyType, int $partyId): ?array;
}

<?php

declare(strict_types=1);

namespace App\Core\Engines\Approval;

use Illuminate\Database\Eloquent\Model;

/**
 * একটা কাগজ সই দেওয়ার সময় যেমন ছিল, এখনো তেমনই আছে কি না।
 *
 * ── ⭐ মালিকের সিদ্ধান্ত, ২৪ সেপ্টেম্বর ২০২৬ ─────────────────────────
 * *"যেকোনো ঘর বদলালেই"* সই বাতিল। ⓘ তিনি কড়া দিকটা বেছেছেন, আর
 * কারণটা পরিষ্কার: আজ অঙ্ক ঠিক রেখে **পণ্য বদলে দিলে পুরনো সইটাই চলে**।
 *
 * ── ⚠️ কেন ঘরের তালিকা নয়, গোটা কাগজের ছাপ ──────────────────────────
 * ⓘ তালিকা রাখলে প্রতিটা মডিউলকে মনে করে *"এই ঘরটাও গুরুত্বপূর্ণ"*
 * লিখতে হত। ⛔ আর মানুষ যেটা মনে রাখতে হয় সেটাই ভোলে — একটা নতুন
 * কলাম যোগ হত, কেউ তালিকায় বসাতে ভুলে যেত, আর ঐ ঘরটা **নীরবে
 * অরক্ষিত** থেকে যেত।
 *
 * ⭐ উল্টো দিকটা নিরাপদ: সব ঘর ধরা হয়, আর যেগুলো **ইচ্ছাকৃতভাবে**
 * বাদ সেগুলো এখানে এক জায়গায় লেখা — ছোট, পড়া যায়, আর নতুন কলাম
 * আপনা থেকেই সুরক্ষিত।
 */
final class DocumentFingerprint
{
    /**
     * যে ঘরগুলো বদলালে সই বাতিল হয় না — কারণসহ।
     *
     * ⚠️ তালিকাটা ছোট রাখা ইচ্ছাকৃত: প্রতিটা সারি একটা সিদ্ধান্ত, আর
     * প্রতিটা সারি একটা ফাঁক।
     *
     * @var list<string>
     */
    private const NOT_THE_PAPER = [
        /* ⓘ প্রতিটা সংরক্ষণেই বদলায় — ধরলে প্রতিবার নতুন অনুমোদন লাগত */
        'updated_at',
        'created_at',

        /* ⓘ ছাপা বা শেয়ারের গোনা — কাগজের কথা নয়, ব্যবহারের কথা */
        'printed_count',
        'shared_count',
        'printed_at',

        /* ⚠️ অনুমোদনের নিজের অবস্থা — নাহলে সই দেওয়ামাত্র ছাপ বদলে যেত */
        'status',
        'approved_at',
        'approved_by',
        'posted_at',

        /* ⓘ যন্ত্রের নিজের হিসাব, মানুষের সিদ্ধান্ত নয় */
        'row_hash',
        'prev_hash',
        'public_id',
    ];

    /**
     * ⭐ কাগজটার এখনকার ছাপ।
     *
     * ── ⓘ সারিগুলোও ধরা হয় ──────────────────────────────────────────
     * ⚠️ কেবল মাথার ঘরগুলো নিলে **পণ্যের সারি বদলানো ধরা পড়ত না** —
     * অথচ ঠিক সেটাই সবচেয়ে বিপজ্জনক বদল। ⓘ যে সম্পর্কগুলো ইতিমধ্যে
     * তোলা আছে (কোনগুলো, তা কাগজ ঠিক করে — [[asStored()]]) কেবল সেগুলো — নাহলে একটা ছাপ নিতে
     * গিয়ে গোটা ডাটাবেস তুলে আনত।
     */
    public function of(Model $document): string
    {
        return hash('sha256', json_encode($this->shapeOf($this->asStored($document)), JSON_THROW_ON_ERROR));
    }

    /**
     * ⛔ কাগজটা **যেমন ডাটাবেজে আছে** — হাতের কপিটা যেমন, তেমন নয়।
     *
     * ── ⚠️ যা ধরা পড়ল, ২৪ সেপ্টেম্বর ২০২৬ ──────────────────
     * ⓘ `Model::create()` সারিটা আবার পড়ে না — হাতের অবজেক্টে
     * কেবল যে ঘরগুলো দেওয়া হয়েছিল সেগুলোই থাকে। ⛔ ডাটাবেজের
     * ডিফল্টগুলো (`is_active = 1`, `qty = 0`) ওখানে নেই।
     *
     * ⚠️ ফল: অনুরোধের দিন নেওয়া ছাপ আর পরে ডাটাবেজ থেকে পড়া
     * সারির ছাপ কখনো মিলত না — কাগজটা এক চুলও না বদলালেও।
     * ⓘ তখন [[ApprovalExceptions::changedAfterSigning()]] প্রতিটা অনুমোদিত
     * কাগজকে *"সইয়ের পর বদলেছে"* বলত, আর তালিকাটা এত ভরা থাকত
     * যে কেউ ওটা পড়ত না — আর সত্যিকারের একটা বদল ওই ভিড়ে হারাত।
     *
     * ── ⓘ হাতের অবজেক্টটা ছোঁয়া হয় না ─────────────────────
     * ⛔ `refresh()` ডাকলে যিনি কাগজটা নিয়ে কাজ করছেন তাঁর
     * অসংরক্ষিত বদলগুলো মুছে যেত — একটা ছাপ নেওয়া কখনো কারো
     * কাজ মুছে দেবে না। ⓘ তাই আলাদা একটা কপি।
     *
     * ── ⓘ সারিগুলো হাতেরটাই ──────────────────────────────
     * যে সম্পর্কগুলো তোলা আছে সেগুলো সাথে যায়, আর ওগুলো
     * এমনিতেই ডাটাবেজ থেকে পড়া — তাই ওখানে এই ফাঁকটা নেই।
     */
    private function asStored(Model $document): Model
    {
        if (! $document->exists) {
            return $document;
        }

        $stored = $document->newQuery()->find($document->getKey());

        if ($stored === null) {
            /*
             * ⓘ গ্লোবাল স্কোপ লুকিয়ে দিয়েছে, নাহলে সারিটা আর নেই।
             * ⚠️ দুই অবস্থাতেই হাতের কপিটাই সবচেয়ে ভালো উত্তর — ছাপ
             * না নিয়ে ফেরত যাওয়ার চেয়ে ভালো।
             */
            return $document;
        }

        /*
         * ⭐ ছাপে কোন সারি — কাগজের ঘোষণা থেকে, হাতে কী তোলা আছে তা থেকে নয় (২৮ সেপ্টেম্বর ২০২৬)।
         *
         * ── ⛔ কী ভাঙা ছিল ─────────────────────────────────────────────
         * ⓘ আগে হাতের কপির তোলা সম্পর্কগুলোই ছাপে যেত। ⚠️ তাই একই কাগজের
         * ছাপ ডাকার জায়গা ধরে বদলাত, আর বদলহীন কাগজও "সইয়ের পর বদলেছে"
         * হয়ে নতুন সই চাইত:
         *   · খরচের ভাউচার — `create()` ফেরায় `lines`-সহ, `post()` তোলে
         *     `lines.account`: সই হয়ে যাওয়ার পর "পোস্ট" আবার সই চাইত
         *     ([[AnExpenseNobodySaidYesToTest]]);
         *   · কাউন্টারের চালান — [[DirectSaleService::finishHeld()]] দেখে
         *     `lines`+`warehouse` নিয়ে, [[DeliveryChallanService::confirm()]]
         *     `lines.product`+`lines.orderLine`+`warehouse` নিয়ে: দ্বিতীয় প্রশ্ন
         *     লেনদেনের ভিতরে নতুন অনুরোধ খুলে থামত, আর ফেরত-গড়ানোয় সেটা মুছত —
         *     সই-হওয়া বিক্রি চিরকাল আটকে (লাইভে INV-0003, INV-0005)।
         *
         * ── ⭐ এখন ─────────────────────────────────────────────────────
         * ⓵ কাগজ `fingerprintRelations()` বললে — ঠিক ঐগুলো;
         * ⓶ না বললে, কাগজের `lines()` থাকলে — কেবল `lines`;
         * ⓷ নাহলে কেবল মাথার ঘর।
         * ⓘ তিনটাতেই সারিগুলো ডাটাবেজ থেকে নতুন করে তোলা, হাতেরগুলো উপেক্ষা —
         * তাই যে-ই ডাকুক, একই কাগজের একই ছাপ।
         * ⚠️ সারির ভিতরের সম্পর্ক (পণ্য, খাত) ছাপে নেই: ওদের আইডি সারিতেই আছে,
         * তাই পণ্য বা খাত বদলালে ছাপ এমনিতেই বদলায়।
         */
        $stored->setRelations([])->load($this->relationsOf($document));

        /*
         * ⓘ কিন্তু যা **এখনো ডাটাবেজে নেই** — একটা প্রস্তাব — সেটা কাগজেরই অংশ।
         *
         * ⚠️ বাকির সীমা বাড়ানোয় নতুন অঙ্কটা একটা না-সংরক্ষিত সম্পর্ক হিসেবে
         * কাগজে লাগানো থাকে ([[CustomerService::withProposedLimit()]]), কারণ সইয়ের
         * আগে সেটা কোথাও লেখা যায় না। ⛔ ওটা বাদ দিলে "১ লাখ থেকে ৫০ লাখ" আর
         * "১ লাখ থেকে ২ লাখ" একই ছাপ পেত, আর একটা প্রত্যাখ্যাত অঙ্ক অন্য
         * অঙ্কের অনুরোধও আটকে দিত ([[TheSignatureWasForOneLakhAndFiftyWereSetTest]])।
         * ⭐ নিয়মটা তাই পরিষ্কার: ডাটাবেজ থেকে তোলা সারি উপেক্ষা (নতুন করে তোলা
         * হয়), ডাটাবেজে-না-থাকা প্রস্তাব রাখা।
         */
        foreach ($document->getRelations() as $name => $related) {
            if ($related instanceof Model && ! $related->exists) {
                $stored->setRelation($name, $related);
            }
        }

        return $stored;
    }

    /** @return list<string> */
    private function relationsOf(Model $document): array
    {
        if (method_exists($document, 'fingerprintRelations')) {
            return $document->fingerprintRelations();
        }

        return method_exists($document, 'lines') ? ['lines'] : [];
    }


    /**
     * @return array<string, mixed>
     */
    private function shapeOf(Model $document): array
    {
        $out = [];

        /*
         * ⭐ কাগজের নিজের সংকীর্ণ ব্যতিক্রম — ২৭ সেপ্টেম্বর ২০২৬।
         *
         * ⓘ উপরের তালিকা সব কাগজের। কোনো কাগজের একটা ঘর যদি সইয়ের শর্ত না
         * হয়ে **প্রমাণ** হয় (যেমন ভাউচারের ব্যাংক লেনদেন নম্বর — টাকা নড়ার
         * পরে জন্মায়), সেটা কাগজটা নিজেই বলে (`fingerprintIgnores()`)।
         * ⚠️ তালিকাটা এখানে সবার জন্য বাড়ানো হয়নি: তাহলে আদায়, পরিশোধ
         * সব কাগজেই ঘরটা ছাপের বাইরে চলে যেত।
         */
        $skip = method_exists($document, 'fingerprintIgnores')
            ? [...self::NOT_THE_PAPER, ...$document->fingerprintIgnores()]
            : self::NOT_THE_PAPER;

        foreach ($document->getAttributes() as $key => $value) {
            if (in_array($key, $skip, true)) {
                continue;
            }

            $out[$key] = $value === null ? null : (string) $value;
        }

        ksort($out);

        /*
         * ⓘ সারিগুলো — কেবল যেগুলো ইতিমধ্যে তোলা আছে।
         *
         * ⚠️ ক্রমটা `id` ধরে সাজানো হয়, নাহলে একই সারিগুলো অন্য ক্রমে
         * এলে ছাপ বদলে যেত আর কাগজ না বদলেও সই বাতিল হত।
         */
        foreach ($document->getRelations() as $name => $related) {
            if ($related === null) {
                continue;
            }

            $rows = $related instanceof Model ? [$related] : $related;

            $lines = [];

            foreach ($rows as $row) {
                if ($row instanceof Model) {
                    $lines[] = $this->shapeOf($row);
                }
            }

            usort($lines, fn (array $a, array $b) => ($a['id'] ?? '') <=> ($b['id'] ?? ''));

            $out['~'.$name] = $lines;
        }

        return $out;
    }
}

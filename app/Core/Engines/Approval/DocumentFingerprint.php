<?php

declare(strict_types=1);

namespace App\Core\Engines\Approval;

use Illuminate\Database\Eloquent\Model;

/**
 * একটা কাগজ সই দেওয়ার সময় যেমন ছিল, এখনো তেমনই আছে কি না।
 *
 * ── ⭐ মালিকের সিদ্ধান্ত, ২৪ সেপ্টেম্বর ২০২৬ ─────────────────────────
 * *"যেকোনো ঘর বদলালেই"* সই বাতিল। ⓘ তিনি কড়া দিকটা বেছেছেন, আর
 * কারণটা পরিষ্কার: আজ অঙ্ক ঠিক রেখে **পণ্য বদলে দিলে পুরনো সইটাই চলে**।
 *
 * ── ⚠️ কেন ঘরের তালিকা নয়, গোটা কাগজের ছাপ ──────────────────────────
 * ⓘ তালিকা রাখলে প্রতিটা মডিউলকে মনে করে *"এই ঘরটাও গুরুত্বপূর্ণ"*
 * লিখতে হত। ⛔ আর মানুষ যেটা মনে রাখতে হয় সেটাই ভোলে — একটা নতুন
 * কলাম যোগ হত, কেউ তালিকায় বসাতে ভুলে যেত, আর ঐ ঘরটা **নীরবে
 * অরক্ষিত** থেকে যেত।
 *
 * ⭐ উল্টো দিকটা নিরাপদ: সব ঘর ধরা হয়, আর যেগুলো **ইচ্ছাকৃতভাবে**
 * বাদ সেগুলো এখানে এক জায়গায় লেখা — ছোট, পড়া যায়, আর নতুন কলাম
 * আপনা থেকেই সুরক্ষিত।
 */
final class DocumentFingerprint
{
    /**
     * যে ঘরগুলো বদলালে সই বাতিল হয় না — কারণসহ।
     *
     * ⚠️ তালিকাটা ছোট রাখা ইচ্ছাকৃত: প্রতিটা সারি একটা সিদ্ধান্ত, আর
     * প্রতিটা সারি একটা ফাঁক।
     *
     * @var list<string>
     */
    private const NOT_THE_PAPER = [
        /* ⓘ প্রতিটা সংরক্ষণেই বদলায় — ধরলে প্রতিবার নতুন অনুমোদন লাগত */
        'updated_at',
        'created_at',

        /* ⓘ ছাপা বা শেয়ারের গোনা — কাগজের কথা নয়, ব্যবহারের কথা */
        'printed_count',
        'shared_count',
        'printed_at',

        /* ⚠️ অনুমোদনের নিজের অবস্থা — নাহলে সই দেওয়ামাত্র ছাপ বদলে যেত */
        'status',
        'approved_at',
        'approved_by',
        'posted_at',

        /* ⓘ যন্ত্রের নিজের হিসাব, মানুষের সিদ্ধান্ত নয় */
        'row_hash',
        'prev_hash',
        'public_id',
    ];

    /**
     * ⭐ কাগজটার এখনকার ছাপ।
     *
     * ── ⓘ সারিগুলোও ধরা হয় ──────────────────────────────────────────
     * ⚠️ কেবল মাথার ঘরগুলো নিলে **পণ্যের সারি বদলানো ধরা পড়ত না** —
     * অথচ ঠিক সেটাই সবচেয়ে বিপজ্জনক বদল। ⓘ যে সম্পর্কগুলো ইতিমধ্যে
     * তোলা আছে (`relationLoaded`) কেবল সেগুলো — নাহলে একটা ছাপ নিতে
     * গিয়ে গোটা ডাটাবেস তুলে আনত।
     */
    public function of(Model $document): string
    {
        return hash('sha256', json_encode($this->shapeOf($this->asStored($document)), JSON_THROW_ON_ERROR));
    }

    /**
     * ⛔ কাগজটা **যেমন ডাটাবেজে আছে** — হাতের কপিটা যেমন, তেমন নয়।
     *
     * ── ⚠️ যা ধরা পড়ল, ২৪ সেপ্টেম্বর ২০২৬ ──────────────────
     * ⓘ `Model::create()` সারিটা আবার পড়ে না — হাতের অবজেক্টে
     * কেবল যে ঘরগুলো দেওয়া হয়েছিল সেগুলোই থাকে। ⛔ ডাটাবেজের
     * ডিফল্টগুলো (`is_active = 1`, `qty = 0`) ওখানে নেই।
     *
     * ⚠️ ফল: অনুরোধের দিন নেওয়া ছাপ আর পরে ডাটাবেজ থেকে পড়া
     * সারির ছাপ কখনো মিলত না — কাগজটা এক চুলও না বদলালেও।
     * ⓘ তখন [[ApprovalExceptions::changedAfterSigning()]] প্রতিটা অনুমোদিত
     * কাগজকে *"সইয়ের পর বদলেছে"* বলত, আর তালিকাটা এত ভরা থাকত
     * যে কেউ ওটা পড়ত না — আর সত্যিকারের একটা বদল ওই ভিড়ে হারাত।
     *
     * ── ⓘ হাতের অবজেক্টটা ছোঁয়া হয় না ─────────────────────
     * ⛔ `refresh()` ডাকলে যিনি কাগজটা নিয়ে কাজ করছেন তাঁর
     * অসংরক্ষিত বদলগুলো মুছে যেত — একটা ছাপ নেওয়া কখনো কারো
     * কাজ মুছে দেবে না। ⓘ তাই আলাদা একটা কপি।
     *
     * ── ⓘ সারিগুলো হাতেরটাই ──────────────────────────────
     * যে সম্পর্কগুলো তোলা আছে সেগুলো সাথে যায়, আর ওগুলো
     * এমনিতেই ডাটাবেজ থেকে পড়া — তাই ওখানে এই ফাঁকটা নেই।
     */
    private function asStored(Model $document): Model
    {
        if (! $document->exists) {
            return $document;
        }

        $stored = $document->newQuery()->find($document->getKey());

        if ($stored === null) {
            /*
             * ⓘ গ্লোবাল স্কোপ লুকিয়ে দিয়েছে, নাহলে সারিটা আর নেই।
             * ⚠️ দুই অবস্থাতেই হাতের কপিটাই সবচেয়ে ভালো উত্তর — ছাপ
             * না নিয়ে ফেরত যাওয়ার চেয়ে ভালো।
             */
            return $document;
        }

        $stored->setRelations($document->getRelations());

        return $stored;
    }

    /**
     * @return array<string, mixed>
     */
    private function shapeOf(Model $document): array
    {
        $out = [];

        foreach ($document->getAttributes() as $key => $value) {
            if (in_array($key, self::NOT_THE_PAPER, true)) {
                continue;
            }

            $out[$key] = $value === null ? null : (string) $value;
        }

        ksort($out);

        /*
         * ⓘ সারিগুলো — কেবল যেগুলো ইতিমধ্যে তোলা আছে।
         *
         * ⚠️ ক্রমটা `id` ধরে সাজানো হয়, নাহলে একই সারিগুলো অন্য ক্রমে
         * এলে ছাপ বদলে যেত আর কাগজ না বদলেও সই বাতিল হত।
         */
        foreach ($document->getRelations() as $name => $related) {
            if ($related === null) {
                continue;
            }

            $rows = $related instanceof Model ? [$related] : $related;

            $lines = [];

            foreach ($rows as $row) {
                if ($row instanceof Model) {
                    $lines[] = $this->shapeOf($row);
                }
            }

            usort($lines, fn (array $a, array $b) => ($a['id'] ?? '') <=> ($b['id'] ?? ''));

            $out['~'.$name] = $lines;
        }

        return $out;
    }
}

<?php

declare(strict_types=1);

namespace App\Core\Engines\Approval;

use App\Core\Support\Money;
use App\Models\Approval;
use Illuminate\Database\Eloquent\Model;

/**
 * একটা কাগজ নিশ্চিত করার আগে অনুমোদন লাগে কি না।
 *
 * ── কেন এটা কোরে, প্রতিটা মডিউলে নয় ─────────────────────────────────
 * চেকলিস্টের §২-এর নিয়মটা এক লাইনের: *"প্রতিটা মডিউল কেবল নিজের Request
 * পাঠাবে; Rule · Matrix · UI এখানেই একবার।"* প্রশ্নটা — "অনুমোদন কি
 * আটকাচ্ছে?" — প্রতিটা মডিউলে হুবহু এক, আর ছয় জায়গায় ছয়বার লিখলে
 * একদিন একটা কপি অন্যদের থেকে আলাদা হয়ে যেত। ⚠️ সবচেয়ে বাজে দিকটা হলো
 * সেই আলাদা হওয়াটা **নীরব**: একটা মডিউল অনুমোদন চাওয়া বন্ধ করে দিলে
 * কিছুই ভাঙে না, কেবল সইটা আর চাওয়া হয় না।
 *
 * ⓘ Accounts-এর [[VoucherApproval]] এর আগে লেখা, আর সে ভাউচারের নিজের
 * ধরন-নির্দিষ্ট কাজও করে। ওটা এখানে টেনে আনা হয়নি — চলন্ত জিনিস ভাঙার
 * তাড়া নেই। নতুন যা যুক্ত হচ্ছে সবই এই পথে আসে।
 *
 * ── তিনটা অবস্থা, আর তিনটাই দরকারি ──────────────────────────────────
 *   `null` ফেরা      → এগিয়ে যাও (ছক নেই · অঙ্ক সীমার নিচে · অনুমোদন হয়ে গেছে)
 *   PENDING ফেরা     → কেউ সইয়ের অপেক্ষায়
 *   REJECTED ফেরা    → "না" বলা হয়েছে, আর কাগজটা তারপর বদলায়নি
 *
 * ⚠️ **ডিফল্ট পথটাই সবচেয়ে জরুরি।** কোনো কোম্পানি ছক না বসালে
 * `ApprovalEngine::request()` `null` ফেরায়, আর সব **আজকের মতোই** চলে।
 * এটা সুবিধা নয়, শর্ত: এই পাহারা বসানোর পর যেন এমন একটাও প্রতিষ্ঠান না
 * থাকে যেখানে ক্রয়াদেশ নিশ্চিত করা বন্ধ হয়ে গেল।
 */
final class DocumentApproval
{
    public function __construct(private readonly ApprovalEngine $approvals) {}

    /**
     * কাগজটা আটকাচ্ছে এমন কিছু আছে কি?
     *
     * @param  string|null  $amount  ছকের সীমা এর সাথেই মেলানো হয়; না জানা
     *                               থাকলে `null`, আর তখন সীমা যা-ই হোক
     *                               অনুমোদন লাগে (`ApprovalFlow::appliesTo`)
     */
    /**
     * @param  array<string, mixed>  $fields
     */
    public function stopping(
        Model $document,
        string $module,
        string $action,
        ?string $amount = null,
        ?string $reason = null,
        array $fields = [],
    ): ?Approval {
        /*
         * ⭐ ঘরগুলো কাগজ থেকেই — ২৪ সেপ্টেম্বর ২০২৬।
         *
         * ── ⛔ শর্ত বসালে প্রবাহটা **বন্ধ** হয়ে যেত ─────────────
         * ⓘ সাতটা সেবা [[assertClear()]] ডাকে, আর একটা ঘর পাঠাত
         * না। ⚠️ [[ApprovalCondition::matches()]] ঘর না পেলে *"মেলে না"*
         * বলে — তাই একটা শর্ত লেখা হত অনুমোদন তুলে দেওয়া।
         *
         * ⛔ ফলটা সবচেয়ে খারাপ দিকে: মালিক শর্ত লিখে ভাবতেন নিয়ম
         * কড়া হলো, অথচ কাগজগুলো সই ছাড়াই পার হত।
         *
         * ── ⓘ কেন সাত জায়গায় তালিকা লেখা হয়নি ──────────────
         * [[DocumentFingerprint]]-এর অবিকল একই যুক্তি: তালিকা রাখলে
         * প্রতিটা মডিউলকে মনে করে *"এই ঘরটা পাঠা"* লিখতে হত, আর
         * মানুষ যেটা মনে রাখতে হয় সেটাই ভোলে।
         *
         * ⚠️ ডাকা জায়গা নিজে ঘর পাঠালে **সেটাই জেতে** — কারণ কিছু
         * শর্ত কাগজের ঘরে থাকে না (যেমন হিসাব করা শতকরা)।
         */
        $onThePaper = ApprovalEngine::fieldsOf($document);

        /*
         * ⚠️ ডাকা জায়গার ঘর সবসময় জেতে, আর কাগজের ঘরগুলো তার
         * উপরে যোগ হয় — কিছু শর্ত কাগজের ঘরে থাকে না (যেমন
         * হিসাব করা শতকরা), আর তখন সেবাটা নিজে পাঠায়।
         */
        $matchOn = [...$onThePaper, ...$fields];

        $latest = $this->approvals->latestFor($document, $action);

        /*
         * অনুমোদন পাওয়া গেছে — এগোও, আর **নতুন অনুরোধ কোরো না**।
         *
         * ⚠️ `ApprovalEngine::approve()` নিজে কাজটা এগোয় না, কেবল
         * অনুরোধটাকে `approved` করে। অর্থাৎ মানুষটাকে ফিরে এসে আবার
         * "নিশ্চিত" চাপতে হয়। ওই দ্বিতীয় চাপে আবার `request()` ডাকলে
         * সে **পুরনো অনুরোধটা pending নয় বলে খুঁজে পেত না** আর একটা
         * নতুন অনুরোধ বানাত — কাগজটা তখন অসীম লুপে পড়ত: অনুমোদন পেলেই
         * আবার নতুন অনুমোদন লাগত।
         */
        /*
         * ⚠️ …তবে সইটা যে অঙ্কের উপর দেওয়া হয়েছিল, কাগজটা এখনো সেই
         * অঙ্কেই আছে কি না সেটা দেখে। ⛔ না দেখলে ৫০ হাজারে দেওয়া সই
         * দিয়ে ৫ লাখ পাশ হয়ে যেত — কারণসহ
         * [[Approval::covers()]]-এ।
         *
         * ⓘ অঙ্ক বদলালে নিচে গিয়ে **নতুন একটা অনুরোধ** বসে, আর পরের
         * বার `latestFor()` সেই নতুন pending সারিটাই পায় — তাই উপরের
         * অসীম লুপটা ফেরে না।
         */
        $superseded = null;

        /*
         * ⭐ কাগজটা এখন যেমন আছে — তার ছাপ।
         *
         * ⓘ একবারই নেওয়া হয়, আর দুই জায়গায় লাগে: সইটা এখনো
         * খাটে কি না দেখতে, আর নতুন অনুরোধে বসাতে।
         */
        $hash = app(DocumentFingerprint::class)->of($document);

        if ($latest?->status === Approval::APPROVED) {
            if ($latest->stillCovers($amount, $hash)) {
                return null;
            }

            /*
             * ⭐ পুরনো সইটা কোন অঙ্কের ছিল — মনে রাখা হয়, ২২ সেপ্টেম্বর ২০২৬।
             *
             * ── ⚠️ কেন, নাহলে দ্বিতীয় অনুরোধটা রহস্য ───────────────────
             * অঙ্ক বদলালে নিচে নতুন একটা অনুরোধ বসে, আর সইকারীর ইনবক্সে
             * **একই কাগজ দ্বিতীয়বার** এসে হাজির হয়। ⛔ কারণ না জানলে
             * সেটা দেখতে ভুলের মতো লাগে, আর মানুষ ভাবেন ব্যবস্থাটা
             * দুইবার চাইছে।
             *
             * ⓘ কারণটা লিখে রাখলে পর্দা বলতে পারে: *"আগের সই ছিল ৫০
             * হাজারে, কাগজ এখন ৫ লাখ"* — আর তখন দ্বিতীয় অনুরোধটা
             * **ব্যাখ্যা**, বিরক্তি নয়।
             */
            $superseded = $latest;
        }

        /*
         * প্রত্যাখ্যাত — আর তারপর কাগজটা বদলায়নি।
         *
         * নীরবে আবার অনুরোধ পাঠালে **প্রত্যাখ্যানের কোনো মানে থাকত না**:
         * যিনি "না" শুনলেন তিনি আবার বোতামটা চেপে আবার পাঠাতেন। আবার
         * চাওয়ার পথ একটাই — কাগজটা বদলানো, অর্থাৎ "না"-র কারণটা মেটানো।
         */
        if ($latest?->status === Approval::REJECTED && ! $this->changedSince($document, $latest)) {
            return $latest;
        }

        return $this->approvals->request(
            document: $document,
            module: $module,
            action: $action,
            amount: $amount,

            /*
             * ⓘ `approvals.payload` ঘরটা প্রথম দিন থেকেই আছে, আর মাইগ্রেশনে
             * লেখা ছিল এটা "প্রস্তাবিত বদলটা" ধরার জন্য। ⚠️ আজ পর্যন্ত
             * কোনো ডাকা জায়গা ওটা ভরত না, তাই লাইভে সবগুলোই NULL।
             */
            /*
             * ⭐ দুইটা জিনিস একই ঘরে, আর সেটা ইচ্ছাকৃত।
             *
             * ⓘ কাগজের ঘরগুলো — শর্ত মাপার জন্য
             * ([[ApprovalCondition]]) — আর পুরনো সইটা কোন অঙ্কে ছিল।
             *
             * ⚠️ একই ঘরে রাখা হয়েছে কারণ দুইটাই *"এই
             * অনুরোধটা কোন বাস্তবতায় বসেছিল"* প্রশ্নের উত্তর,
             * আর দুইটাই পরে পড়ে দেখার জন্য।
             */
            payload: array_filter([
                ...$fields,

                /*
                 * ⭐ ঘরের **নাম**, মান নয়।
                 *
                 * ⓘ [[ApprovalExceptions::flowsThatCanNeverCatch()]]-এর দরকার
                 * কেবল নামগুলো: *"এই কাজে কোন ঘরগুলো সত্যিই আসে"*।
                 *
                 * ⛔ মানগুলো রাখলে প্রতিটা সারি মোটা হত, আর বেতনের
                 * অঙ্ক একটা দ্বিতীয় টেবিলে জমা হত — যেটা কেউ চায়নি।
                 */
                'fields_seen' => array_keys($matchOn) ?: null,
                'supersedes' => $superseded === null ? null : (int) $superseded->id,
                'was_amount' => $superseded?->amount === null ? null : (string) $superseded->amount,
            ], fn ($v) => $v !== null) ?: null,

            stateHash: $hash,

            // ⓘ মাপা হয় গোটা কাগজ দিয়ে, জমা থাকে কেবল নাম
            matchOn: $matchOn,

            reason: $reason,

            /*
             * ⚠️ কে চাইছেন — `auth()->id()`-র উপর ছেড়ে দেওয়া যায় না।
             *
             * `approvals.requested_by` null নিতে পারে না, আর কমান্ড লাইন ·
             * সিডার · কিউ ওয়ার্কার · ইমপোর্ট — কোথাওই লগইন করা কেউ নেই।
             * ওগুলোতেও কাগজ নিশ্চিত হয়, আর তখন সৎ উত্তর একটাই: **যিনি
             * কাগজটা লিখেছিলেন**।
             */
            userId: auth()->id() ?? $this->authorOf($document),
        );
    }

    /**
     * একই প্রশ্ন, কিন্তু উত্তরটা যখন পর্দায় বলতে হবে।
     *
     * ── কেন ব্যতিক্রম, ফেরত মান নয় ──────────────────────────────────
     * `confirm()` ধরনের মেথডগুলো ইতিমধ্যেই নিয়ম ভাঙলে
     * `ValidationException` ছোঁড়ে ("কেবল খসড়া নিশ্চিত হয়"), আর পর্দাগুলো
     * সেটা দেখাতে জানে। অনুমোদনের বার্তাটা অন্য পথে পাঠালে প্রতিটা
     * কন্ট্রোলারে নতুন একটা শাখা লাগত, আর যে কন্ট্রোলার ভুলে যেত সেখানে
     * কাগজটা নীরবে **অনুমোদন ছাড়াই** থেমে থাকত — কোনো বার্তা ছাড়া।
     *
     * @param  string  $field  ফর্মের কোন ঘরের নিচে বার্তাটা বসবে
     */
    /**
     * @param  array<string, mixed>  $fields  শর্ত মাপার জন্য কাগজের ঘর
     */
    public function assertClear(
        Model $document,
        string $module,
        string $action,
        string $field,
        ?string $amount = null,
        ?string $reason = null,
        array $fields = [],
    ): void {
        $stopping = $this->stopping($document, $module, $action, $amount, $reason, $fields);

        if ($stopping === null) {
            return;
        }

        /*
         * ⓘ [[HeldForApproval]] — `ValidationException`-এরই উপ-ধরন, তাই
         * যে ছয়টা সেবা এটা ডাকে তাদের আচরণ হুবহু আগের মতো। ⭐ তফাত
         * কেবল এই: কাগজটা সাথে যায়, তাই সরাসরি ক্রয়ের পর্দা মানুষকে
         * সোজা খসড়াটার কাছে নিয়ে যেতে পারে (১৯ সেপ্টেম্বর ২০২৬)।
         */
        throw HeldForApproval::on(
            $document,
            $field,
            $stopping->status === Approval::REJECTED
                ? __('core.approval.rejected', [
                    'reason' => (string) $stopping->decisions()->latest('id')->value('remarks'),
                ])
                : $this->awaitingWord($stopping, $module, $action),
        );
    }

    /**
     * "অপেক্ষায়" বার্তাটা — **কেন** অপেক্ষায়, সেটাসহ।
     *
     * ── ⭐ মালিকের প্রশ্ন, ২৩ সেপ্টেম্বর ২০২৬ ─────────────────────────
     * তিনি একটা বিলের পর্দা দেখিয়ে বললেন: *"limit nai keno ei kota
     * likhena?"* — কাগজে বাকির সীমা ৫০,০০০, বিল ৮৯,৭২০, আর বার্তাটা
     * কেবল বলছিল *"অনুমোদনের জন্য পাঠানো হয়েছে"*।
     *
     * ⛔ নিয়মটা এই ফাইলের বাইরে আগেই লেখা ছিল, আর মানা হয়নি: [[lang/bn/core]]-এ
     * এই দুইটা বার্তার মাথায় মন্তব্য — *"'না' বলার কারণটা বার্তার সাথেই
     * যায়, নাহলে পরের কাজটা হয় একটা ফোন কল"*। ⓘ `rejected` কারণ বলত,
     * `awaiting` বলত না।
     *
     * ⚠️ আর কারণটা কোথাও খুঁজতে হয় না — অনুরোধের সারিতে `requested_reason`
     * আর `amount` দুইটাই আগে থেকেই বসে। ⓘ সেগুলো অব্যবহৃত ছিল, অর্থাৎ
     * তথ্যটা জমা হচ্ছিল আর কেউ পড়ছিল না।
     *
     * ⓘ কারণ না থাকলে পুরনো বাক্যটাই ফেরে — যে ছকে কারণ লেখা হয় না,
     * তার বার্তা একটুও বদলায় না।
     */
    private function awaitingWord(Approval $stopping, string $module, string $action): string
    {
        $why = trim((string) $stopping->requested_reason);

        /*
         * ⚠️ কারণ না থাকলে চুপ করে থাকা নয় — **কোন ছক** থামিয়েছে সেটা বলা।
         *
         * ⓘ বেশিরভাগ ডাকে `reason` হিসেবে কাগজের মন্তব্য যায়, আর ওটা
         * প্রায়ই খালি। ⛔ তখন পুরনো বার্তাটা ফিরত, আর মালিকের প্রশ্নটাই
         * থেকে যেত: *কীসের জন্য পাঠানো হলো?*
         *
         * ⭐ ছকের নামটা মডিউল নিজেই ঘোষণা করে (`<module>::approval.<action>`),
         * তাই এখানে কোনো মডিউলের নাম হাতে লেখা নেই — কোর কোনো মডিউল
         * চেনে না (সেকশন ১৯.৭)।
         *
         * ⓘ অনুবাদ না থাকলে `__()` চাবিটাই ফেরত দেয় — তখন কাঁচা চাবি
         * দেখানোর চেয়ে পুরনো বাক্যটাই ভালো, আর সেটাই করা হয়।
         */
        if ($why === '') {
            $key = "{$module}::approval.{$action}";
            $what = __($key);

            if ($what === $key) {
                return __('core.approval.awaiting');
            }

            $why = $what;
        }

        /*
         * ⓘ অঙ্কটা থাকলে সাথে যায় — *"৳৮৯,৭২০"* পড়লে মানুষ সাথে সাথে
         * বোঝেন কোন কাগজটার কথা হচ্ছে। ⚠️ সব ছক অঙ্ক পাঠায় না, তাই
         * শূন্য হলে কিছুই বসে না — শূন্য টাকার কথা বললে বার্তাটা বরং
         * বিভ্রান্ত করত।
         */
        $amount = (string) ($stopping->amount ?? '0');

        if (bccomp($amount, '0', 4) > 0) {
            $why .= ' · ৳'.Money::format($amount);
        }

        return __('core.approval.awaiting_because', ['reason' => $why]);
    }

    /**
     * সিদ্ধান্তের পর কাগজটা বদলেছে কি?
     *
     * `decided_at` না থাকলে ধরে নেওয়া হয় বদলায়নি — অর্থাৎ **আটকে থাকাই
     * ডিফল্ট**। উল্টোটা ধরলে একটা অসম্পূর্ণ সারি প্রত্যাখ্যানটাকে নীরবে
     * অকেজো করে দিত।
     */
    private function changedSince(Model $document, Approval $approval): bool
    {
        /*
         * ⭐ প্রশ্নটা ছাপকে করা হয়, ঘড়িকে নয় — ২৪ সেপ্টেম্বর ২০২৬।
         *
         * ── ⛔ ঘড়ি ধরে মাপার ভুলটা ───────────────────────────
         * ⓘ আগে লেখা ছিল `updated_at > decided_at`। ⚠️ MySQL-এর
         * DATETIME সেকেন্ডে মাপে, তাই একই সেকেন্ডে ফেরত আর সংশোধন
         * হলে দুইটা **সমান**, আর উত্তর হত *"বদলায়নি"*।
         *
         * ⛔ ফল নীরব: যিনি ফেরত পেয়ে সঙ্গে সঙ্গে তারিখটা ঠিক করলেন,
         * তাঁর দ্বিতীয় অনুরোধটা গিলে ফেলা হত, আর কাগজটা ফেরত অবস্থায়
         * বসে থাকত — কোনো বার্তা ছাড়া।
         *
         * ── ⓘ পুরনো সারিগুলোর ছাপ নেই ──────────────────────────
         * ওগুলোর জন্য ঘড়ির নিয়মটা থাকে, অবিকল আগের মতো।
         */
        if ($approval->state_hash !== null) {
            return ! hash_equals(
                (string) $approval->state_hash,
                app(DocumentFingerprint::class)->of($document),
            );
        }

        $changed = $document->getAttribute('updated_at');

        if ($approval->decided_at === null || $changed === null) {
            return false;
        }

        return $changed->greaterThan($approval->decided_at);
    }

    /**
     * কাগজটা কে লিখেছিলেন।
     *
     * প্রতিটা কাগজে `created_by` থাকে না (কিছু কাগজ যন্ত্রের তৈরি), তাই
     * না পেলে `null` — আর তখন ইঞ্জিন নিজেই ব্যর্থ হবে, নীরবে ভুল
     * কারো নামে বসিয়ে দেওয়ার চেয়ে যা ভালো।
     */
    private function authorOf(Model $document): ?int
    {
        $author = $document->getAttribute('created_by');

        return $author === null ? null : (int) $author;
    }

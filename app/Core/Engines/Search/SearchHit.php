<?php

declare(strict_types=1);

namespace App\Core\Engines\Search;

/**
 * সার্চের একটা ফলাফল — একটা সারি, পড়ার মতো করে।
 *
 * ── ⭐ কেন নতুন কোনো গড়ন আবিষ্কার করা হয়নি ───────────────────────────
 * এই চারটা ঘর হুবহু [[App\Core\Contracts\Drillable]]-এর চারটা পদ্ধতি —
 * `drillSourceType()`, `drillDocumentNo()`, `drillLabel()`, `drillRoute()`।
 * ⓘ আর ঐ ইন্টারফেসটা রিপোতে **আগে থেকেই আছে, ৫০টা মডেল সেটা মানে**।
 *
 * ⚠️ অর্থাৎ সার্চের জন্য কোনো মডেলে নতুন কিছু বসাতে হয়নি: যে জিনিস
 * খতিয়ানের ড্রিল-ডাউনে "এটা কোন কাগজ, কার, কোথায়" বলতে পারে, সে-ই
 * সার্চের ফলাফলেও ঠিক ঐ কথাটাই বলতে পারে।
 *
 * ⛔ দ্বিতীয় একটা উৎস বানালে দুইটা জায়গায় একই সত্য থাকত, আর একদিন
 * দুইটা আলাদা উত্তর দিত — আজ এই রিপোতে ভাঙা জিনিসগুলোর প্রায় সবই
 * ঠিক ঐ আকারের।
 */
final readonly class SearchHit
{
    public function __construct(
        /**
         * ⓘ যন্ত্রের নাম — `customer`, `account`, `sales_invoice`।
         *
         * ⭐ অনূদিত নামের পাশে এটাও রাখা হয়, আর কারণটা দুইটা: পর্দা
         * ধরন ধরে আইকন বা দল বানাতে পারে, আর **দাবি লেখা যায়** —
         * অনূদিত লেখা ধরে পরীক্ষা লিখলে ভাষা বদলালেই সেটা ভাঙত।
         */
        public string $slug,

        /** কী ধরনের কাগজ, মানুষের ভাষায় — "গ্রাহক", "হিসাব খাত"। */
        public string $type,

        /** নম্বর, থাকলে — "INV-0012"। মাস্টার রেকর্ডে প্রায়ই কোড। */
        public string $documentNo,

        /** মানুষের ভাষায় নাম — "রহিম ট্রেডার্স"। */
        public string $label,

        /** কোথায় নিয়ে যাবে — সম্পূর্ণ ঠিকানা। */
        public string $url,
    ) {}

    /**
     * তালিকায় যা দেখা যাবে।
     *
     * ⓘ নম্বর আর নাম দুইটাই থাকলে দুইটাই দেখানো হয়: কেউ নম্বর মনে রাখেন
     * (হিসাবরক্ষক), কেউ নাম (বিক্রয়কর্মী)। ⚠️ একটা বাদ দিলে তাঁদের একজন
     * ফলাফল দেখেও চিনতে পারতেন না।
     */
    public function heading(): string
    {
        return trim($this->documentNo === '' ? $this->label : $this->documentNo.' · '.$this->label, ' ·');
    }
}

<?php

declare(strict_types=1);

namespace App\Core\Engines\Backup;

/**
 * একটা গন্তব্য কী কী করতে পারে — আর ইঞ্জিন এর বাইরে কিছু জানে না।
 *
 * ── কেন এই কন্ট্রাক্টটাই পুরো নকশার মেরুদণ্ড ──────────────────────────
 * মালিকের ব্লুপ্রিন্টের শেষ লাইন: *"Google Drive/OneDrive/Dropbox-কে
 * backup-এর সমার্থক না ধরে Backup Destinations হিসেবে রাখা। তাহলে
 * ভবিষ্যতে নতুন cloud, S3, NAS, remote server বা অন্য hosting যোগ করলেও
 * core engine পরিবর্তন করতে হবে না।"*
 *
 * আর ৩ সেপ্টেম্বর ২০২৬-এ তিনি যেটা যোগ করেছেন, সেটা এটাকে ঐচ্ছিক থেকে
 * বাধ্যতামূলক করে: **ABOS দুইভাবেই বিক্রি হবে** — আমাদের সার্ভারে, আর
 * ক্রেতার নিজের সার্ভারে।
 *
 * ⚠️ ক্রেতার ঘরে আমাদের Mac mini নেই, আমাদের Google অ্যাকাউন্ট নেই,
 * আমাদের EBN হোস্টিংও নেই। ইঞ্জিনে ওগুলোর একটা নামও থাকলে সেই কোড
 * ক্রেতার ইনস্টলে **অর্ধেক অচল** হয়ে যেত।
 *
 * তাই ইঞ্জিন জানে কেবল: *"একটা ফাইল আছে, ওটা রাখো; পরে ফেরত দাও।"*
 *
 * ── বাস্তবায়নের ক্রম, আর কেন এই ক্রম ─────────────────────────────────
 *
 *   local      একটা পথ                     কোনো নিবন্ধন লাগে না
 *   sftp       host + user + key           অন্য কম্পিউটার, NAS
 *   s3         access key + secret         Backblaze · Wasabi · DO · MinIO
 *   gdrive …   ⚠️ OAuth — মালিকের নিবন্ধন লাগে, তাই পরে
 *
 * প্রথম তিনটা **গ্রাহক নিজে সাজাতে পারেন** — দুইটা লাইন কপি করে বসিয়ে
 * দেওয়া। শেষেরগুলোয় ABOS-এর নিজের ডেভেলপার অ্যাপ লাগে, আর অন্য
 * কোম্পানির ব্যবহারের জন্য Google সেটাকে "verified" চায় — কয়েক
 * সপ্তাহের পর্যালোচনা, বছরে নবায়ন। **তাই ক্লাউড একটা বিক্রয়-বৈশিষ্ট্য,
 * ভিত্তি নয়।**
 */
interface Destination
{
    /**
     * একটা স্থানীয় ফাইল গন্তব্যে রাখা।
     *
     * ⚠️ ব্যর্থ হলে **ব্যতিক্রম ছুড়তে হবে, `false` ফেরত নয়** — নাহলে
     * ডাকা পক্ষ ভুলে গেলে ব্যর্থতাটা নীরবে হারিয়ে যেত, আর রানটা
     * "সফল" লেখা থাকত। ব্যাকআপে নীরব ব্যর্থতাই সবচেয়ে খারাপ ব্যর্থতা:
     * টের পাওয়া যায় কেবল যেদিন ফাইলটা দরকার হয়।
     */
    public function put(string $localFile, string $remoteName): void;

    /** গন্তব্য থেকে একটা ফাইল স্থানীয়ভাবে নামানো — restore-এর সময়। */
    public function get(string $remoteName, string $localFile): void;

    /**
     * ওখানে কী কী আছে — নাম ও আকার।
     *
     * @return list<array{name: string, bytes: int, at: ?string}>
     */
    public function list(): array;

    /** একটা পুরনো কপি মোছা — retention-এর কাজ। */
    public function delete(string $remoteName): void;

    /**
     * এখন কি সত্যিই পৌঁছানো যায়?
     *
     * ── কেন এটা কন্ট্রাক্টের অংশ, বাইরের কোনো যাচাই নয় ───────────────
     * **যে গন্তব্য কোনোদিন পরীক্ষা করা হয়নি, সেটা গন্তব্য নয় — একটা
     * আশা।** একটা ভুল পথ, একটা মেয়াদোত্তীর্ণ চাবি বা একটা খোলা
     * পেনড্রাইভ — তিনটাই সেটিংসের পাতায় নিখুঁত দেখায়, আর তিনটাই
     * বিপদের দিনে ফাঁকা।
     *
     * তাই প্রতিটা driver-কে নিজের স্বাস্থ্য বলতে জানতে হয়, আর পর্দায়
     * প্রতিটা গন্তব্যের পাশে একটা "পরীক্ষা করুন" বোতাম থাকে।
     *
     * ⚠️ এটা **লিখেও দেখে**, কেবল পথ আছে কিনা তা নয়: `is_dir()` সত্যি
     * বলে অথচ ডিস্ক read-only — এমন হয়, আর তখন ব্যাকআপের রাতে গিয়ে
     * ধরা পড়ত।
     */
    public function health(): Health;

    /** পর্দায় দেখানোর জন্য — "প্রধান গুদামের পেনড্রাইভ (K:)" জাতীয়। */
    public function describe(): string;
}
